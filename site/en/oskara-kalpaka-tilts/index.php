<div aria-labelledby="heading4720" class="collapse" data-parent="#accordion" id="collapse4720">
<div class="card-body">
<p>The bridge across the Karosta Canal bears the name of Oskars Kalpaks - Commander of 1st Latvian Independent Battalion, also known as “Kalpaks Battalion”, however, colloquially it is often called also as the Karosta Bridge.<br/> </p><h5>The unique and so far, the only swing bridge in Latvia was opened for traffic on 19<br/>August 1906.</h5><p> </p><p>The bridge was damaged during World War I and rebuilt soon after the War. In 1926, the steamship “Narne” accidentally crashed into the bridge and destroyed it seriously, and even though repaired, it underwent yet another deliberate damage by the Soviet Army during World War II.</p><p>Before Latvia regained its independence, the territory of Karosta (War Port, as translated literally) was a closed military site, thus, the traffic over the bridge was controlled round the clock by the militaries. Crossing the bridge to Karosta was only possible with special permits for a few hours a day, the rest of the time the bridge was open to the traffic of Soviet warships. Interestingly, throughout the years of Soviet occupation, the name of the bridge was “The Red Army Bridge” and regained its current name only after Latvia became free.</p><p> </p><h5>The bridge weighs 300 tons and has been construed in two separate parts (northern and southern) and consists of two identical cantilevers. The bridge carriageway is 7.3 meters wide, and the surface is made of wooden planks. The total length of the bridge is 133 meters. The height of the bridge above the water level is 8.32 meters.</h5><p> </p><p>In the summer of 2006, the Georgian-flagged tanker “Anna” accidentally collided into the northern abutment of the bridge, and it was only after reconstruction, that Oskars Kalpaks Bridge was officially opened again for traffic in August 2009.</p><br/>
