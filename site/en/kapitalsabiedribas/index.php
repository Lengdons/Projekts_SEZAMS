  // Build 3-Row Staggered Honeycomb Track (46-column cycle with transposed offsets [0, 15, 31])
  const track = document.getElementById("hexWheelTrack");
  const viewport = document.getElementById("hexWheelViewport");
  const HEX_W = 148;
  const HEX_H = 168;
  const COL_STEP = 162;
  const ROW_STEP = 132;
  const COLS_PER_ROW = 46;
  const ROW_COL_OFFSETS = [0, 15, 31];
  const TOTAL_WIDTH = COLS_PER_ROW * COL_STEP;

  const wheelItems = [];

  for (let copy = 0; copy < 2; copy++) {
    for (let c = 0; c < COLS_PER_ROW; c++) {
      for (let r = 0; r < 3; r++) {
        const pIdx = (c + ROW_COL_OFFSETS[r]) % PARTNERS.length;
        const p = PARTNERS[pIdx];
        const xOffset = (r === 1) ? COL_STEP / 2 : 0;
        const x = (copy * TOTAL_WIDTH) + (c * COL_STEP) + xOffset;
        const y = 36 + (r * ROW_STEP);

        const item = document.createElement("div");
        item.className = "hex-wheel-item";
        item.dataset.partnerId = p.id;
        item.style.left = x + "px";
        item.style.top = y + "px";

