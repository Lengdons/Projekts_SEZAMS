          '</button>';

        item.addEventListener("click", function () {
          if (dragMoved) return;
          selectPartnerInPortal(p.id, true);
        });

        track.appendChild(item);
        wheelItems.push({ el: item, baseX: x, y: y, partnerId: p.id });
      }
    }
