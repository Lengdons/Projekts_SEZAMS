  function selectPartnerInPortal(partnerId, openCardBelow) {
    const p = PARTNERS.find(function (item) { return item.id === partnerId; });
    if (!p) return;
    activePartnerId = partnerId;

    document.querySelectorAll(".hex-wheel-item").forEach(function (el) {
