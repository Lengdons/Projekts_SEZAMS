<h1 class="article-title">Electronic Ascending-Bid Auction of Property at Brīvības Street 98A (Completed)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><strong>Regarding the results of the property auction:</strong></p><p>On 28 August 2025, the electronic auction organised by the Liepāja Special Economic Zone Authority for part of the property at Brīvības Street 98A, Liepāja, concluded. The highest bid of <strong>EUR 166,140.00</strong> (one hundred and sixty-six thousand one hundred and forty euros), excluding VAT, was made by SIA “Hermes invest”, registration No. 42103078050, registered address: Vecā ostmala 54, Liepāja, LV-3401. The results were approved at the LSEZ Board meeting on 3 September 2025, Board Decision No. 67.</p><p>___________________________________</p><p>The Liepāja Special Economic Zone Authority, unified registration No. LV90000329402, is holding an electronic ascending-bid auction for property at Brīvības Street 98A, Liepāja, cadastral No. 17000220153, consisting of a building and a land plot with a total area of approximately <strong>5,132 m²</strong> (the area will be confirmed after surveying).</p><p><strong>Starting price:</strong> EUR 142,000.00 (one hundred and forty-two thousand euros and 00 cents). <strong>Bid increment:</strong> EUR 1,420.00 (one thousand four hundred and twenty euros and 00 cents). <strong>Security deposit:</strong> EUR 14,200.00 (fourteen thousand two hundred euros and 00 cents).</p><p>Payment of the purchase price shall be made as follows:</p><ul><li>Within 10 working days after the preliminary agreement enters into force, the buyer shall make an advance payment of 30% (thirty per cent) of the purchase price.</li><li>The remaining purchase price shall be paid within two weeks after signing the purchase agreement.</li></ul><p>The auction starts on <strong>29 July 2025 at 13:00</strong> and ends on <strong>28 August 2025 at 13:00</strong>.</p><p>Applicants may register for the auction from 29 July 2025 at 13:00 until 18 August 2025 at 23:59 at <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>.</p><p>To participate, bidders must pay a security deposit of 10% of the starting price, i.e. EUR 14,200.00, before the registration deadline to the Liepāja Special Economic Zone Authority, registration No. LV90000329402, AS “SEB banka”, account <strong>LV42UNLA0012000609480</strong>, stating “Security deposit for the auction of property at Brīvības Street 98A”.</p><p>The auction takes place electronically at <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>. For information, call 29294267 or email <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
