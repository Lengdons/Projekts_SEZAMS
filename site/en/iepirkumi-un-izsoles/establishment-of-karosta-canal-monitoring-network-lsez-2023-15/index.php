<h1 class="article-title">Establishment of the Karosta Canal Monitoring Network (ID No. LSEZ 2023/15)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>The Procurement Commission of the Liepāja Special Economic Zone Authority has adopted a decision on the results of the open procurement procedure “Establishment of the Karosta Canal Monitoring Network” (LSEZ 2023/15), awarding the contract to SIA “Isliena V” (registration No. 5000204363) for a total contract value of EUR 79,280.00 excluding value added tax.</p><p> </p><p><strong>CPV code</strong></p><p>CPV code: 45122000-8 (Test drilling work).</p><p><strong>Project</strong></p><p>The project is implemented with co-financing from the Norwegian Financial Mechanism 2014–2021 programme “Climate Change Mitigation, Adaptation and Environment”. The subject of the contract, “Establishment of the Karosta Canal Monitoring Network at the Port of Liepāja” (hereinafter the Contract), is one of the activities of the project “Remediation of the Historically Polluted Site at Karosta Canal, Port of Liepāja” (hereinafter the Project), implemented by the Liepāja Special Economic Zone Authority (hereinafter the Contracting Authority).</p><p><strong>Contract performance period and location</strong></p><p>1. Contract performance deadline: the work must be completed within three (3) months, but no later than 26 April 2024.</p><p>2. Place of performance: the work area (Figure 6.2) is Karosta Canal at the Port of Liepāja, part of the port's internal waters (cadastral Nos. 1700-010-0073 and 1700-010-0306), and an auxiliary technical site adjoining the disposal area and managed by the LSEZ Authority (cadastral No. 1700-010-0072).</p><p><strong>Procurement procedure</strong></p><p>Open procurement in accordance with the Procurement Guidelines for Public Service Providers (hereinafter the Guidelines). Available from the Procurement Monitoring Bureau (iub.gov.lv).</p><p>Tenders must be submitted through the e-tendering subsystem of the Electronic Procurement System (EIS) (<a href="https://www.eis.gov.lv/EKEIS/Supplier">https://www.eis.gov.lv/EKEIS/Supplier</a>/) by 13 February 2024 at 10:00.</p></div>
