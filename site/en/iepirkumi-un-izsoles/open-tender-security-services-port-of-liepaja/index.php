<h1 class="article-title">Open Tender for Security Services at the Port of Liepāja (LSEZ 2021/58/K)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>The subject of this procurement is physical and technical security services in accordance with the technical specifications and draft contract.</p><p><strong>CPV code:</strong> 79710000-4.</p><p>Tenders must be submitted through the EIS e-tendering subsystem no later than <strong>21 May 2021 at 10:00</strong>.</p><p>The contracting authority’s public online portal in the state electronic information system for receiving tenders and applications is available via EIS: <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>. The contracting authority publishes information there about subsequent invitations to tender, planned procurements, concluded contracts, discontinued procedures and other procurement-related information required by law.</p><p>After evaluating the tender submitted by AS “G4S”, registration No. 40103058465, the procurement commission determined that both the tenderer and the submitted tender comply with the requirements of the open tender rules.</p><p>AS “G4S” offered a contract price of <strong>EUR 842,878.80 excluding VAT</strong>.</p><p>Under the open tender rules, the selection criterion is the most economically advantageous tender, based on the lowest contract price, with evaluation criteria consisting of price and criteria related to the subject of the contract as set out in Clause 5.2.4.2 of the tender rules.</p><p>The commission decided that the right to conclude the procurement contract in the open tender “Provision of Security Services in the Port of Liepāja”, identification No. LSEZ2021/58/K, may be awarded to AS “G4S”, registration No. 40103058465, at its proposed contract price of EUR 842,878.80 excluding VAT.</p></div>
