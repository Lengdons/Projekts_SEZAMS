<h1 class="article-title">Electronic Ascending-Bid Auction of 130 Shock-Absorbing Fender Units</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>The Liepāja Special Economic Zone Authority is organising an electronic ascending-bid auction for the disposal of its movable property: a total of 130 shock-absorbing fenders.</p>
<p>The goods are offered in four lots: three lots of 40 (forty) fenders each and one lot of 10 (ten) fenders. Individual fenders will not be sold separately.</p>
<p><strong>Starting price (reserve price):</strong></p>
<ul><li>One lot of 40 (forty) fenders: EUR 4,800.00 (four thousand eight hundred euros).</li><li>One lot of 10 (ten) fenders: EUR 1,200.00 (one thousand two hundred euros).</li></ul>
<p><strong>Bid increment:</strong></p>
<ul><li>One lot of 40 (forty) fenders: EUR 150.00 (one hundred and fifty euros).</li><li>One lot of 10 (ten) fenders: EUR 40.00 (forty euros).</li></ul>
<p>Value added tax will be applied to the auction price.</p>
<p>The auction security deposit amounts to 10% of the starting price of each lot (EUR 480.00 for a lot of 40 fenders and EUR 120.00 for a lot of 10 fenders). Within 20 (twenty) days from the auction start date, anyone wishing to participate must transfer the deposit to the Liepāja Special Economic Zone Authority, registration No. 90000329402, AS “Swedbank”, account No. LV12HABA0001407037000, with the payment reference “Security deposit for fender auction”, and submit an application for authorisation to participate via <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>.</p>
<p>The auction takes place on the electronic auction website <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>.</p>
<p>The auction opens on 9 September 2024 at 13:00 and closes on 30 September 2024 at 13:00.</p>
<p>Bidder registration is open from 9 September 2024 at 13:00 until 19 September 2024 at 23:59 on the electronic auction website <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>.</p>
<p>The goods may be inspected in person at Sliežu iela 9, Liepāja, by prior appointment with Viesturs Romanovs, Deputy Head of the Authority's Infrastructure Department, phone: 26795153, email: <a href="mailto:viesturs.romanovs@lsez.lv">viesturs.romanovs@lsez.lv</a>.</p>
<p>The auction regulations are available on <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a> and the Authority's website at <a href="https://liepaja-sez.lv/lv/authority/izsoles-sludinajumi">https://liepaja-sez.lv/lv/parvalde/izsoles-sludinajumi</a>.</p></div>
