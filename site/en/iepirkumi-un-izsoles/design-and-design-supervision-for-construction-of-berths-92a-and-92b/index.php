<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><strong>PROCUREMENT NOT SUBJECT TO THE PUBLIC SERVICE PROVIDERS PROCUREMENT LAW</strong> — preparation of the construction design and design supervision for the construction of Berths No. 92A and No. 92B at the Port of Liepāja.</p><p><strong>Subject of procurement:</strong> Preparation of the construction design and design supervision for the project “Construction of Berths No. 92A and No. 92B at the Port of Liepāja”, in accordance with Annex 7 to the tender regulations, “Construction Design Contract (Draft Contract)”, and Annex 8, “Draft Design Supervision Contract”.</p><p><strong>CPV codes:</strong> 71320000-7 — Engineering design services; 71248000-8 — Supervision of project and documentation.</p><p>The design and design supervision activities are planned to be undertaken and financed under the European Maritime, Fisheries and Aquaculture Fund, within the “Action Plan 2023–2027 for the Fisheries Development Programme 2021–2027”, activity “Implementation of Community-Led Local Development Strategies”, measure 4.1 M4/R1, supported action “Strengthening the Development of Port Infrastructure”.</p><p>Tenders must be submitted in the e-tenders subsystem of the Electronic Procurement System (EIS): <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>, by the submission deadline indicated in the notice on the Procurement Monitoring Bureau (IUB) website and in the EIS e-tenders subsystem.</p><p>Tenders will be opened in the EIS e-tenders subsystem at the time specified in the IUB notice and in the EIS e-tenders subsystem.</p><p><strong>Contractor:</strong> SIA “CHR Design Solutions”.</p><p><strong>Contract price:</strong> EUR 68,300.00 excluding VAT.</p></div>
