<h1 class="article-title">Open Tender for Construction Works in Liepāja Industrial Park, Stage 1 (Sections of N and F Streets)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><strong>Procurement ID No. LSEZ2023/6/K</strong></p><p><strong>Description of the procurement subject:</strong> Construction works in the Liepāja Industrial Park on sections of N and F Streets in accordance with the construction design “Construction of Street Infrastructure in the Territory of the Former Liepājas metalurgs Plant, Stage 2 (Sections of N, F and C Streets)”, Stage 2.1 (sections of N and F Streets), prepared by SIA “BM-projekts”, and the construction design “Construction of District Heating Networks in the Territory of the Former Liepājas metalurgs Plant, Stage 2 (Sections of N, F and C Streets)”, Stage 2.1 (sections of N and F Streets), prepared by SIA “Liepājas enerģija” (Annex 10 to the tender regulations), hereinafter referred to as the Project Technical Documentation.</p><p>Project No. 3.1.1.3.i.0/1/23/A/CFLA/004 “Development of the Liepāja Industrial Park Territory, Stage 1” is implemented under Investment 3.1.1.3.i “Investments in Public Business Infrastructure for the Development of Industrial Parks and Territories in the Regions”, within Reform and Investment Area 3.1 “Regional Policy” of the European Union Recovery and Resilience Facility Plan.</p><p><strong>CPV codes:</strong></p><ul><li>45233120-6 — Road construction works.</li><li>45231000-5 — Construction work for pipelines, communication and power lines.</li><li>44163121-4 — Heating pipelines.</li><li>34928400-2 — Urban infrastructure.</li><li>34993000-4 — Road lights.</li></ul><p><strong>Contract performance period and location:</strong> The contractor must complete the works within <strong>250 (two hundred and fifty) days</strong> after the construction site is handed over to the contractor for commencement of works by a handover and acceptance certificate. The works will be carried out on N and F Streets in the Liepāja Industrial Park.</p><p><strong>Procurement procedure:</strong> The procedure is conducted in accordance with the Public Procurement Law and takes the form of an open tender. The grounds for awarding a single procurement contract without dividing the procurement into lots are: the same group of potential tenderers, one construction site, and one period of construction works at the site.</p><p>Tenders will be opened in the EIS e-tender subsystem on <strong>16 November 2023 at 15:00</strong>.</p><p>Direct and unrestricted electronic access to the tender regulations and annexes is provided through the contracting authority's buyer profile in the Electronic Procurement System: <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>.</p></div>
