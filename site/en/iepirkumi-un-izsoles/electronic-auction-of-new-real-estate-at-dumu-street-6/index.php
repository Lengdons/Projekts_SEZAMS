<h1 class="article-title">Electronic Ascending-Bid Auction of Newly Formed Real Estate at Dūmu Street 6</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>The Liepāja Special Economic Zone Authority, unified registration No. LV90000329402, is holding an electronic ascending-bid auction for newly formed real estate at <strong>Dūmu Street 6, Liepāja</strong>, comprising a building with cadastral designation 17000220059068 and a land plot with cadastral designation 17000220351, with a total land area of <strong>46,766 m²</strong>.</p><p><strong>Starting price:</strong> EUR 480,000.00 (excluding any applicable VAT); <strong>bid increment:</strong> EUR 4,800.00; <strong>auction security deposit:</strong> EUR 48,000.00.</p><p>The purchase price shall be paid as follows:</p><ul><li>Within 10 working days after the preliminary agreement enters into force, the purchaser shall pay an advance of 30% of the purchase price.</li><li>The remainder shall be paid within two weeks after the purchase agreement is signed.</li></ul><p>The auction starts on <strong>4 August 2026 at 13:00</strong> and ends on <strong>3 September 2026 at 13:00</strong>.</p><p>Participants may register from <strong>4 August 2026 at 13:00</strong> until <strong>24 August 2026 at 23:59</strong> at the electronic auction website <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>To participate, a person must pay the security deposit of 10% of the starting price, i.e. EUR 48,000.00, before the registration deadline into the account of the Liepāja Special Economic Zone Authority, registration No. LV90000329402, AS “SEB banka”, account No. <strong>LV42UNLA0012000609480</strong>, with the payment reference “Security deposit for the auction of real estate at Dūmu Street 6, Liepāja”.</p><p>The auction is held electronically at <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>. Enquiries: telephone 29294267, email <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
