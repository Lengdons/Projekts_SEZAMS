<h1 class="article-title">Port Services in the Port of Liepaja Become More Accessible</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>The Liepaja SEZ Authority, in cooperation with the Freeport of Riga Authority and the Freeport of Ventspils Authority, has completed the most ambitious Latvian port cooperation project to date in the field of digitalization.</p><p>The newly developed Port and Multimodal Logistics Services Platform brings together information on vessel visits, berths, port services, permits, passes, contracts and payments in one place. It also enables users to track vessel movements in real time and use digital maps containing port infrastructure data.</p><p>For customers and services at the Port of Liepaja, this means:</p><ul><li>faster exchange of information and data;</li><li>fewer manual tasks and less duplicate data entry;</li><li>more convenient communication and process coordination.</li></ul><p>The platform is integrated with the State Joint Stock Company “Latvian Railways”, SKLOIS and other national and port information systems, laying the foundation for a unified digital ecosystem for Latvian ports.</p><p>The project was implemented from December 2024 to August 2026. It was funded with EUR 3.24 million from the European Union Recovery Fund.</p></div>
