<h1 class="article-title">Open Tender: Demolition of Berth No. 1 at the Port of Liepāja (LSEZ 2021/67/K)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Subject of the procurement: demolition works at Berth No. 1 at the Port of Liepāja, in accordance with the procurement documents and applicable regulatory requirements.</p><p>The construction works will be carried out and financed under a project implemented within Specific Objective 6.1.1, “Increase the safety of major ports and improve the mobility of the transport network”, of the Operational Programme “Growth and Employment”.</p><p>Interested suppliers may examine and obtain the procurement documents electronically, free of charge, on the <a href="http://www.liepaja-sez.lv/lv/parvalde/iepirkumi">Liepāja SEZ Authority website</a> and through the <a href="https://www.eis.gov.lv/">EIS</a>. Printed procurement documents may also be examined free of charge at the Liepāja Special Economic Zone Authority, in the Procurement Specialist's office (ground floor), Fēniksa Street 4, Liepāja, until 2 July 2021 at 10:00, on working days from 08:00 to 12:00 and from 13:00 to 16:30 (Fridays until 16:00), by arranging the visit in advance with the contracting authority's contact person.</p></div>
