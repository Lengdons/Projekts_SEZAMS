<div class="col-12 col-md-3 column-content">
<img alt="icon" class="icon" src="../../img/block/columns/168/1725616669_kruizu-kugjis.svg"/>
<p>Despite that the Port of Liepaja has for many years been mainly recognized as a successful regional cargo transshipment center, the cruising interest has been recently growing, as well. Previously, thousands of tourists each year were arriving to visit the city by sea on board the Ro-Ro ferry on the route Liepaja – Travemunde (Germany), however, we are now looking further to welcome the city guests on board the cruise ships, as well!</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icon" class="icon" src="../../img/block/columns/169/1725616901_enkurs.svg"/>
<p>Today, the City of Liepaja may call itself a truly new cruise destination. The fun of a cruise is equal parts what you do on board and what you do on shore. No cruising experience is complete without a shore excursion – thus, on arrival, the cruise ships are moored alongside the berths in a direct vicinity of the port entrance, from where the tourists can get to the city center in a few minutes by bus or by car.</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icon" class="icon" src="../../img/block/columns/170/1725616778_divas-majinas.svg"/>
<p>The City of Liepaja offers guided walking or bus tours that allow tourists to experience the local history, culture, cuisine, shopping, to enjoy its landscaped parks, historical and contemporary architecture, the Blue Flag beach and much more. </p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icon" class="icon" src="../../img/block/columns/171/1725617099_baltijas-karte.svg"/>
<p>The city guests, preferring the military heritage tourism, are welcome to visit the largest historical military territory in the Baltics – part of the city area, named Karosta, which was built before World War I for the needs of the army. It is unique in the historical and architectural context not only in Latvia, but also the world. </p>
</div>
