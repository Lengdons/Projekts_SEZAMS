<h1 class="article-title">Diversity of Cargo Types Ensures Stable Operations at the Port of Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Stevedoring companies at the Port of Liepāja handled 2.54 million tonnes of cargo in the first four months of 2024, comparable to the same period in 2023. The port’s stability rests on its diversity of cargo types and traditional emphasis on locally sourced cargo. During these four months, 479 ships were served, 24,691 passengers travelled through the port, 31,945 powered and unpowered ro-ro units were transported by ferry, and 1,967 container units were handled.</p><p>Locally sourced goods account for more than 50% of cargo at the Port of Liepāja. Grain and grain products, timber, wood chips, cement and ferry cargo supplied by local manufacturers are joined in spring by peat extracted in Latvia’s Kurzeme region. The port stevedoring company Mols L has successfully cooperated for four years with SIA BaltBio, whose main business is peat extraction and transport.</p><p>Peat is exported from the Port of Liepāja to several European countries, including Germany and Denmark. On average, four or five vessels, each carrying just under 3,000 tonnes, are loaded every spring. According to SIA BaltBio board member Matīss Kozlovs, that is enough peat for European countries to grow tomatoes and cucumbers. “It is advantageous for our company to export peat from the port closest to the extraction site, and Mols L works quickly and efficiently.” Mols L has operated steadily in the port’s Winter Harbour for more than 30 years, handling mainly various locally sourced cargoes.</p><p>Dry bulk cargo remains the largest group at the Port of Liepāja, accounting for 67% of all shipments. General cargo is the second largest group, representing 30%, or 759.2 thousand tonnes, during the first four months of the year. The largest portion of general cargo comes from the Liepāja–Travemünde ferry route. This year the route transported 608,545.25 tonnes, or 31,945 units, an increase of 15.63%. Āris Ozoliņš, Chairman of the Board of Liepāja SEZ company Terrabalt, puts it simply: “We have to work! We have diversified our risks and cargo flows. The cargo is there.”</p><p>Liquid bulk is the smallest cargo group, accounting for just 3% of all shipments, or 81.2 thousand tonnes.</p></div>
