<h1 class="article-title">Port of Liepāja Actively Handles Grain Harvested by Latvian Farmers in September</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>In September this year, the Port of Liepāja actively handled grain harvested by Latvian farmers. Agricultural products accounted for more than half of all cargo handled (329.6 thousand tonnes), including soy imports from Argentina. In total, 635.8 thousand tonnes of cargo were handled at the port in September, 27.97% more than in September 2024. As an active part of the Liepāja Special Economic Zone, the port continues to attract local cargo and plays an important logistical role in exporting manufactured products and facilitating trade. Dry bulk shipments included construction materials (75.9 thousand tonnes), wood chips (20.6 thousand tonnes) and wood pellets (17.2 thousand tonnes). General cargo was dominated by ro-ro shipments (139 thousand tonnes), supported by the regular ferry service between Liepāja and Travemünde in Germany. In September, the port received and served 99 ships, while passenger traffic amounted to 8,232 people. Since 2018, the Port of Liepāja has maintained stable annual cargo turnover of 7–7.5 million tonnes and adapted to changes in the transport sector by supplementing traditional cargo operations with manufacturing and higher-value-added products. September also saw the successful completion of the assembly of two port cargo-unloading units, which were shipped to Canada on a specialised vessel. During the first nine months of this year, total cargo turnover amounted to 5.1 million tonnes, 139.9 thousand tonnes or 2.7% less than during the corresponding period last year. The grain season started later than usual due to rain, while demand for energy-related cargo such as wood chips remains relatively low. During the period, the port handled 86,615 ro-ro units, served 871 vessels and welcomed 81,798 passengers.</p></div>
