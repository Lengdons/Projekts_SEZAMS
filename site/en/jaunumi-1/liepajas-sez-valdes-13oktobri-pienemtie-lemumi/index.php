<h1 class="article-title">Decisions Adopted by the Liepāja SEZ Board on 13 October</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>On 13 October 2023, the Liepāja SEZ Board held its regular meeting, reviewing and supporting three investment projects by Liepāja SEZ companies totalling EUR 446,531.76 and considering several issues relating to property, leases, rights of first refusal and disposals.</p><p> </p><p>Long-term land lease agreement</p><p>The Liepāja SEZ Board decided to conclude a 20-year land lease agreement with Latvijas Mobilais Telefons Ltd for the property at 18 Atmodas Boulevard in Liepāja. The 600 m² plot will be used to operate and maintain a mobile telecommunications base station with a radio tower and conduct associated commercial activities.</p><p> </p><p>Rights of first refusal</p><p>The Liepāja SEZ Board decided not to exercise its right of first refusal for the property at 2 Zviedru Street in Liepāja, situated within the SEZ, because it is not needed for the Authority’s functions.</p><p> </p><p>Disposal of real estate</p><p>The Board agreed to the disposal of the plot at 1A Cukura Street in Liepāja because it is not needed for the Authority’s functions.</p><p> </p><p>Implementation of investment projects</p><p>The Board reviewed and supported three investment projects by Liepāja SEZ companies totalling EUR 446,531.76.</p><ul><li>MetARS plans to purchase welding equipment and a welding fume filtration system for EUR 8,761.76. The project is scheduled for 20 October 2023 to 31 December 2024. According to its business declaration, MetARS is a small enterprise and may receive the maximum permitted aid intensity of 60% for these investments.</li><li>LIEPAJA BULK TERMINAL LTD continues investing in measures to prevent dust from cargo handling from spreading beyond the terminal. Between 20 October 2023 and 31 August 2025, the company plans a ship-loader aspiration system to collect dust, at a total cost of EUR 349,770. LIEPAJA BULK TERMINAL LTD is a large enterprise and is eligible for a maximum aid intensity of 40%.</li><li>The Board also supported an investment project by Ekers Stividors LP Ltd to purchase and install a bulk handling grab for fine-fraction cargo. The project is planned for 18 October to 1 December 2023, at a total cost of EUR 38,000. According to its declaration, Ekers Stividors LP is a medium-sized enterprise and the maximum permitted aid intensity is 50%.</li></ul><p> </p><p>By this point in 2023, the Liepāja SEZ Authority had concluded 11 investment agreements with SEZ companies, with total planned investment of EUR 4,835,371.52.</p></div>
