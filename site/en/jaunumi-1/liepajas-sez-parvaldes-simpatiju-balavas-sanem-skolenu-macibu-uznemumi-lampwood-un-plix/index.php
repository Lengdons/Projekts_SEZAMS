<h1 class="article-title">LAMPwood and PLIX Receive the Liepāja SEZ Authority’s Special Recognition Awards</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>For the second year in a row, the Liepāja SEZ Authority has participated in judging the national final of Latvia’s best student-run companies, awarding its special recognition prize in both the lower-secondary and upper-secondary categories.</p><p>This year, the lower-secondary award went to LAMPwood for creating a sustainable and distinctive interior product — a lamp. The judges also praised its aesthetically designed stand, engaging logo, confident presentation, cohesive team, growth-oriented approach and products reflecting the spirit of Liepāja. LAMPwood is a student company from Liepāja State Gymnasium, founded by Raivo Egmanis and Emīlija Betrama.</p><p>The upper-secondary award went to PLIX for developing and manufacturing a compact plastic recycling machine — a sustainable solution supporting the circular economy. The team demonstrated innovative improvements to the equipment, mastered the necessary production software and adopted a knowledge-, experimentation- and development-based approach. PLIX is a student company from Riga State Technical School, whose members are Marks Žihars, Laura Krasņikova and Tomass Lībenzobs.</p><p>Student-run companies offer young people the chance to learn their first business skills while still at school, taking a product from idea to sale. Students from Liepāja have always been active and achieved strong results. These companies encourage and promote entrepreneurship through practical learning, sparking curiosity, building confidence and motivating students to pursue new goals.</p><p>From 27 to 28 April, Liepāja hosts “Gen-E” Young Entrepreneurs Days, the national final for Latvia’s student-run companies, organised by the Investment and Development Agency of Latvia (LIAA) and Junior Achievement Latvia (JA Latvia). Over two days, 31 of the country’s best teams will present their products and business ideas, competing for the chance to represent Latvia at the European final in Riga this year.</p><p>Over the two days, teams from 31 of Latvia’s best student-run companies will present their products and business ideas, competing for the chance to represent Latvia at this year’s European final in Riga.</p><p>Ten lower-secondary and 21 upper-secondary student-run companies have qualified, having demonstrated outstanding product development, entrepreneurial thinking and presentation skills throughout the academic year.</p></div>
