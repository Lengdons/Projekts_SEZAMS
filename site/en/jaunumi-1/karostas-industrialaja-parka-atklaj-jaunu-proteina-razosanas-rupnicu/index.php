<h1 class="article-title">New Protein Production Plant Opens in Karosta Industrial Park</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>On 19 June, the Golden Field Factory LV protein production facility in Karosta Industrial Park was officially opened. The plant marks the return of agricultural product processing to Liepāja and the arrival of the first investments from the United Arab Emirates and the United States.</p><p>The new plant provides more than 50 jobs and represents an investment of EUR 16 million. It plans to process locally sourced and imported peas and beans into protein and starch for use in the food industry. All output is intended for export.</p><p>“This is already the fourth factory in Karosta Industrial Park and the twenty-fourth built in Liepāja over the last seven years, but it is certainly a special one. First, it will process agricultural products — beans and peas — into high-value-added protein. Second, it is the first facility to successfully preserve and integrate historic Karosta buildings,” says Liepāja SEZ Manager Uldis Hmieļevskis.</p><p>The building at 11 Zemgales Street was commissioned by the Liepāja municipal Building Authority on 29 November 2022 as the office and production building of SIA EB Liepāja in Karosta Industrial Park, with a total floor area of 4,802.4 m². SIA EB Liepāja later leased the building to Golden Field Factory LV SIA.</p><p>Design work began in March 2020 and construction in August 2021. This is the fourth factory in Karosta Industrial Park, but the first to restore and incorporate historic Karosta architecture. Architect Gundars Vīksna integrated the historic buildings into the new plant’s design, implemented by contractor SIA UPTK. “When developing the idea of Karosta Industrial Park, the municipality and the Liepāja SEZ Authority agreed that Zemgales Street’s historic appearance should be preserved, and this was later incorporated into the development requirements. As a result, one of the buildings on Zemgales Street underwent a complete revival, while part of another building’s facade was preserved and linked to the spacious production premises. The surrounding area was also landscaped and parking was constructed.”</p><p>Background:</p><p>The idea for Karosta Industrial Park emerged in 1999 to encourage job creation, increase tax revenue for the city and state, and provide additional resources for education, culture, sport and other projects. Building new factories in Karosta was not feasible or attractive to investors until 2015, when the municipality and Liepāja SEZ Authority prepared almost 20 hectares of land for business development.</p></div>
