<h1 class="article-title">AE Partner continues to grow and strengthen production capacity</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>AE Partner Liepāja Special Economic Zone (LSEZ) SIA, a manufacturer of high-quality electrical control and monitoring equipment, ended 2025 with steady growth in both turnover and profit.</p><p>In 2025, AE Partner LSEZ SIA recorded net turnover of EUR 75.6 million, up 2% year on year. It is important to note that the 2024 financial results benefited from extraordinary income related to the restructuring of the AE Partner Group, whereas the 2025 figures reflect normal business performance without such one-off items. The company's profit rose to EUR 3.6 million in 2025.</p><p>Investment in expanding production in Liepāja made a significant contribution to the development of the company, which operates in Latvia and Denmark.</p><p>‘By expanding our production and office facilities by a total of 5,000 square metres, we achieved an immediate positive impact while also providing the capacity needed for further growth. We look to the future with confidence, knowing that decisions based on our strategy create a solid foundation for continued development,’ comments Morten Bitsch Janik, Chief Business Development, Finance and IT Officer of AE Partner LSEZ SIA.</p><p>Profit in 2025 was also supported by dividends received from the subsidiary AE Partner DK A/S and targeted improvements in working capital management, including lower inventory levels and greater operational efficiency.</p><p>With its focus on expanding and diversifying its customer portfolio, making full use of production capacity, increasing efficiency and investing in infrastructure and digital tools, AE Partner expects stable, sustainable growth in 2026 as well.</p><p> </p><p>About AE Partner Liepāja Special Economic Zone SIA</p><p>AE Partner Liepāja Special Economic Zone SIA is a company based in Latvia and Denmark with more than 20 years of experience developing, manufacturing and servicing automation system solutions for industries including manufacturing, logistics, shipping and renewable energy.</p><p>AE Partner’s main production facility is located in Liepāja. With more than 500 employees, the company is one of the region’s largest employers.</p><p>Some 98% of the products and services supplied by AE Partner LSEZ SIA are exported to more than 25 countries across all continents, with Europe as its main export market.</p><p>AE Partner’s operations are guided by its core values: honesty, openness, teamwork, commitment and mutual respect, reflected in its relationships with employees, customers and business partners.</p></div>
