<h1 class="article-title">Van Oord Signs Agreement to Build Offshore Wind Support Base and Heavy Cargo Terminal in Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>To promote offshore wind energy development in the Baltic Sea, leading industry company Van Oord Dredging and Marine Contractors B.V. (Van Oord) plans to establish a world-class offshore wind farm support base and heavy cargo terminal at the Port of Liepāja. This is provided for in a land reservation agreement concluded between Van Oord and the Liepāja Special Economic Zone (Liepāja SEZ) Authority.</p><p>During the two-year reservation period, Van Oord will carry out preparations including research, business planning, design and the recruitment of industry partners. The Dutch company plans to begin building the offshore wind support base in the outer harbour of the Port of Liepāja in 2026, with commissioning expected by mid-2027.</p><p>The new terminal will address the shortage of port infrastructure capacity needed to build wind farms in the Baltic Sea. It will also handle other oversized cargo and support manufacturing. A 55-hectare area will be created through land reclamation, providing new multifunctional cargo-handling facilities and space for manufacturing and assembly operations. Van Oord project manager Mark Bot said: “Van Oord aspires to be an initiator in accelerating the energy transition. This project is a strong example of how Van Oord can fulfil that role and bring positive change for future generations.”</p><p>By becoming a developer of port infrastructure associated with offshore wind projects in the Baltic Sea, Van Oord actively supports the transition to renewable energy. Its commitment to building this much-needed infrastructure reflects the company’s aim of creating a better world for future generations.</p><p>Liepāja SEZ CEO Uldis Hmieļevskis welcomed the decision of Van Oord, one of the offshore wind industry’s major players, to choose Liepāja as a centre for Baltic Sea wind energy. “The offshore wind support base at the Port of Liepāja will promote economic development and attract substantial foreign investment focused on a sustainable economy and green energy production. This is only one of Liepāja’s projects that will strengthen energy independence in Latvia and Europe.”</p><p>Under the signed land reservation agreement, Van Oord will act as developer and investor, designing and building the offshore wind support base and heavy cargo terminal in the outer harbour of the Port of Liepāja. The project will occupy 55 hectares of the total 560-hectare area. The outer harbour is a unique part of the port, protected by breakwaters, with three port entrances and extensive opportunities for offshore wind and green energy projects.</p></div>
