<h1 class="article-title">O. Kalpaks Bridge to Close for Three Days for an International Film Production</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>From 16 to 24 October, Liepāja will briefly become a filming location for an international production. The city will host filming of an adaptation of “The Girl with the Dragon Tattoo”, from the internationally popular Millennium book series, produced by Left Bank Pictures, known for “The Crown” and “Dept Q”. Oskars Kalpaks Bridge has been selected as one of the series’ key filming locations. The bridge will close to pedestrians and road traffic for three days, and shipping traffic will also be restricted.</p><p>Filming on O. Kalpaks Bridge will take place from 19 to 21 October. Drivers, cyclists and pedestrians are asked to plan their journeys to and from Karosta in advance and allow additional travel time. Working with the municipality, special buses will run along a diversion route. Details of this service will be posted at both ends of the bridge. Regular public transport will also be diverted.</p><p>Closure of O. Kalpaks Bridge to pedestrians and vehicles:</p><ul><li>From 08:00 on 19 October 2026 until 22:00 on 21 October 2026.</li></ul><p>Access to the square near O. Kalpaks Bridge and to the access road and parking area at the southern breakwater of Karosta Canal will also be restricted during filming.</p><p>Vessel traffic in Karosta Canal will be restricted during filming. The Liepāja SEZ Authority thanks the stevedoring companies at the Port of Liepāja for supporting this major film project and rescheduling their operations where possible. Five port terminals operate actively in Karosta Canal — Baltic Transhipment Center, Schwenk, DG Termināls, Norsaf and Baltex Bulk — as does LZK, which continues ship repair work at the Tosmare docks.</p><p>The selection of Oskars Kalpaks Bridge as a central filming location will bring Liepāja significant international attention. The production is expected to reach millions of viewers in different countries, giving the city a powerful platform for raising its profile.</p><p>Successfully hosting a production of this scale will reinforce Liepāja’s reputation as an internationally connected, professional port city capable of managing complex projects. “It increases the chances of attracting future film, arts and creative-industry projects, bringing long-term economic and reputational benefits to the city and the wider region.”</p></div>
