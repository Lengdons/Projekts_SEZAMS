<h1 class="article-title">Feasibility Assessment of the Karosta Canal Contaminated Sediment Disposal Site Completed</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>From 1 August to 31 October 2024, the Liepāja Special Economic Zone Authority implemented the Norwegian Financial Mechanism 2014–2021 programme “Climate Change Mitigation, Adaptation and Environment” Bilateral Cooperation Fund initiative entitled “Preparation of a Technical and Economic Assessment for Development of the Historic Contaminated Sediment Disposal Site in the Karosta Canal at the Port of Liepāja” (hereinafter the Initiative).</p><p>The Karosta Canal and its historic seabed pollution form a unique contaminated site harming the Baltic Sea environment, not only in Latvia but across the Baltic Sea region. Since 1994, the Liepāja SEZ Authority has undertaken targeted work to restore the canal. Major remediation campaigns in 2015 and 2023 removed more than 200,000 m³ of contaminated sediment, which was placed in the historic contaminated sediment disposal site in the Karosta Canal at the Port of Liepāja. This site is a specially enclosed section of the canal waters designed for safe containment of the deposited sediment.</p><p>Despite numerous studies of the environmental situation and completed remediation work, the further development of the sediment disposal site had not previously been studied, including how to limit the spread of pollutants, consider development alternatives or evaluate management scenarios. Under the Initiative, the Liepāja SEZ Authority therefore worked with Norwegian partners — the Norwegian Institute for Water Research (NIVA) and Norwegian Geotechnical Institute (NGI) — which have extensive expertise in remediation of historic marine pollution and in establishing and managing contaminated sediment disposal facilities. Together they developed alternatives for the site and identified the most promising management scenarios.</p><p>Based on the preliminary assessment, NGI and NIVA recommended removing the remaining Karosta Canal seabed areas with the highest pollutant concentrations. Removing an additional 100,000 m³ of historically contaminated sediment in the final remediation stage would take up to 196 tonnes of hazardous chemicals out of the canal environment.</p><p>When evaluating alternatives to reduce greenhouse gas and hazardous-substance emissions from the deposited sediment, the best-performing option was to install an additional 60-centimetre-thick protective layer isolating the contaminated material.</p><p> </p><p>Working together for a green Europe!</p><p>The project is funded under the Norwegian Financial Mechanism 2014–2021 programme “Climate Change Mitigation, Adaptation and Environment”. Total project costs are EUR 264,500.00, all of which is financed by the Norwegian Financial Mechanism.</p></div>
