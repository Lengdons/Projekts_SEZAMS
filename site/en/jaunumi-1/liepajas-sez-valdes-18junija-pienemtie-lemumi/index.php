<h1 class="article-title">Decisions Adopted by the Liepāja SEZ Board on 18 June</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>On 18 June 2024, the Liepāja Special Economic Zone (Liepāja SEZ) Board held its regular meeting. It considered eight agenda items, adopted six decisions and heard information reports on Liepāja SEZ operations and planned development projects.</p><p>Investment agreement. The Board considered an application by JM Properties, a Liepāja SEZ company, for the project “Construction of a New Production Building at 11 Virssardzes Street, Liepāja” and supported its implementation from 19 June 2024 to 31 December 2025, for a total of EUR 6.5 million. JM Properties is a property developer, and the new facility will support the expansion of Jensen Metal’s production.</p><p>Amendments to property agreements. The Board decided to extend until 31 January 2025 the agreement with BaltEx Bulk concerning reservation of the land plot at 7 Pulvera Street, Liepāja, in the Liepāja SEZ. The purpose is to prepare a minimum-composition construction design for the “Construction of a Cargo Area at 5 Pulvera Street, Liepāja”. The Board also permitted KB Tosmare to sublet approximately 400 m² of land at 42/44 Ģenerāļa Baloža Street to Tolmets Kurzeme, subject to the lease concluded between the Liepāja SEZ Authority and KB Tosmare on 3 November 2021.</p><p>The Board also consented to the mortgaging of the building rights granted to ICS Property under its 29 April 2019 agreement with the Liepāja SEZ Authority, as security for obligations, in accordance with that agreement.</p><p>Demolition of a building. To continue developing the Liepāja Industrial Park, create new industrial development areas and begin infrastructure construction on the former Liepājas metalurgs site, integrating the area into Liepāja’s urban structure and returning it to economic use through environmentally friendly and sustainable industrial development in line with the local plan and Development Plan, the Board approved the demolition of a minor structure at 94A Brīvības Street, Liepāja.</p><p>Free-zone status. The Board supported the request by Norplast Piemare, a Liepāja SEZ joint-stock company, to grant free-zone status to its territory at 11/13 Kaiju Street, Liepāja, and to revoke free customs zone certificate No. 13 for Port of Liepāja Berth 64/65 and certificate No. 15 for Berths 73/74/75/76.</p></div>
