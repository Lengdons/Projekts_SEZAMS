<h1 class="article-title">Liepāja SEZ Authority Announces Tender for Reconstruction of Berth 46 at the Port of Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>To support the development of freight and passenger ferry routes serving the Port of Liepāja and ensure uninterrupted flows of goods, the Liepāja SEZ Authority is continuing its plans to reconstruct Berth 46. Regular ferry services are strategically important not only to Liepāja and Latvia but also to the economy and military mobility of the European Union. Last year, the berth handled 1.8 million tonnes of cargo valued at approximately EUR 4 billion.</p><p>The reconstruction will allow two cargo vessels or cargo-passenger ferries, each up to 240 metres long and with a draught of up to 11 metres, to be safely served simultaneously. Work will include installing additional mooring dolphins, reconstructing berth structures and increasing water depth from 10.5 to 12.0 metres. To accommodate newer RO-RO/RO-PAX ferries, the berth will also require shore-side power supply systems and local wastewater reception facilities. Completion of the reconstruction of Berth 46 is planned by 31 December 2027.</p><p>Berth 46 is situated in the Freeport area of the Port of Liepāja, in the central section of the eastern shoreline. It is 51.5 metres wide, 204.5 metres long on the northern side and 181.0 metres long on the southern side. The berth was built between 1972 and 1975 to accommodate and service Soviet naval vessels and submarines. Today, it serves the regular Liepāja–Travemünde ferry route and is subjected to considerable stress as powerful ship engines are used during berthing and departure. Reconstruction is necessary because persistent construction defects and general deterioration, despite repair work, have irreversibly affected the berth’s technical condition and operational safety.</p><p> </p></div>
