<div class="col-12 col-md-4 description">
<p>During the first eight months of 2023, the Port of Liepaja handled 4.6 million tonnes of various cargoes. Bulk cargo remained the largest category, accounting for 68% of the total, including grain and grain products at 44%, or 2.01 million tonnes. Ro-ro cargo turnover also remained stable with positive momentum. This reflects demand for goods and coordinated cooperation between businesses and the Liepaja SEZ Authority in attracting new logistics routes and cargo, including local shipments, alongside investment in infrastructure.</p>
