<h2>Construction of the Access Road to Berth 92 at the Port of Liepaja Nears Completion</h2>
<span class="mb-3">20.08.2026.</span>
</div>
<a aria-label="Read more" class="mb-3 news_link d-none d-md-block" href="/site/en/jaunumi-1/noslegumam-tuvojas-piebraucama-cela-izbuve-uz-liepajas-ostas-92-piestatni/index.php">Read more</a>
</div>
<div class="col-12 col-md-4 description">
<p>The Liepaja SEZ Authority continues to improve infrastructure for fishermen by constructing an access road to Berth 92 at the port. The project is funded by the European Maritime, Fisheries and Aquaculture Fund under the 2021–2027 programme for fisheries development. It includes a publicly accessible 364-metre road, smart lighting and a stormwater drainage system. Following the procurement procedure, the works are being carried out by SIA “CTB”, whose bid of EUR 303,617.32 was the most economically advantageous. Construction is scheduled for completion by the end of August.</p>
