<h1 class="article-title">Celebrate Sea Festival on the Water with a Rowing Competition and a Ship and Boat Parade</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>For the eighth time, the Liepāja SEZ Authority invites everyone to celebrate Sea Festival with the event “Across the City, from Lake to Sea”, taking place on 10 July in the Trade Canal near the marina. The event will open with the Seafarers’ Rowing Competition at 16:00. Participants will gather for the parade from 19:00 to 20:00, and at 20:00 the Port of Liepāja tugboats will open the parade with the sound of their horns. The promenade on the Jaunliepāja side will also be open to spectators from 16:00.</p><p>The “Across the City, from Lake to Sea” event will begin with the Seafarers’ Rowing Competition. There is something new this year: to encourage those who do not consider themselves seafarers and are not familiar with rowing, a hobby category will offer a shorter, easier course where participants can experience teamwork. Experienced rowers are, of course, equally welcome. Register here: <a href="https://ej.uz/pieteikumaanketajurasbrauceji">https://ej.uz/pieteikumaanketajurasbrauceji</a></p><p> </p><p>PROGRAMME:</p><p>16:00–19:00 SEAFARERS’ ROWING COMPETITION</p><p>19:00–20:00 PREPARATIONS FOR THE PARADE</p><p>20:00–21:00 SHIP AND BOAT PARADE</p><p> </p><p>FOR SPECTATORS</p><p>GATHERING POINT – Vecā ostmala and Jaunā ostmala waterfronts opposite the marina.</p><p> </p><p>FOR PARTICIPANTS</p><p>SEAFARERS’ ROWING COMPETITION</p><ul><li>Find like-minded people, register, practise and take part.</li><li>Each team must have seven members (six rowers and one person keeping the rowing rhythm or calling commands).</li><li>Registration for the competition and training sessions: <a href="https://ej.uz/pieteikumaanketajurasbrauceji">https://ej.uz/pieteikumaanketajurasbrauceji</a></li></ul><p>SHIP AND BOAT PARADE</p><p>To take part in the parade, register yourself, your team and your watercraft by 9 July.</p><ul><li>Registration: <a href="https://forms.isdev.lv/kugu-un-laivu-parade">https://forms.isdev.lv/kugu-un-laivu-parade</a></li><li>Parade assembly points:</li></ul><p>– seagoing boats by the Customs House in the Trade Canal;</p><p>– lake boats in the canal between the bridges.</p><p> </p><p>The Liepāja SEZ Authority invites everyone to take an active part in the rowing competition and the ship and boat parade, or to come and watch. This year, the Jaunā ostmala waterfront will once again open to spectators for the event. It is planned to become a public area in the future, similar to Vecā ostmala, where port operations, ships and business activities successfully coexist with residents and tourists.</p></div>
