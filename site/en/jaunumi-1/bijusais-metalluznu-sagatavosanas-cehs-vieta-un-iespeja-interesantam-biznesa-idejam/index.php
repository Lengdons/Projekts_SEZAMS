<h1 class="article-title">Former Scrap Metal Preparation Workshop Offers Opportunities for New Business Ideas</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>As work continues on the Liepāja Industrial Park at the former Liepājas metalurgs plant, the Liepāja Special Economic Zone (Liepāja SEZ) Authority has announced an auction for the former scrap metal preparation workshop at 6 Dūmu Street, Liepāja. The property being sold includes a building with an area of 25,200 m² and a land plot of approximately 46,800 m². Bidders can register on the electronic auction platform until 24 August of this year; the auction will close on 3 September at 13:00.</p><p>The Liepāja SEZ Authority initially consolidated the properties on the site of the former Liepājas metalurgs plant, worked with the municipality to develop a local spatial plan and began constructing streets and utilities. Property auctions are the next step in involving businesses in the regeneration and transformation of the industrial area, offering the opportunity to acquire existing industrial buildings and renovate them to meet the needs of a modern green-economy business environment.</p><p>The former Liepājas metalurgs industrial area is gradually being reintegrated into the city, making it accessible to the public and attractive to investors.</p><p>The Liepāja Industrial Park is being developed by the Liepāja SEZ Authority and the Liepāja City Municipality on the site of the former Liepājas metalurgs plant, between Brīvības Street, Meldru Street, Ezermalas Street, Parka Street and Zemnieku Street in Liepāja. It borders Lake Liepāja, a specially protected NATURA 2000 nature area. Under the approved development strategy, the aim is to attract more than EUR 275 million in private investment and create at least 1,500 new jobs.</p></div>
