<h1 class="article-title">Liepāja SEZ Authority Invites Visitors to the “Made in Liepāja” Exhibition</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>From 31 January to 1 February, the “Made in Liepāja” exhibition will take place at the Liepāja Olympic Centre. More than 180 companies will present the city’s diverse business environment at their stands. The exhibition will also include a conference where experts will discuss the economic development challenges facing Latvia and Liepāja. Admission is free. School and university students are especially encouraged to attend and explore future job opportunities in Liepāja.</p><p>At 11:00, Liepāja Mayor Gunārs Ansiņš and Minister of Economics Viktors Valainis will open the “Made in Liepāja” exhibition and conference, followed by presentations in the Rose Hall:</p><p>• At 11:10, University of Latvia professor and chair of the Latvian Strategy and Economic Solutions Institute (LaSER) Daunis Auers will discuss development scenarios for Latvia and regional economies;</p><p>• At 11:40, entrepreneur and architect Uldis Pīlēns will share his experience and an inspirational story.</p><p>From 13:00 to 15:15, panel discussions in the Tango Hall will explore Liepāja’s economy and future opportunities: “The Status Quo of Liepāja’s Economy — From Post-Soviet Decline to the Largest Regional Manufacturing Centre” and “What Will Liepāja’s Economy Look Like in 2040?”. Two seminars will follow: “Digitalisation in Business: Experiences and Opportunities” at 14:30 and “Innovative Thinking in Business”, a workshop for entrepreneurs led by innovation and idea management lecturer Dr Elīna Miķelsone, at 15:15.</p><p>At the Liepāja SEZ Authority stand, visitors will be able to learn about the city’s industrial parks, companies operating there and the challenges of developing Liepāja’s industries of the future.</p><p>The first streets in Liepāja Industrial Park, on the site of the former Liepājas Metalurgs factory, will be constructed this year. Visitors will be invited to contribute ideas and suggestions for naming the new streets.</p><p>The Liepāja SEZ Authority particularly encourages young people to visit the exhibition and help shape the business environment. Together with the Education Department and the city’s general education schools, it is organising a competition inviting young people to propose ideas for the development of Liepāja’s economy. Participants must choose one of the proposed topics, prepare a presentation of their ideas using information gained at the exhibition (as a document, presentation or video), and email it to komunikacija@lsez.lv with the subject “Opinion Workshop”. Prizes will be awarded to the best entries.</p><p>Competition topics:</p><ol><li>Five key things that make a company attractive to employees.</li><li>What skills are needed by employees who are in demand in the labour market?</li><li>Five key characteristics of Liepāja as a high-quality business environment.</li><li>Where does money come from?</li><li>Five risks that could negatively affect business activity.</li></ol></div>
