<h1 class="article-title">Liepāja SEZ Authority Completes the Design of the Reconstruction of Berth No. 46 at the Port of Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>The objective of the project “Ensuring Safe Mooring of Ro-Ro Ferries at the Port of Liepāja” (hereinafter the Project) is to ensure safe mooring of RO-RO ferries at the Port of Liepāja, thereby strengthening TEN-T infrastructure capacity and improving access to domestic and international markets through better maritime transport connections.</p><p>On 20 September 2024, the Liepāja Special Economic Zone Authority and CHR Design Solutions Ltd signed a contract to prepare the construction design for “Reconstruction of Berth No. 46 at the Port of Liepāja”. On 20 August 2025, the Liepāja City Building Authority confirmed that the design conditions of building permit No. BIS-BV-4.2-2025-18 (7/2025), issued on 21 January 2025, had been fulfilled, thus confirming the completion of the design.</p><p>The project involves installing additional mooring dolphins, reconstructing the berth structures and increasing the water depth from 10.5 to 12.0 metres. This will ensure the safe handling of RO-RO/RO-PAX ferries up to 240.0 metres long and with a draught of up to 11.0 metres.</p><p>The total cost of implementing the project is EUR 23,090,050.</p><p>The project “Ensuring Safe Mooring of Ro-Ro Ferries at the Port of Liepāja” (acronym 22-LV-TG-LPXRORO) is partly funded under the CEF2027 programme (topic ID CEF-T-2022-COMPGEN-MARP-WORKS, project No. 101122785). The Connecting Europe Facility contribution covers 30% of the eligible project costs, amounting to EUR 6,927,015.</p></div>
