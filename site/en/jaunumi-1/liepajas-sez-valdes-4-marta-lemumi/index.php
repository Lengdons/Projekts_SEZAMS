<h1 class="article-title">Liepāja SEZ Board Decisions of 4 March</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>On 4 March this year, the Liepāja SEZ Board held its regular meeting and considered matters relating to tugboat services at the Port of Liepāja, an agreement granting building rights in the Liepāja Industrial Park, two real estate reservation agreements and the disposal of real estate.</p><p> </p><p>Tugboat services at the Port of Liepāja</p><p>Tugboat services at the Port of Liepāja will continue to be provided by Towmar Liepājā Ltd. The Liepāja SEZ Board reviewed the documents submitted and decided to conclude an agreement with Towmar Liepājā Ltd for the provision of tugboat services at the port.</p><p>The decision to conclude a tugboat services agreement with Towmar Liepājā Ltd aims to promote competition in the market for such services at the Port of Liepāja by entrusting them to private-sector companies. This directly implements the purpose of Section 18 of the Law on Ports: commercial activities in a port may be carried out under an agreement, subject to the prescribed minimum requirements. In this legal relationship, the Liepāja SEZ Authority acts solely as a public-law supervisory body overseeing compliance with safety and technical requirements and does not itself engage in commercial activity in this market.</p><p> </p><p>Agreement granting building rights</p><p>On 10 November 2025, the Liepāja SEZ Authority and ZET Ltd signed an agreement reserving building rights for a property at 111A Brīvības Street in the Liepāja Industrial Park. Having fulfilled the reservation agreement conditions, the company confirmed its readiness to sign an agreement granting building rights to construct and commission a 5 MW battery energy storage system (BESS) by 29 March 2027.</p><p>Having evaluated the documents, the Liepāja SEZ Board decided to conclude an agreement with ZET Ltd granting building rights for the property at 111A Brīvības Street in the Liepāja Industrial Park until 1 March 2056.</p><p> </p><p>Consent to the disposal of property</p><p>The Liepāja SEZ Board considered the disposal by auction of the property at 13 Sarkanā Street in Liepāja, organised by its owner, the Liepāja City Municipality. Since the property is not required for the Liepāja SEZ Authority’s core functions, the Board agreed to its disposal.</p><p> </p><p>Reservation of building rights for land plots</p><p>The Liepāja SEZ Board considered and decided to conclude two agreements reserving building rights for land plots:</p><ul><li>With VIA-S Properties Ltd, for two years, to begin implementing a modular housing production facility project on approximately 3.3 hectares at the junction of Inženieru and Eksporta Streets in the Liepāja Industrial Park;</li><li>With CIS Liepaja Ltd, for two years, covering two land plots in the Liepāja SEZ which, after being combined, will form a property of approximately 31.7 hectares. The company plans to develop a green hydrogen production plant using PEM electrolysis technology.</li></ul></div>
