<h1 class="article-title">Liepāja Positions Itself as an Offshore Wind Energy Hub in the Eastern Baltic Sea</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Liepāja Special Economic Zone (Liepāja SEZ) Manager Uldis Hmieļevskis attended the Offshore Energy Exhibition &amp; Conference in Amsterdam from 27 to 29 November, visited the ports of Rotterdam and Amsterdam, and met senior representatives of leading energy and logistics companies in the European Union.</p><p>Following the working visit to the Netherlands, Hmieļevskis said the trip had reinforced his understanding of the EU’s ambitious goal of developing 150 GW of new capacity by 2050. “It is a major challenge: manufacturing capacity and port capacity will both need to triple. For Liepāja and Latvia, this creates an opportunity to build new factories producing foundations, towers, blades and perhaps even generators.</p><p>Existing businesses will have opportunities to manufacture various components and parts. Liepāja Maritime College could train seafarers specifically for wind farm construction and maintenance, allowing them to work in their profession closer to home instead of spending months on long voyages.”</p><p>The Baltic Sea is the North Sea 2.0 — an informal term used by the offshore wind industry in the Netherlands to describe the Baltic Sea’s potential in achieving the European Union’s energy independence and climate neutrality goals. The Netherlands has extensive energy-sector experience, dating from offshore oil and gas platforms in the North Sea to today’s offshore wind farms.</p><p>The Liepāja SEZ Manager said that visiting the ports of Amsterdam and Rotterdam and participating in the wind energy exhibition and conference had resulted in valuable discussions, new contacts and talks about development projects. The Liepāja SEZ Authority is expected to participate in several major projects in the port and industrial areas.</p><p>“The offshore wind industry is substantial, and Latvia must seize the opportunities it offers: creating jobs and expertise, supplying existing businesses with green energy, and developing new industries that will be in demand in the future,” said Liepāja SEZ Manager Uldis Hmieļevskis.</p><p><br/> </p></div>
