<h2>Third Phase of the Karosta Canal Environmental Remediation Project Completed</h2>
<span class="mb-3">29.12.2023.</span>
</div>
<a aria-label="Read more" class="mb-3 news_link d-none d-md-block" href="/site/en/jaunumi-1/nosledzas-karostas-kanala-vides-sanacijas-projekta-iii-karta/index.php">Read more</a>
</div>
<div class="col-12 col-md-4 description">
<p>The Liepaja SEZ Authority has implemented the project “Remediation of Historically Contaminated Areas in the Karosta Canal of the Port of Liepaja”, aimed at reducing the harmful effects of historically contaminated sediments on the environment, human health and the ecological condition of the Baltic Sea. Funded by the Norwegian Financial Mechanism 2014–2021 programme “Climate Change Mitigation, Adaptation and Environment”, the project removed a total of 145,199 cubic metres of historically contaminated sediments containing approximately 298 tonnes of hazardous chemicals. This was the third phase of the Karosta Canal remediation project.</p>
