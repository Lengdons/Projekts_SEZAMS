<div class="col-12 col-md-4 description">
<p>The Liepaja Special Economic Zone Authority has signed an agreement with Eko osta Ltd. to carry out remediation works in the Karosta Canal of the Port of Liepaja and remove historically contaminated sediments. Under the agreement, the works must begin after the remediation programme has been developed and approved, but no later than 1 April 2023, and must be completed by 30 November 2023. Approximately 164,000 cubic metres of contaminated sediment are to be dredged at a total contract value of EUR 3,497,260.00.  </p>
