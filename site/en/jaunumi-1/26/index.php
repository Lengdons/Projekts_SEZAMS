<h2>Liepaja: An Offshore Wind Energy Hub in the Eastern Baltic Sea</h2>
<span class="mb-3">14.04.2022.</span>
</div>
<a aria-label="Read more" class="mb-3 news_link d-none d-md-block" href="/site/en/jaunumi-1/liepaja-atkrastes-veja-energijas-nozares-centrs-baltijas-juras-austrumu-dala/index.php">Read more</a>
</div>
<div class="col-12 col-md-4 description">
<p>On 14 April, a discussion entitled “Latvian Ports as the Foundation of Energy Independence” took place in Liepaja, led by Transport Minister Jānis Vitenbergs and Economics Minister Ilze Indriksone. The discussion focused on the Baltic Sea’s potential for offshore wind farm development and the need for Latvia’s major ports to attract private investment. Liepaja SEZ CEO Uldis Hmieļevskis presented plans for an offshore wind support base at the Port of Liepaja. The proposed location meets eight of the ten requirements: all planned wind farms in Latvian territorial waters lie within a 100 km radius, and all planned wind farms in the Baltic states lie within 250 km.</p>
