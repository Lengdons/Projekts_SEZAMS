<h2>Norwegian Experience in the Sustainable Restoration of Contaminated Water Bodies After Remediation</h2>
<span class="mb-3">09.06.2022.</span>
</div>
<a aria-label="Read more" class="mb-3 news_link d-none d-md-block" href="/site/en/jaunumi-1/norvegijas-pieredze-ilgtspejiga-piesarnotu-udens-tilpnu-gultnu-atjaunosana-pec-sanacijas-d/index.php">Read more</a>
</div>
<div class="col-12 col-md-4 description">
<p>At the knowledge-sharing seminar “Reducing and Preventing Pollution: Effective Environmental Management Systems in Industrial Waterways” on 3 June, representatives of the Norwegian Institute for Water Research (NIVA) shared their experiences, both successful and less successful, with the natural recovery of contaminated sediments in water bodies after the partial removal of polluted sediment. Experts from the State Environmental Service, Liepaja City Council and the Liepaja Special Economic Zone Authority (LSEZ) also shared their experience in reducing pollution. The event was organised as part of the project “Remediation of Historically Contaminated Areas in the Karosta Canal of the Port of Liepaja”, implemented by the Liepaja Special Economic Zone Authority in cooperation with the Norwegian Institute for Water Research and the Baltic Coasts association. </p>
