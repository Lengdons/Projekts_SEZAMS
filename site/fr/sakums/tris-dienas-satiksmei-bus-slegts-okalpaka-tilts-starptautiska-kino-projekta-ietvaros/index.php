<h1 class="article-title">Dans le cadre d'un projet cinématographique international, le pont O. Kalpak sera fermé à la circulation pendant trois jours</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Du 16 au 24 octobre, Liepāja deviendra brièvement un lieu de tournage pour l'industrie cinématographique internationale. L'adaptation du roman "La Fille au tatouage de dragon" de la célèbre série de livres "Millennium", produite par la société "Left Bank Pictures", connue pour des projets tels que "The Crown" et "Dept Q", sera tournée dans la ville. Un rôle particulier dans ce projet est attribué au pont d'Oskar Kalpak, choisi comme l'un des lieux de tournage les plus importants de toute la série. Le pont sera fermé aux piétons et à la circulation automobile pendant trois jours pendant le tournage, et la circulation des navires sera restreinte.</p><p>Le tournage sur le pont O. Kalpaka aura lieu du 19 au 21 octobre. Pendant cette période, nous invitons les conducteurs, les cyclistes et les piétons à planifier à temps leur trajet vers et depuis Karosta et à s'attendre à un éventuel temps supplémentaire sur la route. En coopération avec la municipalité, une circulation spéciale de bus sera assurée le long de la route de contournement. Des informations sur ce service seront affichées aux deux extrémités du pont. En revanche, les transports publics seront détournés vers des itinéraires contournés. </p><p>Fermeture du pont O. Kalpaka pour les piétons et les véhicules :</p><ul><li>du 19 octobre 2026 à 8h00 au 21 octobre à 22h00</li></ul><p>De plus, pendant la durée du tournage, l'accès à la zone proche du pont O. Kalpaka ainsi qu'à la route d'accès et au parking de la jetée du côté sud du canal Karosta sera restreint.</p><p>La circulation maritime dans le canal Karosta sera restreinte pendant toute la durée du tournage. L'administration de la ZES de Liepāja exprime sa gratitude aux entreprises de manutention du port de Liepāja, qui soutiennent l'important projet de l'industrie cinématographique et ont reprogrammé leur travail autant que possible. Cinq terminaux portuaires fonctionnent activement dans le canal de Karosta - "Baltic Transshipment Center", "Schwenk", "DG Termināls", "Norsaf", "Baltex Bulk" et la société LZK, qui poursuit activement la réparation des navires sur les quais de Tosmares.</p><p>Il est significatif que le pont Oskar Kalpak ait été choisi comme l'un des lieux de tournage centraux de ce projet, attirant particulièrement l'attention internationale sur Liepāja. Le film touchera des millions de spectateurs dans différents pays, devenant ainsi une puissante plateforme de sensibilisation à la ville.</p><p>La mise en œuvre réussie d'un projet de cette envergure renforce la réputation de Liepāja en tant que ville portuaire ouverte sur le monde, professionnelle et capable de mettre en œuvre des projets complexes. "Cela augmente les chances d'attirer de nouveaux projets d'industries cinématographiques, artistiques et créatives à l'avenir, créant ainsi des avantages économiques et de réputation à long terme pour la ville et la région."</p></div>
