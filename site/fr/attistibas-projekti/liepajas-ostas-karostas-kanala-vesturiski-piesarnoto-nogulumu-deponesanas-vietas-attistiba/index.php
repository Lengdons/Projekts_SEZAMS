<h1 class="article-title">Élaboration d'une évaluation technico-économique du développement du site de dépôt de sédiments historiquement pollué du canal Karosta du port de Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Entre le 1er août 2024 et le 31 octobre 2024, l'Administration de la zone économique spéciale de Liepāja a mis en œuvre l'instrument financier norvégien 2014-2021. du programme « Atténuation du changement climatique, adaptation à celui-ci et à l'environnement » de l'initiative du Fonds de coopération bilatérale « Développement de l'évaluation technico-économique du développement du site de dépôt de sédiments historiquement pollué du canal Karosta du port de Liepāja » (ci-après - l'Initiative). </p><p>Le canal Karosta du port de Liepāja et la pollution historique dans son lit constituent un lieu pollué unique dégradant l'environnement de la mer Baltique, non seulement en Lettonie, mais également à l'échelle de toute la région de la mer Baltique. Depuis 1994, l'administration de la zone économique spéciale de Liepāja mène des actions ciblées visant à restaurer l'environnement du canal de Karosta, à la suite desquelles des campagnes ambitieuses de dépollution du canal de Karosta ont été mises en œuvre en 2015 et 2023, supprimant plus de 200 000 m de l'environnement du canal.<sup>3</sup> sédiments contaminés et les déposer sur le site de dépôt de sédiments historiquement contaminés du canal Karosta du port de Liepāja. Le lieu de dépôt des sédiments historiquement pollués du canal de Karosta est une partie spécialement délimitée de la zone d'eau du canal de Karosta, où un stockage sûr des sédiments pollués déposés est assuré. </p><p>Malgré de nombreuses études consacrées à la situation environnementale et aux travaux d'assainissement du canal de Karosta et aux travaux d'assainissement mis en œuvre dans le canal de Karosta, aucune recherche n'a été menée jusqu'à présent sur le développement ultérieur du site de dépôt de sédiments contaminés, y compris les travaux d'assainissement. limiter la propagation des polluants qui y sont déposés et développer des alternatives pour l'aménagement du site de dépôt et évaluer des scénarios de gestion. C'est pourquoi, dans le cadre de l'Initiative, en coopération avec les partenaires norvégiens - l'Institut norvégien de recherche sur l'eau (NIVA) et l'Institut norvégien de géotechnique (NGI), qui possèdent une expérience considérable non seulement dans l'assainissement de la pollution historique du milieu marin, mais aussi dans la création de sites d'élimination de sédiments contaminés et leur gestion successive, les alternatives de développement et la gestion la plus prospective du site de dépôt de sédiments historiquement contaminés dans le canal Karosta du port de Liepāja ont été développées. scénarios. </p><p><strong>Travaillons ensemble pour une Europe verte !</strong></p><p>Le projet est financé dans le cadre du programme d'instruments financiers norvégiens 2014-2021 « Atténuation du changement climatique, adaptation et environnement ». Le coût total du projet est de 264 500,00 EUR, dont 264 500,00 EUR sont financés par l'instrument financier norvégien.</p></div>
