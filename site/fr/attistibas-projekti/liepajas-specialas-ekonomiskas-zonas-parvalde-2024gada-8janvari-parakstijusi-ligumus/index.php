<h1 class="article-title"> Le 8 janvier 2024, l'Administration de la zone économique spéciale de Liepāja a signé des contrats pour le début des travaux de construction du projet « Développement du territoire du parc industriel de Liepāja, phase 1 »</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Le 8 janvier 2024, l'Administration de la zone économique spéciale de Liepāja a signé des contrats pour le début des travaux de construction du projet « Développement du territoire du parc industriel de Liepāja, phase 1 ». Dans le cadre du projet, le territoire de l'ancienne usine « Liepājas Metalurgs » à Liepāja entre la rue Brīvības, la rue Meldru, la rue Liepājas Ezer, la rue Ezermalas, la rue Parka et la rue Zemnieku sera reconstruit avec les territoires adjacents bordant le lac Liepājas, en construisant une infrastructure de voirie publique avec des réseaux d'ingénierie, pour assurer l'infrastructure commerciale de base, créant un parc industriel opérationnel d'importance nationale, assurant une fonctionnalité développée du territoire conformément aux a approuvé la stratégie de développement à long terme du parc industriel de Liepāja pour 2023-2038.</p><p>L'objectif du projet est de transformer le territoire de l'ancienne usine « Liepājas metalurgs » en un parc éco-industriel vert d'importance nationale, en construisant des infrastructures de base modernes, en attirant les investisseurs, en créant une production à haute valeur ajoutée orientée vers l'exportation dans les industries RIS3 et en créant des emplois qualifiés et bien rémunérés.</p><p>Le projet prévoit d'investir dans la construction d'infrastructures accessibles au public - rues et communications techniques prévues dans celles-ci.</p><p>À la suite de la mise en œuvre du projet, plusieurs avantages importants à long terme seront créés :</p><ul><li>l'augmentation de l'emploi dans la région favorisera l'activité économique de la ville de Liepāja, du district sud de Kurzeme et de la région de Kurzeme et réduira le fardeau social ;</li><li>attirer des industries à plus forte valeur ajoutée et les spécialistes nécessaires, ce qui favorisera le développement des domaines de l'éducation et de la recherche et assurera la croissance d'une main-d'œuvre instruite tant dans la région de Kurzeme qu'en Lettonie ;</li><li>le développement d'industries à plus forte valeur ajoutée, de leurs mécanismes de coopération et de leur écosystème orientés vers des solutions neutres pour le climat, qui favoriseront le développement de solutions innovantes et la création de nouvelles entreprises à l'échelle locale ;</li><li>augmenter les recettes fiscales dans les budgets de l'État et des collectivités locales, ce qui apportera une contribution significative au financement des fonctions de l'État et des collectivités locales.</li></ul><p>Le financement du projet est assuré par le plan 3.1 du mécanisme de relance et de résilience de l’Union européenne. » à la sous-section 3.1.1.3.i de l'orientation de réforme et d'investissement « Politique régionale ». investissements dans le cadre des « Investissements dans les infrastructures publiques des entreprises pour le développement des parcs industriels et des territoires des régions ».</p></div>
