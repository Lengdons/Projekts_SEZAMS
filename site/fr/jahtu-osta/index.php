<p>Afin d'organiser le trafic maritime en toute sécurité, il est recommandé aux petits navires équipés d'une station radio ondes ultra-courtes d'assurer en permanence les communications radio sur le canal ondes ultra-courtes 11.</p><p>Il convient de noter que tout participant au trafic maritime qui peut naviguer en toute sécurité en dehors des principales voies de navigation ne doit pas entraver la circulation des navires le long de celles-ci. La circulation des yachts et des petits bateaux dans le port doit se faire de manière à ne pas gêner les navires naviguant le long du chenal. Lors de la navigation dans les eaux du port de Liepāja, les « Règles sur la circulation des navires dans les eaux intérieures » et les « Règles du port de Liepāja » doivent être respectées.</p><p>Un yacht, un cotre ou un bateau de plaisance est considéré comme un petit bateau si sa longueur est inférieure à 24 mètres.</p><p>La navigation des yachts et des bateaux de plaisance est autorisée dans le canal commercial.</p><p>La limite de vitesse pour les petits navires dans le canal commercial est de 5 nœuds (9 km/h). Dans le reste de la zone d'eau du port, il n'y a pas de limite de vitesse, mais il est nécessaire de naviguer à une vitesse qui ne mette pas en danger les autres usagers de la route, les personnes, les navires amarrés et autres structures flottantes ou fixes, compte tenu notamment de l'influence de la vague créée par le navire.</p><br/>
