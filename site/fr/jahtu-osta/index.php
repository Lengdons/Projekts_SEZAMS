<div class="card-body">
<ul><li>Afin de garder longtemps une embarcation à l'un des postes d'amarrage de la marina de Liepāja, il est nécessaire de conclure un accord d'amarrage de yacht/bateau avec l'administration de la zone économique spéciale de Liepāja en remplissant le formulaire de déclaration au centre de la marina.</li><li>Les contrats d'amarrage des yachts/cotres pour leur stationnement longue durée aux postes d'amarrage de la marina sont conclus selon le principe du premier arrivé, premier servi, dans la limite des places allouées à cet effet. Les réservations de places ne sont pas fournies.</li><li>Afin d'appliquer le tarif mensuel pour l'amarrage longue durée, la durée minimale de conclusion d'un contrat d'amarrage yacht/cotre est de 2 mois. Durant la saison, les places disponibles sont proposées aux clients sur liste d'attente selon le principe du premier arrivé, premier servi.</li></ul><br/>
