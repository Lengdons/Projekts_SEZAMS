<h1 class="article-title">Vente aux enchères répétée avec une marche ascendante pour l'immobilier rue Naglu 1</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>L'Administration de la zone économique spéciale de Liepāja, numéro d'enregistrement unifié. LV90000329402, organise une nouvelle vente aux enchères électronique avec un échelon ascendant pour des biens immobiliers situés rue Naglu 1, Liepāja, cadastre no. 17000220152, qui sera composé d'un bâtiment portant la désignation cadastrale 17000220059027 et d'une unité foncière d'une superficie totale de 15048 m2.</p><p>Prix de départ – 295 000,00 EUR (deux cent quatre-vingt-quinze mille euros et 00 centimes), étape d'enchère – 2950,00 EUR (deux mille neuf cent cinquante euros et 00 centimes), argent de sécurité de l'enchère – 29 500,00 EUR (vingt-neuf mille cinq cents euros et 00 centimes). Le paiement de l'achat peut être effectué dans l'ordre suivant :</p><p>- Dans les 10 jours ouvrables après la date d'entrée en vigueur du contrat préliminaire, l'acheteur verse un acompte de 30 % (trente pour cent) du prix d'achat.</p><p>- L'acheteur paie la partie restante des frais d'achat dans les deux semaines suivant la conclusion du contrat d'achat.</p><p>La vente aux enchères commence le 20.02.2026. à 13h00 et se termine le 23.03.2026. à 13h00.</p><p>Les candidats peuvent s'inscrire à la vente aux enchères à partir du 20.02.2025. à 13h00 jusqu'au 12.03.2025. à 23h59 sur le site des enchères : <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>.</p><p>Une personne qui souhaite participer à l'enchère doit payer un dépôt de garantie - 10 % (dix pour cent) du prix de départ du bien immobilier à vendre aux enchères, soit 29 500,00 EUR (vingt-neuf mille cinq cents euros et 00 centimes), qui est crédité sur le compte courant de l'administration LSEZ : administration de la zone économique spéciale de Liepāja, numéro d'enregistrement unifié. LV90000329402, JSC "SEB banka", compte n° LV42UNLA0012000609480, avec l'étiquette "Immobilier rue Naglu 1 sécurité des enchères". L'enchère se déroule par voie électronique sur le site Internet : <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>. Pour la vente aux enchères immobilière, appelez le 29294267, adresse e-mail : raivo.spaks@lsez.lv.</p></div>
