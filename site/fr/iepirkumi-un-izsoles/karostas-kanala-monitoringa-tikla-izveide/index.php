<h1 class="article-title">Création du réseau de surveillance du canal Karosta (Id. No. LSEZ 2023/15)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>La Commission des marchés publics de l'administration de la zone économique spéciale de Liepāja a pris une décision sur les résultats du marché ouvert « Création du réseau de surveillance du canal de Karosta » (LSEZ 2023/15), attribuant le contrat à SIA « Isliena V » (5000204363) pour un prix total du contrat de 79 280,00 EUR, hors taxe sur la valeur ajoutée.</p><p>&nbsp;</p><p><strong>Code CPV</strong></p><p>Code CPV : 45122000-8 (Travaux de forages exploratoires)</p><p><strong>Projet</strong></p><p>Le projet est mis en œuvre dans le cadre du cofinancement du fonds du programme d'instruments financiers norvégien 2014-2021 « Atténuation, adaptation et environnement du changement climatique ». L'objet du contrat « Établissement d'un réseau de surveillance du port de Liepāja canal Karosta » (ci-après - l'accord) est l'une des mesures mises en œuvre par la zone économique spéciale de Liepāja (ci-après - le client) dans le cadre du projet « Sites historiquement contaminés du canal Karosta du port de Liepāja » (ci-après - le projet).</p><p><strong>Heure et lieu d'exécution du contrat</strong></p><p>1. Délai d'exécution du contrat : doit être assuré dans 3 (trois) mois, mais au plus tard le 26 avril 2024.</p><p>2. Lieu d'exécution du contrat : Le lieu d'exécution des travaux (figure 6.2) est le canal Karosta du port de Liepāja, la partie des eaux intérieures du port (cadastre n° 1700-010-0073 ; 1700-010-0306) et le territoire de la zone auxiliaire technologique, qui est adjacente au lieu de dépôt et qui est gérée par le conseil de la LSEZ (cadastre n° 1700-010-0306). 1700-010-0072).</p><p><strong>Procédure de passation des marchés</strong></p><p>Marchés publics ouverts conformément aux lignes directrices en matière de passation des marchés pour les prestataires de services publics (ci-après - lignes directrices). Disponible : Lignes directrices en matière de passation des marchés pour les prestataires de services publics | Bureau de contrôle des marchés publics (iub.gov.lv).</p><p>Les offres doivent être soumises dans le sous-système d'appel d'offres électronique du système électronique de passation des marchés (ci-après - EIS) (<a href="https://www.eis.gov.lv/EKEIS/Supplier">https://www.eis.gov.lv/EKEIS/Supplier</a>/) jusqu'au 13 février 2024 à 10h00</p></div>
