<h1 class="article-title">Élaboration d'un article explicatif et supervision de l'auteur pour l'objet "Construction d'une allée sur la rue Roņu 6"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>MARCHÉS AUXQUELS LA LOI SUR LES MARCHÉS DES PRESTATAIRES DE SERVICES PUBLICS NE S'APPLIQUE PAS - Élaboration d'une note explicative et supervision de l'auteur pour l'objet "Construction d'une allée dans la rue Roņu 6, Liepāja"</p><p>Objet de l'achat :</p><p>Élaboration d'un texte explicatif et supervision de l'auteur pour l'objet "Construction d'une allée dans la rue Roņu 6, Liepāja"" conformément à l'annexe 7 du règlement "Projet de contrat - Accord de lettre explicative", à l'annexe 8 "Projet d'accord de supervision de l'auteur - Accord de supervision de l'auteur" et à l'annexe 9 du règlement "Tâche de conception".</p><p>Code CPV : 71320000-7 (services de conception technique), 71248000-8 (supervision de projet et de documentation)</p><p>Les travaux de conception et de supervision des auteurs seront réalisés et financés par le Fonds européen pour les affaires maritimes, la pêche et l'aquaculture « Plan d'action 2023-2027 du Programme de développement de la pêche 2021-2027 » sous la forme de l'action « Mise en œuvre de stratégies de développement local pilotées par les communautés » action 4.1. Activités soutenues par M4/R1 dans le cadre du projet « Renforcement du développement des infrastructures portuaires ».</p><p>Les offres doivent être soumises dans le sous-système d'appel d'offres électronique du système électronique de passation des marchés, ci-après dénommé EIS (<a href="https://www.eis.gov.lv/EKEIS/Supplier/">https://www.eis.gov.lv/EKEIS/Supplier/</a>).</p><p>&nbsp;</p><p>Approvisionnement</p><p><strong>"Élaboration d'un article explicatif et supervision de l'auteur pour l'objet "Construction d'une allée à la rue Roņu 6, Liepāja"</strong></p><p>Fournisseur : SIA "Ceļu injinjeri"</p><p>Prix du contrat: 17760,00 EUR</p></div>
