<div class="row">
<div class="col"><div class="col-12 output"><p>Sur la base du Règlement du Cabinet des Ministres n° 183 du 28 mars 2017 « Procédures relatives aux procédures de passation des marchés et aux appels d'offres de conception des prestataires de services publics », sous-section 233.4, l'appel d'offres ouvert « Gestion des déchets générés lors de l'exploitation des navires, Annexe I de la Convention MARPOL dans le port de Liepāja » (id. No. LSEZ 2025/17) a été clôturé, tel qu'il a été soumis dans les documents de procédure de passation de marchés. offres qui ne répondent pas aux exigences spécifiées.</p><p>______________________________________________</p><p><strong>Objet de l'achat :</strong></p><p><strong>Déchets de l'Annexe I de la Convention MARPOL générés lors de l'exploitation des navires</strong></p><p><strong>gestion dans le port de Liepāja</strong></p><p><strong>NUMÉRO D'IDENTIFICATION LSEZ 2025/17</strong></p><p><strong>Code CPV</strong>: 9000000-7 (Eaux usées, ordures, nettoyage et services environnementaux).</p><p>Les offres doivent être soumises dans le système électronique de passation des marchés (ci-après - EIS), sous-système d'appels d'offres électroniques. <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a></p><p>jusqu'à <strong>pour la date limite de soumission spécifiée dans le sous-système d'appels d'offres électroniques de l'EIS</strong>.</p><p>&nbsp;</p><p>Les offres sont ouvertes dans le délai spécifié dans le sous-système d'appels d'offres électroniques de l'EIS.</p></div>
