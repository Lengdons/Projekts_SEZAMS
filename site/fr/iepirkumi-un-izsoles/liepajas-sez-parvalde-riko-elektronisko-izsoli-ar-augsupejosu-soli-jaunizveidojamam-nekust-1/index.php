<h1 class="article-title">Le conseil d'administration de la ZES de Liepāja organise une vente aux enchères électronique avec une progression pour les biens immobiliers nouvellement créés à la rue Eksporta 3</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>L'Administration de la zone économique spéciale de Liepāja, numéro d'enregistrement unifié LV90000329402, organise une vente aux enchères électronique avec un échelon croissant pour les biens immobiliers nouvellement créés dans la rue Eksporta 3, Liepāja, qui consistera en une unité foncière d'une superficie totale de 51 521 m.<sup>2</sup> et 12 bâtiments.</p><p>Prix de départ – <strong>680 000,00 EUR</strong> (six cent quatre vingt mille <i>euros</i> et 00 cents), étape d'enchère - <strong>6 800.00  EUR</strong> (six mille huit cents <i>euros</i> et 00 cents), argent de sécurité des enchères - <strong>68 000.00 EUR</strong> (soixante huit mille <i>euros</i> et 00 centimes). Le paiement de l'achat peut être effectué dans l'ordre suivant :</p><ul><li>Dans les 10 jours ouvrables après la date d'entrée en vigueur du contrat préliminaire, l'acheteur verse un acompte de 30 % (trente pour cent) du prix d'achat. </li><li>La partie restante des frais d'achat doit être payée par l'acheteur dans les deux semaines suivant la conclusion du contrat d'achat.</li></ul><p>La vente aux enchères commence le 06.10.2026. à 13h00 et se termine le 05.11.2026. à 13h00</p><p>Les candidats peuvent s'inscrire à la vente aux enchères à partir du 06.10.2026. à 13h00 jusqu'au 26.10.2026. à 23h59 sur le site des enchères :  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Une personne qui souhaite participer à l'enchère doit payer un dépôt de garantie - 10 % (dix pour cent) du prix de départ du bien immobilier à mettre aux enchères, avant la date limite d'enregistrement des enchères, c'est-à-dire <strong>68 000.00 EUR</strong> (soixante huit mille <i>euros</i> et 00 centimes), qui peut être crédité sur le compte courant de l'administration LSEZ : administration de la zone économique spéciale de Liepāja, numéro d'enregistrement unifié. LV90000329402, AS "SEB banka", compte n° LV42UNLA0012000609480, marqué "Immobilier rue Eksporta 3, Liepāja, sécurité des enchères". </p><p>L'enchère se déroule par voie électronique sur le site Internet : <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Pour les enchères immobilières, appelez le 29294267, adresse e-mail : <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
