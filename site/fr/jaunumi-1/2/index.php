<h2>La construction de la route d'accès au poste d'amarrage 92 du port de Liepāja est en voie d'achèvement</h2>
<span class="mb-3">20.08.2026.</span>
</div>
<a aria-label="Lire la suite" class="mb-3 news_link d-none d-md-block" href="/site/fr/jaunumi-1/noslegumam-tuvojas-piebraucama-cela-izbuve-uz-liepajas-ostas-92-piestatni/index.php">Lire la suite</a>
</div>
<div class="col-12 col-md-4 description">
<p>L'administration de la ZES de Liepāja continue d'améliorer les infrastructures nécessaires aux pêcheurs en construisant la route d'accès à la 92e jetée du port. Le projet est financé par le Programme d'action pour le développement de la pêche 2021-2027 du Fonds européen pour les affaires maritimes, la pêche et l'aquaculture. pour l'année. Dans le cadre du projet, une voie d'accès publique de 364 mètres est en cours de construction, ainsi qu'un système intelligent d'éclairage et d'évacuation des eaux pluviales. Selon les résultats du marché, les travaux sont réalisés par la SIA "CTB", qui a proposé la solution économiquement la plus avantageuse pour un montant de 303.617,32 euros. Les travaux de construction devraient être terminés d'ici la fin août.</p>
