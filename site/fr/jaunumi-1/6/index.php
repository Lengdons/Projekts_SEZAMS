</div>
<div class="col-12 col-md-4 description">
<p>Le budget 2026 de l'administration de la ZES de Liepāja a été créé de manière conservatrice et équilibrée, garantissant à la fois l'exercice des fonctions de base et la poursuite de la mise en œuvre de projets d'investissement axés sur le développement dans les zones portuaires et industrielles. L'orientation stratégique de 2026 vise à accroître l'efficacité opérationnelle, à construire des infrastructures, à introduire la gestion numérique dans le port et à améliorer la cybersécurité. Le conseil d'administration de la ZES de Liepāja a approuvé le budget 2026 avec un chiffre d'affaires prévu de 17,9 millions. EUR.  </p>
