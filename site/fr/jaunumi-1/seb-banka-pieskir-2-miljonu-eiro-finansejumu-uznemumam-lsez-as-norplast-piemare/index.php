<h1 class="article-title">SEB banka accorde un financement de 2 millions d'euros pour la construction de l'usine de production de LSEZ AS "Norplast Piemare".</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>SEB banka a accordé un financement d'un montant de 2 millions d'euros à la société de la zone économique spéciale de Liepāja « Norplast Piemare » AS pour la construction d'une nouvelle usine de production dans le port de Liepāja. L'usine de production prévue aura une largeur de près de 2 000 mètres carrés et sa construction devrait être achevée dès l'automne 2024. Elle produira de très grands produits composites, dont la production n'était pas possible jusqu'à présent en Lettonie. L'emplacement de l'usine à proximité immédiate de la jetée du port offrira des avantages logistiques et facilitera le transport de marchandises volumineuses.</p><p>"Norplast Piemare" est l'une des filiales de la société norvégienne "ENTEC Group", entrée à Liepāja il y a plusieurs années, lorsque ses actions ont été rachetées par la société "Entec Norplast". "Entec Norplast" est une société de capitaux norvégienne fondée en Lettonie en 2001, spécialisée dans la production de produits en fibre de verre utilisés dans les équipements de sécurité des navires, l'extraction pétrolière, le transport, les loisirs actifs, le traitement des eaux usées, la pisciculture et d'autres domaines. L'entreprise possède déjà une usine de production à Saldu et ses produits sont exportés dans le monde entier. </p><p>"SEB banka coopère depuis longtemps avec Entec Norplast, qui a réussi à conquérir une niche dans la production de produits spécifiques de grande taille à partir de matériaux composites. La nouvelle usine de production disposera, par exemple, d'étangs à poissons de grande taille, l'emplacement de l'installation de production dans le port est important pour le transport. Nous sommes heureux de pouvoir soutenir l'expansion de la production en Lettonie et de coopérer avec une entreprise internationalement reconnue et appréciée dans son créneau, qui se développe et se développe en Lettonie", déclare le conseil d'administration de SEB banka. membre Arnis Škapars.</p><p>"Cette installation de production est une étape importante dans le développement stratégique, qui est lié au développement à long terme de nos entreprises. Nous sommes des entreprises en croissance, et la nouvelle usine à Liepāja nous donne l'opportunité de croître, ainsi qu'une opportunité unique d'envoyer de grandes constructions composites directement à nos clients depuis le quai en eau profonde dont nous disposons. Nous sommes heureux que notre partenaire financier - SEB banka - ait également évalué le potentiel des entreprises dans un domaine d'activité très spécifique. L'histoire du développement des entreprises "Entec Norplast" et "Norplast Piemare" en Lettonie continuera avec plus de capacité, désormais dans deux usines de production à Saldu et Liepāja", déclare Māris Meija, directeur de "Entec Norplast" et président du conseil d'administration de LSEZ "Norplast Piemare".</p></div>
