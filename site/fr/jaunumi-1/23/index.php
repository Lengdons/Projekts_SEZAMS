<h2>Le troisième cycle du projet de réhabilitation environnementale du canal Karosta touche à sa fin</h2>
<span class="mb-3">29.12.2023.</span>
</div>
<a aria-label="Lire la suite" class="mb-3 news_link d-none d-md-block" href="/site/fr/jaunumi-1/nosledzas-karostas-kanala-vides-sanacijas-projekta-iii-karta/index.php">Lire la suite</a>
</div>
<div class="col-12 col-md-4 description">
<p>L'administration de la ZES de Liepāja a mis en œuvre le projet « Zones historiquement polluées des travaux d'assainissement du canal Karosta du port de Liepāja » dans le but de réduire l'impact négatif des sédiments historiquement pollués du canal Karosta sur l'environnement, la santé humaine et l'état écologique de la mer Baltique. Le projet est financé dans le cadre du programme d'instrument financier norvégien 2014-2021 « Atténuation du changement climatique, adaptation à celui-ci et à l'environnement » et un total de 145 199 mètres cubes de sédiments historiquement contaminés contenant environ 298 tonnes de produits chimiques dangereux ont été éliminés. Il s'agissait du troisième cycle du projet de réhabilitation du canal Karosta.</p>
