</div>
<div class="col-12 col-md-4 description">
<p>L'Administration de la zone économique spéciale de Liepāja a conclu un contrat avec SIA « Eko osta » pour la réalisation des travaux de réhabilitation du canal Karosta du port de Liepāja et l'élimination des sédiments historiquement pollués. Selon l'accord conclu, les travaux de réhabilitation devraient commencer après l'élaboration et l'approbation du programme de réhabilitation du canal Karosta, mais au plus tard le 1er avril 2023, mais devraient être achevés d'ici le 30 novembre 2023. Dans le cadre du contrat, il est prévu d'évacuer environ 164 000 m3 de sédiments contaminés et le montant total du contrat est de 3 497 260,00 EUR.  </p>
