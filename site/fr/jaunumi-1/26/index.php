<h2>Liepāja - le centre de l'industrie de l'énergie éolienne offshore dans la partie orientale de la mer Baltique</h2>
<span class="mb-3">14.04.2022.</span>
</div>
<a aria-label="Lire la suite" class="mb-3 news_link d-none d-md-block" href="/site/fr/jaunumi-1/liepaja-atkrastes-veja-energijas-nozares-centrs-baltijas-juras-austrumu-dala/index.php">Lire la suite</a>
</div>
<div class="col-12 col-md-4 description">
<p>Le 14 avril, une discussion sur « Les ports lettons comme base de l'indépendance énergétique » a eu lieu à Liepāja, présidée par le ministre des Transports Jānis Vitenbergs et la ministre de l'Économie Ilze Indriksone, et qui s'est concentrée sur le potentiel de la mer Baltique pour le développement de parcs éoliens. L'aspect le plus important des négociations a été la nécessité pour les grands ports de Lettonie d'attirer des investisseurs privés pour assurer ce développement. Au cours de la discussion, Uldis Hmieļevskis, directeur de la ZES de Liepāja, a présenté le plan élaboré visant à créer une base de soutien à l'énergie éolienne offshore dans le port de Liepāja, qui remplit pleinement huit conditions sur dix et comprend tous les parcs éoliens prévus dans les eaux territoriales lettones dans un rayon de 100 km et tous les parcs éoliens prévus dans les États baltes dans un rayon de 250 km.</p>
