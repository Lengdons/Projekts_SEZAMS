<span class="mb-3">09.06.2022.</span>
</div>
<a aria-label="Lire la suite" class="mb-3 news_link d-none d-md-block" href="/site/fr/jaunumi-1/norvegijas-pieredze-ilgtspejiga-piesarnotu-udens-tilpnu-gultnu-atjaunosana-pec-sanacijas-d/index.php">Lire la suite</a>
</div>
<div class="col-12 col-md-4 description">
<p>Le 3 juin de cette année, lors du séminaire d'échange d'expériences « Réduction et prévention de la pollution : systèmes efficaces de gestion environnementale dans les voies navigables industrielles », des représentants de l'Institut norvégien de recherche sur l'eau (NIVA) ont partagé leurs expériences réussies et moins réussies en matière de récupération naturelle des sédiments pollués dans les masses d'eau après élimination partielle des sédiments pollués. Lors de l'événement, des experts du Service national de l'environnement, de la municipalité de Liepāja et de l'Administration de la zone économique spéciale de Liepāja (LSEZ) ont également partagé leur expérience dans le domaine de la réduction de la pollution. L'événement est organisé dans le cadre du projet « Travaux de réhabilitation du canal Karosta du port de Liepāja des sites historiquement contaminés » (ci-après - le projet), qui est mis en œuvre par l'administration de la zone économique spéciale de Liepāja, en coopération avec l'Institut norvégien de recherche sur l'eau et l'association « Baltijas Krasti ». </p>
