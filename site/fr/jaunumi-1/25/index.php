</div>
<div class="col-12 col-md-4 description">
<p>Au cours des huit mois de 2023, 4,6 millions de tonnes ont été manutentionnées dans le port de Liepāja. tonnes de marchandises diverses. Le plus grand groupe de marchandises reste celui des marchandises en vrac, qui représentent 68 % de toutes les marchandises, y compris les marchandises en vrac. céréales et produits céréaliers 44% ou 2,01 millions la tonne. Le port de Liepāja maintient toujours un chiffre d'affaires de fret Ro-Ro stable avec une dynamique positive. Cela est lié à la demande et au chiffre d'affaires des marchandises, ainsi qu'à la coopération unie et réfléchie des entrepreneurs et de l'administration de la zone économique spéciale de Liepāja pour attirer de nouvelles directions logistiques et de nouvelles marchandises, en continuant à attirer des marchandises locales, ainsi qu'aux investissements mutuels dans le développement des infrastructures.</p>
