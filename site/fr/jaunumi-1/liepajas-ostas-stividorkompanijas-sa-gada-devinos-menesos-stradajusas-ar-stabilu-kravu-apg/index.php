<h1 class="article-title">Les entreprises de manutention du port de Liepāja ont travaillé avec un chiffre d'affaires stable au cours des neuf mois de cette année</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Au cours des neuf mois de 2024, les entreprises de manutention du port de Liepāja ont manutentionné 5.247.263,28 tonnes de marchandises diverses, assurant un flux de marchandises stable avec un solde positif (+1,12%). Les conditions préalables à un fonctionnement stable sont la diversité des flux de marchandises, la capacité de s'adapter aux conditions et la coopération avec l'administration de la ZES de Liepāja pour attirer de nouvelles marchandises. Au cours des neuf mois de cette année, 1 000 navires et 85 051 passagers ont été accueillis dans le port de Liepāja.</p><p><br/>Dans le segment du fret en vrac, au cours des neuf mois de 2024, 3,36 millions de tonnes ont été manutentionnées dans le port de Liepāja. tonnes, ce qui représente 64 % du volume total de marchandises. Entre janvier et septembre, 2,27 millions ont été transbordés. tonnes de céréales et produits céréaliers. L'exportation des céréales cultivées en Lettonie se poursuit activement pour le troisième mois. Les producteurs de céréales locaux soulignent l'importance du port de Liepāja pour assurer l'exportation des céréales, à la fois en garantissant des conditions de coopération flexibles et en disposant d'une large capacité d'entrepôt.</p><p>Dans le segment du vrac, exportations stables de copeaux de bois de chauffage et de matériaux de construction. Les plus grands terminaux de marchandises en vrac - LSEZ SIA "Liepāja Bulk Terminal" et LSEZ SIA "Ekers Stividors LP" ont transbordé respectivement 1,7 million de tonnes au cours des neuf mois de cette année. tonnes et 1,1 million la tonne.</p><p><br/>Le volume de marchandises diverses au cours de la période spécifiée cette année est de 1,69 million de tonnes, ce qui représente une augmentation stable de + 16,5 % par rapport aux neuf mois de 2023. Le plus grand groupe de fret est le fret roulier, suivi du bois.</p><p>D'autre part, les cargaisons en vrac dans le port de Liepāja au cours des neuf mois de cett