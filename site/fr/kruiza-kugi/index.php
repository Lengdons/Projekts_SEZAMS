<div class="columns mt-5">
<div class="row">
<div class="col-12 col-md-3 column-content">
<img alt="icône" class="icon" src="../../img/block/columns/168/1725616669_kruizu-kugjis.svg"/>
<p>Le port de Liepāja a été reconnu comme un centre régional de transbordement de marchandises performant, tandis que l'intérêt du secteur des croisières pour Liepāja s'est également accru récemment. Des milliers de touristes sont déjà arrivés à Liepāja par voie maritime sur la route du ferry depuis Traveminde en Allemagne. On pense désormais que les visiteurs de la ville pourraient également venir sur des bateaux de croisière.</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icône" class="icon" src="../../img/block/columns/169/1725616901_enkurs.svg"/>
<p>Un voyage en croisière n'est pas seulement du temps passé à bord : aucun voyage n'est complet sans une excursion à terre. Liepāja est l'une des destinations de croisière les plus récentes de la côte ouest de la mer Baltique, offrant la meilleure expérience aux passagers des navires de croisière.</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icône" class="icon" src="../../img/block/columns/170/1725616778_divas-majinas.svg"/>
<p>Les quais des navires de croisière sont situés à proximité immédiate du port, offrant un accès facile au centre-ville et à d'autres destinations touristiques, où des visites guidées à pied ou en bus sont proposées pour explorer l'histoire locale, la culture, la cuisine, les parcs paysagers, l'architecture historique et moderne, les plages Pavillon Bleu et bien plus encore.</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icône" class="icon" src="../../img/block/columns/171/1725617099_baltijas-karte.svg"/>
<p>Les visiteurs de la ville qui choisissent le tourisme du patrimoine militaire peuvent visiter le plus grand territoire militaire historique des pays baltes - une partie de la ville appelée Karosta, construite au 19ème siècle à des fins militaires. Il est unique dans son contexte historique et architectural, non seulement en Lettonie, mais aussi dans le monde entier.</p>
</div>
