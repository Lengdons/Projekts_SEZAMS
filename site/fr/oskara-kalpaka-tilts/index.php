<h5 class="mb-0">
<button aria-controls="collapse4720" aria-expanded="false" class="accordion-button collapsed" data-bs-target="#collapse4720" data-bs-toggle="collapse">

Histoire du pont

</button>
</h5>
</div>
<div aria-labelledby="heading4720" class="collapse" data-parent="#accordion" id="collapse4720">
<div class="card-body">
<p>Jusqu'au début du XXe siècle, Karosta n'avait pas de connexion directe avec le reste de la ville de Liepāja, car la route était interrompue par un large canal d'entrée du port. La circulation sur le canal était assurée par un grand ferry à vapeur. Afin de relier Liepāja au port d'Alexandre III à cette époque, les travaux de conception du pont-levis ont commencé en 1903 et en 1904, la construction du pont conçu par l'ingénieur allemand Harald Hall a commencé sur la Manche. Les structures métalliques du pont ont été fabriquées dans la ville russe de Briansk, tandis que les mécanismes de rotation et le moteur électrique ont été fabriqués en Belgique.</p><p> </p><h5>Il a été inauguré le 19 août 1906 et c'est l'un des plus anciens ponts à structure métallique de Lettonie, un monument d'ingénierie.</h5><p> </p><p>En 1908, une publication intitulée "Drehbrücke über den großen Hafenkanal in Libau" a été publiée dans la revue de littérature technique allemande "Zeitschrift des vereines deutscher Ingenieure", qui est la seule source authentique sur la construction du pont, les charges calculées et le fonctionnement des mécanismes de coupe.</p><p>Au cours de ses 117 années d'existence, le pont a survécu à deux guerres et à différents propriétaires, ce qui a affecté son fonctionnement. Pendant la Première Guerre mondiale, le pont a explosé, mais après la guerre, il a été restauré, mais déjà en 1926, il a été à nouveau endommagé par le bateau à vapeur "Narne". Le pont a été reconstruit à nouveau, mais il a également été endommagé pendant la Seconde Guerre mondiale, lorsque l'armée soviétique a bombardé le port de Liepāja.</p><p> </p><h5>Le pont pèse 300 tonnes et se compose de deux parties (côtés nord et sud) constituées de deux porte-à-faux identiques. La largeur de la chaussée du pont est de 7,3 mètres, dont le tablier est constitué de planches de bois. La longueur de la console côtière est de 27,55 mètres et la longueur du canal est de 38,95 mètres. La longueur totale du pont est de 133 mètres avec une portée de 27,55 mètres + 77,9 mètres + 27,55 mètres. La hauteur du pont au-dessus du niveau de l'eau est de 8,32 mètres.</h5><p> </p><p>L'ingénieur allemand Harald Hall a conçu le pont de manière à ce qu'il soit sûr et puisse fonctionner même par vent fort. Chaque partie du pont pouvant être découpée repose sur un point d'appui - l'appui et aligne précisément la pente, qui est assurée par des poids en béton.</p><p>Le pont Oskar Kalpak étant un bâtiment doté d'un patrimoine culturel et historique, lors de toute réparation, il doit être conservé exactement dans la même forme dont a hérité le port de Liepāja aujourd'hui.</p><br/>
