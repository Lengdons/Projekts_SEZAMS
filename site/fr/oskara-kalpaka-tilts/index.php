<div class="col"><h1 class="block-title mb-5">Le pont peut être ouvert au trafic maritime<span></span></h1><div class="col-12 output"><h6><strong>de 01h00 à 05h00</strong></h6><h6><strong>de 10h30 à 12h00</strong></h6><h6><strong>de 14h30 à 15h30</strong></h6><h6><strong>de 19h30 à 21h00</strong></h6><p> </p><h6>Le pont ne sera pas coupé aux heures spécifiées s'il n'y a pas de trafic maritime prévu ou si cela ne peut être fait en raison des conditions météorologiques.</h6></div>
