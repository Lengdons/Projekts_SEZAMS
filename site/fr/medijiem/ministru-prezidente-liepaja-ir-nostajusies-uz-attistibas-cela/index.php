<h1 class="article-title">Premier ministre : Liepāja est sur la voie du développement</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Liepāja s'est engagée sur une voie de développement stable, qui doit être poursuivie en soutenant les projets des investisseurs, en réduisant les exigences bureaucratiques, en renforçant l'éducation compétitive et en soutenant les plans des Forces armées nationales (NBS) visant à développer le port militaire de Liepāja Karosta. C'est ce qu'a souligné le Premier ministre Evika Siliņa, qui s'est rendu à Liepāja vendredi 5 avril, lors d'une visite régionale.</p><p>« Liepāja est à la fois un centre de culture et de tourisme et un centre de production. La ville se prépare à devenir la capitale européenne de la culture en 2027 et de nouvelles entreprises manufacturières y ont vu le jour très rapidement ces dernières années. Il est important que l'infrastructure de la ville continue à se développer, où les investissements appropriés provenant des fonds de l'Union européenne et d'autres sources financières jouent un rôle majeur, ainsi que la réduction des exigences bureaucratiques. C'est pourquoi nous félicitons que l'Université de Liepāja vient de rejoindre l'Université technique de Riga afin de renforcer la spécialisation en sciences et technologies de l'ingénieur pour les besoins du développement de l'industrie de la ville et de la région", souligne E. Siliņa.</p><p>Le Premier ministre a visité l'entreprise « AE Partner », spécialisée dans la production de systèmes d'automatisation et de panneaux de commande électriques de haute qualité ; le terminal d'exportation d'eau potable nouvellement construit de SIA « Eipu » ; "Global Wolf Motors" SIA, fabricant de scooters militaires "Mosphera". Il y a également eu une discussion sur les principaux défis et plans de développement des entrepreneurs de Liepāja.</p></div>
