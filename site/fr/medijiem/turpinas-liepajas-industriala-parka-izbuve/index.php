<h1 class="article-title">La construction du parc industriel de Liepāja se poursuit</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Du 8 au 14 avril, la circulation dans la rue Brīvības en direction du centre-ville sera déviée sur une seule voie, ce qui est lié aux travaux de construction du projet « Construction d'infrastructures routières sur le territoire de l'ancienne usine « Liepājas metalurgs », phase 1 ». <br/><br/>Après la pause technologique de la période hivernale, la construction des rues et des communications techniques dans le futur parc industriel de Liepāja se poursuit activement. </p><ul><li>La construction du tronçon de la rue Čuguna et de l'intersection réglable se poursuit, qui sera une nouvelle entrée de la rue Brīvības avec toutes les infrastructures et commodités nécessaires sur une longueur de 120 m.</li><li>Les travaux de construction pour l'extension de la rue Martena (400 m) ont commencé.</li><li>Un projet de construction a été développé et un processus de passation de marchés a été annoncé pour réaliser les travaux de construction visant à démanteler la base de fioul, à nettoyer la zone contaminée et à construire une connexion de 400 m de long avec la rue Eksporta.</li></ul><p>Le parc industriel de Liepāja est développé par l'administration de la ZES de Liepāja et la municipalité de la ville d'État de Liepāja dans la zone de l'ancienne usine « Liepājas Metalurgs » entre la rue Brīvības, la rue Meldru, la rue Ezermalas, la rue Parka et la rue Zemnieku à Liepāja. Il borde le lac Liepāja, qui est une zone naturelle spécialement protégée NATURA 2000. Selon la stratégie de développement approuvée, il est prévu d'attirer des investissements privés de plus de 275 millions. EUR et créer au moins 1 500 nouveaux emplois. </p></div>
