<h1 class="article-title">"Liepāja a une longueur d'avance" - a admis le ministre de l'Economie Viktors Valainis lors de sa visite</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Aujourd'hui 17 mai, le ministre de l'Économie Viktors Valainis s'est rendu à Liepāja pour une visite de travail d'une journée. Le développement du secteur énergétique, de l'industrie manufacturière, des emplois bien rémunérés et qualifiés, des investissements dans le transport de marchandises et le développement des exportations, du logement et d'un certain nombre d'autres questions importantes de développement économique ont été discutés avec la direction de la ville-état de Liepāja et de la zone économique spéciale de Liepāja.</p><p>"Liepāja a déjà une longueur d'avance et s'efforce résolument d'atteindre les objectifs fixés par l'État dans le domaine du développement économique, en doublant l'économie d'ici 10 ans, en créant une nouvelle approche du secteur de l'énergie, en développant les parcs éoliens offshore et la production d'hydrogène, en promouvant la productivité et la production à haute valeur ajoutée", a reconnu le ministre de l'Économie Viktors Valainis.</p><p>Lors de la visite de travail à Liepāja, le ministre de l'Économie a fait connaissance avec des entreprises manufacturières, des parcs industriels, des terminaux d'exportation d'eau et des projets de développement dans le domaine de l'énergie. Le ministre a souligné que les projets du secteur énergétique pourraient assurer un développement économique plus rapide du pays, basé sur les technologies modernes, et Liepāja a une vision claire de la manière de développer à la fois la base d'énergie éolienne offshore et de progresser progressivement vers la production d'hydrogène et d'avions à hydrogène.</p><p>Le ministre de l'Économie a également salué la gestion de la ZES de Liepāja, qui a contribué à attirer des investissements, à la construction de nouvelles usines et à la création de nouveaux emplois qualifiés. "Aujourd'hui, lorsque nous discutons à nouveau de la réforme de la gestion des activités portuaires et de transit, nous constatons que le modèle de Liepāja fonctionne. Les entrepreneurs, avec la municipalité et l'État, s'assoient à la même table et réfléchissent à la manière de mieux développer la zone économique et d'attirer les investissements. Les autres ports pourraient également aspirer à un tel modèle de gestion. Je suis heureux de ce que j'ai vu aujourd'hui à Liepāja, des ambitions des entrepreneurs de doubler les volumes de production, des projets de développement lancés d'une valeur de plusieurs dizaines de millions. Nous ferons tout pour soutenir entrepreneurs."</p></div>
