</div>
<a aria-label="Lire la suite" class="mb-3 news_link d-none d-md-block" href="/site/fr/medijiem/paraksta-vienosanos-par-finansejuma-pieskirsanu-infrastrukturas-izbuvei/index.php">Lire la suite</a>
