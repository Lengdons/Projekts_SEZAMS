<div class="col-12 col-md-4 description">
<p>L'administration de la ZES de Liepāja a conclu un accord avec l'Agence centrale des finances et des contrats sur le financement du mécanisme de redressement et de résilience d'un montant de 10 millions. d'un montant d'EUR pour la mise en œuvre du projet « 1er cycle de développement des infrastructures du parc industriel de Liepāja ». Dans le cadre du projet, il est prévu de construire des réseaux d'approvisionnement en électricité et trois tronçons de rues avec des communications techniques (adduction d'eau, assainissement domestique, assainissement des eaux pluviales, réseaux d'approvisionnement en chaleur) sur une vaste zone. Cela permettra l'ouverture partielle de la zone fermée de l'usine à l'accès du public et créera une opportunité d'attirer les premiers investisseurs. </p>
