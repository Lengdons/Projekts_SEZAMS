<h1 class="article-title">La stabilité de l'exploitation du port de Liepāja est assurée par la variété des types de marchandises</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Au cours des quatre mois de 2024, les entreprises de manutention du port de Liepāja ont traité 2,54 millions de tonnes. tonnes de marchandises diverses, ce qui équivaut à 4 mois de 2023. La stabilité du fonctionnement du port est assurée par la variété des types de marchandises et l'accent déjà traditionnel mis sur les marchandises d'origine locale. Au cours des 4 mois de cette année, 479 navires ont été entretenus, 24 691 passagers ont été transportés, tandis que le nombre d'unités roulières automotrices/sans moteur transportées par ferry était de 31 945 et celui des unités de conteneurs de 1 967.</p><p>Le volume de marchandises d'origine locale dans le port de Liepāja représente plus de 50 %. La tourbe obtenue en Lettonie, à Kurzeme, s'ajoute aux céréales et produits céréaliers, au bois, aux copeaux de bois, au ciment, ainsi qu'au volume de marchandises transportées sur la ligne de ferry, fournies par les entreprises industrielles nationales, au cours des mois de printemps. L'entreprise de manutention portuaire de Liepāja "Mols L" coopère avec succès depuis la quatrième année avec SIA BaltBio, dont l'activité principale est l'extraction et le transport de tourbe.</p><p>La tourbe est exportée depuis le port de Liepāja vers plusieurs pays européens comme l’Allemagne, le Danemark et d’autres. En moyenne, 4 à 5 navires, soit moins de 3 000, sont chargés chaque printemps dans le port de Liepāja. tonnes chacun. C'est suffisant pour que les pays européens plantent des tomates et des concombres, souligne Matīss Kozlovs, membre du conseil d'administration de SIA "BaltBio". "Il est avantageux pour l'entreprise d'exporter la tourbe depuis le port, plus proche du site d'extraction, et "Mols L" travaille de manière rapide et efficace." Depuis plus de 30 ans, "Mols L" travaille de manière stable dans le port d'hiver du port de Liepāja et traite principalement divers types de marchandises d'origine locale.</p><p>Le fret en vrac reste le plus grand groupe de marchandises dans le port de Liepāja et représente 67 % de toutes les marchandises. Le deuxième plus grand groupe de fret est le fret général, avec 30% ou 759,2 milliers de tonnes au cours des quatre mois de cette année. Le plus grand volume de marchandises dans le segment des marchandises diverses est assuré par le transport sur la ligne de ferry Liepāja-Travemunde. Cette année, la quantité de marchandises transportées sur la ligne de ferry est de 608.545,25 tonnes ou 31.945 unités et représente une augmentation de +15,63%. Āris Ozoliņš, président du conseil d'administration de la société de capitaux "Terrabalt" de la ZES de Liepāja, est succinct : "Nous devons travailler ! Nous avons des risques et des flux de marchandises diversifiés. Il y a des charges."</p><p>Les marchandises en vrac constituent le groupe de marchandises relativement le plus petit et ne représentent que 3 % de toutes les marchandises, soit 81 200. une tonne.</p></div>
