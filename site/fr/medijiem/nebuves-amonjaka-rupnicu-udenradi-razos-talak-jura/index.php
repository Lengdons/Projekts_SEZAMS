<h1 class="article-title">Aucune usine d’ammoniac ne sera construite, l’hydrogène sera produit plus loin dans la mer</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Lors de la réunion de travail, le directeur de « CIS Liepāja » Tors Arne Pedersen a annoncé qu'en accord avec la direction de la ZES de Liepāja, l'emplacement possible de l'usine de production d'hydrogène prévue a été modifié - plus au nord dans la zone portuaire et qu'en raison de l'évolution du marché et de la demande, « CIS Liepāja » a abandonné le développement du projet de production d'ammoniac vert. </p><p>Tor Arne Pedersen a souligné que la sécurité passe avant tout. "Depuis le début du développement du projet, nous recherchons les meilleurs emplacements et solutions technologiques pour l'usine et le terminal de production d'hydrogène vert. La sécurité est quelque chose que nous prenons très au sérieux et nous sommes pleinement conscients qu'elle est d'une importance cruciale pour le projet. Pour cette raison, nous avons également examiné de plus près diverses solutions, comment nous pouvons résoudre la sécurité de la meilleure façon possible. Ceci est important pour nous en tant que développeurs de projets, tant pour la municipalité que pour l'administration de la ZES de Liepāja".</p><p>Au cours de la réunion de travail, le directeur de "CIS Liepāja" Tors Arne Pedersens a présenté une fois de plus l'idée du projet, son avancement, les actionnaires de l'entreprise et l'expérience dans le développement et l'avancement de divers projets. En réponse à la question de savoir pourquoi Liepāja, Tor Arne Pedersens a admis qu'ils ont d'abord étudié tous les pays nordiques - la Norvège, la Suède, la Finlande, où le principal obstacle était le déficit des réseaux électriques à haute tension, puis ils se sont tournés vers les pays baltes. Les recommandations de l'ambassade de Norvège en Lettonie et l'environnement commercial de haute qualité à Liepāja, ainsi que la zone économique spéciale de Liepāja et ses avantages, ont joué un rôle important. À l'heure actuelle, des recherches ont été lancées et une évaluation des risques et de l'impact environnemental est en cours. </p><p>Afin de se familiariser avec l'avancement des projets d'industrie durable sur le territoire de la zone économique spéciale de Liepāja, la direction de la ZES de Liepāja et le conseil municipal, les membres de la municipalité, les promoteurs de projets d'investissement, la direction du Service national de l'environnement et les représentants des organisations environnementales se sont réunis pour une réunion de travail commune.</p><p> </p></div>
