<h2>Dans le cadre d'un projet cinématographique international, le pont O. Kalpak sera fermé à la circulation pendant trois jours</h2>
<span class="mb-3">16.10.2026.</span>
</div>
<a aria-label="Lire la suite" class="mb-3 news_link d-none d-md-block" href="/site/fr/medijiem/tris-dienas-satiksmei-bus-slegts-okalpaka-tilts-starptautiska-kino-projekta-ietvaros/index.php">Lire la suite</a>
