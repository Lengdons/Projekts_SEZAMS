<h1 class="article-title">Le troisième cycle du projet de réhabilitation environnementale du canal Karosta touche à sa fin</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Le projet est financé dans le cadre du programme d'instrument financier norvégien 2014-2021 « Atténuation du changement climatique, adaptation à celui-ci et à l'environnement » et un total de 145 199 mètres cubes de sédiments historiquement contaminés contenant environ 298 tonnes de produits chimiques dangereux ont été éliminés. Il s'agissait du troisième cycle du projet de réhabilitation du canal Karosta.</p><p>Les travaux du canal de Karosta ont été réalisés par la SIA "Eko osta", conformément au contrat conclu et au programme de réhabilitation du canal de Karosta approuvé. Les travaux de réhabilitation du canal Karosta ont débuté en avril 2023, mais se sont terminés le 5 décembre 2023. Le montant total du marché s'élevait à 3.334.877,50 euros, hors taxe sur la valeur ajoutée.</p><p>Gunārs Ansiņš, président du conseil municipal de Liepāja, a souligné l'importance du travail effectué, car Liepāja a obtenu le point chaud HELCOM en 1992 en raison de la pollution du canal Karosta. "C'était une situation très compliquée lorsque, dans un petit canal, nous avions à la fois un héritage militaire soviétique, des navires et des sous-marins coulés, et plus de 100 éléments différents du tableau de Mendeleïev. Cela signifiait que nous, en tant que Lettonie, Liepāja et la région de la mer Baltique, devions nettoyer progressivement le canal, ce que nous faisons étape par étape."</p><p>Uldis Hmieļevskis, directeur de la ZES de Liepāja, déclare que le port incl. Le canal Karosta fait partie intégrante de la ZES de Liepāja et doit donc être entretenu, y compris l'héritage de l'époque soviétique. "Pour pouvoir développer le transport maritime, afin que de nouveaux terminaux puissent être construits dans le port, nous devons nettoyer le canal, et cela a été fait. Beaucoup de travail a été fait."</p><p>Avec l'aide d'un instrument financier norvégien, l'administration de la zone économique spéciale de Liepāja a mis en œuvre le troisième cycle de réhabilitation du canal de Karosta afin de réaliser un investissement sérieux dans l'atténuation des risques de changement climatique et de propagation de la pollution historique dans la mer Baltique et l'environnement environnant. Le chef de projet, Ivo Kolinņš, souligne que les travaux se poursuivront et que les actions futures à court et à long terme sont claires, afin de minimiser la pollution historique et son impact sur l'ensemble de l'écosystème de la mer Baltique.</p><p>Aujourd'hui, le territoire de Karosta devient une partie socio-économique et domestique de plus en plus importante de Liepāja, c'est pourquoi les travaux de nettoyage du canal réalisés avec l'aide du projet permettront aux résidents locaux et aux touristes de profiter des valeurs de Karosta dans un environnement plus propre et de meilleure qualité, favorisant la restauration de ses écosystèmes aquatiques et la réduction de la pollution.</p></div>
