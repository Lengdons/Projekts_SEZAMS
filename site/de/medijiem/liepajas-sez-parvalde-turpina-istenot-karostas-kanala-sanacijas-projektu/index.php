<h1 class="article-title">Liepaja SEZ Authority setzt Karosta Canal Recovery-Projekt fort</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>19. dieses Jahres. Bei Luftfahrzeugen mit einer Masse von mehr als 250 kg oder weniger stellt der Luftfahrtunternehmer sicher, dass das Luftfahrzeug die Anforderungen des Anhangs II erfüllt. Am September trafen sich Experten der Liepaja Special Economic Zone Authority und des Vereins Baltic Coasts mit Projektpartnern - Norwegian Water Research Institute Vertreter im Rahmen des Erfahrungsaustausches in Oslo. NFI/AK/02.Historisch kontaminierte Standorte im Rahmen von Sanierungsarbeiten des Karosta-Kanals des Hafens Liepaja.</p><p>Die Aufgabe des Erfahrungsaustausches besteht darin, neben dem erfolgreichen kontrollierten Ansatz zur Wiederherstellung der natürlichen Karosta-Kanalumgebung auch Erfahrungen zu sammeln oder selbstreinigende Prozesse nach Sanierungsarbeiten des Karastas-Kanals für dieses Projekt geplant. Der Selbstreinigungsansatz soll laufende natürliche Bioabbauprozesse anwenden, die die Bioverfügbarkeit oder Toxizität von Schadstoffen im Sediment verringern.</p><p><strong>Wir arbeiten zusammen für ein grünes Europa!</strong></p></div>
