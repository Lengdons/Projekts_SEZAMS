<h1 class="article-title">Management der Europäischen Bank für Wiederaufbau und Entwicklung lernt Liepaja Projekte für nachhaltige Industrie kennen</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>11. Im Mai in London präsentierten Jānis Lapiņš, Beraterin von Liepaja SEZ-Manager für Projekte im Bereich erneuerbare Energien, zusammen mit dem Liepaja Centre for Sustainable Industry Unternehmen das Management der Europäischen Bank for Reconstruction and Development (EBRD) mit geplanten Projekten in Liepaja. Während des Arbeitstreffens wurde das separate Projekt im Detail diskutiert - LSEZ Ltd. NorSAF, CIS Liepaja und das internationale Konsortium der niederländischen Firma Van Ord sowie belgische Unternehmen Euroports und Smulders, geplante Finanzierungsmodelle und mögliche Zusammenarbeit mit der EBWE. </p><p>Der Berater des Managers Jānis Lapiņš informierte über die Entwicklung von Liepaja- und Liepaja SEZ-Projekten und erläuterte die Voraussetzungen und Grundlagen für die Gründung des Liepaja Sustainable Industry Centre sowie das Projekt Liepaja Industrial Park. Die Veranstaltung wurde in Zusammenarbeit mit der EBWE , der LIAA und der Botschaft Lettlands in Großbritannien organisiert. Auch der Botschafter Lettlands im Vereinigten Königreich Atis Lots nahm an dem Treffen teil.</p><p>Liepaja hat klar nachhaltiges Denken in seinen Entwicklungscode aufgenommen und die Grundprinzipien Bildung, Wissenschaft, Innovation und Kreislaufwirtschaft eindeutig gewählt. Die Konzentration solcher Privatunternehmer in Liepaja eröffnet beispiellose Möglichkeiten, das Wohlbefinden jedes Kunden und jeder Stadt durch die Entwicklung neuer exportorientierter Industrien zu entwickeln und zu steigern. Sie werden einen wesentlichen Beitrag zum Bruttoinlandsprodukt Lettlands leisten und es natürlich ermöglichen, die Liepaja-Wirtschaftskapazität und die Möglichkeiten für ein besseres Leben deutlich zu erhöhen.</p><p> </p><p><strong>Zur Bezugnahme</strong></p><p>Die Europäische Bank für Wiederaufbau und Entwicklung (EBRD) ist eine internationale Finanzinstitution, die den Übergang zu einer offenen Marktwirtschaft erleichtert und dabei insbesondere auf die Förderung nachhaltiger Energie- und industrieller Entwicklung durch die Unterstützung kohlenstoffarmer, ressourceneffizienter und innovativer Lösungen setzt. Die EBWE bietet finanzielle Investitionen, Beratungsleistungen und Unterstützung für politische Reformen, vor allem im privaten Sektor sowie einzelne öffentliche Projekte in den Bereichen Infrastruktur, Produktion, Energie und Handel. Die Tätigkeit der Bank basiert auf einem einzigartigen politischen Mandat und wird nur Ländern gewährt, die die Grundsätze Demokratie, Pluralismus und Marktwirtschaft durch Kredite, Beteiligungsinvestitionen und Garantien für eine nachhaltige industrielle Transformation und Energiewende respektieren.</p></div>
