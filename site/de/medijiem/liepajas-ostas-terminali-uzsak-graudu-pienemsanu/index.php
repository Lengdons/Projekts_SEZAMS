<h1 class="article-title">Hafen von Liepaja Terminals beginnen Korn zu erhalten</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>22. Am Juli nahm die LSEZ Ltd. - Dan Storea Termināls das erste Weizenkorn an, das in Lettland angebaut und angebaut wurde. Das ist der Beweis, dass die neue Getreidesaison begonnen hat. Insgesamt sind fünf trockene Schüttgutterminals im Hafen von Liepaja mit einer Gesamtspeicherkapazität von ~ 400mila m aktiv.<sup>3</sup>.</p><p>Wie Evita Dambe, Terminal- und Logistikmanagerin von LSEZ Ltd. - "Dan Store" bestätigt hat, wurde heute morgen die erste Weizenfracht angenommen, was bedeutet, dass die Bauern angefangen haben, Getreide zu wachsen und Getreide in den Hafen zu nehmen. Die Getreideaufnahme dauerte den ganzen Tag an.</p><p>Das größte Trockengut-Terminal LSEZ Ltd., Liepaja Bulk Terminals, setzt die Vorbereitung auf die neue Getreidesaison durch Organisation und Verbesserung der Infrastruktur fort, während Gerstenfrachten in Lagerhäusern im Gebiet Liepaja SEZ, Brivibas Street, akzeptiert werden. Juris Matvejevs, Head of LSEZ Ltd., Liepaja Bulk Terminals, räumt ein, dass dieses Jahr alles etwas schneller ist, aber es ist zu früh, um Vorhersagen über die Qualität und den Ertrag von Getreide auszudrücken. Juris Matvejs gab auch zu, dass das Getreide im August in Lagern gelagert werden wird, aber die aktivste Exportzeit wird im September beginnen, wenn Qualität, Preis und Verträge festgelegt werden.</p><p>Traditionell gilt der Beginn der neuen Getreidesaison als 1. August.</p></div>
