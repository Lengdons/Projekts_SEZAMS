<h1 class="article-title">Die Saeima billigt Änderungen des Gesetzes über die Anwendung von Steuern in freien Häfen und besonderen Wirtschaftszonen.</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Das genehmigte Gesetz der Saeima über die Anwendung von Steuern in freien Häfen und Sonderwirtschaftszonen hat eine Reihe von Bedingungen aufgenommen, die künftig Liepāja SEZ-Kapitalgesellschaften fördern, neue Investoren anziehen und den Wettbewerb mit anderen besonderen Wirtschaftszonen im Ostseeraum verringern könnten.</p><p>Wichtigste Änderungen:</p><p>· Verlängerung der Frist für die Berechnung der erwarteten Lohnkosten auf den 31. Dezember 2035 (bis zum 31. Dezember 2024). Dies wird es Liepāja ermöglichen, weiterhin qualifizierte und gut bezahlte Arbeitskräfte anzuziehen.</p><p>· Um zu bestimmen, dass in Zukunft auch Sachanlagen für den Kauf in finanziellen Mietverträgen zur Verfügung stehen.</p><p>· Die Schiffbauindustrie und synthetische Fasern werden in Zukunft nach dem Gesetz gefördert.</p><p>Liepāja SEZ Law erklärt, dass LiepajaSEZ mit dem Ziel gegründet wird, Handel, Industrie, Schifffahrt und Luftverkehr sowie internationalen Warenaustausch über Lettland zu entwickeln und zu fördern. Ihre Aufgabe ist es, Investitionen in Produktion und Infrastruktur zu gewinnen und neue Arbeitsplätze in Liepāja zu schaffen. Liepāja SEZ muss die Entwicklung der Region Liepāja fördern.</p><p><strong>In der Zeit von der Gründung der Spezialwirtschaftszone Liepāja im Jahr 1997 bis 2023 haben die Kapitalgesellschaften von Liepāja SEZ rund 403 Millionen investiert. Davon EUR Moderne Technologien.</strong></p><p>Im Jahr 2023 haben Liepāja Special Economic Zone Authority und Liepāja SEZ Unternehmen 15 Vereinbarungen über die Durchführung von Investitionen geschlossen, deren Investitionssumme insgesamt 5 481 903,28 EUR beträgt.</p><p>2024. Liepāja SEZ Vorstand genehmigt 5 Investitionsvorhaben für den geplanten Gesamtbetrag der Investitionen 4,390 Mio. EUR</p><p> </p></div>
