<h1 class="article-title">Der Hafen von Liepāja beendet erfolgreich die Tests von Robotern auf dem Wasser</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Mit Unterstützung von Liepāja SEZ Authority und Port Captain 12. und 13. Im Juni hat das lettische Unternehmen "Aerone" seine Arbeit erfolgreich durchgeführt, um ein spezielles Robotergerät zu testen, das die Erdung von Windgeneratoren auf dem Wasser steuern soll, bevor es in der Nordsee arbeitet. Uldis Hmielevskis, Leiterin von Liepāja SEZ, weist darauf hin, dass dies ein großartiges Beispiel dafür ist, dass die Windenergieindustrie den lettischen Wissenschaftlern, Herstellern und Dienstleistern Möglichkeiten bietet, neue Technologien, Dienstleistungen zu entwickeln, sowohl beim Bau von Windparks als auch bei der Wartung neue Arbeitsplätze zu schaffen.</p><p>"Aerones" ist ein neues und schnell wachsendes Unternehmen, das weltweit Windkraftanlagenwartung mit Robotern betreibt. Nach Angaben des führenden Ingenieurs Egils Gēcis wurden sowohl Technologie als auch Software und Roboter in Lettland geschaffen, die für das lokale Engineering-Team arbeiten. Die Nachfrage nach Solar- und Windpark Wartung steigt, so dass sich das Unternehmen schnell entwickeln kann, ständig auf der Suche nach neuen Mitarbeitern. Aerones ist in 25 Ländern tätig - 45 Teams, jeweils mit einer Reihe von Robotern.</p><p>Bis jetzt arbeiteten die Aerones an Land, aber nun entschieden sie sich, ihre Energien auf dem Wasser zu probieren, während sie Offshore-Windenergieanlagen bedienen. Im Hafen von Liepāja wurden Tests mit intelligenten Geräten durchgeführt, die Menschen in sehr gefährlicher Arbeit ersetzen. Der geräumige Liegeplatz des Hafens von Liepāja war für die Erprobung neuer Roboter und Technologie geeignet.</p><p>Egils Geecis, ein führender Ingenieur in Aerone, weist darauf hin, dass es immer mehr Turbinen auf der Welt gibt und es nicht leicht ist, Menschen zu finden, die ihnen dienen. Hier kommen Roboter, um zu helfen. Der Hafen hat eine der vielen "Unternehmen," die das Unternehmen zu diesem Zweck entwickelt. Die Verwaltung der Liepāja SEZ Authority und des Hafens gab uns die Möglichkeit, unsere Technik zu testen, zu überprüfen, wie sie für die Arbeit an Wasser geeignet ist. Wir haben ein Ankersystem, sie müssen mit Hilfe eines Schiffes platziert werden, durch das wir Seile ziehen können, dank dem Sie den Roboter steuern können. Heute haben wir den ganzen Tag getestet, alles war sehr gut. Als nächstes gehen wir nach Schottland."<br/>Windkraftanlagen sowohl auf Land als auch auf See zu halten ist nicht einfach. Sie müssen überprüft, gereinigt und regelmäßig korrigiert werden. Die Leute tun es in der Regel, aber es ist sehr gefährlich, also entwerfen wir Roboter und verwenden sie. "Es ist einzigartig, dass wir das alles mit Robotern machen und sie fernsteuern. Es ist schneller, effizienter und es besteht kein Risiko für Menschen," sagte Egils Gecis.</p></div>
