<div class="col"><h1 class="block-title mb-5">Brücke kann für den Versand geöffnet werden<span></span></h1><div class="col-12 output"><h6><strong>von 01:00 bis 05:00</strong></h6><h6><strong>von 10:30 bis 12:00 Uhr</strong></h6><h6><strong>von 14:30 bis 15:30 Uhr</strong></h6><h6><strong>von 19:30 bis 21:00 Uhr</strong></h6><p> </p><h6>Die Brücke wird nicht zu bestimmten Zeiten abgeschnitten, es sei denn, es gibt einen Linienschifffahrtsdienst oder wegen der Wetterbedingungen.</h6></div>
