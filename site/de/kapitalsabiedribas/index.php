      return;
    }

    const metrics = analyzeLogoLuminance(imgEl, partnerId);
    const darknessFromLum = Math.max(0, Math.min(1, (165 - metrics.avgLum) / 130));
    const darknessScore = Math.max(darknessFromLum, Math.min(1, metrics.darkRatio * 1.15));

    if (darknessScore > 0.25) {
