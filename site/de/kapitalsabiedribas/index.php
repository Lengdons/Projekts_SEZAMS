    if (!isDragging) return;
    const dx = e.clientX - dragStartX;
    if (Math.abs(dx) > 5) dragMoved = true;
    scrollX = dragScrollStart - dx;
  });

  window.addEventListener("mouseup", function () {
    isDragging = false;
  });

  viewport.addEventListener("wheel", function (e) {
    if (Math.abs(e.deltaX) > Math.abs(e.deltaY) || e.shiftKey) {
      e.preventDefault();
      scrollX += (e.deltaX || e.deltaY) * 0.85;
    }
  }, { passive: false });

  function animateWheel() {
    if (!isDragging) {
      const currentSpeed = activePartnerId ? 0.14 : (isHovering ? 0.22 : speed);
      scrollX += currentSpeed;
    }

    if (scrollX >= TOTAL_WIDTH) scrollX -= TOTAL_WIDTH;
    if (scrollX < 0) scrollX += TOTAL_WIDTH;

    track.style.transform = "translate3d(" + (-scrollX) + "px, 0, 0)";

    const vpWidth = viewport.clientWidth;
    const halfVp = vpWidth / 2;
    const fadeZone = Math.min(220, Math.max(130, vpWidth * 0.15));
    const clearHalfSpan = Math.max(100, halfVp - fadeZone);

    for (let i = 0; i < wheelItems.length; i++) {
      const item = wheelItems[i];
      const itemCenter = item.baseX - scrollX + (HEX_W / 2);

      if (itemCenter < -220 || itemCenter > vpWidth + 220) {
        continue;
      }

      const distFromCenter = Math.abs(itemCenter - halfVp);
      if (distFromCenter <= clearHalfSpan) {
        item.el.style.opacity = "1";
        item.el.style.transform = "scale(1)";
        if (!item.el.classList.contains("active-hex")) {
          item.el.style.filter = "drop-shadow(0 8px 18px rgba(0, 28, 67, 0.08))";
        }
      } else {
        const edgeProgress = Math.min(1, (distFromCenter - clearHalfSpan) / fadeZone);
        const smoothEdge = edgeProgress * edgeProgress;
        const scale = 1 - (smoothEdge * 0.14);
        const opacity = Math.max(0.04, 1 - (smoothEdge * 0.94));
        const blurPx = (smoothEdge * 6.5).toFixed(1);

        item.el.style.opacity = opacity.toFixed(2);
        item.el.style.transform = "scale(" + scale.toFixed(3) + ")";
        if (!item.el.classList.contains("active-hex")) {
          item.el.style.filter = "blur(" + blurPx + "px) drop-shadow(0 8px 18px rgba(0, 28, 67, 0.06))";
        }
      }
    }

    requestAnimationFrame(animateWheel);
  }

  requestAnimationFrame(animateWheel);
