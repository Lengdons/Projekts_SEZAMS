<h1 class="article-title">Annahme durch den Rat "Liepāja SEZ" am 22. April.</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>22. April 2024 Die Vorstandssitzung der Special Economic Zone Liepāja (Liepāja SEZ) fand statt, in der fünf Fragen im Zusammenhang mit Abschluss, Klärung und Verpfand von Immobilienverträgen geprüft und unterstützt wurden.</p><p><br/><strong>Zum Abschluss der langfristigen Grundstücksverpachtung</strong><br/>Basierend auf 23. Januar 2024 Kaufvertrag für das Lagergebäude in der SpīÃ¤ra Straße 15/17In Liepāja hat der Vorstand von Liepāja SEZ den Mietvertrag mit dem früheren Eigentümer des Gebäudes und den Abschluss eines neuen Grundstücksmietvertrags mit dem neuen Eigentümer beendet. Immobilien SpīÃ¤ri Straße 15/17, Liepāja befindet sich im Gebiet des Hafens von Liepāja und ist der Grundmietvertrag für Gebäudemanagement notwendig.</p><p><br/><strong>Änderungen des Vertrags über die Gewährung von Baurechten</strong>.<br/>2022 19. Mai Im Januar hat zwischen der Liepāja SEZ Authority und der SIA EIPU eine Vereinbarung über die Erteilung von Baurechten für Immobilien im Gebiet des Hafens von Liepāja in der Oskara Kalpaka Street 117, Liepāja, geschlossen. Nach der Messung des Grundstücksteils wurde die Baufläche spezifiziert. Der Vorstand der Liepāja SEZ hat beschlossen, das Abkommen über die Erteilung von Baurechten an Land in der Oskara Kalpaka Street 117, Liepāja, zu klären.</p><p><br/><strong>Bei Reservierung von Grundmieten und/oder Baurechten</strong><br/>Der Vorstand von Liepāja SEZ hat eine Vereinbarung über die Reservierung der Grundstücksmiete und/oder Baurechte mit der SIA "GI Termināls" für 2 Jahre über die Entwicklung von Bauplänen für den Bau von Immobilien im Gebiet des Hafens von Liepaya in 8 Pulvera Street, Liepāja geschlossen.</p><p><br/><strong>Zum Abschluss der langfristigen Grundstücksverpachtung</strong><br/>Der Vorstand der Liepāja SEZ hat einen Mietvertrag mit der Joint Stock Company "Sadales tīkls" über Immobilien in Ostas iela 6/8, Liepāja für 30 Jahre abgeschlossen. Die Entscheidung ist notwendig, um den bestehenden 10 kV-Verteilpunkt am Boden zu verwalten und aufrechtzuerhalten.</p><p><br/><strong>Auf Zustimmung zur Verpflich tung des Baurechts</strong><br/>Liepāja SEZ Vorstand bewertet und vereinbart Baurechte, die gewährt wurden 29. Mai 2018 zwischen der Liepāja SEZ Authority und der Gesellschaft mit beschränkter Haftung "Cotton" Vereinbarung, zugesagt für den Ausbau der kommerziellen Aktivitäten. Immobilien in Pulvera Street 4Ein Bauprojekt wurde in Liepāja, Produktionsanlage aus Holzwollefasergewebe, durchgeführt.</p></div>
