<h1 class="article-title">Mitteilung über die Immobilienauktion bei Pulvera iela 29</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Liepāja SEZ Authority organisiert eine schriftliche Versteigerung von Mietrechten für Immobilien im Besitz der Verwaltung von Liepāja SEZ, Pulvera iela 29. </p><p>Ziel der Auktion ist es, den Mieter der Leasing-Einrichtung zu bestimmen, der das wirtschaftlich günstigste Angebot zur Errichtung von Leasingrechten anbietet und sich verpflichtet, im Rahmen der sanitären Gebühren für Schiffe, die gemäß Anhang I zu Marpol in den Hafen von Liepāja einreisen, übertragene Abfälle zu akzeptieren und eine angemessene Behandlung dieser Abfälle sicherzustellen. Regulierungsanforderungen.</p><p>Sie können die Ankündigung der Auktion in Liepāja SEZ Authority Website Beschaffung und Auktion Abschnitt kennen lernen: <a href="/site/de/iepirkumi-un-izsoles/pazinojums-par-nekustama-ipasuma-izsoli-pulvera-iela-29/index.php">https://liepaja-sez.lv/lv/iepirkumi-un-izsoles/pazinojums-par-nekustama-ipasuma-izsoli-pulvera-iela-29</a></p></div>
