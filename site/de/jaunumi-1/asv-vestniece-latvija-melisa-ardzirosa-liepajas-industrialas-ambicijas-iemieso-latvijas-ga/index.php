<h1 class="article-title">Botschafterin der Vereinigten Staaten in Lettland Melissa Argirosa, Liepajas industrielle Ambitionen verkörpern lettischen Geist.</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Es ist klar, dass Liepajas industrielle Ambitionen den Geist Lettlands verkörpern. 16. Im April lernte sie den Betrieb des Hafens von Liepāja und die besondere Wirtschaftszone kennen. Liepāja SEZ General Manager Uldis Hmielevskis stellte den Botschafter vor, um grüne Energie- und Industrieprojekte zu planen, die im Liepāja Sustainable Industry Centre zusammengeführt werden und einander ergänzen.</p><p>Eine davon ist direkt mit dem US-amerikanischen globalen Engineering-Unternehmen KBR verbunden, das NorSAFs Werk mit nachhaltigem Flugkraftstoff (SAF) und synthetischem Kraftstoff (eSAF) versorgen wird. Der Umsatz von KBR im vergangenen Jahr betrug 7,8 Milliarden Dollar und es spezialisiert sich sowohl auf High-Tech-Entwicklung und Implementierung, die Schaffung großer Fabriken verschiedener Technologien in vielen Teilen der Welt, aber zum ersten Mal in den Baltischen. Einschließlich KBR betreibt seit 60 Jahren und einem Jahr NASA-Aufträge für Weltraummissionen im Wert von Milliarden.</p><p>Jānis Kisiels, Mitglied des Vorstands der "NorSAF" LSEZ Ltd.: "Wir sind stolz darauf, mit einem so professionellen, erfahrenen und erfolgreichen Unternehmen wie KBR zusammen zu arbeiten, um das größte Hightech-Projekt über nachhaltige Flugkraftstoffe in den baltischen Ländern zu entwickeln und umzusetzen. Es ist auch spannend, die Arbeit von KBR täglich zu beobachten. Das Unternehmen ist ein wichtiger Partner der NASA, der mit technischer Expertise und operativer Unterstützung an Missionen wie Artemis-Programm und James Webb Space Telescope teilnimmt. Mit Hilfe dieser Technologien wird NorSAF die Energie- und regionale Sicherheit Lettlands und Europas stärken, indem eine nachhaltige Verfügbarkeit von Flugkraftstoff gewährleistet wird.</p><p>Das Liepāja SEZ Unternehmen NoRSAF entwickelt in der Special Economic Zone Liepāja Industriebetrieb für nachhaltigen Luftverkehr (SAF) und synthetische Brennstoffe (eSAF). Die Anlage soll innovative Technologien nutzen, die von KBRs zugelassen sind, sowie Rohstoffe , Bioethanol und grüner Wasserstoff, um die Produktion von Flugkraftstoffen der nächsten Generation im Einklang mit den Dekarbonisierungszielen der EU zu gewährleisten.</p></div>
