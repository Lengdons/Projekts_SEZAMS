<h1 class="article-title">Die SEB Bank stellt 2 Mio. EUR für den Bau der Produktionseinheit von LSEZ AS, Noorplast Piemare bereit.</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Finanzierung durch die SEB Bank 2 Mio. EUR für Liepāja Special Economic Zone Unternehmen √Norplast Piemare Verordnung AS neue Produktionsstätte für den Bau im Hafen von Liepāja. Der geplante Produktionsstandort wird fast 2000 Quadratmeter breit, und seine Konstruktion wird voraussichtlich bereits abgeschlossen sein 2024. Im Herbst . Es wird sehr große Verbundwerkstoffe produzieren, deren Produktion in Lettland nicht möglich war. Die Lage der Fabrik in unmittelbarer Nähe des Hafenplatzes wird logistische Vorteile bieten und den Transport von Schüttgut erleichtern.</p><p>Die norwegische Tochtergesellschaft der Gesellschaft "Entec Group" trat vor einigen Jahren in Liepāja ein, als ihre Aktien von der Firma "Entec Norplast" erworben wurden. Entec Noraplast" ist eine norwegische Kapitalgesellschaft mit Sitz in Lettland 2001. Im Jahr ist er auf die Herstellung von Glasfasern für Schiffssicherheitsausrüstung, Ölgewinnung, Transport, aktive Erholung, Abwasserbehandlung, Fischzucht und andere spezialisiert. Das Unternehmen verfügt bereits über eine Produktionsstätte in Saldus und seine Produkte werden weltweit exportiert. </p><p>Die SEB-Bank kooperiert seit langem mit Entec Norplast, der es geschafft hat, die Nische bei der Produktion von spezifischen sperrigen Produkten aus Verbundmaterialien zu erobern. Die neue Anlage wird zum Beispiel großflächige Fischbecken umfassen, deren Standort für den Transport wichtig ist. Wir freuen uns, dass wir den Ausbau der Produktion in Lettland unterstützen und mit international anerkannten und bewerteten Unternehmen zusammenarbeiten können, die in Lettland wachsen und sich entwickeln, sagte Arnis Škapars, Mitglied des Vorstands der SEB Bank.</p><p>Diese Anlage ist ein wichtiger Schritt in der strategischen Entwicklung unserer Unternehmen. Wir sind Wachstumsunternehmen, und das neue Objekt in Liepāja gibt uns die Möglichkeit zu wachsen, sowie eine einzigartige Gelegenheit, große Verbundstrukturen direkt an unsere Kunden aus dem Tiefwasser-Pier zu senden. Es ist eine Freude, dass unser Finanzpartner SEB Bank auch das Potenzial von Unternehmen in einem sehr spezifischen Tätigkeitsbereich geschätzt hat. Die Entwicklungsgeschichte von Entec Norplast und Noorplast Piemare wird mit noch größerer Kapazität in Lettland, jetzt zwei Produktionseinheiten in Saldus und Liepāja, weiterführen, sagt Māris Meija, CEO und Vorstandsvorsitzender der LSEZ Noorplast Piemare.</p></div>
