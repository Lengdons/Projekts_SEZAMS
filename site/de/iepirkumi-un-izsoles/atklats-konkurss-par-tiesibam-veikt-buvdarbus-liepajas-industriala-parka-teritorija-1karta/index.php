<div class="col"><div class="col-12 output"><p><strong>Beschaffungsnummer LSEZ2023/6/K</strong></p><p>&nbsp;</p><p><strong>Beschreibung des Gegenstands der Beschaffung:</strong></p><p>&nbsp;</p><p>Bauarbeiten auf dem Gebiet des Industrieparks Liepaja in der 2. Etappe ("N" Straßenabschnitt, "F" Straßenabschnitt und "C" Straßenabschnitt) - 2.1. Etappe (die Abschnitte der ehemaligen Fabrik von Liepaja Metallurgs) und nach SIA Energie von Liepaya Bau der ehemaligen Fabrik im Gebiet von Liepaja metallurgs, 2. Stufe ("N" Straßenabschnitt, "F" Straßenabschnitt und "C")), 2.1. Etappe (die Abschnitte des ehemaligen Werks "Liepāja metalurgs") (Anhang 10 der Verordnung), nachstehend "Technische Dokumentation des Projekts" genannt.</p><p>&nbsp;</p><p>Projekt 3.1.1.3.i.0/1/1/23/A/CFLA/004 Entwicklung des Industrieparks in Liepaja Die erste Stufe wird im Plan zur Sanierung und Resilienz der Europäischen Union 3.1.1.Reformen und Investitionsrichtung "Regionalpolitik" 3.1.3. Regionalentwicklung.</p><p>&nbsp;</p><p>&nbsp;</p><p><strong>CPV-Codes</strong></p><p>45233120-6 - Straßenbauarbeiten.</p><p>45231000-5 Bauarbeiten für Rohrleitungen, Kommunikation und Stromleitungen.</p><p>44163121-4 √ Heizungsleitungen.</p><p>34928400-2 - Stadtinfrastruktur.</p><p>34993000-4 √ Straßenbeleuchtung.</p><p>&nbsp;</p><p>&nbsp;</p><p><strong>Zeitpunkt und Ort der Vertragserfüllung</strong></p><p>&nbsp;</p><ol><li>Bei der Planung der Bauarbeiten muss der Auftragnehmer die Fertigstellung der Arbeiten 250 (zweihundertfünfzig) Tage nach Übergabe der Baustelle an den Bauherrn sicherstellen.</li><li>Baustelle: √N- und √F-ielas, Gebiet des Industrieparks Liepaja.</li></ol><p>&nbsp;</p><p><strong>Vergabeverfahren</strong></p><p>&nbsp;</p><ol><li>Das Vergabeverfahren wird nach dem öffentlichen Vergaberecht durchgeführt . Die Art des Vergabeverfahrens ist ein offenes Angebot.</li><li>Die Gründe für die Vergabe eines Auftragsvertrags ohne jede Aufteilung der Aufträge sind: eine Reihe von Bietern; eine Baustelle; eine Frist für die Ausführung von Werken auf der Website.</li></ol><p>&nbsp;</p><p>Die Eröffnung der Angebote erfolgt im Teilsystem EIS e-Wettbewerb <strong>16. November 2023 um 15.00 Uhr</strong>.</p><p>&nbsp;</p><p>Die Verordnungen mit Anhängen bieten direkten und kostenlosen elektronischen Zugang zum Kundenprofil des Kunden im elektronischen Beschaffungssystem (<a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>).</p></div>
