<h1 class="article-title">Liepāja SEZ Authority organisiert eine elektronische Auktion mit aufsteigendem Schritt für Immobilien bei Brīvības iela 98 (Auktion geschlossen)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><i><strong>Auf Immobilien Auktion Ergebnisse:</strong></i></p><p><i>11. September 2025 Immobilien von Liepāja Special Economic Zone Authority in der Brivibas Street organisiert ist geschlossen 98, in Liepāja, elektronische Auktion.</i></p><p><i>8. Oktober 2025 Der Verwaltungsrat der Sonderwirtschaftszone Liepāja hat eine Entscheidung Nr.104 Das Ergebnis der Auktion wird genehmigt 9. September 2025 Gesetz der Hofverwaltung Nr. 4184890/0/2025- die Annahme einer Auktion als nicht erfolgt.</i></p><p>____________________________________________</p><p>Liepāja Special Economic Zone Authority, einheitliche Registrierung Nr.LV90000329402, organisiert eine elektronische Auktion mit aufsteigendem Schritt für Immobilien in Brivibas Street 98, in Liepāja, Katasterbezeichnung 17000220152bestehend aus einem Gebäude, das vom Kataster bestimmt wird 17000220059027 und Grundstücke mit Gesamtfläche ~15046 m<sup>2</sup> (Bereiche, die nach Abschluss der Erhebung festzulegen sind).</p><p>Ursprünglicher Preis √ 295 000.00 EUR (zweihundertfünfundneunzigtausend Euro, und 00 (cents), Auktionsschritt 2950.00 EUR (zweitausend neunhundertfünfzig Euro und 00 (cents), Auktionssicherheit √ 29 500.00 EUR ( Euro, und 00 Cents). Die Zahlung für den Kauf erfolgt in folgender Reihenfolge:</p><ul><li>Innerhalb von 10 Werktagen nach Inkrafttreten des Vorschlags zahlt der Käufer eine Vorauszahlung von 30% (dreißig Prozent) der Kaufgebühr.</li><li>Der Käufer zahlt den verbleibenden Teil der Kaufgebühr innerhalb von zwei Wochen nach Abschluss des Kaufvertrages.</li></ul><p>Auktion beginnt 7.08.2025. Uhr13:00 und schließen 8.09.2025. Uhr13:00.</p><p>Bieter können sich für eine Auktion anmelden von: 7.08.2025. Uhr13:00 bis 27.08.2025. Uhr 23:59 auf der Website der elektronischen Auktion: <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Die Person, die an der Auktion teilnehmen möchte, muss bis zur Anmeldefrist für die Auktion Sicherheitsgeld einreichen, 10% (zehn Prozent) des Startpreises der zu versteigernden Immobilie, d.h. 29 500,00 EUR (neunundzwanzigtausend fünfhundert Euro und 00 Cent), was dem aktuellen Konto der LSEZ Authority gutgeschrieben werden muss: Liepāja Special Economic Zone Verwaltung, einheitliche Registrierung Nr. LV90000329402, AS "SEB Banka," Konto Nr. LV42UNLA0012000609480, mit der Aufschrift "Immobilien in Brīvības iela 98 Auktionssicherheit."</p><p>Die Versteigerung erfolgt elektronisch unter:<a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Auf Immobilien-Auktionsverfahren Anruf 29294267, E-Mail-Adresse:<a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p><p>Zusätzliche Informationen: Auktionsregeln auf der Website verfügbar<a href="/site/de/iepirkumi-un-izsoles/index.php">https://liepaja-sez.lv/lv/iepirkumi-un-izsoles/</a>.</p></div>
