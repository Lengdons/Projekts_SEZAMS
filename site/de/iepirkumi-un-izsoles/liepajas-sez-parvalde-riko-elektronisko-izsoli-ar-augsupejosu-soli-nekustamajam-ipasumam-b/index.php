<h1 class="article-title">Liepaja SEZ Authority organisiert eine elektronische Auktion mit aufsteigendem Schritt für Immobilien bei Brīvības iela 98 (Auktion geschlossen)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><i><strong>Auf Immobilien Auktion Ergebnisse:</strong></i></p><p><i>Auflage. vom 11. Dezember Im September endete die von Liepaja Special Economic Zone Authority in der 98 Brivibas Street, Liepaja, organisierte Immobilienauktion.</i></p><p><i>Auflage. vom 8. Dezember 1997 Im Oktober hat Liepaja Special Economic Zone Board den Beschluss Nr. 104 angenommen. vom 9. April 2004 Gesetz Nr., erstellt von der Hofverwaltung vom September. 4184890/0/2025-OKT über die Zulassung einer Auktion als Scheitern.</i></p><p>____________________________________________</p><p>Liepaja Special Economic Zone Authority, einheitliche Registrierung Nr. LV90000329402, organisiert eine elektronische Auktion mit einem Schritt nach oben für Immobilien in Brīvības Street 98, Liepaja, kadastrale Bezeichnung 1700220152, die aus einem Gebäude mit der Katasterbezeichnung 170220059027 und einer Landeinheit mit einer Gesamtfläche von 15046 m bestehen wird<sup>2</sup> (Bereiche, die nach Abschluss der Erhebung festzulegen sind).</p><p>Startpreis: 295 000,00 EUR (zweihundert fünfundneunzigtausend Euro und 00 Cent), Auktionsschritt: 2950,00 EUR (2.000 neunhundertfünfzig Euro und 00cent), Ausschreibungssicherheitsgeld: 29 500,00 EUR (zweiundzwanzigtausend Fünfhundert Euro und 00 Zentren). Die Zahlung für den Kauf erfolgt in folgender Reihenfolge:</p><ul><li>Innerhalb von 10 Werktagen nach Inkrafttreten des Vorschlags zahlt der Käufer eine Vorauszahlung von 30% (dreißig Prozent) der Kaufgebühr.</li><li>Der Käufer zahlt den verbleibenden Teil der Kaufgebühr innerhalb von zwei Wochen nach Abschluss des Kaufvertrages.</li></ul><p>Die Auktion beginnt am 7.08.2015. 13:00 Uhr und schließt 8.09.2025. 15.00 Uhr</p><p>Die Bieter können sich ab 7.08.25 für die Auktion anmelden. von 13:00 bis 27.08.2015 9.00 Uhr 23:59 auf der Website der elektronischen Auktion: <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Die Person, die an der Auktion teilnehmen möchte, muss bis zur Anmeldefrist für die Auktion Sicherheitsgeld einreichen, 10% (zehn Prozent) des Startpreises der zu versteigernden Immobilie, d.h. 29 500,00 EUR (neunundzwanzigtausend fünfhundert Euro und 00 Cent), was dem aktuellen Konto der LSEZ Authority gutgeschrieben werden muss: Liepaja Special Economic Zone Verwaltung, einheitliche Registrierung Nr. LV90000329402, AS "SEB Banka," Konto Nr. LV42UNLA0012000609480, mit der Aufschrift "Immobilien in Brīvības iela 98 Auktionssicherheit."</p><p>Die Versteigerung erfolgt elektronisch unter:<a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Auf Immobilien-Auktionsverfahren Anruf 29294267, E-Mail-Adresse:<a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p><p>Zusätzliche Informationen: Auktionsregeln auf der Website verfügbar<a href="https://liepaja-sez.lv/lv/iepirkumi-un-izsoles/">https://liepaja-sez.lv/lv/iepirkumi-un-izsoles/</a>.</p></div>
