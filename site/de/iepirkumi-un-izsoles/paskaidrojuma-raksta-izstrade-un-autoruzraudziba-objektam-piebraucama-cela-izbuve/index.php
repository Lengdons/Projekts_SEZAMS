<div class="row">
<div class="col"><div class="col-12 output"><p>PROCUREMENT, FÜR DEN DIE ÖFFENTLICHEN DIENSTLEISTUNGEN VORLIEGEN NICHT DIE PROCURITIERUNGSREGELN - Entwicklung einer Begründung und Überwachung des Objekts durch den Autor. Bau einer Auffahrt in Roņu iela 6, Liepaja</p><p>Gegenstand der Auftragsvergabe:</p><p>Ausarbeitung einer Begründung und Überwachung des Gegenstands durch den Autor • Errichtung einer Einfahrt in der Straße 6 Roņu, Liepaja, gemäß Anhang 7 der Verordnung.</p><p>CPV-Code: 71320000-7 (Engineering Engineering Design Services), 71248000-8 (Projekt- und Dokumentationsüberwachung)</p><p>Design- und Autorenarbeiten werden im Aktionsplan 2023/2027 des Europäischen Meeres-, Fischerei- und Aquakulturfonds durchgeführt und finanziert. Programme zur Entwicklung der Fischerei 2021/2027. Umsetzung von gemeinschaftlich geführten lokalen Entwicklungsstrategien durch Maßnahmen 4.1. M4/R1 unterstützt im Rahmen des Projekts "Stärkung der Entwicklung der Hafeninfrastruktur."</p><p>Die Angebote sind im elektronischen Beschaffungssystem, nachstehend "EIS" genannt, innerhalb des Teilsystems e-Commerce einzureichen (<a href="https://www.eis.gov.lv/EKEIS/Supplier/">https://www.eis.gov.lv/EKEIS/Supplier/</a>).</p><p>&nbsp;</p><p>Auftragsvergabe</p><p><strong>Entwicklung einer Begründung und Aufsicht des Autors über das Objekt √ Bau einer Einfahrt in der Roņu-Straße 6, Liepaja</strong></p><p>Lieferant: SIA "Train Engineers"</p><p>Vertragspreis: 17760,00EUR</p></div>
