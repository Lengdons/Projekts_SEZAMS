<h1 class="article-title">Liepāja SEZ Authority organisiert eine elektronische Auktion mit Hebeschritt für Immobilien in der Brīvības Street 98A (Versteigerung geschlossen)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><i><strong>Auf Immobilien Auktion Ergebnisse:</strong></i></p><p><i><strong>&nbsp;</strong></i></p><p><i>28. August 2025 Immobilien von Liepāja Special Economic Zone Authority in der Brivibas Street organisiert ist geschlossen 98A, Liepāja, Teile, elektronische Auktion. Höchster Preis 166 140.00 EUR (einhundert sechsundsechzigtausend einhundertvierzig Euro), ohne Mehrwertsteuer, verkauft von Ltd. 42103078050, eingetragener Sitz: Alte Oostmala 54, Liepāja, LV-3401 (Auktionsergebnisse bestätigt) 03.09.2025. Beschluss Nr. des Vorstands der LSEZ67).</i></p><p>___________________________________</p><p>&nbsp;</p><p>Liepāja Special Economic Zone Authority, einheitliche Registrierung Nr.LV90000329402, organisiert eine elektronische Auktion mit aufsteigendem Schritt für Immobilien in Brivibas Street 98A, Liepāja, Katasternummer 17000220153, die aus Gebäude und Landeinheit mit der Gesamtfläche bestehen wird ~5132 m<sup>2</sup>, (das Gebiet wird nach Abschluss der Erhebung festgelegt).</p><p>Ursprünglicher Preis √ <strong>142&nbsp;000.00&nbsp;EUR&nbsp;</strong>() <i>EUR</i> und 00 Cent), der Auktionsschritt <strong>1420.00&nbsp;&nbsp;EUR</strong> (eintausend vierhundert zwanzig) <i>EUR</i> und 00 Cent), Auktionssicherheit √ <strong>14&nbsp;200.00&nbsp;EUR</strong> (vierzehntausend zweihundert) <i>EUR</i> und 00 Cents). Die Zahlung für den Kauf erfolgt in folgender Reihenfolge:</p><ul><li>Innerhalb von 10 Werktagen nach Inkrafttreten des Vorvertrags zahlt der Käufer 30% (dreißig Prozent) aus dem Kaufpreis.</li><li>Der Käufer zahlt den verbleibenden Teil der Kaufpreisgebühr innerhalb von zwei Wochen nach Abschluss des Kaufvertrages.</li></ul><p>Auktion beginnt 29.07.2025. Uhr13:00 und schließen 28.08.2025. Uhr13:00.</p><p>Bieter können sich für eine Auktion anmelden von: 29.07.2025. Uhr13:00 bis 18.08.2025. Uhr 23:59 auf der Website der elektronischen Auktion: <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Die Person, die an der Auktion teilnehmen möchte, muss bis zum Abschluss der Auktionsregistrierung eine Sicherheit hinterlegen. 10% (%) des Startpreises der zu versteigernden Immobilie, d. h. 14 200.00 EUR (vierzehntausend zweihundert<i>EUR</i>und 00 Cent), die dem laufenden Konto der LSEZ Authority gutgeschrieben werden müssen: Liepāja Special Economic Zone Authority, einheitliche Registrierungsnummer. LV90000329402, AS "SEB Banka," Konto Nr.LV42UNLA0012000609480, mit der Aufschrift "Immobilien bei 98A Brīvības Street Auktionssicherheit."</p><p>Die Versteigerung erfolgt elektronisch unter:<a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Auf Immobilien-Auktionsverfahren Anruf 29294267, E-Mail-Adresse:<a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
