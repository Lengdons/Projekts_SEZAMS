<h1 class="article-title">Liepaja SEZ Authority organisiert eine elektronische Auktion mit Hebeschritt für Immobilien in der Brīvības Street 98A (Versteigerung geschlossen)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><i><strong>Auf Immobilien Auktion Ergebnisse:</strong></i></p><p><i><strong>&nbsp;</strong></i></p><p><i>Auflage. 28. Januar 2008 Immobilien von der Liepaja Special Economic Zone Authority in Brīvības Street 98A, Liepaja, Teile, elektronische Auktion organisiert. Der höchste Preis von 166 140,00 EUR (einhundert sechsundsechzigtausend einhundertvierzig Euro), ohne Mehrwertsteuer, wurde durch die Registrierungsnummer der SIA "Hermes Invest" versprochen. 42103078050, legale Adresse: Old oostmala 54, Liepaja, LV-3401 (Auktionsergebnisse genehmigt am 03.09.2025. In der Vorstandssitzung des LSEZ, Beschluss des Vorstands Nr. 67).</i></p><p>___________________________________</p><p>&nbsp;</p><p>Liepaja Special Economic Zone Authority, einheitliche Registrierung Nr. LV90000329402, organisiert eine elektronische Auktion mit einem Schritt nach oben für Immobilien in Brīvības Street 98A, Liepāja, kadastrale Nummer 1700220153, die aus Gebäude und Grundeinheit mit Gesamtfläche besteht ~5132 m<sup>2</sup>, (das Gebiet wird nach Abschluss der Erhebung festgelegt).</p><p>Ursprünglicher Preis √ <strong>142&nbsp;000.00&nbsp;EUR&nbsp;</strong>(1.400.2.000) <i>EUR</i> und 00 Cent), der Auktionsschritt <strong>1420.00&nbsp;&nbsp;EUR</strong> (eintausend vierhundert zwanzig) <i>EUR</i> und 00 Cent), Auktionssicherheit √ <strong>14&nbsp;200.00&nbsp;EUR</strong> (vierzehntausend zweihundert) <i>EUR</i> und 00 Cents). Die Zahlung für den Kauf erfolgt in folgender Reihenfolge:</p><ul><li>Innerhalb von 10 Werktagen nach Inkrafttreten des Vorvertrags zahlt der Käufer 30% (dreißig Prozent) aus dem Kaufpreis.</li><li>Der Käufer zahlt den verbleibenden Teil der Kaufpreisgebühr innerhalb von zwei Wochen nach Abschluss des Kaufvertrages.</li></ul><p>Die Auktion beginnt um 29.07.2025. um 13:00 Uhr und schließt 28.08.25 Uhr. 15.00 Uhr</p><p>Die Bieter können sich für die Auktion ab 29.07.2025 anmelden. von 13:00 bis 18.08.2015 9.00 Uhr 23:59 auf der Website der elektronischen Auktion: <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Eine Person, die an einer Auktion teilnehmen möchte, ist verpflichtet, eine Sicherheit in Höhe von 10% (10%) des Startpreises für das zu versteigernde Grundstück bis zur Anmeldefrist der Versteigerung abzugeben, d. h.: 14 200,00 EUR (vierzehntausend zweihundert<i>EUR</i>und 00 Cent), die dem laufenden Konto der LSEZ Authority gutgeschrieben werden müssen: Liepaja Special Economic Zone Authority, einheitliche Registrierungsnummer. LV90000329402, AS "SEB Banka," Konto Nr.LV42UNLA0012000609480, mit der Aufschrift "Immobilien bei 98A Brīvības Street Auktionssicherheit."</p><p>Die Versteigerung erfolgt elektronisch unter:<a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Auf Immobilien-Auktionsverfahren Anruf 29294267, E-Mail-Adresse:<a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
