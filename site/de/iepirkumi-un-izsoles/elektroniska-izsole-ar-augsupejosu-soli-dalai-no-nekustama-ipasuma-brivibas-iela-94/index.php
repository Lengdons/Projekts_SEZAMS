<h1 class="article-title">Elektronische Auktion mit einem Schritt nach oben für einen Teil der Immobilien an 94 Brīvības Street (Auktion geschlossen)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><i><strong>Auf Immobilien Auktion Ergebnisse:</strong></i></p><p><i>12. September 2025 Immobilieneinheiten von Liepāja Special Economic Zone Authority in der Brivibas Street sind geschlossen 94, in Liepāja, elektronische Auktion. Höchster Preis<strong>378&nbsp;750.00 EUR</strong> (dreihundertachtzigtausend siebenhundertfünfzig Euro), ohne Mehrwertsteuer, versprochen <strong>SIA “Nordic Steel Latvia”</strong>, Registrierungsnummer 40203671003, Anschrift: 33-3F Krišjāņa Valdemāra Street, Riga, LV-1010 (Auktionsergebnisse genehmigt am 08.10.2025. Auf der Vorstandssitzung des LSEZ, Beschluss des Vorstands Nr. 103).</i></p><p>_____________________________________</p><p>Liepāja Special Economic Zone Authority, einheitliche Registrierung Nr.LV90000329402, organisiert eine elektronische Auktion mit einem Schritt nach oben für einen Teil der Immobilien in Brivibas Street 94, in Liepāja, Katasterbezeichnung 17000220059, die aus Arbeiten mit kadastralen Bezeichnungen bestehen wird 17000220059089 und 17000220059090, und Teile der Landeinheit mit Gesamtfläche ~21778 m<sup>2</sup> (Bereiche, die nach Abschluss der Erhebung festzulegen sind).</p><p>Ursprünglicher Preis √ 375 000,00 EUR (375 000,00 EUR (dreihundertfünfundsiebzigtausend Euro), Auktionsschritt 3 750,00 EUR (dreitausend siebenhundertfünfzig Euro), Auktionssicherheit 37 500,00 EUR (dreizig siebentausend fünfhundert <i>EUR</i>). Die Zahlung für den Kauf erfolgt in folgender Reihenfolge:</p><ul><li>Innerhalb von 10 Werktagen nach Inkrafttreten des Vorschlags zahlt der Käufer eine Vorauszahlung von 30% (dreißig Prozent) der Kaufgebühr.</li><li>Der Käufer zahlt den verbleibenden Teil der Kaufgebühr innerhalb von zwei Wochen nach Abschluss des Kaufvertrages.</li></ul><p>Auktion beginnt 12.08.2025. Uhr13:00 und schließen 11.09.2025. Uhr13:00.</p><p>Bieter können sich für eine Auktion anmelden von: 12.08.2025. Uhr13:00 bis 01.09.2025. Uhr 23:59 auf der Website der elektronischen Auktion: <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Die Person, die an der Auktion teilnehmen möchte, muss vom Startpreis des zu versteigernden Immobiliens ein Sicherheitsgeld von 10% (zehn Prozent) einreichen, d. h. 37 500,00 EUR (siebzigtausendfünfhundert Euro), das dem laufenden Konto der LSEZ-Behörde gutgeschrieben werden soll: Liepāja Special Economic Zone Authority, Einzigartige Eintragungsnummer LV90000329402, AS "SEB Banka," Konto Nr. LV42UNLA0012000609480, mit der Aufschrift "Immobilien in 94 Brīvības Street."</p><p>Die Versteigerung erfolgt elektronisch unter:<a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Auf Immobilien-Auktionsverfahren Anruf 29294267, E-Mail-Adresse:<a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
