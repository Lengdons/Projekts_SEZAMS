nhängen ermöglichen direkten und kostenlosen elektronischen Zugang zum Kundenprofil des Kunden EIS <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>.</p><p>1.11.2. Eine in der EIS eingetragene interessierte Partei kann sich als Begünstigter einer Satzung registrieren, siehe: <a href="https://www.eis.gov.lv/EIS/Publications/PublicationView.aspx?PublicationId=883">https://www.eis.gov.lv/EIS/Publications/PublicationView.aspx?PublicationId=883</a>.</p></div>
