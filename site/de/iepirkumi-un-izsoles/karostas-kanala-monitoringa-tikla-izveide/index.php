<h1 class="article-title">Einrichtung eines Überwachungsnetzes für den Karasta-Kanal (Id.Nr.LSEZ 2023/15)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Die Beschaffungskommission der Behörde für besondere Wirtschaftszonen Liepāja hat einen Beschluss über die Einrichtung des Überwachungsnetzes für den Kanal Karosta (LSEZ) angenommen. 2023/15) durch Vergabe des Auftrags an die SIA "Isliena V" (5000204363) zum Gesamtvertragspreis in EUR 79280.00, ohne Mehrwertsteuer.</p><p>&nbsp;</p><p><strong>CPV-Code</strong></p><p>CPV-Code: 45122000-8 (Sondierungsbohrungen)</p><p><strong>Projekt</strong></p><p>Das Projekt wird vom norwegischen Finanzierungsmechanismus durchgeführt. 2014. – 2021. Das jährliche Programm für Klimaschutz, Anpassung und Umwelt im Rahmen des Fonds. Gegenstand der Vereinbarung Die Einrichtung eines Monitoring-Netzwerks für den Kanal Port of Liepāja Karosta (im Folgenden - das Abkommen) ist eine der Maßnahmen, die von Liepāja Special Economic Zone Authority (im Folgenden "der Kunde") im Rahmen des Projekts "Historisch kontaminierte Standorte" im Rahmen der Sanierungsarbeiten des Hafens von Liepāja Karosta Canal (im Folgenden: das Projekt) durchgeführt werden.</p><p><strong>Zeitpunkt und Ort der Vertragserfüllung</strong></p><p>1. Frist für die Vertragserfüllung: zu gewährleisten 3 in (drei) Monaten, spätestens jedoch von 26. April 2024.</p><p>2. Erfüllungsort des Vertrages: Erfüllungsort (6.2. (Abbildung ) ist der Karosta-Kanal des Hafens von Liepāja, Teil der Binnengewässer des Hafens (Kadastral Nr. 1700-010-0073;1700-010-0306) und das Gebiet des technischen Nebengebiets, das neben dem Lagerort liegt und von der LSEZ-Behörde verwaltet wird (Kadastral-Nr. 1700-010-0072).</p><p><strong>Vergabeverfahren</strong></p><p>Offene Aufträge gemäß den Vergaberichtlinien für öffentliche Dienstleistungserbringer (nachstehend "Leitlinien" genannt). Verfügbar: Vergaberichtlinien für öffentliche Dienstleister (Purchase Monitoring Bureau)</p><p>Die Angebote sind im elektronischen Beschaffungssystem (nachstehend "EIS" genannt) innerhalb des Teilsystems "e-Tendering" einzureichen (<a href="https://www.eis.gov.lv/EKEIS/Supplier">https://www.eis.gov.lv/EKEIS/Supplier</a>/) bis 10.00 Uhr am 13. Februar 2024</p></div>
