<h1 class="article-title">Neuauktion mit einem Schritt nach oben für Immobilien an der Naglu Street 1</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Liepaja Special Economic Zone Authority, Unified Registrierung No.LV90000329402, organisiert elektronische Reauktion mit einem Schritt nach oben für Immobilien in der Naglu Street 1, Liepāja, kadastral No. 17000220152 bestehend aus einem Gebäude mit der Katasterbezeichnung 1700220059027 und einer Grundfläche von 15048 m<sup>2</sup>.</p><p>Ursprünglicher Preis √ <strong>295 000.00 EUR </strong>(zweihundert Fünfundneunzigtausend) <i>EUR</i> und 00 Cent), der Auktionsschritt <strong>2950.00  EUR</strong> (zweitausend neunhundertfünfzig) <i>EUR</i> und 00 Cent), Auktionssicherheit √ <strong>29 500.00 EUR</strong> (29.000 500) <i>EUR</i> und 00 Cents). Die Zahlung für den Kauf erfolgt in folgender Reihenfolge:</p><ul><li>Innerhalb von 10 Werktagen nach Inkrafttreten des Vorschlags zahlt der Käufer eine Vorauszahlung von 30% (dreißig Prozent) der Kaufgebühr. </li><li>Der Käufer zahlt den verbleibenden Teil der Kaufgebühr innerhalb von zwei Wochen nach Abschluss des Kaufvertrages.</li></ul><p>Die Auktion beginnt am 19.06.2026. 13:00 Uhr und schließen 20.07.2026. 15.00 Uhr</p><p>Die Bieter können sich für eine Auktion ab 19.06.2026 anmelden. von 13.00 bis 9.07.202026 9.00 Uhr 23:59 auf der Website der elektronischen Auktion:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Die Person, die an der Auktion teilnehmen möchte, muss eine Sicherheit von 10% (zehn Prozent) des Startpreises der zu versteigernden Immobilie, d. h. 29 500,00 EUR (neunundzwanzigtausendfünfhundert) bis zur Anmeldefrist für die Auktion hinterlegen. <i>EUR</i> und 00 Cent), die dem laufenden Konto der LSEZ Authority gutgeschrieben werden müssen: Liepaja Special Economic Zone Authority, einheitliche Registrierungsnummer. LV90000329402, AS "SEB Banka," Konto Nr. LV42UNLA0012000609480, mit der Aufschrift "Auktion Security for Real Estate at Naglu Street 1." </p><p>Die Versteigerung erfolgt elektronisch unter: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Auf Re-Immobilien Auktion Betrieb rufen 29294267, E-Mail-Adresse: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p><p>Zusätzliche Informationen: Auktionsregeln auf der Website verfügbar <a href="../index.php">https://liepaja-sez.lv/lv/iepirkumi-un-izsoles/</a>.</p></div>
