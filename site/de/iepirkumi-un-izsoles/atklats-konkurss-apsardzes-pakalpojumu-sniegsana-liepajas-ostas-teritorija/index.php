<h1 class="article-title">Offene Ausschreibung √ Bereitstellung von Sicherheitsdiensten im Gebiet des Hafens von Liepaja 307, Beschaffungskennung Nr. LSEZ2021/58/K</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Eine Beschreibung des Auftragsgegenstands ist physische und technische Sicherheitsdienste gemäß den technischen Spezifikationen und dem Vertragsentwurf.</p><p>&nbsp;</p><p>CPV-Code: 79710000-4.</p><p>&nbsp;</p><p>Vorschläge sind dem Teilsystem EIS e-Wettbewerb bis spätestens 21. Mai 2021 um 10.00 Uhr vorzulegen.</p><p>&nbsp;</p><p>Öffentliche Website des Kunden im nationalen elektronischen Informationssystem für den Eingang von Angeboten und Anträgen (EIS verfügbar: <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>), in dem der Kunde Informationen über zukünftige Ausschreibungen, geplante Käufe, abgeschlossene Verträge, nicht abgeschlossene Verfahren sowie andere durch gesetzliche Vorschriften festgelegte Vergabeverfahren aufstellt.</p><p>&nbsp;</p><p>Beurteilung des Antragstellers AS ŘG4S , reg.n. In ihrer Vorlage von 40103058465 stellt die Kommission fest, dass das vom Bieter AS ŘG4S eingereichte Angebot und das vom Antragsteller AS √G4S vorgelegte Angebot den Anforderungen des offenen Ausschreibungsverfahrens entsprechen. Der von AS G4S angebotene Vertragspreis beträgt 842878,8 EUR (ohne MwSt.).</p><p>&nbsp;</p><p>Da nach den Bedingungen des öffentlichen Angebots das Kriterium für die Auswahl eines Angebots das wirtschaftlich günstigste Angebot ist - der niedrigste Zuschlagspreis, Kriterien für die Bewertung von Angeboten: Preis- und Bewertungskriterien im Zusammenhang mit dem Gegenstand des Auftrags gemäß Nummer 5.2.4.2 der Referenzbedingungen</p><p>&nbsp;</p><p>Die Kommission beschließt, Sicherheitsdienste im Gebiet des Hafens von Liepaja, Identifizierungsnummer, zu erbringen. LSEZ2021/58/K, mögliche Aufträge werden an AS "G4S" - Reg.nr. 40103058465, zu einem Angebotspreis von 842878.8 EUR (ohne MwSt.).</p></div>
