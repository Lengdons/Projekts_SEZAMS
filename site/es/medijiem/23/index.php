<h2>Finaliza la tercera ronda del proyecto de rehabilitación ambiental del Canal de Karosta</h2>
<span class="mb-3">29.12.2023.</span>
</div>
<a aria-label="Leer más" class="mb-3 news_link d-none d-md-block" href="../nosledzas-karostas-kanala-vides-sanacijas-projekta-iii-karta/index.php">Leer más</a>
</div>
<div class="col-12 col-md-4 description">
<p>La administración de la ZEE de Liepāja ha implementado el proyecto "Obras de remediación de áreas históricamente contaminadas del canal Karosta del puerto de Liepāja" con el objetivo de reducir el impacto negativo de los sedimentos históricamente contaminados del canal Karosta sobre el medio ambiente, la salud humana y el estado ecológico del Mar Báltico. El proyecto se financia en el marco del programa del instrumento financiero noruego 2014-2021 "Mitigación del cambio climático, adaptación a él y al medio ambiente" y se eliminaron en total 145.199 metros cúbicos de sedimentos históricamente contaminados que contenían aproximadamente 298 toneladas de productos químicos peligrosos. Se trataba de la III ronda del proyecto de rehabilitación del Canal de Karosta.</p>
