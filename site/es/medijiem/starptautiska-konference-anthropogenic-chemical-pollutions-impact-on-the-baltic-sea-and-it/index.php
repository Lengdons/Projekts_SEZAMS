<h1 class="article-title">Conferencia internacional "El impacto de la contaminación química antropogénica en el Mar Báltico y sus ecosistemas relacionados"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Los días 11 y 12 de octubre de 2023, Liepāja acogerá el proyecto núm. NFI/AK/02 Conferencia internacional "Obras de rehabilitación del canal Karosta del puerto de Liepāja de sitios históricamente contaminados" "Impacto de la contaminación química antropogénica en el mar Báltico y sus ecosistemas relacionados". Todos están invitados a asistir a la conferencia en vivo.</p><p>La conferencia reunirá a varios investigadores y expertos destacados de la región del Mar Báltico, quienes compartirán sus conocimientos y experiencia en la investigación de la contaminación del agua y la práctica de recultivo de sitios contaminados.</p><p>Puedes leer más sobre la conferencia y su programa: <a href="https://ej.uz/konferenesprogramma">https://ej.uz/konferenesprogramma </a></p><p>El 11 de octubre de 2023, de 10:00 a 18:00, conferencia internacional, presentaciones y paneles de discusión con representantes de instituciones de investigación y gestión ambiental de Letonia, Estonia, Finlandia y Noruega.</p><p>El 12 de octubre de 2023, los participantes tendrán la oportunidad de conocer mejor la historia del territorio de Karosta, los trabajos de restauración ambiental realizados en el proyecto y los resultados obtenidos.</p><p>La conferencia es gratuita y abierta a todos los interesados. Podrás participar tanto de forma presencial como remota en la transmisión en vivo (11 de octubre).</p><p> </p><p><strong>¡Trabajemos juntos por una Europa verde!</strong></p><p>El proyecto está financiado en el marco del programa del Instrumento Financiero Noruego 2014-2021 "Mitigación del cambio climático, adaptación y medio ambiente". El coste total del proyecto es de 5.117.647,05 euros, de los cuales 4.350.000,00 euros están financiados por el instrumento financiero noruego.</p></div>
