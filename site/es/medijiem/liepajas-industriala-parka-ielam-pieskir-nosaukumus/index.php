<h1 class="article-title">Las calles del polígono industrial de Liepāja reciben nombre</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>En la reunión del consejo municipal de la ciudad de Liepāja del 21 de agosto se aprobaron ocho nuevos nombres para las calles previstas en el territorio de la antigua fábrica "Liepājas metalurgs", en el futuro parque industrial de Liepāja.</p><p>Según las opciones propuestas por los propios residentes y los resultados de la votación, se asignaron los siguientes nombres a las calles: Tris skursteni iela, Martena iela, Eksporta iela, Dzelzsgriezėja iela, Inženieru iela, Čuguna iela, Naglu iela, Dūmu iela.</p><p>Los propios residentes participaron activamente en la denominación de las calles. Inicialmente, los habitantes de Liepāja tuvieron la oportunidad de expresar sus propuestas sobre los nombres de las calles del futuro parque industrial en el stand de la Administración de la Zona Económica Especial de Liepāja durante la exposición "Made in Liepāja", donde se recibieron un total de 385 propuestas.</p><p>Luego de evaluar todas las recomendaciones recibidas, se seleccionaron los 14 nombres que más se adecuan a la identidad del lugar, que no se encuentran ya en el listado de nombres de calles existentes, así como aquellos que reflejan simbólicamente el potencial industrial, cultural-histórico y de desarrollo del futuro parque industrial, los cuales fueron sometidos a votación pública. En la votación de los ciudadanos se recibieron 301 votos, como resultado de los cuales se eligieron ocho nombres de calles, que fueron remitidos para su aprobación en la reunión del consejo.</p><p>El Centro Estatal de Idiomas también recibió una opinión positiva sobre la asignación de nombres de calles, en la que se propone, entre otras cosas, aclarar el nombre de "Skurstenu iela" a "Tris skurstenu iela", que, entre otras opciones, es un nombre más adecuado al paisaje urbano y al contexto histórico correspondiente.</p><p>La asignación de nombres de calles es un requisito previo para la inclusión de estas calles en el registro oficial de direcciones.</p><p>Actualmente, en el territorio del parque industrial de Liepāja se están construyendo varias calles nuevas, que también incluyen carriles para peatones y bicicletas, comunicaciones subterráneas de ingeniería, construcción de iluminación y paisajismo. Las obras en las nuevas calles Eksporta e Inženieru están a punto de finalizar y está previsto ponerlas en funcionamiento en un futuro próximo. Continúan las obras en las calles Naglu y Dzelzsgriezėja, donde se colocó la capa base de asfalto.</p><p>Todas las obras de la primera ronda del proyecto deben estar terminadas a finales de 2025.</p></div>
