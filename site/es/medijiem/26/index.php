<h2>Liepāja: el centro de la industria de la energía eólica marina en la parte oriental del Mar Báltico</h2>
<span class="mb-3">14.04.2022.</span>
</div>
<a aria-label="Leer más" class="mb-3 news_link d-none d-md-block" href="../liepaja-atkrastes-veja-energijas-nozares-centrs-baltijas-juras-austrumu-dala/index.php">Leer más</a>
</div>
<div class="col-12 col-md-4 description">
<p>El 14 de abril se celebró en Liepāja un debate "Los puertos letones como base de la independencia energética", que estuvo presidido por el Ministro de Transportes Jānis Vitenbergs y el Ministro de Economía Ilze Indriksone, y que se centró en el potencial del Mar Báltico para el desarrollo de parques eólicos, y el aspecto más importante de las negociaciones fue la necesidad de que los grandes puertos de Letonia atraigan inversores privados para garantizar este desarrollo. Durante el debate, el director de la ZEE de Liepāja, Uldis Hmieļevskis, presentó el plan desarrollado para crear una base de apoyo a la energía eólica marina en el puerto de Liepāja, que cumple plenamente ocho de diez condiciones e incluye todos los parques eólicos previstos en aguas territoriales de Letonia en un radio de 100 km y todos los parques eólicos previstos en los países bálticos en un radio de 250 km.</p>
