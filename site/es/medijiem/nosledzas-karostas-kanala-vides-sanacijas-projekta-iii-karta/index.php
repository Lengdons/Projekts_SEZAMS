<h1 class="article-title">Finaliza la tercera ronda del proyecto de rehabilitación ambiental del Canal de Karosta</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>El proyecto se financia en el marco del programa del instrumento financiero noruego 2014-2021 "Mitigación del cambio climático, adaptación a él y al medio ambiente" y se eliminaron en total 145.199 metros cúbicos de sedimentos históricamente contaminados que contenían aproximadamente 298 toneladas de productos químicos peligrosos. Se trataba de la III ronda del proyecto de rehabilitación del Canal de Karosta.</p><p>Las obras en el canal de Karosta fueron realizadas por SIA "Eko osta", de conformidad con el contrato firmado y el programa de rehabilitación del canal de Karosta aprobado. Las obras de rehabilitación del canal Karosta comenzaron en abril de 2023, pero finalizaron el 5 de diciembre de 2023. El importe total del contrato fue de 3.334.877,50 euros, sin incluir el impuesto sobre el valor añadido.</p><p>Gunārs Ansiņš, presidente del Ayuntamiento de Liepāja, destacó la importancia del trabajo realizado, ya que Liepāja obtuvo en 1992 el punto caliente de HELCOM debido a la contaminación del canal Karosta. "Era una situación muy complicada cuando en un pequeño canal teníamos herencia militar soviética, barcos y submarinos hundidos y más de 100 elementos diferentes de la tabla de Mendeleev. Esto significaba que nosotros, como Letonia, como Liepaja, como la región del Mar Báltico, tenemos que limpiar gradualmente el canal, lo cual estamos haciendo paso a paso".</p><p>El director de la ZEE de Liepāja, Uldis Hmieļevskis, afirma que el puerto, incl. El Canal de Karosta es una parte integral de la ZEE de Liepāja y, en consecuencia, hay que cuidarlo, incluido el legado de la época soviética. "Para poder desarrollar el transporte marítimo y poder construir nuevas terminales en el puerto, necesitamos limpiar el canal y se ha hecho. Se ha hecho mucho trabajo".</p><p>Con la ayuda de un instrumento financiero noruego, la Administración de la Zona Económica Especial de Liepāja implementó la III ronda de rehabilitación del Canal de Karosta con el fin de realizar una inversión importante para mitigar los riesgos del cambio climático y la propagación de la contaminación histórica en el Mar Báltico y el medio ambiente circundante. El director del proyecto, Ivo Kolinņš, destaca que las obras continuarán y que las acciones futuras a corto y largo plazo están claras para minimizar la contaminación histórica y su impacto en todo el ecosistema del Mar Báltico.</p><p>Hoy en día, el territorio de Karosta se está convirtiendo en una parte socioeconómica y doméstica cada vez más importante de Liepāja, por lo que los trabajos de limpieza del canal realizados con la ayuda del proyecto permitirán a los residentes locales y a los turistas disfrutar de los valores de Karosta en un entorno más limpio y de mayor calidad, promoviendo la restauración de sus ecosistemas acuáticos y la reducción de la contaminación.</p></div>
