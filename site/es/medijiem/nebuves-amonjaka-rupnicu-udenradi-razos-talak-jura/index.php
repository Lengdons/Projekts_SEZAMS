<h1 class="article-title">No se construirá una planta de amoníaco, el hidrógeno se producirá más en el mar</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>En la reunión de trabajo, el jefe de "CIS Liepāja", Tors Arne Pedersen, anunció que, de acuerdo con la dirección de la ZEE de Liepaja, se cambió la posible ubicación de la planta de producción de hidrógeno prevista, más al norte en la zona portuaria y que, debido a los cambios en el mercado y la demanda, "CIS Liepāja" abandonó el desarrollo del proyecto de producción de amoníaco verde. </p><p>Tor Arne Pedersen destacó que la seguridad es lo primero. "Desde el inicio del desarrollo del proyecto, hemos estado buscando las mejores ubicaciones y soluciones tecnológicas para la planta y la terminal de producción de hidrógeno verde. La seguridad es algo que nos tomamos muy en serio y somos plenamente conscientes de que es de vital importancia para el proyecto. Por esta razón, también hemos examinado más de cerca varias soluciones, cómo podemos resolver la seguridad de la mejor manera posible. Esto es importante para nosotros como desarrolladores de proyectos, tanto para el municipio como para la administración de la ZEE de Liepāja".</p><p>Durante la reunión de trabajo, el director de "CIS Liepāja", Tors Arne Pedersens, presentó una vez más la idea del proyecto, su avance, los accionistas de la empresa y la experiencia en el desarrollo y avance de diversos proyectos. A la pregunta de por qué Liepāja, Tor Arne Pedersens admitió que inicialmente estudiaron todos los países nórdicos: Noruega, Suecia, Finlandia, donde el principal obstáculo era el déficit de redes eléctricas de alto voltaje, y luego se centraron en los países bálticos. Un papel importante lo desempeñaron las recomendaciones de la Embajada de Noruega en Letonia y el entorno empresarial de alta calidad en Liepaja, así como la zona económica especial de Liepaja y sus ventajas. Actualmente se han iniciado investigaciones y se está realizando una evaluación de riesgos e impacto ambiental. </p><p>Para conocer el progreso de los proyectos industriales sostenibles en el territorio de la zona económica especial de Liepāja, la dirección de la ZEE de Liepāja y el Ayuntamiento, los miembros del municipio, los promotores de proyectos de inversión, la dirección del Servicio Estatal de Medio Ambiente y representantes de organizaciones ecologistas se reunieron en una reunión de trabajo conjunta.</p><p> </p></div>
