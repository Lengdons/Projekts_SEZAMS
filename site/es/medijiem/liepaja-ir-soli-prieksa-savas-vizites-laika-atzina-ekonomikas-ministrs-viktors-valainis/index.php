<h1 class="article-title">"Liepāja está un paso adelante", admitió el Ministro de Economía, Viktors Valainis, durante su visita</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Hoy, 17 de mayo, el Ministro de Economía, Viktors Valainis, visitó Liepāja en una visita de trabajo de un día. Con la dirección de la ciudad estatal de Liepaja y de la zona económica especial de Liepaja se discutieron el desarrollo del sector energético, la industria manufacturera, los empleos cualificados y bien remunerados, las inversiones en el transporte de mercancías y el desarrollo de las exportaciones, la vivienda y una serie de otras cuestiones importantes de desarrollo económico.</p><p>"Liepāja ya está un paso por delante y avanza decididamente hacia la consecución de los objetivos fijados por el Estado en el ámbito del desarrollo económico, duplicando la economía en 10 años, creando un nuevo enfoque en el sector energético, desarrollando parques eólicos marinos y producción de hidrógeno, promoviendo la productividad y la producción con alto valor añadido", reconoció el ministro de Economía, Viktors Valainis.</p><p>Durante la visita de trabajo a Liepāja, el Ministro de Economía conoció empresas manufactureras, parques industriales, terminales de exportación de agua y proyectos de desarrollo en el campo de la energía. El ministro enfatizó que los proyectos del sector energético podrían garantizar un desarrollo económico más rápido del país, que se basa en tecnologías modernas, y Liepāja tiene una visión clara de cómo desarrollar tanto la base de energía eólica marina como cómo avanzar paso a paso hacia la producción de hidrógeno y aviones propulsados ​​por hidrógeno.</p><p>El Ministro de Economía también elogió la gestión de la ZEE de Liepāja, que ha contribuido a la atracción de inversiones, la construcción de nuevas fábricas y la creación de nuevos puestos de trabajo cualificados. "Hoy, cuando volvemos a discutir la reforma de la gestión de las empresas portuarias y de tránsito, vemos que el modelo de Liepāja está funcionando. Los empresarios, junto con el municipio y el estado, se sientan en la misma mesa y planifican cómo desarrollar mejor la zona económica, cómo atraer inversiones. Los otros puertos también podrían aspirar a ese modelo de gestión. Estoy contento por lo que vi hoy en Liepāja, por las ambiciones de los empresarios de duplicar los volúmenes de producción, por los proyectos de desarrollo lanzados por valor de decenas de millones. Haremos todo lo posible. para apoyar a los emprendedores."</p></div>
