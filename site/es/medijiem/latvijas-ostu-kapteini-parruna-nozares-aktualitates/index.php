<h1 class="article-title">Los capitanes portuarios letones discuten la actualidad del sector</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>El 10 de abril, los capitanes de los puertos letones y la dirección de la Administración Marítima se reunieron en Liepāja para una reunión de trabajo con la participación de representantes de la Armada del NBS. Los temas principales son el mantenimiento de calles, el manejo de nuevas cargas, en cooperación con empresarios portuarios, proyectos de desarrollo para la diversificación de las operaciones portuarias, basados ​​en la industria sostenible y los recursos renovables. </p><p>También se discutieron los proyectos de desarrollo previstos para los grandes puertos de Letonia: Riga, Ventspils, Liepāja, que mejoran la seguridad de la navegación y modernizan el control de los barcos y los sistemas de navegación. Los puertos de Liepāja y Ventspils planean anunciar una adquisición conjunta en un futuro próximo para restablecer los sistemas hidrográficos y de gestión de buques en los puertos. Las autoridades portuarias de Salacgriva, Skulte y Pāvilosta también planean proyectos de desarrollo.</p><p>Además, los capitanes portuarios letones conocieron y discutieron los resultados de la auditoría de la Organización Marítima Internacional (OMI), discutieron los pros y los contras del uso de boyas virtuales, las condiciones para el registro de yates y embarcaciones de recreo, así como la necesidad de actualizar el Reglamento Portuario.</p></div>
