<ul><li>Para mantener una embarcación en uno de los amarres del puerto deportivo de Liepāja durante mucho tiempo, es necesario celebrar un acuerdo de amarre para yates/barcos con la administración de la zona económica especial de Liepaja, completando el formulario de declaración en el centro del puerto deportivo.</li><li>Los contratos de amarre de yates/cúteres para su estacionamiento de larga duración en los amarres del puerto deportivo se celebran por orden de llegada, mientras que los espacios asignados para este fin estén disponibles. No se proporcionan reservas de asientos.</li><li>Para aplicar la tarifa mensual por amarre de larga duración, el plazo mínimo para la celebración del contrato de amarre de yate/cúter es de 2 meses. Durante la temporada, los asientos disponibles se ofrecen a los clientes en lista de espera por orden de llegada.</li></ul><br/>
