<div class="row">
<div class="col-12 col-md-6 column-content">
<p>Para los yates que llegan, el puerto de yates proporciona los servicios de atraque necesarios: lugar de amarre, suministro de agua, suministro de electricidad y seguridad del atraque. Para la comodidad de los huéspedes se ofrecen aseos bien equipados, duchas y una sala de lavandería.</p>
</div>
<div class="col-12 col-md-6 column-content">
<p>Desde 2008, el puerto deportivo recibe la Bandera Azul, un certificado ecológico reconocido internacionalmente. La Bandera Azul es una certificación otorgada por la Fundación de Educación Ambiental de que la playa o puerto deportivo cumple con los estrictos estándares de calidad de la fundación.</p>
