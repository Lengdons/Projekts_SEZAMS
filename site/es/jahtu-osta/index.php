<div class="row">
<div class="col"><div class="col-12 output"><h6>El puerto de yates de Liepāja está ubicado al lado del canal comercial, cerca del edificio "Promenade Hotel". Su ubicación permite amarrar los yates en el centro de la ciudad, lo que permite llegar a tiendas, restaurantes, atracciones turísticas, transporte público y al centro de información turística en un paseo de 5 a 10 minutos.</h6></div>
