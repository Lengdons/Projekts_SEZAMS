<h1 class="article-title">Este fin de semana tendrá lugar la exposición "Made in Liepāja"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Liepaja produce y produce mucho. La exposición "Made in Liepāja" ya se celebrará este fin de semana, el 31 de enero y el 1 de febrero. Será una oportunidad para que todos puedan ver los productos de los empresarios de Liepāja. Paralelamente a la exposición, habrá una conferencia sobre los negocios de hoy y del futuro, sobre proyectos de innovación local y soluciones sostenibles.</p><p>Liepāja produce equipos pesados ​​y de gran tamaño necesarios para las operaciones aeroportuarias, la construcción de edificios y la industria, así como sistemas de control electrónico utilizados para equipos navales, repuestos para la industria automotriz e incluso equipos respiratorios para bomberos de todo el mundo. Los productos que se exportan se producen tanto en fábricas como en parques industriales. Liepāja ha podido preservar las tradiciones de producción y desarrollar otras nuevas y actualmente está trabajando para convertirse en un centro de industria sostenible, que utilizará las tecnologías en las que están trabajando los científicos e investigadores.</p><p>Liepāja es la segunda ciudad más productiva de Letonia después de Riga, contribuye significativamente a la economía nacional y aumenta el producto interior bruto del país.</p><p>Más sobre la exposición y conferencia: <a href="https://www.liepaja.lv/izstade-razots-liepaja/?fbclid=IwZXh0bgNhZW0CMTAAAR1GvsIXV3yf6pwBJdpSTjaYvv5ngmZoOss0-0brt7T-Ayet3Vw7Ktuo-HA_aem_ZC7SMAJAlWqxl03twYGN9A" target="_blank"><strong>https://www.liepaja.lv/izstade-razots-liepaja/</strong></a></p></div>
