<div class="col-12 col-md-4 description">
<p>La administración de la ZEE de Liepāja continúa mejorando la infraestructura necesaria para los pescadores mediante la construcción de la carretera de acceso al muelle 92 del puerto. El proyecto está financiado por el Programa de Acción para el Desarrollo Pesquero 2021-2027 del Fondo Europeo Marítimo, de Pesca y Acuicultura. para el año. Como parte del proyecto, se construye una vía de acceso público de 364 metros, así como un sistema inteligente de iluminación y drenaje de aguas pluviales. Según los resultados del concurso, las obras serán realizadas por SIA "CTB", que ofreció la solución económicamente más ventajosa por 303.617,32 euros. Está previsto que las obras de construcción finalicen a finales de agosto.</p>
