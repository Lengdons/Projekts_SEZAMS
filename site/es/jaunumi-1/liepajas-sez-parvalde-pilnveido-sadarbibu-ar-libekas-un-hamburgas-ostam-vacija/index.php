<h1 class="article-title">La administración de la ZEE de Liepaja mejora la cooperación con los puertos de Lübeck y Hamburgo en Alemania </h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>El desarrollo de los puertos, la energía verde y el fortalecimiento de los corredores de transporte fueron los temas principales en los Port Days de Hamburgo y Lübeck, en los que participaron el director de la ZEE de Liepāja, Uldis Hmieļevskis, y el concejal Jānis Lapiņš. </p><p><br/>En las jornadas portuarias letón-alemanas celebradas en Hamburgo y Lübeck los días 14 y 15 de abril se debatió sobre la mejora de la cooperación existente en el ámbito de la logística, la energía sostenible y la transformación del desarrollo portuario. La energía renovable y su transmisión y uso exitosos dependen principalmente de una combinación efectiva de competencias de la industria, la energía y el sector marítimo.</p><p><br/>Travemundi, suburbio de Liepāja y Lübeck, está literalmente conectado seis veces por semana mediante la línea de ferry Stena Line y a menudo se lo conoce como la continuación de la autopista alemana. En 2016, la Autoridad de la ZEE de Liepāja celebró un acuerdo de cooperación con la Autoridad Portuaria de Lübeck y en 2021 con el Puerto de Hamburgo.</p><p><br/>La delegación letona estuvo encabezada por el Ministro de Transportes, Atis Švinka. La visita finalizó con el foro Port Days letón-alemán. En el panel de discusión del foro, el director de la ZEE de Liepāja, Uldis Hmieļevskis, enfatizará la importancia de las asociaciones e innovaciones a largo plazo para fortalecer la competitividad, la seguridad y la sostenibilidad de los puertos, así como los futuros proyectos conjuntos.</p><p><br/>La administración de la ZEE de Liepāja ya participa activamente en la creación de la interconexión eléctrica entre el Báltico y Alemania, en la que Liepāja está marcada como un posible punto de conexión terrestre. Por otro lado, se acaba de cerrar un acuerdo sobre el desarrollo del ecosistema del hidrógeno nórdico-báltico, que lo conectaría con Alemania y convertiría a Liepāja en un punto de conexión terrestre.</p><p><br/>El director de la ZEE de Liepāja, Uldis Hmieļevskis, afirma que esto abrirá una oportunidad para que Letonia se convierta en un país exportador de electricidad eólica y solar y, al mismo tiempo, Liepāja abrirá oportunidades para que se desarrollen nuevos proyectos de inversión con uso intensivo de energía.</p><p><br/>El objetivo de las Jornadas Portuarias Alemanas-Letonas era promover la cooperación entre las empresas de transporte y logística alemanas y letonas, debatiendo en el foro la actualidad del sector, así como reforzar los contactos existentes y crear nuevas conexiones comerciales entre las autoridades y empresas portuarias alemanas y letonas.</p><p> </p><p> </p></div>
