<h1 class="article-title">La administración de la ZEE de Liepāja concluye el proceso de desarrollo del proyecto de construcción "Reconstrucción del muelle nº 46 del puerto de Liepāja"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>El objetivo del proyecto "Garantizar el amarre seguro de ferries Ro-Ro en el puerto de Liepāja" (en adelante, el Proyecto) es garantizar el amarre seguro de ferries RO-RO en el puerto de Liepāja, reforzando así la capacidad de la infraestructura RTE-T y mejorando la accesibilidad de los mercados internos y externos, utilizando mejores conexiones de transporte marítimo.</p><p>El 20 de septiembre de 2024, la Administración de la Zona Económica Especial de Liepāja y SIA "CHR Design Solutions" firmaron un acuerdo sobre el desarrollo del proyecto de construcción "Reconstrucción del muelle nº 46 del puerto de Liepāja". El 20 de agosto de 2025, la Autoridad de Construcción de la ciudad de Liepāja marcó el cumplimiento de las condiciones de diseño en el permiso de construcción No. BIS-BV-4.2-2025-18 (7/2025) del 21 de enero de 2025, aprobando así la finalización del desarrollo del proyecto de construcción "Reconstrucción del muelle del puerto de Liepāja No. 46". </p><p>La ejecución del proyecto incluye la instalación de pilotes de amarre adicionales, la reconstrucción de las estructuras del muelle y el aumento de la profundidad del agua de 10,5 a 12,0 m y garantizará la operación segura del ferry RO - RO / RO - PAX con una longitud máxima de hasta 240,0 metros y un calado de hasta 11,0 metros. </p><p>El coste total de ejecución del proyecto es de 23.090.050 euros. </p><p>El proyecto "Garantizar el amarre seguro de ferries Ro-Ro en el puerto de Liepāja" (acrónimo de proyecto 22-LV-TG-LPXRORO) está parcialmente financiado en el marco del programa CEF2027 (tema ID - CEF-T-2022-COMPGEN-MARP-WORKS, proyecto n.º 101122785). La contribución del Mecanismo Conectar Europa cubre el 30% de los costes subvencionables del proyecto, que ascienden a 6.927.015 EUR.</p></div>
