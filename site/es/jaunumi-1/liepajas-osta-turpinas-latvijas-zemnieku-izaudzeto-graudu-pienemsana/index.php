<h1 class="article-title">Continúa la aceptación de cereales cultivados por agricultores letones en el puerto de Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Liepaja Bulk Terminal, la terminal de carga a granel más grande del puerto de Liepāja, ha celebrado acuerdos con los principales exportadores de cereales de Letonia, incluidos "Baltic Agro", "Latraps" y "Linas Agro", para la aceptación de cereales cultivados por los agricultores letones del 1 de julio de 2026 al 1 de julio de 2027. Actualmente, el trigo cultivado en Letonia se está cargando en la terminal en el buque de clase Panamax "Tuo Fu 8", que recibirá más de 60 mil toneladas de cereales en el puerto. El destino del barco es Abu Dhabi, Emiratos Árabes Unidos.</p><p>La segunda terminal de cereales más grande, "DanStore", también funciona de acuerdo con los contratos firmados. Según la dirección de la terminal, actualmente hay capacidad de almacenamiento gratuita, ya que las entregas de la nueva cosecha son relativamente lentas. Si otros años se han formado largas colas de camiones en la terminal a esta hora, este año no se observa tal situación. La empresa admite que algunos productores de cereales letones esperan condiciones de venta más favorables y precios más altos. Actualmente, el precio de los cereales se sitúa entre 250 y 260 euros por tonelada, uno de los más altos de los últimos años.</p><p>En los próximos días "DanStore" espera un barco entregado por la empresa "Baltic Agro", que cargará aproximadamente 27 mil toneladas de cereales letones. El destino de la carga será Nigeria.</p><p>El grano letón llega al puerto de Liepāja no sólo por carretera, sino también por ferrocarril. El 2 de septiembre, la terminal LBT aceptó un tren con 26 vagones o 1.820 toneladas de cereales de "Baltic Agro", y se espera otro tren con 26 vagones de la cooperativa "Latraps".</p><p>Históricamente, así como después de la reanudación de sus operaciones en los años noventa del siglo XX, el puerto de Liepāja ha desarrollado intencionalmente el manejo de carga agrícola, prestando especial atención a las terminales de granos y atendiendo carga de origen local. Un lugar importante en el flujo de carga del puerto es la exportación de cereales cultivados en Letonia a los mercados mundiales.</p><p>Actualmente, en el puerto de Liepāja funcionan varias terminales de carga agrícola, cuya capacidad total de manipulación alcanza aproximadamente los 5 millones de toneladas al año. La capacidad total de almacenamiento de las terminales para el almacenamiento simultáneo de granos es de aproximadamente 730 mil toneladas.</p><p>Las terminales de cereales del puerto de Liepāja cooperan con empresas letonas y extranjeras que garantizan la compra, el almacenamiento y la entrega de cereales en las cadenas mundiales de suministro de alimentos. Todas las operaciones de carga, incluida la manipulación de carga en tránsito de cereales, se llevan a cabo en el puerto de Liepāja de acuerdo con los requisitos reglamentarios de la Unión Europea y la Comisión Europea.</p></div>
