<h1 class="article-title">Embajadora de Estados Unidos en Letonia, Melissa Argziros, "Las ambiciones industriales de Liepāja encarnan el espíritu de Letonia"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>"Está claro que las ambiciones industriales de Liepāja encarnan el espíritu de Letonia", admitió la embajadora de Estados Unidos en Letonia, Melissa Argžiros, que el 16 de abril conoció el funcionamiento del puerto de Liepāja y de la zona económica especial. El director de la ZEE de Liepāja, Uldis Hmieļevskis, también presentó al embajador los proyectos industriales y de energía verde previstos que se combinan en el Centro de Industria Sostenible de Liepaja y se complementan entre sí.</p><p>Uno de ellos está directamente relacionado con la empresa estadounidense de tecnología de ingeniería global KBR, que suministrará a la planta NorSAF tecnología de producción de combustible de aviación sostenible (SAF) y combustible sintético (eSAF). KBR facturó el año pasado 7,8 mil millones de dólares y se especializa tanto en el desarrollo como en la implementación de altas tecnologías, creando fábricas a gran escala de diversas tecnologías en muchos lugares del mundo, pero por primera vez en los países bálticos. Además, desde hace 60 años, KBR realiza pedidos a la NASA para misiones espaciales por valor de miles de millones año tras año.</p><p>Jānis Kisiels, miembro de la junta directiva de LSEZ SIA "NorSAF": "Estamos orgullosos de poder trabajar codo a codo con una empresa tan profesional, experimentada y exitosa como KBR para desarrollar e implementar el primer proyecto de alta tecnología en los países bálticos y el más grande del norte de Europa en el campo del combustible de aviación sostenible. También es emocionante observar el trabajo de KBR todos los días: la compañía es un socio importante de la NASA, que participa con competencia técnica y apoyo operativo en misiones como el programa Artemis y el James Webb Space Telescope Utilizando estas tecnologías, NorSAF fortalecerá la seguridad energética y regional de Letonia y Europa, garantizando la disponibilidad sostenible de combustible de aviación".</p><p>NorSAF, empresa de capital de la ZEE de Liepāja, está desarrollando una planta de producción a escala industrial de combustible de aviación sostenible (SAF) y combustible sintético (eSAF) en la zona económica especial de Liepāja. La planta planea utilizar tecnologías innovadoras con licencia de KBR, así como materias primas (CO₂, bioetanol e hidrógeno verde) para garantizar la producción de combustibles de aviación de próxima generación de acuerdo con los objetivos de descarbonización de la UE.</p></div>
