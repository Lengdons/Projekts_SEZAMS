<h1 class="article-title">Licitación abierta para la "Compra de electricidad para las necesidades de la administración de la zona económica especial de Liepāja" Número de identificación de la adquisición: LSEZ2021/73/K</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>El objeto de la contratación es la compra de electricidad para las necesidades de la administración de la ZEE de Liepāja, que debe realizarse de conformidad con los requisitos del presente reglamento y los apéndices adjuntos (en adelante, el Reglamento). El objeto de la contratación no incluye el transporte (suministro) de electricidad, transmisión y distribución.</p><p>&nbsp;</p><p>Código de nomenclatura del objeto de la licitación (CPV) - 09310000-5.</p><p>&nbsp;</p><p>El contrato de adquisición se concluye de conformidad con el proyecto de contrato de adquisición (Apéndice 6 del Reglamento).</p><p>&nbsp;</p><p>El plazo de prestación del servicio es de 4 (cuatro) meses - desde el 1 de diciembre de 2021 hasta el 31 de marzo de 2022.</p><p>&nbsp;</p><p>&nbsp;</p><p>La información adicional proporcionada a los proveedores sobre los documentos de contratación y las modificaciones a los documentos de contratación (si corresponde) estarán disponibles en el sitio web de la Administración de la Zona Económica Especial de Liepāja. <a href="../index.php">http://www.liepaja-sez.lv/es/parvalde/iepirkumi</a>  y EIS en el perfil del comprador <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>  en el subsistema de licitación electrónica en el apartado de esta contratación abierta.</p><p>&nbsp;</p><p>La oferta deberá presentarse antes del 15 de noviembre de 2021 a las 10:00 horas de forma electrónica en el subsistema de licitaciones electrónicas EIS.</p></div>
