<h1 class="article-title">La Junta de la ZEE de Liepaja organiza una subasta electrónica con un paso ascendente para los inmuebles de nueva creación en la calle Eksporta 3</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>La Administración de la Zona Económica Especial de Liepāja, con el número de registro unificado LV90000329402, está celebrando una subasta electrónica con un paso ascendente para bienes inmuebles de nueva creación en la calle Eksporta 3, Liepāja, que consistirá en una unidad de terreno con una superficie total de 51521 m<sup>2</sup> y 12 edificios.</p><p>Precio inicial – <strong>680.000,00 euros</strong> (seiscientos ochenta mil <i>euros</i> y 00 centavos), paso de subasta - <strong>6.800,00 EUR</strong> (seis mil ochocientos <i>euros</i> y 00 centavos), dinero de garantía de subasta - <strong>68.000,00 euros</strong> (sesenta y ocho mil <i>euros</i> y 00 céntimos). El pago de la compra se podrá realizar en el siguiente orden:</p><ul><li>Dentro de los 10 días hábiles siguientes a la fecha de entrada en vigor del contrato preliminar, el comprador abona un anticipo del 30% (treinta por ciento) del precio de compra. </li><li>El resto del importe de la compra será abonado por el comprador en un plazo de dos semanas a partir de la celebración del contrato de compra.</li></ul><p>La subasta comienza el 06.10.2026. a las 13:00 y finaliza el 05.11.2026. a las 13:00</p><p>Los solicitantes pueden registrarse para la subasta a partir del 06.10.2026. a las 13:00 hasta el 26.10.2026. a las 23:59 en el sitio web de la subasta:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Una persona que quiera participar en la subasta deberá pagar un depósito de garantía: el 10% (diez por ciento) del precio inicial del inmueble a subastar, antes de la fecha límite de registro de la subasta, es decir. <strong>68.000,00 euros</strong> (sesenta y ocho mil <i>euros</i> y 00 centavos), que pueden acreditarse en la cuenta corriente de la administración de la LSEZ: administración de la zona económica especial de Liepaja, registro unificado no. LV90000329402, AS "SEB banka", número de cuenta LV42UNLA0012000609480, marcada "Bienes inmuebles en Eksporta Street 3, Liepāja, garantía de subasta". </p><p>La subasta se realiza electrónicamente en el sitio web: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Para la subasta de inmuebles llamar al 29294267, dirección de correo electrónico: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
