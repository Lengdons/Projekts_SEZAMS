<h1 class="article-title">Creación de la red de seguimiento del canal Karosta (Id. No. LSEZ 2023/15)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>La Comisión de Adquisiciones de la Administración de la Zona Económica Especial de Liepāja ha tomado una decisión sobre los resultados de la contratación abierta "Establecimiento de la red de seguimiento del canal Karosta" (LSEZ 2023/15), adjudicando el contrato a SIA "Isliena V" (5000204363) por un precio total del contrato de 79280,00 EUR, sin incluir el IVA.</p><p>&nbsp;</p><p><strong>código CPV</strong></p><p>Código CPV: 45122000-8 (Trabajos de perforación exploratoria)</p><p><strong>Proyecto</strong></p><p>El proyecto se implementa dentro de la cofinanciación del fondo del programa noruego del instrumento financiero 2014-2021 "Mitigación del cambio climático, adaptación y medio ambiente". El objeto del contrato "Establecimiento de una red de vigilancia del puerto de Liepāja Canal Karosta" (en adelante, el Acuerdo) es una de las medidas implementadas por la Zona Económica Especial de Liepaja (en adelante, el Cliente) en el marco del proyecto "Sitios históricamente contaminados del Canal Karosta del puerto de Liepāja" (en adelante, el Proyecto).</p><p><strong>Hora y lugar de ejecución del contrato.</strong></p><p>1. Plazo de ejecución del contrato: deberá garantizarse en 3 (tres) meses, pero a más tardar el 26 de abril de 2024. </p><p>2. Lugar de ejecución del contrato: El lugar de ejecución de las obras (Figura 6.2) es el canal Karosta del puerto de Liepāja, la parte de las aguas interiores del puerto (catastro No. 1700-010-0073; 1700-010-0306) y el territorio del área auxiliar tecnológica, que es adyacente al lugar de depósito y que está gestionado por la junta de LSEZ (catastro No. 1700-010-0072).</p><p><strong>Procedimiento de contratación</strong></p><p>Contratación abierta de conformidad con las Directrices de Contratación para proveedores de servicios públicos (en adelante, Directrices). Disponible: Directrices de adquisiciones para proveedores de servicios públicos | Oficina de Supervisión de Adquisiciones (iub.gov.lv). </p><p>Las ofertas deberán presentarse en el subsistema de licitación electrónica del Sistema Electrónico de Contratación (en adelante, EIS) (<a href="https://www.eis.gov.lv/EKEIS/Supplier">https://www.eis.gov.lv/EKEIS/Supplier</a>/) hasta el 13 de febrero de 2024 a las 10:00 horas.</p></div>
