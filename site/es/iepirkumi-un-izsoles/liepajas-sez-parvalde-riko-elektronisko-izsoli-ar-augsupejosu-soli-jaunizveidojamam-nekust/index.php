<h1 class="article-title">La Junta de la ZEE de Liepaja organiza una subasta electrónica con un paso ascendente para los inmuebles de nueva creación en la calle Dūmu 6</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>La Administración de la Zona Económica Especial de Liepāja, número de registro unificado LV90000329402, está celebrando una subasta electrónica con paso ascendente para bienes inmuebles de nueva creación en la calle Dūmu 6, Liepāja, que consistirá en un edificio con designación catastral 17000220059068 y una unidad de terreno con designación catastral 17000220351 con una superficie total de 46.766 m<sup>2</sup>.</p><p>Precio inicial – 480.000,00 EUR (cuatrocientos ochenta mil <i>euros</i> y 00 céntimos), paso de subasta – 4.800,00 EUR (cuatro mil ochocientos <i>euros</i> y 00 céntimos), dinero de garantía de la subasta – 48.000,00 EUR (cuarenta y ocho mil <i>euros</i> y 00 céntimos). El pago de la compra se podrá realizar en el siguiente orden:</p><ul><li>Dentro de los 10 días hábiles siguientes a la fecha de entrada en vigor del contrato preliminar, el comprador abona un anticipo del 30% (treinta por ciento) del precio de compra. </li><li>El resto del importe de la compra será abonado por el comprador en un plazo de dos semanas a partir de la celebración del contrato de compra.</li></ul><p>La subasta comienza el 04.08.2026. a las 13:00 y finaliza el 03.09.2026. a las 13:00</p><p>Los solicitantes pueden registrarse para la subasta a partir del 04.08.2026. a las 13:00 hasta el 24.08.2026. a las 23:59 en el sitio web de la subasta:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Una persona que quiera participar en la subasta deberá pagar un depósito de garantía: el 10% (diez por ciento) del precio inicial del inmueble subastado, es decir, 48.000,00 EUR (cuarenta y ocho mil <i>euros</i> y 00 centavos), que pueden acreditarse en la cuenta corriente de la administración de la LSEZ: administración de la zona económica especial de Liepaja, registro unificado no. LV90000329402, AS "SEB banka", número de cuenta LV42UNLA0012000609480, marcada "Propiedad en Dūmu Street 6, Liepāja, seguridad de subasta". </p><p>La subasta se realiza electrónicamente en el sitio web: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Para la subasta de inmuebles llamar al 29294267, dirección de correo electrónico: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
