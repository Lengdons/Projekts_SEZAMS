<h1 class="article-title">Nueva subasta con paso ascendente para inmuebles en la calle Naglu 1</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Administración de la Zona Económica Especial de Liepāja, registro unificado no. LV90000329402, está llevando a cabo una nueva subasta electrónica con paso ascendente para bienes inmuebles en la calle Naglu 1, Liepaja, catastro no. 17000220152, el cual estará compuesto por un edificio con designación catastral 17000220059027 y una unidad de terreno con una superficie total de 15048 m<sup>2</sup>.</p><p>Precio inicial – <strong>295.000,00 euros </strong>(doscientos noventa y cinco mil <i>euros</i> y 00 centavos), paso de subasta - <strong>2950,00 EUR</strong> (dos mil novecientos cincuenta <i>euros</i> y 00 centavos), dinero de garantía de subasta - <strong>29.500,00 EUR</strong> (veintinueve mil quinientos <i>euros</i> y 00 céntimos). El pago de la compra se podrá realizar en el siguiente orden:</p><ul><li>Dentro de los 10 días hábiles siguientes a la fecha de entrada en vigor del contrato preliminar, el comprador abona un anticipo del 30% (treinta por ciento) del precio de compra. </li><li>El resto del importe de la compra será abonado por el comprador en un plazo de dos semanas a partir de la celebración del contrato de compra.</li></ul><p>La subasta comienza el 19.06.2026. a las 13:00 y finaliza el 20.07.2026. a las 13:00.</p><p>Los solicitantes pueden registrarse para la subasta a partir del 19.06.2026. a las 13:00 hasta el 09.07.2026. a las 23:59 en el sitio web de la subasta:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>La persona que quiera participar en la subasta deberá pagar un depósito de garantía - el 10% (diez por ciento) del precio inicial del inmueble a subastar, es decir, 29.500,00 euros (veintinueve mil quinientos <i>euros</i> y 00 centavos), que pueden acreditarse en la cuenta corriente de la administración de la LSEZ: administración de la zona económica especial de Liepaja, registro unificado no. LV90000329402, JSC "SEB banka", número de cuenta LV42UNLA0012000609480, con la etiqueta "Bienes inmuebles en la calle Naglu 1, subasta de seguridad". </p><p>La subasta se realiza electrónicamente en el sitio web: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Para repetir subasta inmobiliaria llamar al 29294267, dirección de correo electrónico: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p><p>Información adicional: Las bases de la subasta están disponibles en el sitio web. <a href="../index.php">https://liepaja-sez.lv/es/iepirkumi-un-izsoles/</a>.</p></div>
