<h1 class="article-title">Nueva subasta con paso ascendente para inmuebles en la calle Naglu 1</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Administración de la Zona Económica Especial de Liepāja, registro unificado no. LV90000329402, está llevando a cabo una nueva subasta electrónica con paso ascendente para bienes inmuebles en la calle Naglu 1, Liepaja, catastro no. 17000220152, el cual estará compuesto por un edificio con denominación catastral 17000220059027 y una unidad de terreno con una superficie total de 15048 m2.</p><p>Precio inicial – 295.000,00 EUR (doscientos noventa y cinco mil euros con 00 céntimos), paso de subasta – 2950,00 EUR (dos mil novecientos cincuenta euros con 00 céntimos), dinero de garantía de la subasta – 29.500,00 EUR (veintinueve mil quinientos euros con 00 céntimos). El pago de la compra se podrá realizar en el siguiente orden:</p><p>- Dentro de los 10 días hábiles siguientes a la fecha de entrada en vigor del precontrato, el comprador abona un anticipo del 30% (treinta por ciento) del precio de compra.</p><p>- El comprador paga la parte restante del precio de compra dentro de las dos semanas siguientes a la celebración del contrato de compra.</p><p>La subasta comienza el 20.02.2026. a las 13:00 y finaliza el 23.03.2026. a las 13:00.</p><p>Los solicitantes pueden registrarse para la subasta a partir del 20.02.2025. a las 13:00 hasta el 12.03.2025. a las 23:59 en el sitio web de la subasta: <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>.</p><p>Una persona que quiera participar en la subasta debe pagar un depósito de garantía: el 10% (diez por ciento) del precio inicial del inmueble a subastar, es decir, 29.500,00 EUR (veintinueve mil quinientos euros con 00 céntimos), que se acredita en la cuenta corriente de la administración de la LSEZ: administración de la zona económica especial de Liepāja, registro unificado no. LV90000329402, JSC "SEB banka", número de cuenta LV42UNLA0012000609480, con la etiqueta "Bienes inmuebles en la calle Naglu 1, subasta de seguridad". La subasta se realiza electrónicamente en el sitio web: <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>. Para la subasta de bienes inmuebles, llame al 29294267, dirección de correo electrónico: raivo.spaks@lsez.lv.</p></div>
