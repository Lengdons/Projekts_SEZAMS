          }
        }
      }

      if (totalWeight < 5) {
        logoLuminanceCache[partnerId] = { avgLum: 180, darkRatio: 0.1 };
      } else {
        logoLuminanceCache[partnerId] = {
          avgLum: weightedLumSum / totalWeight,
          darkRatio: darkPixelWeight / totalWeight
        };
      }
    } catch (err) {
      logoLuminanceCache[partnerId] = { avgLum: 75, darkRatio: 0.65 };
    }
    return logoLuminanceCache[partnerId];
  }

  function applyDynamicPortalShading(partnerId, imgEl) {
