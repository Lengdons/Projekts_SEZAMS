<h1 class="article-title">Garantizar el amarre seguro de los ferries Ro-Ro en el puerto de Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Garantizar un tráfico regular y continuo de transbordadores depende directamente del estado técnico de la infraestructura portuaria utilizada para su servicio. Muelle del puerto de Liepāja núm. 46 fue construido entre 1972 y 1975 con el objetivo de proporcionar estacionamiento y mantenimiento a barcos y submarinos de la Armada Soviética. En las condiciones actuales, los muelles que sirven para el tráfico regular de transbordadores están expuestos a mayores cargas causadas por el amarre y desamarre de los barcos del muelle con potentes motores marinos, es decir, a una carga que excede la carga sobre las estructuras de un muelle creadas por los barcos en los años 1970 y 1980.</p><p>El objetivo del proyecto "Garantizar el amarre seguro de ferries Ro-Ro en el puerto de Liepāja" (en adelante, el Proyecto) es garantizar el amarre seguro de ferries RO-RO en el puerto de Liepāja, reforzando así la capacidad de la infraestructura RTE-T y mejorando la accesibilidad de los mercados internos y externos, utilizando mejores conexiones de transporte marítimo.</p><p>La ejecución del proyecto incluye la instalación de pilotes de amarre adicionales, la reconstrucción de las estructuras del muelle y el aumento de la profundidad del agua de 10,5 a 12,0 m y garantizará la operación segura del ferry RO - RO / RO - PAX con una longitud máxima de hasta 240,0 metros y un calado de hasta 11,0 metros. </p><p>El coste total de ejecución del proyecto es de 23.090.050 euros. </p><p>El proyecto "Garantizar el amarre seguro de ferries Ro-Ro en el puerto de Liepāja" (acrónimo de proyecto 22-LV-TG-LPXRORO) está parcialmente financiado en el marco del programa CEF2027 (tema ID - CEF-T-2022-COMPGEN-MARP-WORKS, proyecto n.º 101122785). La contribución del Mecanismo Conectar Europa cubre el 30% de los costes subvencionables del proyecto, que ascienden a 6.927.015 EUR.</p></div>
