<h1 class="article-title"> El 8 de enero de 2024, la Administración de la Zona Económica Especial de Liepāja firmó contratos para el inicio de las obras de construcción del proyecto "Desarrollo del territorio del Parque Industrial de Liepāja, Fase 1".</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>El 8 de enero de 2024, la Administración de la Zona Económica Especial de Liepāja firmó contratos para el inicio de las obras de construcción del proyecto "Desarrollo del territorio del Parque Industrial de Liepāja, Fase 1". Como parte del proyecto, el territorio de la antigua fábrica "Liepājas Metalurgs" en Liepāja entre las calles Brīvības, Meldru, Liepājas Ezer, Ezermalas, Parka y Zemnieku se reconstruirá con los territorios adyacentes que bordean el lago Liepājas, mediante la construcción de infraestructura de calles públicas con redes de ingeniería, para garantizar la infraestructura comercial básica, creando un parque industrial operativo de importancia nacional, asegurando la funcionalidad desarrollada del territorio de acuerdo con el aprobado. Estrategia de desarrollo a largo plazo del parque industrial de Liepaja para 2023-2038.</p><p>El objetivo del proyecto es transformar el territorio de la antigua fábrica "Liepājas metalurgs" en un parque ecoindustrial verde de importancia nacional, mediante la construcción de infraestructura básica moderna, la atracción de inversores, la creación de una producción de alto valor añadido orientada a la exportación en las industrias RIS3 y la creación de puestos de trabajo cualificados y bien remunerados.</p><p>El proyecto prevé inversiones en la construcción de infraestructura pública: calles y comunicaciones de ingeniería previstas en ellas.</p><p>Como resultado de la implementación del proyecto, se generarán varios beneficios importantes a largo plazo:</p><ul><li>el aumento del empleo en la región promoverá la actividad económica de la ciudad de Liepāja, el distrito de Kurzeme del Sur y la región de Kurzeme y reducirá la carga social;</li><li>atracción de industrias con mayor valor añadido y especialistas necesarios, que promoverán el desarrollo de los campos de la educación y la investigación y garantizarán el crecimiento de una fuerza laboral educada tanto en la región de Kurzeme como en Letonia;</li><li>el desarrollo de industrias de mayor valor agregado, sus mecanismos de cooperación y ecosistema orientados a soluciones climáticamente neutrales, que promoverán el desarrollo de soluciones innovadoras y la formación de nuevas empresas a escala local;</li><li>aumentar los ingresos fiscales en los presupuestos de los gobiernos estatales y locales, lo que proporcionará una contribución significativa a la financiación de las funciones de los gobiernos estatales y locales.</li></ul><p>La financiación del proyecto corre a cargo del Plan 3.1 del Mecanismo de Recuperación y Resiliencia de la Unión Europea. en la subsección 3.1.1.3.i de la dirección de reforma e inversión "Política Regional". inversiones en el marco de “Inversiones en infraestructura pública empresarial para el desarrollo de parques industriales y territorios en las regiones”.</p></div>
