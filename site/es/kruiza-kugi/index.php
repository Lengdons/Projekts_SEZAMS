<div class="col-12 col-md-3 column-content">
<img alt="icono" class="icon" src="../../img/block/columns/168/1725616669_kruizu-kugjis.svg"/>
<p>El puerto de Liepāja ha sido reconocido como un exitoso centro regional de transbordo de carga, mientras que últimamente también ha ido creciendo el interés de la industria de cruceros en Liepaja. Ya miles de turistas llegaron a Liepāja por mar en la ruta del ferry desde Traveminde, en Alemania. Ahora se cree que los visitantes de la ciudad también podrían venir en cruceros.</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icono" class="icon" src="../../img/block/columns/169/1725616901_enkurs.svg"/>
<p>Un viaje en crucero no es sólo tiempo a bordo: ningún viaje está completo sin una excursión en tierra. Liepāja es uno de los destinos de cruceros más nuevos en la costa oeste del Mar Báltico y ofrece la mejor experiencia para los pasajeros de cruceros.</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icono" class="icon" src="../../img/block/columns/170/1725616778_divas-majinas.svg"/>
<p>Los muelles de cruceros están ubicados muy cerca del paso del puerto, lo que brinda fácil acceso al centro de la ciudad y otros destinos turísticos, donde se ofrecen recorridos guiados a pie o en autobús para explorar la historia, cultura, gastronomía, parques paisajísticos, arquitectura histórica y moderna, playas con Bandera Azul y más.</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icono" class="icon" src="../../img/block/columns/171/1725617099_baltijas-karte.svg"/>
<p>Los visitantes de la ciudad que opten por el turismo patrimonial militar pueden visitar el territorio militar histórico más grande de los países bálticos: una parte de la ciudad llamada Karosta, que fue construida en el siglo XIX con fines militares. Es único en su contexto histórico y arquitectónico, no sólo en Letonia, sino también en todo el mundo.</p>
</div>
