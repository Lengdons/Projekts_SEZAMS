<h5 class="mb-0">
<button aria-controls="collapse4720" aria-expanded="false" class="accordion-button collapsed" data-bs-target="#collapse4720" data-bs-toggle="collapse">

Historia del puente

</button>
</h5>
</div>
<div aria-labelledby="heading4720" class="collapse" data-parent="#accordion" id="collapse4720">
<div class="card-body">
<p>Hasta principios del siglo XX, Karosta no tenía conexión directa con el resto de la ciudad de Liepāja, porque la carretera estaba interrumpida por un amplio canal de entrada al puerto. El tráfico a través del canal se mantenía mediante un gran ferry propulsado por vapor. Para conectar Liepāja con el entonces puerto de Alejandro III, en 1903 se inició el diseño del puente levadizo y en 1904 comenzó la construcción del puente diseñado por el ingeniero alemán Harald Hall sobre el canal. Las estructuras metálicas del puente se fabricaron en la ciudad rusa de Bryansk, mientras que los mecanismos de giro y el motor eléctrico se fabricaron en Bélgica.</p><p> </p><h5>Fue inaugurado el 19 de agosto de 1906 y es uno de los puentes de estructuras metálicas más antiguos de Letonia, un monumento de ingeniería.</h5><p> </p><p>En 1908, en la revista de literatura técnica alemana "Zeitschrift des vereines deutscher Ingenieure" se publicó una publicación titulada "Drehbrücke über den großen Hafenkanal in Libau", que es la única fuente auténtica sobre la construcción del puente, las cargas calculadas y el funcionamiento de los mecanismos de corte.</p><p>Durante sus 117 años de existencia, el puente ha sobrevivido a dos guerras y a diferentes propietarios, lo que afectó el funcionamiento del puente. Durante la Primera Guerra Mundial, el puente fue volado, pero después de la guerra fue restaurado, pero ya en 1926 fue dañado nuevamente por el vapor "Narne". El puente fue reconstruido de nuevo, pero también sufrió daños durante la Segunda Guerra Mundial, cuando el ejército soviético bombardeó el puerto de Liepāja.</p><p> </p><h5>El puente pesa 300 toneladas y consta de dos partes (lado norte y sur) formadas por dos voladizos idénticos. La anchura de la calzada del puente es de 7,3 metros, cuyo tablero está hecho de tablas de madera. La longitud de la consola costera es de 27,55 metros y la longitud del canal es de 38,95 metros. La longitud total del puente es de 133 metros con un esquema de luces de 27,55 metros + 77,9 metros + 27,55 metros. La altura del puente sobre el nivel del agua es de 8,32 metros.</h5><p> </p><p>El ingeniero alemán Harald Hall diseñó el puente de tal manera que fuera seguro y pudiera funcionar incluso con vientos más fuertes. Cada parte del puente que se puede cortar descansa sobre un punto de apoyo: el soporte y alinea exactamente la pendiente, lo que se garantiza mediante pesas de hormigón.</p><p>Dado que el puente Oskar Kalpak es un edificio con un patrimonio cultural e histórico, durante cualquier reparación debe conservarse exactamente en la misma forma en que lo heredó el puerto de Liepāja en la actualidad.</p><br/>
