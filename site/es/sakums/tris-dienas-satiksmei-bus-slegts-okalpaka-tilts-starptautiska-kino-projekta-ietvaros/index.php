<h1 class="article-title">En el marco de un proyecto cinematográfico internacional, el puente O. Kalpak permanecerá cerrado al tráfico durante tres días</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Del 16 al 24 de octubre, Liepāja se convertirá brevemente en un lugar de rodaje para la industria cinematográfica internacional. En la ciudad se rodará la adaptación de la novela "La chica del dragón tatuado" de la popular serie de libros "Millennium", producida por la empresa "Left Bank Pictures", conocida por proyectos como "The Crown" y "Dept Q". En este proyecto se concede un papel especial al puente de Oskar Kalpak, elegido como uno de los lugares de rodaje más importantes de toda la serie. El puente estará cerrado al tráfico de peatones y vehículos durante tres días durante el rodaje, y se restringirá el tráfico de barcos.</p><p>El rodaje en el puente O. Kalpaka se llevará a cabo del 19 al 21 de octubre. Durante este tiempo, invitamos a conductores, ciclistas y peatones a planificar a tiempo su viaje hacia y desde Karosta y a contar con un posible tiempo adicional en la carretera. En colaboración con el municipio se habilitará un tráfico especial de autobuses a lo largo de la carretera de circunvalación. La información sobre este servicio se publicará en ambos extremos del puente. Por otro lado, el transporte público se desviará por rutas desviadas. </p><p>Cierre del puente O. Kalpaka para peatones y vehículos:</p><ul><li>desde el 19 de octubre de 2026 a las 08.00 horas hasta el 21 de octubre de 2026 a las 22.00 horas</li></ul><p>Además, durante el rodaje, estará restringido el acceso a la zona cercana al puente O. Kalpaka y a la vía de acceso y estacionamiento del muelle en el lado sur del canal Karosta.</p><p>Mientras dure el rodaje, el tráfico de barcos en el canal Karosta estará restringido. La administración de la ZEE de Liepāja expresa su agradecimiento a las empresas estibadoras del puerto de Liepāja, que apoyaron el importante proyecto de la industria cinematográfica y reprogramaron su trabajo en la medida de lo posible. En el canal de Karosta operan activamente cinco terminales portuarias: "Baltic Transshipment Center", "Schwenk", "DG Termināls", "Norsaf", "Baltex Bulk" y la empresa LZK, que continúa activamente reparando barcos en los muelles de Tosmares.</p><p>Es significativo que el puente Oskar Kalpak fuera elegido como uno de los lugares centrales de rodaje de este proyecto, atrayendo especial atención internacional a Liepāja. La película llegará a millones de espectadores en diferentes países, convirtiéndose en una poderosa plataforma para promover el conocimiento de la ciudad.</p><p>La implementación exitosa de un proyecto de esta escala fortalece la reputación de Liepāja como una ciudad portuaria, profesional y abierta internacionalmente capaz de implementar proyectos complejos. "Esto aumenta las posibilidades de atraer nuevos proyectos cinematográficos, artísticos y de industrias creativas en el futuro, creando beneficios económicos y de reputación a largo plazo tanto para la ciudad como para la región".</p></div>
