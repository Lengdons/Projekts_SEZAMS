  // Offscreen canvas luminance analyzer to dynamically shift blue shading for darker logos
  function analyzeLogoLuminance(imgEl, partnerId) {
    if (logoLuminanceCache[partnerId] !== undefined) {
      return logoLuminanceCache[partnerId];
    }
    try {
      const canvas = document.createElement("canvas");
      const ctx = canvas.getContext("2d");
      const w = 64;
      const h = 64;
      canvas.width = w;
      canvas.height = h;
      ctx.drawImage(imgEl, 0, 0, w, h);
      const data = ctx.getImageData(0, 0, w, h).data;

      let weightedLumSum = 0;
      let totalWeight = 0;
      let darkPixelWeight = 0;

      for (let i = 0; i < data.length; i += 4) {
        const r = data[i];
        const g = data[i + 1];
        const b = data[i + 2];
        const a = data[i + 3] / 255;

        if (a > 0.12) {
          const isNearWhiteBg = r > 240 && g > 240 && b > 240;
          if (!isNearWhiteBg) {
            const lum = 0.2126 * r + 0.7152 * g + 0.0722 * b;
            weightedLumSum += lum * a;
            totalWeight += a;
            if (lum < 110) {
              darkPixelWeight += a;
            }
          }
        }
      }

      if (totalWeight < 5) {
        logoLuminanceCache[partnerId] = { avgLum: 180, darkRatio: 0.1 };
      } else {
        logoLuminanceCache[partnerId] = {
          avgLum: weightedLumSum / totalWeight,
          darkRatio: darkPixelWeight / totalWeight
        };
      }
    } catch (err) {
      logoLuminanceCache[partnerId] = { avgLum: 75, darkRatio: 0.65 };
    }
    return logoLuminanceCache[partnerId];
  }

