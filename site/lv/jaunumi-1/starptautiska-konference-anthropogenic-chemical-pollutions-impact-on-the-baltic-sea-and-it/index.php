<h1 class="article-title">Starptautiskā konference ''Anthropogenic chemical pollution’s impact on the Baltic Sea and its related ecosystems''</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>2023. gada 11. - 12. oktobrī Liepājā norisināsies projekta Nr. NFI/AK/02 “Vēsturiski piesārņotas vietas Liepājas ostas Karostas kanāla sanācijas darbi” starptautiskā konference ''Anthropogenic chemical pollution’s impact on the Baltic Sea and its related ecosystems''. Konferenci apmeklēt tiešraidē aicināts ikviens.</p><p>Konference pulcēs vairākus Baltijas jūras reģiona vadošos pētniekus un ekspertus, kas dalīsies savās zināšanās un pieredzē ūdens piesārņojuma pētniecībā un piesārņoto vietu rekultivācijas praksē.</p><p>Vairāk par konferenci un tās programmu var lasīt: <a href="https://ej.uz/konferenesprogramma">https://ej.uz/konferenesprogramma </a></p><p>2023. gada 11. oktobrī 10:00 - 18:00 starptautiskā konference, prezentācijas un paneļdiskusijas ar pārstāvjiem no Latvijas, Igaunijas, Somijas un Norvēģijas pētnieciskajām un vides pārvaldības institūcijām.</p><p>2023. gada 12. oktobrī, dalībniekiem būs iespēja labāk iepazīties ar pašas Karostas teritorijas vēsturi, projektā paveiktajiem vides atjaunošanas darbiem un sasniegtajiem rezultātiem.</p><p>Konference ir bezmaksas un ir atvērta visiem interesentiem. Piedalīties var gan klātienē, gan attālināti tiešraides translācijā (11. oktobris).</p><p> </p><p><strong>Strādājam kopā zaļai Eiropai!</strong></p><p>Projekts tiek finansēts Norvēģijas finanšu instrumenta 2014.–2021.gada perioda programmas “Klimata pārmaiņu mazināšana, pielāgošanās tām un vide” ietvaros. Projekta kopējās izmaksas ir 5 117 647,05 EUR, no kurām 4 350 000,00 EUR ir Norvēģijas finanšu instrumenta finansējums.</p></div>
