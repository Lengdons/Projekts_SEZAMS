<h1 class="article-title">Jahtu osta noslēdz aktīvo sezonu</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>1. novembrī tradicionāli noslēdzas aktīvā jahtu sezona. Šogad Liepājas Jahtu ostā apkalpotas 243 jahtas, kas ir par par 15 jahtām vairāk. Visos sezonas mēnešos novērojams apkalpoto jahtu pieaugums, izņemot jūliju, kas tradicionāli bijis viens no aktīvākajiem mēnešiem. Joprojām visvairāk viesjahtu bija no Lietuvas un Polijas, bet bija arī pa jahtai no tādām tālām valstīm kā Čīle, Austrālija, Jaunzēlande.</p><p>Jau vairākus gadus burāšanas tradīcijas Baltijas jūrā ir mainījušās, ko ietekmē vairāki ārēji apstākļi – sākotnēji covid pandēmija, bet nu jau vairākus gadus ģeopolitiskā situācija. Jahtu plūsmu ietekmēja Krievijas agresija Ukrainā, kas gan tieši neskar Baltijas jūras reģionu, bet drošības apsvērumu dēļ atturēja daudzu valstu jahtsmeņus no burāšanas.</p><p>Kā norāda Jahtu ostas vadītājs Kārlis Kints, apkalpoto jahtu skaits ir lielāks nekā gadu iepriekš, un jahtas bieži vien uzturas ilgāk nekā vienu nakti. “Tas ir labi, jo tas nozīmē, ka burātājiem Liepāja patīk. Tā ir laba reklāma sniegtajam servisam un pilsētai.” Tāpat Kārlis Kints norādīja, ka sezonas noslēgums aizvien ir simbolisks, jo ikviena jahta tiks pieņemta, ja tā būtu atburājusi līdz Liepājai.</p><p>Šajā sezonā pie Jahtu ostas piestātnēm varēja pamanīt ne vienu vien burinieku, kuri te iegriezās gan dodoties regatēs, gan apmācot jaunos burātājus, gan izbaudot burāšanas prieku.</p><p>Jūras svētku laikā Liepājas SEZ pārvalde pie Jahtu ostas vienkopus pulcēja jūras un ezera peldlīdzekļus uz atraktīvu parādi, kas nu jau kļuvusi par jauku tradīciju un iemantojusi jau lielu popularitāti gan dalībnieku, gan skatītāju vidu. Pasākums “Pilsētas platumā no ezera uz jūru” notika jau sesto reizi.</p><p>Atskatoties uz statistiku, redzams, ka arī šogad visaktīvāk Liepājas ostu apmeklējuši burātāji no Lietuvas, Polijas, Vācijas un Skandināvijas valstīm. Vistālāko ceļu bija mērojoši peldlīdzekļi no ASV Jaunzēlandes, Austrālijas, Čīles un Maršalu salām.  Kā ierasts, Jahtu ostā visvairāk darba bijis trīs vasaras mēnešos – jūnijā apkalpotas 64, jūlijā 70, savukārt augustā ienāca 57 jahtas.</p><p>Uzziņai:</p><ul><li>Jahtu ostu savā pārvaldībā Liepājas SEZ pārvalde pārņēma 2015. gadā, savukārt 2020.gadā tika sākta tās rekonstrukcija ar jaunas infrastruktūras izbūvi, tostarp jaunas servisa ēkas uzcelšanu, kas ļāva paaugstināt ostas sniegto pakalpojumu līmeni burātājiem.</li><li>Tāpat kā citus gadus, arī 2024. gadā, Jahtu osta Liepājā vienīgā Latvijā varēja lepoties ar vides un servisa kvalitātes simbolu – Zilo karogu.</li></ul></div>
