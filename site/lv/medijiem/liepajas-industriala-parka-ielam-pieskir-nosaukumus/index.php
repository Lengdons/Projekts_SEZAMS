<h1 class="article-title">Liepājas industriālā parka ielām piešķir nosaukumus</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Liepājas valstspilsētas pašvaldības domes sēdē, 21. augustā, apstiprināti astoņi jauni ielu nosaukumi plānotajām ielām bijušās rūpnīcas “Liepājas metalurgs” teritorijā – topošajā Liepājas industriālajā parkā.</p><p>Atbilstoši pašu iedzīvotāju izvirzītajiem variantiem un balsojumam rezultātiem, piešķirti sekojoši ielu nosaukumi: Trīs skursteņu iela, Martena iela, Eksporta iela, Dzelzsgriezēja iela, Inženieru iela, Čuguna iela, Naglu iela, Dūmu iela.</p><p>Ielu nosaukuma piešķiršanā tika aktīvi iesaistīti paši iedzīvotāji. Sākotnēji liepājniekiem par topošā industriālā parka ielu nosaukumiem bija iespēja izteikt savus priekšlikumus Liepājas speciālās ekonomiskās zonas pārvaldes stendā izstādes “Ražots Liepāja” laikā, kur kopumā tika saņemti 385 ierosinājumi.</p><p>Izvērtējot visus saņemtos ieteikumus, atlasīti 14 vietas identitātei atbilstošākie nosaukumi, kas jau nav esošo ielu nosaukumu sarakstā, kā arī tādi, kas simboliski atspoguļo topošā industriālā parka rūpniecisko, kultūrvēsturisko un attīstības potenciālu, un tie tālāk virzīti publiskajai balsošanai. Iedzīvotāju balsojumā saņemta 301 balss, kā rezultātā izvēlēti astoņi ielu nosaukumi, kuri virzīti apstiprināšanai domes sēdē.</p><p>Ielu nosaukumu piešķiršanai saņemts arī Valsts valodas centra pozitīvs atzinums, kurā, citstarp, starp izvēlētajiem iedzīvotāju variantiem rosināts precizēt nosaukumu no “Skursteņu iela” uz “Trīs skursteņu iela”, kas ir iederīgāks nosaukums attiecīgajā pilsētvides ainavā un vēsturiskajā kontekstā.</p><p>Ielu nosaukumu piešķiršana ir priekšnoteikums šo ielu iekļaušanai oficiālajā adresācijas reģistrā.</p><p>Šobrīd Liepājas Industriālā parka teritorijā notiek vairāku jaunu ielu izbūve, kas sevī ietver arī gājēju, velo celiņu, pazemes inženierkomunikāciju, apgaismojuma izbūvi un apzaļumošanu. Jaunizbūvētajās Eksporta un Inženieru ielās darbi ir finiša taisnē un plānots tuvākajā laikā tās nodot ekspluatācijā. Darbi turpinās Naglu un Dzelzsgriezēja ielās, kur uzklāta asfalta pamatkārta.</p><p>Visi darbi projekta 1. kārtas ietvaros jāpabeidz līdz 2025. gada beigām.</p></div>
