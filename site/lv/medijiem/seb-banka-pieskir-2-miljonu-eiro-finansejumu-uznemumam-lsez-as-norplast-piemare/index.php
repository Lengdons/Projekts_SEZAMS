<h1 class="article-title">SEB banka piešķir 2 miljonu eiro finansējumu uzņēmuma LSEZ AS “Norplast Piemare” ražotnes būvniecībai</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>SEB banka piešķīrusi finansējumu 2 miljonu eiro apmērā Liepājas Speciālās ekonomiskās zonas uzņēmumam  “Norplast Piemare” AS jaunas ražotnes celtniecībai Liepājas ostā. Plānotā ražotne būs gandrīz 2000 kvadrātmetrus plaša, un tās būvniecību iecerēts pabeigt jau 2024. gada rudenī. Tajā tiks izgatavoti ļoti liela izmēra kompozītmateriālu izstrādājumi, kuru ražošana līdz šim Latvijā nebija iespējama. Ražotnes atrašanās tiešā ostas piestātnes tuvumā sniegs loģistikas priekšrocības un atvieglos lielgabarīta kravu transportēšanu.</p><p>“Norplast Piemare” ir viens no Norvēģijas uzņēmuma “ENTEC Group” meitas uzņēmumiem, kas Liepājā ienāca pirms vairākiem gadiem, kad tā akcijas iegādājās uzņēmums “Entec Norplast”. “Entec Norplast” ir Norvēģijas kapitāla uzņēmums, kas Latvijā dibināts 2001. gadā, un specializējas stikla šķiedras produkcijas ražošanā, kas tiek izmantota kuģu drošības aprīkojumā, naftas ieguvē, transportā, aktīvajā atpūtā, notekūdeņu attīrīšanā, zivju audzēšanā un citās jomās. Uzņēmumam jau ir ražotne Saldū, un tā produkcija tiek eksportēta visā pasaulē. </p><p>“SEB banka jau ilgstoši sadarbojas ar “Entec Norplast”, kas ir spējis iekarot nišu specifisku lielgabarīta produktu ražošanā no kompozītmateriāla. Jaunajā ražotnē taps, piemēram, liela izmēra zivju baseini, kuru transportēšanai svarīga ir ražotnes atrašanās ostā. Esam gandarīti, ka varam atbalstīt ražošanas paplašināšanu Latvijā un sadarboties ar savā nišā starptautiski atpazīstamu un novērtētu uzņēmumu, kurš aug un attīstās Latvijā,” saka SEB bankas valdes loceklis Arnis Škapars.</p><p>“Šī ražotne ir būtisks stratēģiskās attīstītības solis, ar kuru tiek saistīta mūsu uzņēmumu ilgtermiņa attīstība. Mēs esam izaugsmes uzņēmumi, un jaunais objekts Liepājā sniedz mums iespēju augt, kā arī unikālu iespēju nosūtīt lielas kompozītmateriālu konstrukcijas tieši mūsu klientiem no mums pieejamās dziļūdens piestātnes. Prieks, ka arī mūsu finanšu partneris – SEB banka – ir novērtējis uzņēmumu potenciālu visai specifiskā darbības jomā. Uzņēmumu “Entec Norplast” un “Norplast Piemare” attīstības stāsts Latvijā turpināsies ar vēl lielāku jaudu, nu jau divās ražotnēs Saldū un Liepājā,” saka “Entec Norplast” vadītājs un LSEZ “Norplast Piemare” valdes priekšsēdētājs Māris Meija.</p></div>
