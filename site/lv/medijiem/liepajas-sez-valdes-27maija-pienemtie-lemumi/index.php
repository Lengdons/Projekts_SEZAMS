<h1 class="article-title">Liepājas SEZ valdes 27.maijā pieņemtie lēmumi</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>2024. gada 27. maijā notika kārtējā Liepājas speciālās ekonomiskās zonas (Liepājas SEZ) valdes sēde, kurā izskatīja 11 darba kārtības jautājumus, pieņēma četrus lēmumus, kā arī iepazinās ar informatīvajiem ziņojumiem par Liepājas SEZ darbību un plānotajiem attīstības projektiem. </p><p><br/><strong>Par ieguldījumu līguma slēgšanu</strong><br/>Liepājas SEZ valde izskatīja, un atbalstīja “AE Partner” Liepājas speciālās ekonomiskās zonas SIA ieguldījumu projektu “Iepakošanas iekārtu iegāde” īstenošana. Projektu plānots realizēt laika posmā no 2024. gada 1. jūnija līdz 2024. gada 31. jūlijam par kopējo summu 9 765,00 EUR.</p><p><br/><strong>Par pārjaunojuma līguma slēgšanu</strong><br/>2006. gada 17. jūnijā starp Liepājas SEZ pārvaldi un Sabiedrībai ar ierobežotu atbildību “Amserv Krasta”, noslēgts nomas līgums par nekustamo īpašumu – Brīvības iela 146B, Liepājā. Nomas līguma mērķis – autosalona būvniecība, kā arī citas komercdarbības veikšana. Nomas termiņš – 2031. gada 16. jūlijs. Izskatot “Liepaja Property” SIA iesniegumu, Liepājas SEZ pārvalde nolēma pārjaunot nomas līgumu, aktualizējot nomnieka nosaukumu uz “Liepaja Property” SIA, tādējādi novēršot nesakritības nomas līgumā un zemesgrāmatu datos.</p><p><br/><strong>Par grozījumu izdarīšanu līgumā par apbūves tiesības piešķiršanu</strong><br/>2018. gada 14. maijā starp Liepājas SEZ pārvaldi un Liepājas speciālās ekonomiskās zonas “BaltEx Bulk” SIA noslēgts līgums par apbūves tiesības piešķiršanu Liepājas ostas teritorijā, Pulvera ielā 11, Liepājā. Apbūves tiesība piešķirta Būvprojekta “Noliktava – 1” realizācijai. Līguma termiņš – 2038. gada 1. jūnijs. Liepājas SEZ valde izskatot saņemto iesniegumu, nolēma atbalstīt Liepājas speciālās ekonomiskās zonas “BaltEx Bulk” SIA palielināt krauvu laukuma platību, kas saistīts ar žoga pārcelšanu un slēgt vienošanos par grozījumu izdarīšanu apbūves tiesību līgumā.</p><p><br/><strong>Par velkoņu pakalpojumiem</strong><br/>Liepājas SEZ valde izskatīja iesniegtos dokumentus un nolēma slēgt ar UAB “Mabrocona” līgumu par velkoņu pakalpojuma sniegšanu Liepājas ostā.</p></div>
