<h1 class="article-title">"AE Partner" turpina izaugsmi un stiprina ražošanas kapacitāti</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Augstas kvalitātes elektrovadības un kontroles iekārtu ražotājs AE Partner Liepājas speciālās ekonomiskās zonas (LSEZ) SIA ar stabilu izaugsmi noslēdzis 2025. gadu, palielinot gan apgrozījumu, gan arī peļņu.</p><p>2025. gadā AE Partner LSEZ SIA neto apgrozījums sasniedza 75,6 miljonu eiro, kas ir par 2% vairāk nekā gadu iepriekš. Būtiski, ka 2024. gadā finanšu rezultātus pozitīvi ietekmēja ārpuskārtas ienākumi, kas bija saistīti ar AE Partner grupas restrukturizāciju, savukārt 2025. gads atspoguļo normālu finanšu sniegumu bez šādām vienreizējiem pozīcijām. Uzņēmuma peļņa 2025. gadā palielinājusies līdz 3,6 miljoniem eiro. </p><p>Nozīmīgu ietekmi uz Latvijā un Dānijā bāzētā uzņēmuma attīstību radīja investīcijas ražošanas paplašināšanā Liepājā.</p><p>“Kopumā paplašinot uzņēmuma ražošanas un biroja telpas par 5000 kvadrātmetru, mēs guvām ne vien tūlītēju pozitīvu ietekmi, bet nodrošinām arī nepieciešamo kapacitāti turpmākajai izaugsmei. Nākotnē mēs skatāmies ar pārliecību, ka stratēģijā balstītie biznesa lēmumi veido stabilu pamatu turpmākajai attīstībai," komentē AE Partner LSEZ SIA biznesa attīstības, finanšu un IT vadītājs Mortens Bitšs Janiks (CBO Finances and IT Morten Bitsch Janik)</p><p>2025. gada peļņu pozitīvi ietekmēja arī saņemtās dividendes no meitas uzņēmuma AE Partner DK A/S, kā arī mērķtiecīgi uzlabojumi apgrozāmo līdzekļu pārvaldībā, samazinot krājumu apjomu un uzlabojot darbības efektivitāti. </p><p>Ņemot vērā uzņēmuma fokusu uz mērķtiecīgu klientu portfeļa paplašināšanu un diversificēšanu, pilnvērtīgi izmantojot ražošanas kapacitāti, efektivitātes kāpināšanu, investīcijām infrastruktūrā un digitālajos rīkos, AE Partner ir stabilas un ilgtspējīgas izaugsmes prognozes arī 2026. gadam.</p><p> </p><p><strong> Par AE Partner Liepājas speciālās ekonomiskās zonas SIA</strong></p><p>  AE Partner Liepājas speciālās ekonomiskās zonas SIA ir Latvijā un Dānijā bāzēts uzņēmums ar vairāk nekā 20 gadu pieredzi automatizācijas sistēmu risinājumu izstrādē, ražošanā un servisa nodrošināšanā tādām nozarēm kā ražošana, loģistika, kuģniecība, atjaunojamās enerģijas ražošana un citās.   </p><p>AE Partner galvenā ražotne atrodas Liepājā. Ar vairāk nekā 500 darbiniekiem uzņēmums ir viens no lielākajiem darba devējiem reģionā.   </p><p>98% AE Partner LSEZ SIA saražotās produkcijas un pakalpojumu tiek eksportēti uz vairāk nekā 25 valstīm visos kontinentos, bet galvenais eksporta tirgus ir Eiropa.  </p><p>AE Partner darbība ir balstīta pamatvērtībās:  godīgums, atklātība, komandas darbs, ieinteresētība un abpusēja cieņa, kas izpaužas attiecībās ar darbiniekiem, klientiem un sadarbības partneriem.  </p></div>
