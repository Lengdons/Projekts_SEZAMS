<h1 class="article-title">Liepājas SEZ valdes 15.septembrī pieņemtie lēmumi</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>2023. gada 15. septembrī notika kārtējā Liepājas SEZ valdes sēde, kurā tika pieņemti 4 lēmumi. Liepājas SEZ valde izdarīja grozījumus līgumā par Karostas kanāla sanācijas darbu veikšanu, nolēma pagarināt līgumu par ostas kuģu kanālu un akvatorijas dziļumu uzturēšanas darbu veikšanu, slēgt pāratjaunojuma līgumu un atbalstīja LSEZ SIA “Terrabalt” ieguldījumu līguma slēgšanu.</p><p><strong>Par līguma pagarināšanu</strong></p><p>Liepājas speciālās ekonomiskās zonas valde izskatīja un nolēma slēgt ar Sabiedrība ar ierobežotu atbildību “AQUATEX” vienošanos par grozījumu izdarīšanu 2022. gada 11. oktobrī noslēgtajā līgumā “Liepājas ostas kuģu kanālu un akvatorijas dziļumu uzturēšanas darbi”, izmantojot līgumā noteikuma par iespēju līgumu pagarināt uz laiku līdz vienam gadam.</p><p>Liepājas SEZ valde iepazinās ar Karostas kanāla sanācijas projekta īstenošanas gaitu un apstākļiem nolēma pagarināt līguma termiņu par 31 kalendāro dienu. 2023. gada 18. jūlijā, īstenojot kanāla piesārņoto nogulumu sanācijas darbus, Karostas kanāla akvatorijā tika atklāta 1952. gada ražojuma aviācijas bumba FAB-500, kā rezultātā tika pārtraukti jebkādi piesārņoto nogulumu sanācijas darbi uz vairākām dienām. Sanācijas darbu veikšana šobrīd norit ievērojot maksimālus drošības pasākumus, kas ievērojami palēnina darbu izpildi - nogulumu izņemšanas un transportēšanas uz deponēšanas vietu iepriekš plānoto dienas apjoms.</p><p><strong>Par ieguldījuma projekta īstenošanu</strong></p><p>Liepājas speciālās ekonomiskās zonas valde nolēma slēgt ar LSEZ “Terrabalt” SIA līgumu par ieguldījumu projekta “Jauna termināltraktora MAFI R 332 iegāde” veikšanu, ko plānots realizēt laika posmā no 2023.gada 21.septembra līdz 2025.gada 30.jūnijam par kopējo summu 192 000,00 EUR.</p><p><strong>Par līguma pāratjaunojumu</strong></p><p>Liepājas speciālās ekonomiskās zonas valde nolēma slēgt nomas tiesību pārjaunojuma līgumu, saskaņā ar kuru tiek atceltas saistību tiesības, kas izriet no 2004. gada 1. aprīlī starp Liepājas speciālās ekonomiskās zonas pārvaldi un SIA LSEZ “Liepaja Bulk Terminal LTD” noslēgtā līguma par nekustamā īpašuma Atslēdznieku iela 41, Liepājā nomu, pārvēršot tās jaunās saistībās tā, ka SIA LSEZ “Liepaja Bulk Terminal LTD” vietā iestājas SIA “Baltic System Transport”.</p><p>Pamats: 2023. gada 11. aprīļa pirkuma līgumus, kurš nosaka ka nekustamā īpašuma jaunais īpašnieks ir SIA “Baltic System Transport”, kuru Kurzemes rajona tiesas reģistrējusi zemesgrāmatā.</p></div>
