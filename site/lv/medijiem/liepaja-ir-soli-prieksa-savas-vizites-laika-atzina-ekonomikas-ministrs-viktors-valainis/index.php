<h1 class="article-title">“Liepāja ir soli priekšā” – savas vizītes laikā atzina ekonomikas ministrs Viktors Valainis</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Šodien, 17. maijā, vienas dienas darba vizītē Liepāju apmeklēja ekonomikas ministrs Viktors Valainis. Enerģētikas nozares attīstība, apstrādes rūpniecība, labi apmaksātas, kvalificēta darba vietas, ieguldījumi kravu pārvadājumos un eksporta attīstība, mājokļi un vēl virkne nozīmīgu ekonomikas attīstības jautājumu tika pārrunāti ar Liepājas valstspilsētas un Liepājas speciālās ekonomiskās zonas vadību.</p><p>“Liepāja jau ir soli priekšā, un mērķtiecīgi virzās, lai sasniegtu valsts nospraustos mērķus ekonomikas attīstības jomā, dubultojot ekonomiku 10 gadu laikā, veidojot jaunu pieeju enerģētikas nozarei, attīstot atkrastes vēja parkus un ūdeņraža ražošanu, veicinot produktivitāti un ražošanu ar augstu pievienoto vērtību”, atzina ekonomikas ministrs Viktors Valainis.</p><p>Darba vizītes laikā Liepājā ekonomikas ministrs iepazinās ar apstrādes rūpniecības uzņēmumiem, industriālajiem parkiem, ūdens eksporta terminālu un attīstības projektiem enerģētikas jomā. Ministrs uzsvēra, ka tieši enerģētikas nozares projekti varētu nodrošināt straujāku valsts ekonomisko attīstību, kas balstīta modernās tehnoloģijās un Liepājai ir skaidrs redzējums kā attīstīt gan atkrastes vēja enerģijas bāzi, gan kā soli pa solim virzīties, lai ražotu ūdeņradi un ar ūdeņradi darbināmas lidmašīnas.</p><p>Ekonomikas ministrs atzinīgi novērtēja arī Liepājas SEZ pārvaldību, kas ir veicinājusi investīciju piesaisti, jaunu rūpnīcu būvniecību un jaunu, kvalificētu darbavietu izveidošanu. “Šodien, kad atkal diskutējam par ostu un tranzītbiznesa pārvaldības reformu, redzam, ka Liepājas modelis strādā. Uzņēmēji kopā ar pašvaldību un valsti sēž pie viena galda un plāno, kā labāk attīstīt ekonomisko zonu, kā piesaistīt investīcijas. Arī pārējās ostas varētu tiekties uz šādu pārvaldības modeli. Man ir prieks par šodien Liepājā redzēto, par uzņēmēju ambīcijām dubultot ražošanas apjomus, par uzsāktajiem daudzu desmitu miljonu attīstības projektiem. Mēs darīsim visu, lai atbalstītu uzņēmējus.”</p></div>
