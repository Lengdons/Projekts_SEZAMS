<h1 class="article-title">Starptautiska kino projekta ietvaros trīs dienas satiksmei būs slēgts O. Kalpaka tilts</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>No 16. – 24. oktobrim Liepāja uz īsu brīdi pārtaps par starptautiskas kinoindustrijas filmēšanas laukumu. Pilsētā tiks uzņemta pasaulē populārās “Millennium” grāmatu sērijas romāna “Meitene ar pūķa tetovējumu” ekranizācija, kuru producē kompānija “Left Bank Pictures”, kas pazīstama ar tādiem projektiem kā “The Crown” un “Dept Q”. Īpaša loma šajā projektā atvēlēta Oskara Kalpaka tiltam, kas izvēlēts kā viena no nozīmīgākajām filmēšanas lokācijām visā seriālā. Tilts trīs dienās uz filmēšanas laiku tiks slēgts gājējiem un autotransportam, kā arī tiks ierobežota kuģu satiksme.</p><p>Filmēšana uz O.Kalpaka tilta notiks no 19. līdz 21. oktobrim. Šajā laikā aicinām autovadītājus, velosipēdistus un gājējus savlaicīgi plānot pārvietošanos uz un no Karostas, un rēķināties ar iespējamu papildu laiku ceļā. Sadarbībā ar pašvaldību tiks nodrošināti speciālo autobusu satiksme pa apbraucamo ceļu. Informācija par šo pakalpojumu būs izvietota abos tilta galos. Savukārt sabiedriskais transports tiks novirzīts pa apbraucamajiem maršrutiem. </p><p>O.Kalpaka tilta slēgšana gājējiem un transporta līdzekļiem:</p><ul><li>no 2026. gada 19. oktobra plkst. 08.00 līdz 21. oktobra plkst. 22.00</li></ul><p>Tāpat uz filmēšanas laiku tiks ierobežota piekļuve laukumam pie O.Kalpaka tilta un Karostas kanāla dienvidu puses mola piebraucamajam ceļam un stāvlaukumam.</p><p>Uz filmēšanas laiku tiks ierobežota kuģu satikme Karostas kanālā. Liepājas SEZ pārvalde izsaka pateicību Liepājas ostas stividorkompānijām, kuras atbalsta nozīmīgo kinoindustrijas projektu un iespēju robežās pārplānoja savus darbus. Karostas kanālā aktīvi darbojas pieci ostas termināli  – “Baltic Transhipment Center”, “Schwenk”, “DG Termināls”, “Norsaf”, “Baltex Bulk” un uzņēmums LZK, kas Tosmares dokos aktīvi turpina kuģu remontus.</p><p>Nozīmīgi, ka Oskara Kalpaka tilts šajā projektā izvēlēts kā viena no centrālajām filmēšanas vietām, pievēršot Liepājai īpašu starptautisku uzmanību. Filma sasniegs miljoniem skatītāju dažādās valstīs, kļūstot par spēcīgu platformu pilsētas atpazīstamības veicināšanai.</p><p>Veiksmīga šāda mēroga projekta īstenošana stiprina Liepājas reputāciju kā starptautiski atvērtai, profesionālai un sarežģītus projektus realizēt spējīgai ostas pilsētai. “Tas palielina iespējas nākotnē piesaistīt jaunus kino, mākslas un radošo industriju projektus, radot ilgtermiņa ekonomiskos un reputācijas ieguvumus gan pilsētai, gan reģionam.”</p></div>
