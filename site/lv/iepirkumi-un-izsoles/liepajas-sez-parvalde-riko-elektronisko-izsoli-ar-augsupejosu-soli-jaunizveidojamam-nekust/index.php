<h1 class="article-title">Liepājas SEZ pārvalde rīko elektronisko izsoli ar augšupejošu soli jaunizveidojamam nekustamajam īpašumam Dūmu ielā 6</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Liepājas speciālās ekonomiskās zonas pārvalde, vienotais reģistrācijas Nr.LV90000329402, rīko elektronisko izsoli ar augšupejošu soli jaunizveidojamam nekustamajam īpašumam Dūmu ielā 6, Liepājā, kas sastāvēs no būves ar kadastra apzīmējumu 17000220059068 un zemes vienības ar kadastra apzīmējumu 17000220351 ar kopējo platību 46 766 m<sup>2</sup>.</p><p>Sākumcena – 480 000.00 EUR (četri simti astoņdesmit tūkstoši <i>euro</i> un 00 centi), izsoles solis – 4 800.00  EUR (četri tūkstoši astoņi simti <i>euro</i> un 00 centi), izsoles nodrošinājuma nauda – 48 000.00 EUR (četrdesmit astoņi tūkstoši <i>euro</i> un 00 centi). Samaksa par pirkumu veicama sekojošā kārtībā:</p><ul><li>10 darba dienu laikā pēc priekšlīguma spēkā stāšanās dienas pircējs samaksā avansa maksājumu 30% (trīsdesmit procentus) no pirkuma maksas. </li><li>Pārējo pirkuma maksas daļu pircējs samaksā divu nedēļu laikā no pirkuma līguma noslēgšanas.</li></ul><p>Izsole sākas 04.08.2026. plkst.13:00 un noslēdzas 03.09.2026. plkst.13:00</p><p>Izsolei pretendenti var reģistrēties no 04.08.2026. plkst.13:00 līdz 24.08.2026. plkst. 23:59 izsoļu elektroniskajā vietnē:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Personai, kura vēlas piedalīties izsolē, līdz izsoles reģistrācijas beigu termiņam jāiemaksā nodrošinājuma nauda – 10% (desmit procenti) no izsolāmā nekustamā īpašuma sākumcenas, t.i., 48 000.00 EUR (četrdesmit astoņi tūkstoši <i>euro</i> un 00 centi), kas ieskaitāma LSEZ pārvaldes norēķinu kontā: Liepājas speciālās ekonomiskās zonas pārvalde, vienotais reģistrācijas Nr. LV90000329402, AS "SEB banka", konta Nr.LV42UNLA0012000609480, ar atzīmi "Nekustamā īpašuma Dūmu ielā 6, Liepājā, izsoles nodrošinājums". </p><p>Izsole norisinās elektroniski vietnē: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Par nekustamā īpašuma izsoles norisi zvanīt 29294267, e-pasta adrese: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
