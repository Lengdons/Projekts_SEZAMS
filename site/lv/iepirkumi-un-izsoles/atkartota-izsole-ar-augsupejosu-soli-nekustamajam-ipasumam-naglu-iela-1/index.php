<h1 class="article-title">Atkārtota izsole ar augšupejošu soli nekustamajam īpašumam Naglu ielā 1</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Liepājas speciālās ekonomiskās zonas pārvalde, vienotais reģistrācijas Nr.LV90000329402, rīko elektronisko atkārtotu izsoli ar augšupejošu soli nekustamajam īpašumam Naglu ielā 1, Liepājā, kadastra Nr. 17000220152, kas sastāvēs no būves ar kadastra apzīmējumu 17000220059027 un zemes vienības ar kopējo platību 15048 m<sup>2</sup>.</p><p>Sākumcena – <strong>295 000.00 EUR </strong>(divi simti deviņdesmit pieci tūkstoši <i>euro</i> un 00 centi), izsoles solis – <strong>2950.00  EUR</strong> (divi tūkstoši deviņi simti piecdesmit <i>euro</i> un 00 centi), izsoles nodrošinājuma nauda – <strong>29 500.00 EUR</strong> (divdesmit deviņi tūkstoši pieci simti <i>euro</i> un 00 centi). Samaksa par pirkumu veicama sekojošā kārtībā:</p><ul><li>10 darba dienu laikā pēc priekšlīguma spēkā stāšanās dienas pircējs samaksā avansa maksājumu 30% (trīsdesmit procentus) no pirkuma maksas. </li><li>Pārējo pirkuma maksas daļu pircējs samaksā divu nedēļu laikā no pirkuma līguma noslēgšanas.</li></ul><p>Izsole sākas 19.06.2026. plkst.13:00 un noslēdzas 20.07.2026. plkst.13:00.</p><p>Izsolei pretendenti var reģistrēties no 19.06.2026. plkst.13:00 līdz 09.07.2026. plkst. 23:59 izsoļu elektroniskajā vietnē:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Personai, kura vēlas piedalīties izsolē, līdz izsoles reģistrācijas beigu termiņam jāiemaksā nodrošinājuma nauda – 10% (desmit procenti) no izsolāmā nekustamā īpašuma sākumcenas, t.i., 29 500.00 EUR (divdesmit deviņi tūkstoši pieci simti <i>euro</i> un 00 centi), kas ieskaitāma LSEZ pārvaldes norēķinu kontā: Liepājas speciālās ekonomiskās zonas pārvalde, vienotais reģistrācijas Nr. LV90000329402, AS "SEB banka", konta Nr.LV42UNLA0012000609480, ar atzīmi "Nekustamā īpašuma Naglu ielā 1 izsoles nodrošinājums". </p><p>Izsole norisinās elektroniski vietnē: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Par atkārtotas nekustamā īpašuma izsoles norisi zvanīt 29294267, e-pasta adrese: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p><p>Papildus informācija: Izsoles noteikumi pieejami mājaslapā <a href="../index.php">https://liepaja-sez.lv/lv/iepirkumi-un-izsoles/</a>.</p></div>
