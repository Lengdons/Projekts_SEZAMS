<h1 class="article-title">Ro-Ro prāmju drošas pietauvošanās nodrošināšana Liepājas ostā</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Regulāras un nepārtrauktas prāmju satiksmes nodrošināšana ir tiešā veidā atkarīga no tās apkalpošanai izmantotās ostas infrastruktūras tehniskā stāvokļa. Liepājas ostas piestātne Nr. 46 ir uzbūvēta laika posmā no 1972. līdz 1975. gadam ar mērķi nodrošināt padomju jūras kara flotes kuģu un zemūdeņu stāvēšanu un apkalpošanu. Mūsdienu apstākļos piestātnes, kuras tiek izmantotas regulāras prāmju satiksmes apkalpošanai, ir pakļautas pastiprinātai slodzei, kuru rada kuģu pietauvošanās un attauvošanās no piestātnes, izmantojot jaudīgus kuģu dzinējus, t.i. slodzei, kas pārsniedz slodzes kādas piestātnes konstrukcijām radīja kuģi 1970. un 1980. gados.</p><p>Projekta “Ro-Ro prāmju drošas pietauvošanās nodrošināšana Liepājas ostā” (turpmāk tekstā: Projekts) mērķis ir nodrošināt drošu RO-RO prāmju pietauvošanos Liepājas ostā, tādējādi stiprinot TEN – T infrastruktūras jaudu un iekšējo un ārējo tirgu pieejamības uzlabošanu, izmantojot uzlabotus jūras transporta savienojumus.</p><p>Projekta īstenošana ietver papildu tauvošanas pāļu uzstādīšanu, piestātnes konstrukciju pārbūvi un ūdens dziļumu palielināšanu no 10,5 līdz 12,0 m un nodrošinās RO - RO/ RO - PAX prāmju ar maksimālo garumu līdz 240,0 metriem un iegrimi līdz 11,0 metriem drošu apkalpošanu. </p><p>Projekta īstenošanas kopējās izmaksas ir 23 090 050 EUR. </p><p>Projekts “Ro-Ro prāmju drošas pietauvošanās nodrošināšana Liepājas ostā” (projekta akronīms 22-LV-TG-LPXRORO) tiek daļēji finansēts CEF2027 programmas ietvaros (tēmas ID - CEF-T-2022-COMPGEN-MARP-WORKS , projekta Nr.101122785). Eiropas infrastruktūras savienošanas instrumenta ieguldījums sedz 30% no projekta attiecināmajām izmaksām 6 927 015 EUR.</p></div>
