<div class="row">
<div class="col"><div class="col-12 output"><p><strong>Plānotais projekta realizācijas laiks:</strong></p><p>2018. gada 16. februāris – 2020.gada 15.augusts</p><p><strong>Projekta ieviesējs:</strong></p><p>Liepājas speciālās ekonomiskās zonas pārvalde</p><p><strong>Projekta kopējās attiecināmās izmaksas:</strong></p><p>EUR 3 000 000, no kurām EUR 2 550 000 ir ES Kohēzijas fonda, bet EUR 450 000 ir Liepājas SEZ pārvaldes finansējums</p><p> </p><p>Liepājas ostas sekmīgas attīstības priekšnoteikumi un tās priekšrocības ir izdevīgs ģeogrāfiskais novietojums. Liepāja ir viena no tikai trim Baltijas jūras austrumu krasta neaizsalstošajām ostām, kas ir īpaši svarīgi ziemas mēnešos, apkalpojot tuvsatiksmes un līnijas satiksmes kuģus.</p><p>Liepājas osta ir būvēta neizmantojot dabiskus veidojumus - upes delta, līcis, lagūna, kas aizsargātu ostu no vēja un viļņu iedarbības, tādēļ no ārējo spēku iedarbības to aizsargā sarežģīta hidrotehnisko aizsarg būvju sistēma, kurā atrodas trīs vārti, kas savieno ostas akvatoriju ar atklāto jūru. Kalpojot militāriem mērķiem, kad Liepāja bija slēgta PSRS bruņoto spēku karabāze, ostas infrastruktūra tika uzturēta nepietiekošā līmenī un apjomā, tādējādi pašlaik daļa no ostas hidrotehniskajām būvēm ir neapmierinošā vai pat avārijas stāvoklī, kā arī no trīs ostas vārtiem regulārai kuģu kustībai tiek izmantoti tikai divi, tādējādi samazinot kuģošanas drošības līmeni, kuģiem ienākot vai izejot no ostas, kā arī pārvietojoties ostas akvatorijā. Tā rezultātā Liepājas ostas hidrotehniskās būves un to stāvoklis ir kļuvuši par problemātiskajiem punktiem, kas ierobežo Eiropas transporta tīkla infrastruktūras efektīvu darbību.</p><p>Projekta “Karostas kanāla un Ziemeļu vārtu hidrotehnisko būvju atjaunošana” mērķis ir uzlabot tuvsatiksmes kuģu kuģošanas drošības līmeni un novērst problemātisko punktu radītos ierobežojumus Eiropas transporta tīkla infrastruktūras darbībā, realizējot Liepājas ostas hidrotehnisko būvju atjaunošanas un pārbūves pasākumus.</p><p> </p><p>Projekta ietvaros tiks realizētas šādas aktivitātes:</p><p>Karostas hidrotehnisko aizsarg būvju atjaunošana;</p><p>Ziemeļu vārtu atvēršana kuģu kustībai.</p><p> </p><p>Projekta ieviešanas rezultātā tiks atjaunotas vai pārbūvētas ostas hidrotehniskās būves, t.sk. rekonstruēti divi moli, kā rezultātā atjaunotās hidrotehniskās būves un Ziemeļu vārtu atvēršana kuģu kustībai ļaus ievērojami uzlabot kuģošanas drošību, tādējādi samazinot jūras satiksmes dalībnieku potenciālos zaudējumus, t.sk., laikapstākļu ietekmēto kuģu dīkstāvju laiku, vides piesārņošanas izmaksas un importējošo valstu tautsaimniecību zaudējumus, kas ir saistīti ar nesavlaicīgu kravu saņemšanu.</p><p>Projekts Nr.6.1.1.0/17/I/004 “Karostas kanāla un Ziemeļu vārtu hidrotehnisko būvju atjaunošana” tiek īstenots darbības programmas "Izaugsme un nodarbinātība" 6.1.1.specifiskā atbalsta mērķa “Palielināt lielo ostu drošības līmeni un uzlabot transporta tīkla mobilitāti” ietvaros.</p></div>
