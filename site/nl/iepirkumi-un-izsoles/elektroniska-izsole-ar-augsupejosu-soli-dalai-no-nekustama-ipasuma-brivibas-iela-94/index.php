<h1 class="article-title">Elektronische veiling met opstap voor een deel van het onroerend goed aan Brīvībasstraat 94 (veiling gesloten)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><i><strong>Over de resultaten van de vastgoedveiling:</strong></i></p><p><i>Op 12 september 2025 eindigde de elektronische veiling van het deel van het onroerend goed aan de Brīvības-straat 94, Liepāja, georganiseerd door de Liepāja Special Economic Zone Administration. De hoogste prijs - <strong>378.750,00 EUR</strong> (driehonderdachtenzeventigduizend zevenhonderdvijftig euro), exclusief BTW, heeft geboden <strong>SIA "Nordic Steel Letland"</strong>, registratienr. 40203671003, juridisch adres: Krišjāņa Valdemāra iela 33-3F, Riga, LV-1010 (veilingresultaten goedgekeurd tijdens de bestuursvergadering van LSEZ op 08.10.2025, bestuursbesluit nr. 103).</i></p><p>_____________________________________</p><p>De Liepāja Special Economic Zone Administration, uniform registratienummer LV90000329402, houdt een elektronische veiling met oplopende trede voor een deel van het onroerend goed aan de Brīvības-straat 94, Liepāja, kadastrale aanduiding 17000220059, dat zal bestaan uit gebouwen met kadastrale aanduiding 17000220059089 en 17000220059090, en delen van de landeenheid met een totale oppervlakte van ~21778 m<sup>2</sup> (het gebied zal worden gespecificeerd nadat het onderzoek is voltooid).</p><p>Startprijs – € 375.000,00 (€ 375.000,00 (driehonderdvijfenzeventigduizend euro), veilingstap – € 3.750,00 (drieduizend zevenhonderdvijftig euro), veilingwaarborggeld – € 37.500,00 (zevenendertigduizend vijfhonderd <i>euro</i>). U kunt de aankoop in de volgende volgorde betalen:</p><ul><li>Binnen 10 werkdagen na de datum van inwerkingtreding van de voorlopige overeenkomst betaalt de koper een voorschot van 30% (dertig procent) van de koopprijs. </li><li>Het resterende deel van de koopsom dient de koper binnen twee weken na het sluiten van de koopovereenkomst te betalen.</li></ul><p>De veiling start op 12.08.2025. om 13.00 uur en eindigt op 11.09.2025. om 13:00 uur.</p><p>Aanvragers kunnen zich vanaf 12.08.2025 inschrijven voor de veiling. om 13:00 uur tot 01.09.2025. om 23:59 uur op de veilingwebsite:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Een persoon die aan de veiling wil deelnemen, moet een borgsom betalen - 10% (tien procent) van de startprijs van het geveilde onroerend goed, d.w.z. EUR 37.500,00 (zevenendertigduizend vijfhonderd euro), die kan worden bijgeschreven op de lopende rekening van de LSEZ-administratie: Liepāja speciale economische zone-administratie, uniform registratienr. LV90000329402, JSC "SEB banka", rekeningnummer LV42UNLA0012000609480, met de tag "Veiligheid van vastgoedveilingen in Brīvības straat 94". </p><p>De veiling vindt elektronisch plaats op de website: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Voor de vastgoedveiling kunt u bellen met 29294267, e-mailadres: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
