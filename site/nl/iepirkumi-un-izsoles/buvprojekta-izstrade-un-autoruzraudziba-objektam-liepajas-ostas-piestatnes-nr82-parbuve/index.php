<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><strong>Onderwerp van aankoop</strong></p><p>Bouwprojectontwikkeling en auteursbegeleiding voor het object "Reconstructie van Liepāja-havenpier nr. 82", in overeenstemming met bijlage 7 van de verordening "Bouwprojectcontract (<i>concept contract</i>)" en Bijlage 8 "Ontwerpovereenkomst voor toezicht op auteursrechten (<i>auteurssupervisiecontractproject</i>)”.</p><p><strong>1.1. CPV-code</strong></p><p>71320000-7 - Technische ontwerpdiensten.</p><p>De ontwerp- en auteurssupervisiewerkzaamheden zullen naar verwachting worden uitgevoerd en gefinancierd door het Europees Fonds voor maritieme zaken, visserij en aquacultuur "Actieplan voor de jaren 2023-2027 van het programma voor de ontwikkeling van de visserij voor de jaren 2021-2027 in de vorm van de actie "Implementatie van door de gemeenschap aangestuurde lokale ontwikkelingsstrategieën" actie 4.1. Activiteiten ondersteund door M4/R1 in het kader van het project "Versterking van de ontwikkeling van haveninfrastructuur".</p><p>Offers must be submitted in the e-tendering subsystem of the Electronic Procurement System, hereinafter referred to as EIS (<a href="https://www.eis.gov.lv/EKEIS/Supplier/"><i>https://www.eis.gov.lv/EKEIS/Supplier/</i></a>). De specifieke deadline voor het indienen van offertes is te vinden in de betreffende mededeling van het Bureau Toezicht Aanbestedingen, hierna IUB genoemd, op de website en in het subsysteem EIS e-tenders.</p><p>Tenders are opened in the EIS e-tenders subsystem. The tender opening time can be seen in the relevant notice on the IUB website and in the e-tenders subsystem of the EIS system.</p><p><strong>Aannemer: SIA "CHR Design Solutions"</strong></p><p><strong>Contractprijs: EUR 51.700,00 exclusief BTW.</strong></p></div>
