<h1 class="article-title">OPEN COMPETITIE Voor het recht om bouwwerkzaamheden uit te voeren op het grondgebied van het industriepark Liepaja, ronde 1 ("N" en "F" straatsecties)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><strong>Aankoop-ID. Nr. LSEZ2023/6/K</strong></p><p>&nbsp;</p><p><strong>Omschrijving van het aanschaffingsartikel:</strong></p><p>&nbsp;</p><p>Bouwwerkzaamheden op het grondgebied van het industriepark Liepāja in de secties "N" en "F" straten volgens het bouwproject ontwikkeld door SIA "BM-projekts" "Aanleg van straatinfrastructuur op het grondgebied van de voormalige fabriek "Liepājas metalurgs" fase 2 ("N" straatgedeelte, "F" straatgedeelte, "C" straatgedeelte)" - 2.1. voor het bouwproject "SAT-constructie op het grondgebied van de voormalige fabriek "Liepājas metalurgs" Fase 2 ("N" straatgedeelte, "F" straatgedeelte, "C" straatgedeelte)", Fase 2.1 ("N" en "F" straatgedeelten) (bijlage 10 van de voorschriften), hierna - Technische projectdocumentatie. </p><p>&nbsp;</p><p>Project nr. 3.1.1.3.i.0/1/23/A/CFLA/004 "Ontwikkeling van het grondgebied van het Liepāja industriepark 1e ronde" wordt geïmplementeerd in het kader van het herstel- en veerkrachtmechanismeplan van de Europese Unie 3.1. Hervormingen en investeringsrichting "Regionaal beleid" 3.1.1.3.i.investeringen "Investeringen in de publieke bedrijfsinfrastructuur voor de ontwikkeling van industrieparken en gebieden in de regio's".</p><p>&nbsp;</p><p>&nbsp;</p><p><strong>CPV-codes</strong></p><p>45233120-6 – Wegenbouwwerkzaamheden.</p><p>45231000-5 – Construction works of pipelines, communications and power supply lines.</p><p>44163121-4 – Verwarmingsbuizen.</p><p>34928400-2 - Stadsinfrastructuur.</p><p>34993000-4 – Straatverlichting.</p><p>&nbsp;</p><p>&nbsp;</p><p><strong>Tijd en plaats van uitvoering van de overeenkomst</strong></p><p>&nbsp;</p><ol><li>Bij het plannen van de uitvoering van bouwwerkzaamheden moet de bouwvakker zorgen voor een termijn van 250 (tweehonderdvijftig) dagen na de overdracht van het bouwobject aan de bouwer voor de aanvang van de werken met de akte van overdracht - aanvaarding.</li><li>Plaats van uitvoering van bouwwerkzaamheden: straten "N" en "F", gebied van het industriepark Liepāja.</li></ol><p>&nbsp;</p><p><strong>Aanbestedingsprocedure</strong></p><p>&nbsp;</p><ol><li>De aanbestedingsprocedure wordt uitgevoerd in overeenstemming met de Wet op de overheidsopdrachten. Het soort aanbestedingsprocedure is een open aanbesteding.</li><li>De rechtvaardiging voor het toekennen van het recht om een ​​aanbestedingsovereenkomst te sluiten zonder de aanbesteding in delen op te delen is: één groep aanvragers; één bouwobject; één periode van bouwwerkzaamheden in de faciliteit.</li></ol><p>&nbsp;</p><p>Inschrijvingen worden geopend in het subsysteem EIS e-tenders <strong>16 november 2023 om 15.00 uur</strong>.</p><p>&nbsp;</p><p>Directe en gratis elektronische toegang tot de regeling met de bijlagen wordt gegarandeerd in het kopersprofiel van de klant in het Elektronische Aanbestedingssysteem (<a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>).</p></div>
