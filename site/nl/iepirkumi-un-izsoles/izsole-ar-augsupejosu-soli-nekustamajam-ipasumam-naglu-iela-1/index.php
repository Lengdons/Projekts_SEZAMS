<h1 class="article-title">Herhaalde veiling met een opwaartse stap voor onroerend goed aan de Naglu-straat 1</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>De Liepāja Special Economic Zone Administration, verenigd registratienr. LV90000329402, houdt een elektronische herveiling met een opwaartse stap voor onroerend goed aan Naglu Street 1, Liepaja, kadasternr. 17000220152, dat zal bestaan ​​uit een gebouw met kadastrale aanduiding 17000220059027 en een grondeenheid met een totale oppervlakte van 15048 m2.</p><p>Startprijs – 295.000,00 EUR (tweehonderdvijfennegentigduizend euro en 00 cent), veilingstap – 2950,00 EUR (tweeduizend negenhonderdvijftig euro en 00 cent), veilingwaarborggeld – 29.500,00 EUR (negenentwintigduizend vijfhonderd euro en 00 cent). U kunt de aankoop in de volgende volgorde betalen:</p><p>- Binnen 10 werkdagen na de datum van inwerkingtreding van de voorlopige overeenkomst betaalt de koper een voorschot van 30% (dertig procent) van de koopprijs.</p><p>- De koper betaalt het resterende deel van de koopsom binnen twee weken na het sluiten van de koopovereenkomst.</p><p>De veiling start op 20.02.2026. om 13.00 uur en eindigt op 23.03.2026. om 13:00 uur.</p><p>Aanvragers kunnen zich vanaf 20.02.2025 inschrijven voor de veiling. om 13:00 uur tot 12.03.2025. om 23:59 uur op de veilingwebsite: <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>.</p><p>Een persoon die aan de veiling wil deelnemen, moet een borgsom betalen - 10% (tien procent) van de startprijs van het te veilen onroerend goed, d.w.z. EUR 29.500,00 (negenentwintigduizend vijfhonderd euro en 00 cent), die wordt bijgeschreven op de lopende rekening van de LSEZ-administratie: Liepāja speciale economische zone-administratie, verenigd registratienr. LV90000329402, JSC "SEB banka", rekeningnummer LV42UNLA0012000609480, met de tag "Onroerend goed op Naglu straat 1 veilingbeveiliging". De veiling vindt elektronisch plaats op de website: <a href="https://izsoles.ta.gov.lv">https://izsoles.ta.gov.lv</a>. Voor de vastgoedveiling kunt u bellen met 29294267, e-mailadres: raivo.spaks@lsez.lv.</p></div>
