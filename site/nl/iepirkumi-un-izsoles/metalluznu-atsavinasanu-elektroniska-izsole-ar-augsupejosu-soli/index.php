<h1 class="article-title">Afvoer van oud metaal in een elektronische veiling met oplopende trede</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>De Liepāja Special Economic Zone Administration (hierna: de Administration) organiseert de verkoop van roerende goederen in eigendom - schroot op een elektronische veiling met oplopende trede.</p><p>De startprijs van de veiling (voorwaardelijke prijs): voor 1 (één) ton van het Product bedraagt 123,08 EUR (honderddrieëntwintig <i>euro</i> en 8 cent), exclusief BTW.</p><p>De veilingstap wordt bepaald: € 5,00 (vijf <i>euro</i> en 0 cent).</p><p>Veilingzekerheid: 10% van de totale prijs van het item - 1.520,04 EUR (duizendvijfhonderdtwintig <i>euro</i> en 4 cent), exclusief BTW, die wordt gevormd uit het geschatte gewicht van het Product (123,5 ton) en de startprijs van het geveilde Product per ton (123,08 EUR). Veilingbeveiliging binnen 10 (tien) dagen vanaf de startdatum van de veiling moet de persoon die wil deelnemen aan de veiling overdragen aan het management, uniform registratienummer LV90000329402, AS "Swedbank", rekeningnummer LV12HABA0001407037000. Vermeld in de betalingsmelding "Voorziening schrootveiling, id. nr. LSEZ IZS 2025/9" en er moet een verzoek tot machtiging voor de veiling op de veilingsite worden verzonden <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>.</p><p>De veiling vindt plaats op de elektronische veilingsite <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>.</p><p>De veiling start op de elektronische veilingsite <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a> 01.12.2025, om 13:00 uur. Aanmelding tot 11.12.2025, om 23.59 uur.</p><p>Het is mogelijk om vertrouwd te raken met het product in de natuur en een controlebeoordeling uit te voeren door vooraf contact op te nemen met Viesturas Romanova, plaatsvervangend hoofd van de afdeling infrastructuur van de administratie, telefoon: 26795153, e-mail: <a href="mailto:viesturs.romanovs@lsez.lv">viesturs.romanovs@lsez.lv</a> .</p></div>
