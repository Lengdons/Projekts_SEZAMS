<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>De omschrijving van het aanbestedingsonderwerp is fysieke en technische beveiligingsdiensten in overeenstemming met de technische specificatie en de conceptovereenkomst.</p><p>&nbsp;</p><p>CPV-code: 79710000-4.</p><p>&nbsp;</p><p>Aanbiedingen moeten uiterlijk 21 mei 2021 om 10.00 uur worden ingediend in het deelsysteem EIS e-tenders.</p><p>&nbsp;</p><p>Openbaar beschikbare website van de klant in het elektronische informatiesysteem van de staat voor het ontvangen van aanbiedingen en aanvragen (beschikbaar in EIS: <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>), waarin de Klant informatie plaatst over toekomstige uitnodigingen om offertes in te dienen, over geplande aankopen, gesloten contracten, onderbroken procedures en andere aanbestedingsgerelateerde informatie gespecificeerd in regelgevingshandelingen.</p><p>&nbsp;</p><p>Beoordelen van de aanvrager JSC "G4S", reg. Nee. 40103058465, ingediende offerte, is de Commissie van oordeel dat de offerte van verzoekster JSC "G4S" en de offerte van verzoekster JSC "G4S" voldoen aan de eisen van het reglement van de openbare aanbesteding. De door AS "G4S" aangeboden contractprijs bedraagt ​​842878,8 euro (exclusief BTW).</p><p>&nbsp;</p><p>Aangezien volgens de regels van de open aanbesteding het criterium voor het selecteren van de aanbieding de economisch meest voordelige aanbieding is - de laagste contractprijs, de criteria voor het beoordelen van de aanbiedingen: de prijs en de evaluatiecriteria met betrekking tot het onderwerp van de aanbestedingsovereenkomst, die zijn bepaald in clausule 5.2.4.2 van de regels</p><p>&nbsp;</p><p>De Commissie besluit in de openbare wedstrijd "Het leveren van veiligheidsdiensten op het grondgebied van de haven van Liepāja", identificatienr. LSEZ2021/58/K, het recht om een ​​eventuele aanbestedingsovereenkomst af te sluiten wordt toegekend aan JSC "G4S", reg. Nee. 40103058465, met de voorgestelde aanneemsom EUR 842878,8 (exclusief BTW). </p></div>
