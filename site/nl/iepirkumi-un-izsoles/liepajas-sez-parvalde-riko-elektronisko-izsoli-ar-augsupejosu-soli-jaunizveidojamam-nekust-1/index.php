<h1 class="article-title">Het bestuur van Liepaja SEZ houdt een elektronische veiling met een opwaartse stap voor nieuw gecreëerd onroerend goed aan Eksporta Street 3</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>De Liepāja Special Economic Zone Administration, uniform registratienummer LV90000329402, houdt een elektronische veiling met oplopende trede voor nieuw gecreëerd onroerend goed aan de Eksporta-straat 3, Liepāja, dat zal bestaan uit een landeenheid met een totale oppervlakte van 51521 m2.<sup>2</sup> en 12 gebouwen.</p><p>Vanafprijs – <strong>€ 680.000,00</strong> (zeshonderdtachtigduizend <i>euro</i> en 00 cent), veilingstap - <strong>6.800,00 EUR</strong> (zesduizend achthonderd <i>euro</i> en 00 cent), veilingzekerheidsgeld - <strong>68.000,00 EUR</strong> (achtenzestigduizend <i>euro</i> en 00 cent). U kunt de aankoop in de volgende volgorde betalen:</p><ul><li>Binnen 10 werkdagen na de datum van inwerkingtreding van de voorlopige overeenkomst betaalt de koper een voorschot van 30% (dertig procent) van de koopprijs. </li><li>Het resterende deel van de koopsom dient de koper binnen twee weken na het sluiten van de koopovereenkomst te betalen.</li></ul><p>De veiling start op 06.10.2026. om 13:00 uur en eindigt op 05.11.2026. om 13:00 uur</p><p>Aanvragers kunnen zich vanaf 06.10.2026 inschrijven voor de veiling. om 13:00 uur tot 26.10.2026. om 23:59 uur op de veilingwebsite:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Een persoon die aan de veiling wil deelnemen, moet een borgsom betalen - 10% (tien procent) van de startprijs van het te veilen onroerend goed, vóór de deadline voor veilingregistratie, d.w.z. <strong>68.000,00 EUR</strong> (achtenzestigduizend <i>euro</i> en 00 cent), die kunnen worden bijgeschreven op de lopende rekening van de LSEZ-administratie: Liepaja speciale economische zone-administratie, uniform registratienr. LV90000329402, AS "SEB banka", rekeningnummer LV42UNLA0012000609480, gemarkeerd met "Onroerend goed aan Eksporta Street 3, Liepāja, veilingbeveiliging". </p><p>De veiling vindt elektronisch plaats op de website: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Voor de vastgoedveiling kunt u bellen met 29294267, e-mailadres: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
