<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><strong>CPV-codes</strong></p><p>45233120-6 - Wegenbouwwerkzaamheden.</p><p>45231000-5 - Construction works of pipelines, communications and power supply lines.</p><p>44163121-4 - Verwarmingsbuizen.</p><p>34928400-2 - Stadsinfrastructuur.</p><p>34993000-4 - Straatverlichting.</p><p>65100000-4 - Watervoorziening en aanverwante diensten.</p><p>&nbsp;</p><p>Project nr. 3.1.1.3.i.0/1/23/A/CFLA/004 "Ontwikkeling van het grondgebied van het Liepāja industriepark 1e ronde" wordt geïmplementeerd in het kader van het herstel- en veerkrachtmechanismeplan van de Europese Unie 3.1. Hervormingen en investeringsrichting "Regionaal beleid" 3.1.1.3.i.investeringen "Investeringen in de publieke bedrijfsinfrastructuur voor de ontwikkeling van industrieparken en gebieden in de regio's".</p><p>&nbsp;</p><p>1.1.1. Bij het plannen van de uitvoering van bouwwerkzaamheden moet de bouwvakker zorgen voor een termijn van 210 (tweehonderdtien) dagen na de overdracht van het bouwobject aan de bouwer voor de aanvang van de werken met de akte van overdracht - aanvaarding.</p><p>1.1.2. Place of execution of construction works: "N" and "F" streets, Liepāja industrial park territory.</p><p>&nbsp;</p><p>1.1.3. The procurement procedure is carried out in accordance with the Law on Public Procurement[1]. Het soort aanbestedingsprocedure is een open aanbesteding.</p><p>1.1.4. De rechtvaardiging voor het toekennen van het recht om een aanbestedingsovereenkomst te sluiten zonder de aanbesteding in delen op te delen is: één groep aanvragers; één bouwobject; één periode van bouwwerkzaamheden in de faciliteit.</p><p>&nbsp;</p><p>Tenders are opened in the EIS e-tenders subsystem. The tender opening time can be seen in the relevant notice on the IUB website and in the e-tenders subsystem of the EIS system.</p><p>&nbsp;</p><p>Directe en gratis elektronische toegang tot de regeling met de bijlagen is gegarandeerd in het kopersprofiel van de klant in het Elektronische Aanbestedingssysteem <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>.</p></div>
