<h1 class="article-title">Een voormalige schrootwerkplaats is een plek en gelegenheid voor interessante zakelijke ideeën</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Voortbouwend op de bouw van het Liepāja Industrial Park op het grondgebied van de voormalige fabriek van Liepāja Metalurgs, heeft de administratie van de Liepāja Speciale Economische Zone (Liepāja SEZ) de veiling aangekondigd van de oude werkplaats voor de voorbereiding van schroot aan Dūmu Street 6, Liepāja. 25,2 duizend. gebouw overgedragen voor onteigening. m<sup>2</sup> in oppervlakte en ~ 46,8 duizend. m<sup>2</sup> een groot stuk grond. Bieders kunnen zich tot 24 augustus van dit jaar aanmelden voor de veiling via de elektronische veilingwebsite, maar de veiling eindigt op 3 september om 13.00 uur.</p><p>De regering van Liepāja SEZ consolideerde aanvankelijk alle eigendommen op het grondgebied van de voormalige metaalfabriek van Liepāja, ontwikkelde samen met de gemeente het lokale plan van het gebied, begon met de aanleg van straten en technische communicatie. Veilingen voor onteigening van onroerend goed zijn de volgende stap om ondernemers te betrekken bij het proces van restauratie en transformatie van een industriegebied, waarbij de mogelijkheid wordt geboden bestaande industriële gebouwen te kopen om deze te renoveren en opnieuw op te bouwen volgens de moderne normen. <i>groene</i> economisch ondernemingsklimaat. </p><p>Het grondgebied van de voormalige Liepājas Metalurgs-fabriek wordt geleidelijk teruggegeven aan de stad, waardoor het toegankelijk wordt voor het publiek en aantrekkelijk voor investeerders. </p><p>Het Liepāja Industrial Park wordt ontwikkeld door de Liepāja SEZ Administration en de Liepāja State City Municipality in het gebied van de voormalige fabriek "Liepājas Metalurgs" tussen Brīvības Street, Meldru Street, Ezermalas Street, Parka Street en Zemnieku Street in Liepāja. Het grenst aan het Liepāja-meer, een speciaal beschermd natuurgebied NATURA 2000. Volgens de goedgekeurde ontwikkelingsstrategie is het de bedoeling om particuliere investeringen van meer dan 275 miljoen aan te trekken. EUR en minstens 1.500 nieuwe banen creëren. </p></div>
