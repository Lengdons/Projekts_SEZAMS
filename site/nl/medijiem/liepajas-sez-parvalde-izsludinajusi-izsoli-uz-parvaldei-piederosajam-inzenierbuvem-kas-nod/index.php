<h1 class="article-title">De Liepāja SEZ Authority heeft een veiling aangekondigd voor de technische gebouwen van de Autoriteit, die de prestaties van de complexe functies van de olie-afvalwaterzuiveringsinstallatie garanderen</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Om de kwaliteit van de geleverde diensten te verbeteren en een effectief beheer te garanderen, heeft de Liepāja SEZ-administratie een veiling aangekondigd voor de technische gebouwen die eigendom zijn van de administratie en die de prestaties van de complexe functies van de olie-afvalwaterzuiveringsinstallatie garanderen. Het doel van de veiling is om te bepalen welke huurder het economisch meest voordelige aanbod zal doen, en gedurende de looptijd van het huurcontract het afval zal accepteren en opruimen dat wordt afgeleverd als onderdeel van de sanitaire kosten van schepen die de haven van Liepāja binnenvaren in overeenstemming met Marpol bijlage I, in overeenstemming met de vereisten van regelgevingshandelingen. Deelnemers kunnen zich tot 11 april 2025 aanmelden voor de veiling.</p><p>De behandelingsfaciliteiten van de haven van Liepāja werden in 2004 in gebruik genomen om oliehoudend afvalwater op te vangen en te zuiveren van schepen die de haven binnenvaren, terwijl ze zorg dragen voor de toestand van het milieu in de Oostzee. Het wordt bepaald door de richtlijn havenafvalacceptatie en verplicht de Liepaja SEZ-administratie om afval te accepteren dat door schepen wordt gegenereerd, inclusief vervuild water, terwijl deze richtlijn tegelijkertijd de procedure voor het reinigen van vervuild water niet regelt.</p><p>De haven van Liepāja is de enige haven in Letland die zelf zorgt voor de behandeling van vervuild water dat door schepen wordt ontvangen. De basisfunctie van de Liepāja SEZ-administratie is zakelijke ondersteuning en voorziening, niet economische activiteit. Bij de audit van de functies van het Liepāja SEZ-management werd geconcludeerd dat het noodzakelijk is om aanvullende diensten te verlenen om de winstgevende economische exploitatie van de zuiveringsfaciliteiten van de Liepaja-haven te garanderen.  </p><p>Door de ervaringen van andere havens te analyseren en te voldoen aan de bepalingen van de wet ter voorkoming van verspilling van financiële fondsen en activa van overheidspersonen, koos het bestuur van Liepaja SEZ een andere, meer winstgevende oplossing voor de behandeling van vervuild water geproduceerd door schepen en besloot een veiling aan te kondigen voor de verhuur van havenzuiveringsapparatuur van Liepaja en het verlenen van diensten.</p><p>Meer informatie: <a href="/site/nl/iepirkumi-un-izsoles/liepajas-specialas-ekonomiskas-zonas-parvaldes-valdijuma-esosa-nekustama-ipasuma-nomas-tie/index.php">https://liepaja-sez.lv/nl/iepirkumi-un-izsoles/liepajas-specialas-ekonomiskas-zonas-parvaldes-valdijuma-esosa-nekustama-ipasuma-nomas-tie</a></p></div>
