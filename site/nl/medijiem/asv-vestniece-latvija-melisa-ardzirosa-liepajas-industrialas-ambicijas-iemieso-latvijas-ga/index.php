<h1 class="article-title">Amerikaanse ambassadeur in Letland Melissa Argziros, "De industriële ambities van Liepāja belichamen de geest van Letland"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>"Het is duidelijk dat de industriële ambities van Liepāja de geest van Letland belichamen", gaf de Amerikaanse ambassadeur in Letland Melissa Argžiros toe, die op 16 april kennis maakte met de werking van de haven van Liepāja en de speciale economische zone. Liepāja SEZ-manager Uldis Hmieļevskis liet de ambassadeur ook kennismaken met de geplande groene energie- en industrieprojecten, die worden gecombineerd in het Liepaja Sustainable Industry Center en elkaar aanvullen.</p><p>Eén daarvan is rechtstreeks verbonden met het Amerikaanse mondiale engineeringtechnologiebedrijf KBR, dat de NorSAF-fabriek zal voorzien van productietechnologie voor duurzame vliegtuigbrandstof (SAF) en synthetische brandstof (eSAF). De omzet van KBR bedroeg vorig jaar 7,8 miljard dollar en is gespecialiseerd in zowel de ontwikkeling als de implementatie van hoogwaardige technologieën, waarbij grootschalige fabrieken voor verschillende technologieën op veel plaatsen in de wereld zijn opgericht, maar voor het eerst in de Baltische staten. Waaronder dat KBR al zestig jaar NASA-bestellingen plaatst voor ruimtemissies ter waarde van miljarden jaar na jaar.</p><p>Jānis Kisiels, bestuurslid van LSEZ SIA "NorSAF": "We zijn er trots op zij aan zij te kunnen werken met zo'n professioneel, ervaren en succesvol bedrijf als KBR om het eerste hightechproject in de Baltische staten en het grootste in Noord-Europa op het gebied van duurzame vliegtuigbrandstof te ontwikkelen en te implementeren. Het is ook spannend om het werk van KBR elke dag te observeren - het bedrijf is een belangrijke partner van NASA, dat met technische competentie en operationele ondersteuning deelneemt aan missies zoals het Artemis-programma en de James Webb Space Telescope. Met behulp van deze technologieën zal NorSAF de energie- en regionale veiligheid van Letland en Europa versterken, waardoor de duurzame beschikbaarheid van vliegtuigbrandstof wordt gegarandeerd.</p><p>Liepāja SEZ-kapitaalmaatschappij NorSAF ontwikkelt een productie-installatie op industriële schaal voor duurzame vliegtuigbrandstof (SAF) en synthetische brandstof (eSAF) in de speciale economische zone van Liepāja. De fabriek is van plan innovatieve technologieën te gebruiken onder licentie van KBR, evenals grondstoffen – CO₂, bio-ethanol en groene waterstof, om de productie van de volgende generatie vliegtuigbrandstoffen te garanderen in overeenstemming met de EU-doelstellingen voor het koolstofarm maken van de economie.</p></div>
