<h1 class="article-title">Wij nodigen u uit om het Maritiem Festival op het water te vieren met de Zeevarenden roeiwedstrijd, schepen- en botenparade</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Voor de achtste keer nodigt de Liepāja SEZ-administratie u uit om het Zeefestival in te luiden met het evenement "De breedte van de stad van het meer tot de zee", dat op 10 juli zal plaatsvinden in het Handelskanaal nabij de jachthaven. Het evenement wordt om 16.00 uur geopend door de roeiwedstrijd Seafarers, van 19.00 - 20.00 uur zal er een bijeenkomst zijn voor de parade, maar om 20.00 uur openen de sleepboten van de haven van Liepāja de parade met scheephoorns. Voor kijkers vanaf 16.00 uur is de boulevard ook aan de Jaunliepāja-zijde geopend.   </p><p>Het evenement "Over de stad van het meer naar de zee" begint met de roeiwedstrijd Zeevarenden. Nieuw dit jaar. Om degenen die zichzelf geen zeilers noemen en roeien niet zo gebruikelijk is, niet bang te maken, zal er een gelegenheid zijn om de teamgeest te voelen in de hobbyklasse, die gepland is voor een kortere en gemakkelijkere afstand. Uiteraard zijn ook roeiers met ervaring welkom op de wedstrijd. U kunt uw lidmaatschap hier aanvragen: <a href="https://ej.uz/pieteikumaanketajurasbrauceji" target="_blank">https://ej.uz/pieteikumaanketajurasbrauceji</a></p><p> </p><p>PROGRAMMA:</p><p>16:00 – 19:00 ZEILEN ROEIWEDSTRIJD</p><p>19:00 – 20:00 VOORBEREIDING OP DE PARADE</p><p>20:00 – 21:00 SCHEPEN- EN BOOTPARADE</p><p> </p><p>VOOR TOESCHOUWERS</p><p>VERGADEREN – Aan de Oude Kade en de Nieuwe Kade tegenover de Jachthaven.</p><p> </p><p>VOOR DEELNEMERS</p><p>ZEILEN ROEIEN WEDSTRIJD      </p><ul><li>Vind een gelijkgestemde, solliciteer, train en doe mee.</li><li>Het team moet uit 7 leden bestaan ​​(6 roeiers en 1 roeiritmebewaarder of omroeper).</li><li>Inschrijven voor wedstrijden en trainingsritten: <a href="https://ej.uz/pieteikumaanketajurasbrauceji" target="_blank">https://ej.uz/pieteikumaanketajurasbrauceji</a></li></ul><p>PARADE VAN SCHEPEN EN BOTEN</p><p>Om deel te nemen aan de optocht dient u uzelf, uw team en watervoertuig vóór 9 juli in te schrijven voor deelname aan de vakantieoptocht.</p><ul><li>Toepassing: <a href="https://forms.isdev.lv/kugu-un-laivu-parade" target="_blank">https://forms.isdev.lv/kugu-un-laivu-parade</a></li><li>Verzamelen voor de optocht:</li></ul><p>                - zeeboten bij het Douanekantoor in het Handelskanaal,</p><p>                - meerboten in het kanaal tussen de bruggen.</p><p> </p><p>De administratie van Liepāja SEZ nodigt u uit om actief deel te nemen aan roeiwedstrijden, scheeps- en botenparade, en om te observeren wat er gebeurt. Ook dit jaar zal de waterkant in de Nieuwe Haven open zijn voor toeschouwers gedurende de duur van het evenement, dat in de toekomst gepland is als een openbare ruimte - vergelijkbaar met die in de Oude Haven, waar de haven, schepen en economische activiteiten succesvol naast elkaar bestaan ​​met de aanwezigheid van bewoners en toeristen.</p></div>
