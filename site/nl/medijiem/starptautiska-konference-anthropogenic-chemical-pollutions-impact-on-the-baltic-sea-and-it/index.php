<h1 class="article-title">Internationale conferentie "De impact van antropogene chemische vervuiling op de Oostzee en de daarmee samenhangende ecosystemen"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Op 11 en 12 oktober 2023 zal Liepāja projectnr. NFI/AK/02 "Rehabilitation works of the Karosta Canal of Liepāja Port of Historically Polluted Sites" internationale conferentie "De impact van antropogene chemische vervuiling op de Oostzee en de bijbehorende ecosystemen". Iedereen is uitgenodigd om de conferentie live bij te wonen.</p><p>De conferentie zal verschillende vooraanstaande onderzoekers en experts uit het Oostzeegebied samenbrengen, die hun kennis en ervaring op het gebied van onderzoek naar waterverontreiniging en de praktijk van hercultivering van vervuilde locaties zullen delen.</p><p>Meer over de conferentie en het programma kunt u lezen: <a href="https://ej.uz/konferenesprogramma">https://ej.uz/konferenesprogramma </a></p><p>Op 11 oktober 2023, 10:00 - 18:00 uur, internationale conferentie, presentaties en paneldiscussies met vertegenwoordigers van Letse, Estse, Finse en Noorse onderzoeks- en milieubeheerinstellingen.</p><p>Op 12 oktober 2023 krijgen de deelnemers de gelegenheid om beter kennis te maken met de geschiedenis van het Karosta-gebied zelf, de milieuherstelwerkzaamheden die in het project zijn uitgevoerd en de behaalde resultaten.</p><p>De conferentie is gratis en staat open voor alle geïnteresseerden. Je kunt zowel persoonlijk als op afstand deelnemen aan de live uitzending (11 oktober).</p><p> </p><p><strong>Laten we samenwerken voor een groen Europa!</strong></p><p>Het project wordt gefinancierd in het kader van het Noorse financiële instrument 2014-2021-programma "Mitigatie van klimaatverandering, aanpassing en het milieu". De totale kosten van het project bedragen 5.117.647,05 euro, waarvan 4.350.000,00 euro wordt gefinancierd door het Noorse financiële instrument.</p></div>
