<h1 class="article-title">De haventerminals van Liepāja beginnen graan te ontvangen</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Op 22 juli accepteerde de LSEZ SIA "Dan Store" terminal de eerste tarwekorrels die in Letland werden geteeld en gedorst. Dit is een bevestiging dat het nieuwe graanseizoen is begonnen. In totaal zijn er vijf bulkladingterminals actief actief in de haven van Liepāja, met een totale opslagcapaciteit van ~ 400.000 m<sup>3</sup>.</p><p>Zoals bevestigd door Evita Dambe, hoofd van de terminal, samenwerking en logistiek van LSEZ SIA "Dan Store", accepteerde de terminal vandaag al in de ochtend de eerste lading tarwe, wat betekent dat de boeren zijn begonnen met het dorsen van het graan en het graan naar de haven brengen. De acceptatie van graan ging de hele dag door.</p><p>De grootste bulkvrachtterminal LSEZ SIA "Liepaja Bulk Terminals" blijft zich voorbereiden op het nieuwe graanseizoen, door de infrastructuur te regelen en te verbeteren, maar gerstlading wordt geaccepteerd in magazijnen op het SEZ-gebied van Liepāja, aan de Brīvības-straat. De manager van LSEZ SIA "Liepaja Bulk Terminals", Juris Matvejevs, geeft toe dat alles dit jaar iets sneller gaat, maar het is nog te vroeg om voorspellingen te doen over de graankwaliteit en opbrengst. Juris Matvejs gaf ook toe dat graan in augustus in pakhuizen zal worden opgeslagen, maar dat de meest actieve exportperiode in september zal beginnen, wanneer de kwaliteit, prijs en contracten zullen worden bepaald.</p><p>1 augustus wordt traditioneel beschouwd als het begin van het nieuwe graanseizoen.</p></div>
