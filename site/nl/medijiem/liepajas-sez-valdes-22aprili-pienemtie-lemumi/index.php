<h1 class="article-title">De besluiten genomen door het bestuur van Liepaja SEZ op 22 april</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Op 22 april 2024 werd de reguliere bestuursvergadering van Liepāja Special Economic Zone (Liepāja SEZ) gehouden, waar vijf kwesties met betrekking tot het afsluiten, specificeren en hypothekeren van vastgoedcontracten werden overwogen en ondersteund.</p><p><br/><strong>Over het afsluiten van een langjarige erfpachtovereenkomst</strong><br/>Op basis van de koopovereenkomst van 23 januari 2024 voor het pakhuis aan de Spīķera-straat 15/17, Liepāja, heeft het bestuur van de Liepāja SEZ de beëindiging van de grondpachtovereenkomst met de vorige eigenaar van het gebouw en het sluiten van een nieuwe grondpachtovereenkomst met de nieuwe eigenaar van het gebouw beoordeeld en een besluit genomen. Het onroerend goed Spīķeru iela 15/17, Liepāja ligt op het grondgebied van de haven van Liepāja en voor het beheer van het gebouw is een grondpachtovereenkomst vereist.</p><p><br/><strong>Over het aanbrengen van wijzigingen in het contract inzake de verlening van opstalrechten</strong>en<br/>Op 19 januari 2022 sloten de Liepāja SEZ Administration en SIA EIPU een overeenkomst over de toekenning van bouwrechten op het onroerend goed gelegen op het grondgebied van de haven van Liepāja aan de Oskara Kalpaka-straat 117, Liepaja. Na het in kaart brengen van een deel van de grondeenheden werd de bebouwingsoppervlakte gespecificeerd. Het bestuur van Liepāja SEZ heeft besloten het gesloten contract over de toewijzing van bouwrechten aan een grondeenheid aan de Oskara Kalpaka-straat 117, Liepāja, te verduidelijken.</p><p><br/><strong>Over het reserveren van perceelpacht- en/of bouwrechten</strong><br/>Het bestuur van Liepāja SEZ heeft een overeenkomst beoordeeld en besloten om een overeenkomst aan te gaan over de reservering van pacht- en/of bouwrechten met SIA "GI Termināls" voor een periode van 2 jaar op het onroerend goed Pulvera-straat 8, Liepāja, gelegen op het grondgebied van de haven van Liepāja, voor de ontwikkeling van het bouwplan "HVO/SAF-fabriek" in de minimale samenstelling van het bouwproject.</p><p><br/><strong>Over het afsluiten van een langjarige erfpachtovereenkomst</strong><br/>Het bestuur van Liepāja SEZ heeft een huurovereenkomst beoordeeld en besloten met de naamloze vennootschap "Sadales tīkls" voor onroerend goed Ostas iela 6/8, Liepāja voor 30 jaar. Het besluit is noodzakelijk voor het beheer en onderhoud van het 10 kV-verdeelpunt gelegen op de landeenheid.</p><p><br/><strong>Voor toestemming voor het verhypothekeren van bouwrechten</strong><br/>Het bestuur van Liepāja SEZ evalueerde en stemde ermee in om de bouwrechten die op 29 mei 2018 waren verleend tussen de administratie van Liepāja SEZ en de naamloze vennootschap "iCotton" te verpanden voor de uitbreiding van commerciële activiteiten. In onroerend goed Pulvera iela 4A, Liepāja, is het bouwproject "Productiefabriek voor katoenvezelproducten" geïmplementeerd.</p></div>
