<h1 class="article-title">De straten van het industriepark Liepāja krijgen namen</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Tijdens de vergadering van de gemeenteraad van de stad Liepāja, op 21 augustus, werden acht nieuwe straatnamen goedgekeurd voor de geplande straten op het grondgebied van de voormalige fabriek "Liepājas metalurgs" - in het toekomstige industriepark Liepāja.</p><p>Volgens de door de bewoners zelf aangedragen opties en de uitslag van de stemming zijn de volgende straatnamen toegekend: Tris skursteni iela, Martena iela, Eksporta iela, Dzelzsgriezėja iela, Inženieru iela, Čuguna iela, Naglu iela, Dūmu iela.</p><p>De bewoners zelf waren actief betrokken bij de naamgeving van de straten. Aanvankelijk kregen inwoners van Liepāja de gelegenheid om hun voorstellen met betrekking tot de namen van de straten van het toekomstige industriepark te uiten op de stand van de Liepaja Special Economic Zone Administration tijdens de tentoonstelling "Made in Liepāja", waar in totaal 385 voorstellen werden ontvangen.</p><p>Na evaluatie van alle ontvangen aanbevelingen werden veertien namen geselecteerd die het meest geschikt zijn voor de identiteit van de plaats, die nog niet op de lijst met bestaande straatnamen staan, en die symbolisch het industriële, cultuurhistorische en ontwikkelingspotentieel van het toekomstige industriepark weerspiegelen, en deze werden verder doorgestuurd naar de publieke stemming. Bij de burgerstemming zijn 301 stemmen binnengekomen, waardoor acht straatnamen zijn gekozen, die ter goedkeuring zijn voorgelegd in de raadsvergadering.</p><p>Ook het Rijkstalencentrum heeft een positief advies gekregen over de toekenning van straatnamen, waarin onder meer wordt voorgesteld om de naam te verduidelijken van ‘Skurstenu iela’ naar ‘Tris skurstenu iela’, wat onder meer een geschiktere naam is in het relevante stedelijke landschap en de historische context.</p><p>Het toekennen van straatnamen is een voorwaarde voor opname van deze straten in het officiële adressenregister.</p><p>Momenteel wordt er gewerkt aan de aanleg van verschillende nieuwe straten op het grondgebied van het Liepāja Industrial Park, dat ook voetgangers- en fietspaden, ondergrondse technische communicatie, de aanleg van verlichting en landschapsarchitectuur omvat. De werkzaamheden aan de nieuw aangelegde straten Eksporta en Inženieru naderen hun voltooiing en het is de bedoeling dat ze in de nabije toekomst in gebruik worden genomen. Er wordt verder gewerkt aan de straten Naglu en Dzelzsgriezėja, waar de basislaag van asfalt is gelegd.</p><p>Alle werken binnen de 1e ronde van het project moeten tegen eind 2025 afgerond zijn.</p></div>
