<h1 class="article-title">In de haven van Liepāja zijn de tests van "Aerones" -robots op het water met succes afgerond</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Met de steun van de Liepāja SEZ-administratie en de Captain's Service van de haven werd op 12 en 13 juni het werk van het Letse bedrijf "Aerones" met succes uitgevoerd om een ​​speciaal robotapparaat te testen dat is ontworpen om de aarding van windgeneratoren op het water te controleren voordat het in de Noordzee aan het werk gaat. Liepāja SEZ-manager Uldis Hmieļevskis wijst erop dat dit een uitstekend voorbeeld is van het feit dat de windenergie-industrie kansen creëert voor Letse wetenschappers, fabrikanten en dienstverleners om nieuwe technologieën en diensten te ontwikkelen en nieuwe banen te creëren, zowel tijdens de bouw van windparken als tijdens het onderhoud ervan.</p><p>Aerones is een jong en snelgroeiend bedrijf dat zich wereldwijd bezighoudt met het onderhoud van windturbines met behulp van robots. Volgens Egils Gēcis, de belangrijkste ingenieur van het bedrijf, zijn zowel de technologie, de software als de robots zelf in Letland gemaakt door een team van binnenlandse ingenieurs. De vraag naar onderhoud van zonne- en windparken groeit, waardoor het bedrijf snel kan groeien en voortdurend op zoek is naar nieuwe medewerkers. Aerones is actief in 25 landen - 45 teams, elk met meerdere robots.</p><p>Tot nu toe werkte "Aerones" op het land, maar nu heeft het besloten zijn kracht op het water te testen en windgeneratoren op zee te onderhouden. In de haven van Liepāja werden tests uitgevoerd met slimme apparatuur die mensen vervangt bij zeer gevaarlijk werk. De brede ligplaats van de haven van Liepāja was geschikt voor het testen van de nieuwe robot en technologie.</p><p>Egils Gēcis, de leidende ingenieur van "Aerones", benadrukt dat er steeds meer turbines in de wereld zijn, en dat het niet zo eenvoudig is om mensen te vinden om ze te onderhouden. "Hier komen robots te hulp. De kade beschikt over een van de vele 'assistenten' die het bedrijf hiervoor heeft ontwikkeld. De Liepaja SEZ Authority en het havenmanagement gaven ons de gelegenheid om onze apparatuur te testen, om te kijken hoe deze geschikt is om op het water te werken. We hebben een ankersysteem, ze moeten met behulp van een schip worden geplaatst, er kunnen touwen doorheen worden getrokken, waardoor je de robot kunt besturen. Vandaag hebben we de hele dag getest, alles is heel goed gelukt. Vervolgens gaan we naar Schotland."<br/>Het onderhouden van windturbines, zowel onshore als offshore, is niet eenvoudig. Ze moeten periodiek worden geïnspecteerd, gereinigd en gerepareerd. Dit wordt meestal door mensen gedaan, maar het is erg gevaarlijk, dus ontwikkelen we robots en gebruiken ze. "Het unieke is dat we dit allemaal doen met robots, die we op afstand besturen. Het is sneller, efficiënter en er zijn geen risico's voor mensen", zegt Egils Gecis.</p></div>
