<h1 class="article-title">Dank aan de zakenlieden die in de Liepāja SEZ-gebieden werken</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Dit jaar bedankte het Liepāja SEZ-bestuur alle ondernemende en creatieve zakenlieden voor het werk dat in 2023 in het Liepaja interieurmuseum werd verricht, wat volgens LSEZ-bestuursvoorzitter Ulda Seskas meer dan symbolisch was. Het historische gebouw werd gebouwd in de tijd dat de handelstradities en de haven in Liepāja zich nog maar net begonnen te ontwikkelen.</p><p> </p><p>Voor bijzonder succes in 2023 ontvingen de volgende prijzen:</p><p>• Večas Ostmalas Business Park voor zelfverzekerde en doordachte ontwikkeling van industrieparken;</p><p>• SIA "Dzelzsbetons MB" voor gerichte ontwikkeling en productie van innovatieve producten;</p><p>• SIA "Mols-L" voor duurzame ontwikkeling en gebruik van hulpbronnen.</p><p>• Nu moderne technologieën ons dagelijks leven binnendringen, werd ook het meest actieve bedrijf op het sociale netwerkplatform "Linkedin" gekozen. De winnaar is LSEZ SIA "Vecās ostmalas bedrijvenpark".</p><p> </p><p>Dit keer ontvingen de ondernemers een onderscheiding van kunstenaar Herbert Erb, gebaseerd op de historische rode baksteen waarop de glazen piramide is gebouwd.</p></div>
