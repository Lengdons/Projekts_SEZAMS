<div class="card-body">
<p>Tot het begin van de 20e eeuw had Karosta geen directe verbinding met de rest van de stad Liepāja, omdat de weg werd onderbroken door een breed toegangskanaal van de haven. Het verkeer over het kanaal werd verzorgd door een grote door stoom aangedreven veerboot. Om Liepāja destijds met de haven van Alexander III te verbinden, werd in 1903 begonnen met het ontwerp van de ophaalbrug en in 1904 begon de bouw van de brug, ontworpen door de Duitse ingenieur Harald Hall, over het kanaal. De metalen constructies van de brug zijn gemaakt in de Russische stad Bryansk, terwijl de draaimechanismen en de elektromotor in België zijn gemaakt.</p><p> </p><h5>Het werd geopend op 19 augustus 1906 en het is een van de oudste bruggen met metalen constructies in Letland, een monument van techniek.</h5><p> </p><p>In 1908 werd een publicatie getiteld "Drehbrücke über den großen Hafenkanal in Libau" gepubliceerd in het Duitse technische literatuurtijdschrift "Zeitschrift des vereines deutscher Ingenieure", de enige authentieke bron over de constructie van de brug, de berekende belastingen en de werking van de snijmechanismen.</p><p>Tijdens haar 117-jarig bestaan ​​heeft de brug twee oorlogen en verschillende eigenaren overleefd, wat de werking van de brug beïnvloedde. Tijdens de Eerste Wereldoorlog werd de brug opgeblazen, maar na de oorlog werd hij gerestaureerd, maar al in 1926 werd hij opnieuw beschadigd door het stoomschip "Narne". De brug werd opnieuw herbouwd, maar werd ook beschadigd tijdens de Tweede Wereldoorlog, toen het aanvallende Sovjetleger de haven van Liepāja beschoot.</p><p> </p><h5>De brug weegt 300 ton en bestaat uit twee delen (noord- en zuidzijde) gemaakt van twee identieke uitkragingen. De breedte van de rijbaan van de brug is 7,3 meter, waarvan het dek is gemaakt van houten planken. De lengte van de walconsole is 27,55 meter en de lengte van het kanaal is 38,95 meter. De totale lengte van de brug bedraagt ​​133 meter met een overspanning van 27,55 meter + 77,9 meter + 27,55 meter. De hoogte van de brug boven het waterniveau bedraagt ​​8,32 meter.</h5><p> </p><p>De Duitse ingenieur Harald Hall ontwierp de brug zo dat hij veilig zou zijn en zelfs bij sterkere wind zou kunnen functioneren. Elk deel van de brug dat kan worden uitgesneden, rust op één steunpunt: het lager en lijnt de helling nauwkeurig uit, wat wordt verzekerd door betonnen gewichten.</p><p>Aangezien de Oskar Kalpak-brug een gebouw is met een cultureel en historisch erfgoed, moet het tijdens elke reparatie in precies dezelfde vorm worden bewaard als het vandaag de dag door de haven van Liepāja is geërfd.</p><br/>
