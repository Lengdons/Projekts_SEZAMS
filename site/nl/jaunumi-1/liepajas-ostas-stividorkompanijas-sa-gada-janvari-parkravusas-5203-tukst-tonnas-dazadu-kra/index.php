<h1 class="article-title">Havenstuwadors in Liepāja hebben in januari van dit jaar 520,3 duizend ton overgeslagen. ton verschillende ladingen</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>In januari 2025 werkten de stuwadoorsbedrijven in de haven van Liepāja stabiel en verwerkten ze in totaal 520,3 duizend goederen. tonnen verschillende soorten vracht. De stijging doet zich voor in de vrachtgroep hout, roro en bouwmaterialen, terwijl de daling zich voordoet in de vrachtgroep landbouw. In januari 2025 was bulkgoederen goed voor 63% van alle overgeslagen vracht, stukgoed voor 32% en bulkgoederen voor 5%.</p><p>De stroom roro-vracht blijft groeien op de veerdienst Liepāja – Traveminde, met zes ritten per week. In januari steeg het aantal vervoerde roro-eenheden met 10%. Ook de omzet van hout en rondhout steeg, met respectievelijk +23,8% en +12,2%.</p><p>De daling in het agrarische vrachtsegment is te wijten aan ongunstige weersomstandigheden en de opgelegde importheffingen. Zoals de manager van LSEZ SIA "Liepaja Bulk Terminal", Juris Matvejevs, opmerkte, was de geplande daling van de vrachtomzet in het agrarische vrachtsegment gepland en logisch. Tegelijkertijd wordt er actief gewerkt aan het aantrekken van een nieuwe vrachtgroep, incl. uit Centraal-Azië.</p><p>De vrachtomzet wordt bepaald door seizoens- en weersomstandigheden en de marktvraag. Bovendien blijkt een succesvolle en stabiele operatie niet meer uit de hoeveelheid afgehandelde tonnen, maar uit de toename van de vlottende activa. De transitsector en de havenactiviteiten ondergaan zeer belangrijke veranderingen. Zo startte ‘Norplast Piemare’ in januari met de actieve productie in een nieuw gebouwde fabriek in het havengebied, waar grote onderdelen uit glasvezel worden geproduceerd. Het bedrijf kan trots zijn op de kleinste vracht, die slechts 19,7 ton woog, waarvan de bijdrage aan de totale vrachtomzet onbeduidend is, maar het economische voordeel is groot. </p><p>In 2025 zal de regering van Liepāja SEZ, in samenwerking met havenondernemers en strategische investeerders, haar werk voortzetten om een ​​symbiose te creëren tussen de transport- en logistieke sector en de productie, waarbij de ontwikkeling wordt aangeboden van nieuwe industrieën die veilig zijn voor mens en milieu en van strategisch belang zijn.</p></div>
