<h1 class="article-title">Als onderdeel van een internationaal bioscoopproject wordt de O. Kalpakbrug drie dagen afgesloten voor verkeer</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Van 16 tot en met 24 oktober verandert Liepāja kortstondig in een filmlocatie voor de internationale filmindustrie. De bewerking van de roman "The Girl with the Dragon Tattoo" van de wereldberoemde boekenreeks "Millennium", geproduceerd door het bedrijf "Left Bank Pictures", bekend van projecten als "The Crown" en "Dept Q", zal in de stad worden opgenomen. Een speciale rol in dit project is weggelegd voor de brug van Oskar Kalpak, gekozen als een van de belangrijkste filmlocaties in de hele serie. De brug zal tijdens het filmen drie dagen gesloten zijn voor voetgangers en autoverkeer, en het scheepvaartverkeer zal worden beperkt.</p><p>De opnames op de O. Kalpaka-brug vinden plaats van 19 tot en met 21 oktober. Gedurende deze tijd nodigen we automobilisten, fietsers en voetgangers uit om hun reis van en naar Karosta tijdig te plannen en rekening te houden met eventuele extra tijd onderweg. In samenwerking met de gemeente wordt er speciaal busverkeer langs de rondweg verzorgd. Informatie over deze dienst zal aan beide uiteinden van de brug worden geplaatst. Aan de andere kant wordt het openbaar vervoer omgeleid via omzeilde routes. </p><p>Sluiting van de O. Kalpaka-brug voor voetgangers en voertuigen:</p><ul><li>van 19 oktober 2026 om 08.00 uur tot 21 oktober om 22.00 uur</li></ul><p>Ook zal gedurende de opnames de toegang tot het gebied nabij de O. Kalpaka-brug en de toegangsweg en parkeerplaats van de pier aan de zuidkant van het Karosta-kanaal beperkt zijn.</p><p>Het scheepsverkeer op het Karosta-kanaal zal tijdens de opnames beperkt zijn. De regering van Liepāja SEZ spreekt haar dank uit aan de stuwadoorsbedrijven in de haven van Liepāja, die het belangrijke filmindustrieproject ondersteunen en hun werk zoveel mogelijk hebben verplaatst. Vijf haventerminals zijn actief actief in het Karosta-kanaal: "Baltic Transshipment Center", "Schwenk", "DG Termināls", "Norsaf", "Baltex Bulk" en het bedrijf LZK, dat actief de scheepsreparaties in de haven van Tosmares voortzet.</p><p>Het is veelbetekenend dat de Oskar Kalpak-brug werd gekozen als een van de centrale filmlocaties in dit project, waardoor Liepāja bijzondere internationale aandacht trok. De film zal miljoenen kijkers in verschillende landen bereiken en een krachtig platform worden om het bewustzijn van de stad te bevorderen.</p><p>Succesvolle implementatie van een project van deze omvang versterkt Liepāja's reputatie als internationaal open, professionele havenstad die in staat is complexe projecten uit te voeren. "Dit vergroot de kansen om in de toekomst nieuwe film-, kunst- en creatieve industrieprojecten aan te trekken, waardoor op de lange termijn economische en reputatievoordelen ontstaan ​​voor zowel de stad als de regio."</p></div>
