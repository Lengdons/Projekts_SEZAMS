<h1 class="article-title">De Liepāja SEZ-administratie rondt het ontwikkelingsproces af van het bouwproject "Reconstructie van de havenpier nr. 46 van Liepāja"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Het doel van het project "Ensuring the safe mooring of Ro-Ro ferries in the port of Liepāja" (hierna: het Project) is het garanderen van de veilige afmeren van RO-RO-veerboten in de haven van Liepāja, waardoor de capaciteit van de TEN-T-infrastructuur wordt versterkt en de toegankelijkheid van interne en externe markten wordt verbeterd, met behulp van verbeterde zeevervoerverbindingen.</p><p>Op 20 september 2024 sloten de Liepāja Special Economic Zone Administration en SIA "CHR Design Solutions" een overeenkomst over de ontwikkeling van het bouwproject "Reconstructie van Liepāja Port Pier No. 46". Op 20 augustus 2025 heeft de bouwautoriteit van de stad Liepāja een stempel gedrukt op de vervulling van de ontwerpvoorwaarden in de bouwvergunning nr. BIS-BV-4.2-2025-18 (7/2025) van 21 januari 2025, waarmee de voltooiing van de ontwikkeling van het bouwproject "Reconstructie van de havenpier nr. 46 van Liepāja" werd goedgekeurd. </p><p>De uitvoering van het project omvat de installatie van extra meerpalen, de reconstructie van de kadeconstructies en het vergroten van de waterdiepte van 10,5 naar 12,0 m en zal de veilige exploitatie van de RO - RO / RO - PAX veerboot met een maximale lengte van maximaal 240,0 meter en een diepgang van maximaal 11,0 meter garanderen. </p><p>De totale kosten voor de uitvoering van het project bedragen 23.090.050 euro. </p><p>Het project "Het veilig afmeren van Ro-Ro-veerboten in de haven van Liepāja" (projectacroniem 22-LV-TG-LPXRORO) wordt gedeeltelijk gefinancierd in het kader van het CEF2027-programma (onderwerp ID - CEF-T-2022-COMPGEN-MARP-WORKS, projectnr. 101122785). De bijdrage van de Connecting Europe Facility dekt 30% van de subsidiabele projectkosten van 6.927.015 euro.</p></div>
