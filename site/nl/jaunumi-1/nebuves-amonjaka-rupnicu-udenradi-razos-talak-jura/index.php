<h1 class="article-title">Er komt geen ammoniakfabriek, waterstof wordt verder in zee geproduceerd</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Tijdens de werkvergadering kondigde het hoofd van "CIS Liepāja" Tors Arne Pedersen aan dat in overeenstemming met het management van de Liepaja SEZ de mogelijke locatie van de geplande waterstofproductie-installatie is gewijzigd - verder naar het noorden in het havengebied en dat "CIS Liepāja" vanwege veranderingen in de markt en de vraag de ontwikkeling van het groene ammoniakproductieproject heeft verlaten. </p><p>Tor Arne Pedersen benadrukte dat veiligheid voorop staat. "Sinds het begin van de projectontwikkeling zijn we op zoek geweest naar de beste locaties en technologische oplossingen voor de groene waterstofproductiefabriek en terminal. Veiligheid is iets dat we zeer serieus nemen en we zijn ons er volledig van bewust dat het van cruciaal belang is voor het project. Om deze reden hebben we ook verschillende oplossingen nader bekeken, hoe we de veiligheid op de best mogelijke manier kunnen oplossen. Dit is belangrijk voor ons als projectontwikkelaars, zowel voor de gemeente als voor de Liepāja SEZ Administration".</p><p>In de loop van de werkvergadering presenteerde de manager van "CIS Liepāja" Tors Arne Pedersens opnieuw het idee van het project, de voortgang ervan, de aandeelhouders van het bedrijf en de ervaring met de ontwikkeling en voortgang van verschillende projecten. In antwoord op de vraag waarom Liepāja, gaf Tor Arne Pedersens toe dat ze aanvankelijk alle Scandinavische landen bestudeerden - Noorwegen, Zweden, Finland, waar het grootste obstakel het tekort aan hoogspanningsnetten was, en daarna verder keken naar de Baltische landen. Een belangrijke rol werd gespeeld door de aanbevelingen van de Noorse ambassade in Letland en het hoogwaardige zakelijke klimaat in Liepaja, samen met de speciale economische zone van Liepaja en de voordelen ervan. Op dit moment is het onderzoek gestart en is er een risico- en milieueffectrapportage aan de gang. </p><p>Om kennis te maken met de voortgang van duurzame industrieprojecten op het grondgebied van de speciale economische zone Liepāja, kwamen het management van Liepāja SEZ en de gemeenteraad, leden van de gemeente, ontwikkelaars van investeringsprojecten, het management van de Staatsmilieudienst en vertegenwoordigers van milieuorganisaties bijeen voor een gezamenlijke werkvergadering.</p><p> </p></div>
