<h1 class="article-title">Liepāja presenteert zichzelf als het centrum van de offshore windenergie-industrie in het oostelijke deel van de Oostzee</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Van 27 tot 29 november nam de manager van de Liepāja Special Economic Zone (Liepāja SEZ), Uldis Hmieļevskis, deel aan de "Offshore Energy Exhibition &amp; Conference" in Amsterdam, bezocht de havens van Rotterdam en Amsterdam en ontmoette de leiders van toonaangevende bedrijven in de energie- en logistieke sector van de Europese Unie.</p><p>Liepāja SEZ-manager Uldis Hmieļevskis gaf na een werkbezoek aan Nederland toe dat hij opnieuw overtuigd was van de ambitieuze doelstellingen van de Europese Unie: het creëren van 150 GW aan nieuwe capaciteit in 2050. “Dit is een grote uitdaging, want om dit te bereiken moeten de productiecapaciteit en de havencapaciteit drie keer worden vergroot. Voor Liepāja en Letland betekent dit de mogelijkheid om nieuwe fabrieken te bouwen die funderingen, masten, vleugels en mogelijk zelfs de generatoren gaan produceren. zichzelf.</p><p>Bestaande bedrijven zullen verschillende componenten en onderdelen kunnen produceren. Het Liepāja Maritiem College zal zeilers rechtstreeks kunnen opleiden voor de bouw en het onderhoud van windparken, waardoor de mogelijkheid wordt geboden om het beroep van zeeman hier thuis uit te oefenen, in plaats van maandenlange reizen ver weg te maken.' </p><p>De Oostzee is Noordzee 2.0 – met die onofficiële naam kijkt de offshore windindustrie in Nederland richting de Oostzee richting de doelstellingen van energieonafhankelijkheid en klimaatneutraliteit die de Europese Unie heeft gesteld – een land dat veel ervaring heeft op het gebied van energie, vanaf het moment dat olie- en gasproductieplatforms in de Noordzee werden gebouwd, tot vandaag de dag, wanneer er windparken in zee worden gebouwd. </p><p>De manager van Liepāja SEZ stelde dat het bezoek aan de havens van Amsterdam en Rotterdam, deelname aan de windenergiebeurs en -conferentie resulteerde in veel interessante discussies en nieuwe contacten waarin ontwikkelingsprojecten werden besproken. De regering van Liepāja SEZ zal zeer binnenkort betrokken worden bij de uitvoering van verschillende ambitieuze projecten, zowel in de haven als in de industriële gebieden.  </p><p>“De offshore windindustrie is groot en Letland moet van de gelegenheid profiteren om deze in zijn voordeel te gebruiken – zowel door het creëren van nieuwe banen, kennis, de mogelijkheid om bestaande bedrijven van groene energie te voorzien, als in de toekomst door het creëren en ontwikkelen van nieuwe, veelgevraagde industrieën”, benadrukt Liepāja SEZ-manager Uldis Hmieļevskis. </p><p><br/> </p></div>
