<h1 class="article-title">Dit weekend vindt de tentoonstelling "Made in Liepāja" plaats</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Liepaja produceert en produceert veel. De tentoonstelling "Made in Liepāja" is dit weekend al te zien - 31 januari en 1 februari. Het zal voor iedereen een kans zijn om de producten van Liepāja-ondernemers te zien. Parallel aan de beurs zal er een conferentie plaatsvinden over het bedrijfsleven van vandaag en in de toekomst, over lokale innovatieprojecten en duurzame oplossingen.</p><p>Liepāja produceert zowel zware als grote apparatuur die nodig is voor luchthavenactiviteiten, bouwconstructies en industrie, evenals elektronische controlesystemen die worden gebruikt voor scheepsuitrusting, reserveonderdelen voor de auto-industrie en zelfs ademhalingsapparatuur voor brandweerlieden over de hele wereld. Producten die worden geëxporteerd, worden zowel in fabrieken als op industrieterreinen geproduceerd. Liepāja heeft productietradities kunnen behouden en nieuwe kunnen ontwikkelen en werkt er momenteel aan om een ​​centrum van duurzame industrie te worden, dat gebruik zal maken van de technologieën waar wetenschappers en onderzoekers aan werken.</p><p>Liepāja is na Riga de meest productieve stad van Letland, levert een aanzienlijke bijdrage aan de nationale economie en verhoogt het bruto binnenlands product van het land.</p><p>Meer over de beurs en conferentie: <a href="https://www.liepaja.lv/izstade-razots-liepaja/?fbclid=IwZXh0bgNhZW0CMTAAAR1GvsIXV3yf6pwBJdpSTjaYvv5ngmZoOss0-0brt7T-Ayet3Vw7Ktuo-HA_aem_ZC7SMAJAlWqxl03twYGN9A" target="_blank"><strong>https://www.liepaja.lv/izstade-razots-liepaja/</strong></a></p></div>
