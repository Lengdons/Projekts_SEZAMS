<h1 class="article-title">Beslissingen genomen door het bestuur van Liepaja SEZ op 15 september</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Op 15 september 2023 vond de reguliere bestuursvergadering van Liepāja SEZ plaats, waar 4 besluiten werden genomen. Het bestuur van Liepāja SEZ heeft wijzigingen aangebracht in het contract voor het herstel van het Karosta-kanaal, besloten het contract voor het havenschipkanaal en onderhoudswerkzaamheden aan de waterdiepte te verlengen, een verlengingscontract af te sluiten en steunde de sluiting van het investeringscontract van LSEZ SIA "Terrabalt".</p><p><strong>Over contractverlenging</strong></p><p>Het bestuur van de speciale economische zone Liepāja overwoog en besloot een overeenkomst aan te gaan met de naamloze vennootschap "AQUATEX" over het aanbrengen van wijzigingen in het contract "Onderhoudswerkzaamheden aan Liepāja-havenscheepskanalen en watergebieddiepten", afgesloten op 11 oktober 2022, waarbij gebruik werd gemaakt van de bepaling in het contract voor de mogelijkheid om het contract met een periode van maximaal één jaar te verlengen.</p><p>Het bestuur van Liepāja SEZ maakte kennis met de voortgang en voorwaarden van de uitvoering van het renovatieproject van het Karostakanaal en besloot de looptijd van het contract met 31 kalenderdagen te verlengen. Op 18 juli 2023 werd tijdens de saneringswerkzaamheden aan de vervuilde sedimenten van het kanaal een FAB-500 luchtbom uit 1952 ontdekt in de wateren van het Karosta-kanaal, waardoor alle saneringswerkzaamheden aan de vervuilde sedimenten gedurende meerdere dagen werden stopgezet. De saneringswerkzaamheden worden momenteel uitgevoerd met maximale veiligheidsmaatregelen, wat de uitvoering van de werken aanzienlijk vertraagt: de hoeveelheid sedimentverwijdering en transport naar de stortplaats die eerder voor die dag was gepland.</p><p><strong>Over de uitvoering van het investeringsproject</strong></p><p>Het bestuur van de speciale economische zone Liepāja heeft besloten een overeenkomst te sluiten met LSEZ "Terrabalt" SIA voor het investeringsproject "Aankoop van een nieuwe MAFI R 332 terminaltrekker", dat naar verwachting zal worden geïmplementeerd in de periode van 21 september 2023 tot 30 juni 2025 voor een totaalbedrag van EUR 192.000,00.</p><p><strong>Over het verlengen van het contract</strong></p><p>Het bestuur van de speciale economische zone Liepaja heeft besloten een huurverlengingsovereenkomst aan te gaan, volgens welke de rechten van verplichtingen die voortvloeien uit het contract dat op 1 april 2004 is gesloten tussen het bestuur van de speciale economische zone Liepaja en SIA LSEZ "Liepaja Bulk Terminal LTD" voor de verhuur van het onroerend goed Atslžijnieku iela 41, Liepāja, worden omgezet in nieuwe verplichtingen, zodat SIA "Liepaja Bulk Terminal LTD" wordt vervangen door SIA Transport 'Baltisch systeem'.</p><p>Grondslag: de koopovereenkomst van 11 april 2023, waarin staat dat de nieuwe eigenaar van het onroerend goed SIA “Baltic System Transport” is, ingeschreven in het kadaster door de rechtbank Kurzeme.</p></div>
