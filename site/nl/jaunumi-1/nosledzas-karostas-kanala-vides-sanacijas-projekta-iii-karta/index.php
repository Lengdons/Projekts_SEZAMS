<h1 class="article-title">De derde ronde van het milieuherstelproject van het Karostakanaal loopt ten einde</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Het project wordt gefinancierd in het kader van het Noorse financiële instrument 2014-2021-programma "Mitigatie van de klimaatverandering, aanpassing eraan en aan het milieu" en in totaal werd 145.199 kubieke meter historisch vervuilde sedimenten verwijderd die ongeveer 298 ton gevaarlijke chemicaliën bevatten. Het was de derde ronde van het rehabilitatieproject van het Karostakanaal.</p><p>De werkzaamheden aan het Karosta-kanaal werden uitgevoerd door SIA "Eko osta", in overeenstemming met het gesloten contract en het goedgekeurde rehabilitatieprogramma van het Karosta-kanaal. De rehabilitatiewerkzaamheden aan het Karosta-kanaal begonnen in april 2023, maar eindigden op 5 december 2023. Het totale contractbedrag bedroeg 3.334.877,50 euro, exclusief BTW.</p><p>Gunārs Ansiņš, voorzitter van de gemeenteraad van Liepāja, benadrukte het belang van het verrichte werk, omdat Liepāja in 1992 de HELCOM-hotspot kreeg vanwege de vervuiling van het Karosta-kanaal. “Het was een zeer gecompliceerde situatie toen we in één klein kanaal zowel militair Sovjet-erfgoed, gezonken schepen en onderzeeërs als meer dan honderd verschillende elementen van Mendelejevs tafel hadden. Dit betekende dat wij, als Letland, als Liepaja, als het Oostzeegebied, het kanaal geleidelijk moeten schoonmaken, wat we stap voor stap doen.”</p><p>Liepāja SEZ-manager Uldis Hmieļevskis stelt dat de haven incl. Het Karostakanaal is een integraal onderdeel van de SEZ van Liepāja en er moet dan ook goed voor worden gezorgd, inclusief de erfenis uit de Sovjettijd. "Om de scheepvaart te kunnen ontwikkelen, zodat er nieuwe terminals in de haven kunnen worden gebouwd, moeten we het kanaal opruimen, en dat is gelukt. Er is veel werk verzet."</p><p>Met behulp van een Noors financieel instrument heeft het bestuur van de Speciale Economische Zone van Liepāja de derde ronde van het herstel van het Karostakanaal uitgevoerd om een ​​serieuze investering te doen in het beperken van de risico's van klimaatverandering en de verspreiding van historische vervuiling in de Oostzee en het omringende milieu. De projectmanager, Ivo Kolinņš, benadrukt dat de werkzaamheden zullen worden voortgezet en dat de toekomstige acties op de korte en lange termijn duidelijk zijn, om de historische vervuiling en de impact ervan op het hele ecosysteem van de Oostzee tot een minimum te beperken.</p><p>Tegenwoordig wordt het grondgebied van Karosta een steeds belangrijker sociaal-economisch en binnenlands deel van Liepāja, dus de kanaalreinigingswerkzaamheden die met behulp van het project worden uitgevoerd, zullen lokale bewoners en toeristen in staat stellen om te genieten van de waarden van Karosta in een schonere en hogere kwaliteit omgeving, waardoor het herstel van de waterecosystemen en de vermindering van vervuiling worden bevorderd.</p></div>
