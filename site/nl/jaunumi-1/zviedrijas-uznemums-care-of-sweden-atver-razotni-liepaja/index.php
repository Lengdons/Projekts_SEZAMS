<h1 class="article-title">Het Zweedse bedrijf "Care of Zweden" opent een productiefabriek in Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Vandaag, 14 mei, werd de nieuwe productiefaciliteit van het Zweedse bedrijf "Care of Zweden" plechtig geopend in Liepāja, Vecās Ostmalas Business Park. Het bedrijf heeft een sterk team van medewerkers opgebouwd die medische matrassen produceren. De totale investering bedraagt ​​circa 2 miljoen. euro.</p><p>Het Zweedse bedrijf "Care of Zweden" houdt zich al vijfentwintig jaar bezig met de productie van twee soorten matrassen: medische preventieve matrassen en elektronisch gestuurde medische matrassen. Om de productiefabriek dichter bij de grondstoffenproducenten en leveranciers te brengen, werd besloten om een ​​productiefabriek in de Baltische staten te bouwen, maar na zorgvuldig onderzoek werd Liepāja als locatie gekozen.</p><p>In het voorjaar van 2023 richtte het Zweedse bedrijf "Care of Zweden" een dochteronderneming op in Letland en sloot een contract voor de huur van 3.000 vierkante meter pand in Liepāja's Old Harbour Business Park, dat speciaal voor de behoeften van het bedrijf in minder dan een jaar werd gebouwd.</p><p>Het bedrijvenpark Vecās ostmalas ligt op het grondgebied van de Speciale Economische Zone van Liepāja, relatief dicht bij het stadscentrum, en momenteel werken er al meer dan twintig huurders - bedrijven van Letse en buitenlandse investeerders.</p><p>Zoals hierboven reeds vermeld, is de beslissing van het Zweedse bedrijf "Care of Zweden" om een ​​productiefabriek in Liepaja te bouwen een bevestiging van de kwaliteit van het Letse en Liepaja zakelijke klimaat, dat wordt bevorderd door het Investerings- en Ontwikkelingsagentschap van Letland, de gemeente Liepaja en de Liepaja Special Economic Zone Administration.</p><p>De omzet van het bedrijf "Care of Zweden" bedroeg in 2023 21 miljoen euro en het exporteert zijn producten naar ongeveer 35 landen over de hele wereld. De grootste exportmarkt is Australië.</p></div>
