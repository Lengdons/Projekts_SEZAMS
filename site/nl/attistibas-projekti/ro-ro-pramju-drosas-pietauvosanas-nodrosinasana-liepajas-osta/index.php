<h1 class="article-title">Zorgen voor een veilige ligplaats van Ro-Ro-veerboten in de haven van Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Het garanderen van een regelmatig en continu veerverkeer is rechtstreeks afhankelijk van de technische staat van de haveninfrastructuur die voor de dienstverlening wordt gebruikt. Liepāja-havenpier nr. 46 werd gebouwd in de periode van 1972 tot 1975 met als doel het bieden van parkeergelegenheid en onderhoud aan schepen en onderzeeërs van de Sovjet-marine. In de huidige omstandigheden worden pieren die worden gebruikt voor het reguliere veerverkeer blootgesteld aan verhoogde belastingen die worden veroorzaakt door schepen die met krachtige scheepsmotoren aan- en afmeren van de pier, dat wil zeggen aan een belasting die groter is dan de belasting op de constructies van een pier die in de jaren zeventig en tachtig door schepen is aangelegd.</p><p>Het doel van het project "Ensuring the safe mooring of Ro-Ro ferries in the port of Liepāja" (hierna: het Project) is het garanderen van de veilige afmeren van RO-RO-veerboten in de haven van Liepāja, waardoor de capaciteit van de TEN-T-infrastructuur wordt versterkt en de toegankelijkheid van interne en externe markten wordt verbeterd, met behulp van verbeterde zeevervoerverbindingen.</p><p>De uitvoering van het project omvat de installatie van extra meerpalen, de reconstructie van de kadeconstructies en het vergroten van de waterdiepte van 10,5 naar 12,0 m en zal de veilige exploitatie van de RO - RO / RO - PAX veerboot met een maximale lengte van maximaal 240,0 meter en een diepgang van maximaal 11,0 meter garanderen. </p><p>De totale kosten voor de uitvoering van het project bedragen 23.090.050 euro. </p><p>Het project "Het veilig afmeren van Ro-Ro-veerboten in de haven van Liepāja" (projectacroniem 22-LV-TG-LPXRORO) wordt gedeeltelijk gefinancierd in het kader van het CEF2027-programma (onderwerp ID - CEF-T-2022-COMPGEN-MARP-WORKS, projectnr. 101122785). De bijdrage van de Connecting Europe Facility dekt 30% van de subsidiabele projectkosten van 6.927.015 euro.</p></div>
