<div class="col-12 col-md-3 column-content">
<img alt="icoon" class="icon" src="../../img/block/columns/168/1725616669_kruizu-kugjis.svg"/>
<p>De haven van Liepāja wordt erkend als een succesvol regionaal vrachtoverslagcentrum, terwijl de belangstelling van de cruise-industrie voor Liepaja de laatste tijd ook is gegroeid. Duizenden toeristen kwamen al over zee naar Liepāja via de veerbootroute vanuit Traveminde in Duitsland. Nu wordt gedacht dat gasten van de stad ook op cruiseschepen zouden kunnen komen.</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icoon" class="icon" src="../../img/block/columns/169/1725616901_enkurs.svg"/>
<p>Een cruisereis betekent niet alleen tijd aan boord; geen enkele reis is compleet zonder een excursie aan wal. Liepāja is een van de nieuwste cruisebestemmingen aan de westkust van de Oostzee en biedt de beste ervaring voor cruisepassagiers.</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icoon" class="icon" src="../../img/block/columns/170/1725616778_divas-majinas.svg"/>
<p>De aanlegsteigers voor cruiseschepen bevinden zich in de nabijheid van de havenpas en bieden gemakkelijke toegang tot het stadscentrum en andere toeristische bestemmingen, waar begeleide wandel- of bustochten worden aangeboden om de lokale geschiedenis, cultuur, keuken, aangelegde parken, historische en moderne architectuur, Blauwe Vlag-stranden en meer te verkennen.</p>
</div>
<div class="col-12 col-md-3 column-content">
<img alt="icoon" class="icon" src="../../img/block/columns/171/1725617099_baltijas-karte.svg"/>
<p>Stadsgasten die kiezen voor militair erfgoedtoerisme kunnen het grootste historische militaire gebied in de Baltische staten bezoeken: een deel van de stad genaamd Karosta, dat in de 19e eeuw voor militaire doeleinden werd gebouwd. Het is uniek in historische en architectonische context, niet alleen in Letland, maar ook wereldwijd.</p>
