<div class="col"><div class="col-12 output"><p><strong>Superficie - 86 ettari</strong><br/><strong>1° turno del progetto - 39,5 ha</strong><br/><strong>Attuazione del progetto - 2023 - 2027</strong></p><p>Poiché la situazione geopolitica, la situazione del mercato e le abitudini della popolazione cambiano rapidamente, aumenta la necessità di soluzioni ponderate, innovative e rispettose dell’ambiente. Uno dei temi di attualità del momento è il progetto di costruzione di diversi parchi eolici offshore nel Mar Baltico. Ciò è giustificato sia dagli accordi interstatali internazionali e dalla pianificazione territoriale del Mar Baltico, che definisce l’ubicazione di tali parchi, sia dalla necessità di aumentare l’indipendenza energetica. </p><p> </p><h5><strong>Nella ZES di Liepāja è stato elaborato un piano di sviluppo portuale che consentirebbe la creazione di un'area di 86 ettari nell'area portuale protetta da frangiflutti</strong></h5><p> </p><p>A partire dal 2027, è prevista la costruzione di diversi parchi eolici offshore nel Mar Baltico, il che aprirà opportunità ai grandi porti lettoni di sviluppare le proprie infrastrutture, creando una base di supporto per i parchi eolici. Il porto di Liepāja è uno dei luoghi più adatti per la realizzazione di tale infrastruttura. È stato sviluppato un piano per costruire una base di supporto per l’energia eolica offshore nel porto di Liepāja, che soddisfa pienamente otto condizioni su dieci e comprende tutti i parchi eolici pianificati nelle acque territoriali lettoni entro un raggio di 100 km e tutti i parchi eolici pianificati negli Stati baltici entro un raggio di 250 km.</p><p>Il concetto di sviluppo del porto di Liepāja, che prevede nella prima fase la costruzione di infrastrutture su un'area di 39,5 ettari. La soluzione tecnica del progetto è stata sviluppata, sono stati identificati gli investimenti necessari, è stata sviluppata una tabella di marcia e un calendario per l'attuazione del progetto - l'attuazione di un tale progetto richiederebbe quattro anni, il che è in linea con i tempi previsti per la costruzione dei parchi eolici offshore previsti nella regione, prevedendo anche una certa riserva di tempo.</p><p> </p><h5><strong>Il progetto di espansione del porto di Liepaja comprende il dragaggio e l'ampliamento del fairway esistente</strong></h5><p> </p><p>L’obiettivo del progetto è creare un’importante base di supporto per la costruzione di parchi eolici offshore nella regione (porto di installazione), fornendo allo stesso tempo un’area per la produzione, la manutenzione e la base di servizi legati all’industria (base O&amp;M). Nello sviluppo del progetto tecnico, i migliori esempi di buone pratiche sono stati presi dai principali porti di servizio del settore in Danimarca, Paesi Bassi e Germania. L'implementazione del progetto è pianificata in 3 fasi, a seconda della situazione del mercato e della domanda. L'ambito totale del progetto è un territorio con una superficie di 86 ettari.</p></div>
