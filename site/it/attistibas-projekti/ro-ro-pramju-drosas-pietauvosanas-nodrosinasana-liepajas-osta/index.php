<h1 class="article-title">Garantire l'ormeggio sicuro dei traghetti Ro-Ro nel porto di Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Garantire un traffico regolare e continuo di traghetti dipende direttamente dalle condizioni tecniche delle infrastrutture portuali utilizzate per il servizio. Molo del porto di Liepāja n. 46 fu costruito nel periodo dal 1972 al 1975 con lo scopo di fornire parcheggio e assistenza alle navi e ai sottomarini della Marina sovietica. Nelle condizioni odierne, i moli utilizzati per servire il traffico regolare dei traghetti sono esposti a maggiori carichi causati dalle navi che attraccano e disormeggiano dal molo utilizzando potenti motori marini, vale a dire per un carico che supera il carico sulle strutture di un molo creato dalle navi negli anni '70 e '80.</p><p>Lo scopo del progetto "Garantire l'ormeggio sicuro dei traghetti Ro-Ro nel porto di Liepāja" (di seguito: il Progetto) è quello di garantire l'ormeggio sicuro dei traghetti Ro-Ro nel porto di Liepāja, rafforzando così la capacità dell'infrastruttura TEN-T e migliorando l'accessibilità dei mercati interni ed esterni, utilizzando migliori collegamenti di trasporto marittimo.</p><p>L'attuazione del progetto prevede l'installazione di ulteriori pali di ormeggio, la ricostruzione delle strutture della banchina e l'aumento della profondità dell'acqua da 10,5 a 12,0 m e garantirà il funzionamento sicuro del traghetto RO - RO / RO - PAX con una lunghezza massima fino a 240,0 metri e un pescaggio fino a 11,0 metri. </p><p>Il costo totale di realizzazione del progetto è di 23.090.050 euro. </p><p>Il progetto "Garantire l'ormeggio sicuro dei traghetti Ro-Ro nel porto di Liepāja" (acronimo di progetto 22-LV-TG-LPXRORO) è parzialmente finanziato nell'ambito del programma CEF2027 (topic ID - CEF-T-2022-COMPGEN-MARP-WORKS, progetto n. 101122785). Il contributo del Connecting Europe Facility copre il 30% dei costi ammissibili del progetto pari a 6.927.015 euro.</p></div>
