<h1 class="article-title"> L'8 gennaio 2024 l'Amministrazione della Zona Economica Speciale di Liepāja ha firmato i contratti per l'inizio dei lavori di costruzione per il progetto "Sviluppo del territorio del Parco Industriale di Liepāja, Fase 1"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>L'8 gennaio 2024 l'Amministrazione della Zona Economica Speciale di Liepāja ha firmato i contratti per l'inizio dei lavori di costruzione per il progetto "Sviluppo del territorio del Parco Industriale di Liepāja, Fase 1". Nell'ambito del progetto, il territorio dell'ex fabbrica "Liepājas Metalurgs" a Liepāja tra Brīvības Street, Meldru Street, Liepājas Ezer, Ezermalas Street, Parka Street e Zemnieku Street sarà ricostruito con i territori adiacenti che si affacciano sul Lago Liepājas, costruendo infrastrutture stradali pubbliche con reti di ingegneria, per garantire le infrastrutture aziendali di base, creando un parco industriale operativo di importanza nazionale, garantendo la funzionalità sviluppata del territorio in conformità con il ha approvato la strategia di sviluppo a lungo termine del parco industriale di Liepaja per il periodo 2023-2038.</p><p>L'obiettivo del progetto è trasformare il territorio dell'ex fabbrica "Liepājas metalurgs" in un parco ecoindustriale verde di importanza nazionale, costruendo moderne infrastrutture di base, attirando investitori, creando una produzione orientata all'esportazione ad alto valore aggiunto nelle industrie RIS3 e creando posti di lavoro qualificati e ben retribuiti.</p><p>Il progetto prevede di investire nella costruzione di infrastrutture accessibili al pubblico: strade e comunicazioni ingegneristiche previste da esse.</p><p>Come risultato dell’implementazione del progetto, verranno creati numerosi benefici significativi a lungo termine:</p><ul><li>l’aumento dell’occupazione nella regione promuoverà l’attività economica della città di Liepāja, del distretto di Kurzeme meridionale e della regione di Kurzeme e ridurrà l’onere sociale;</li><li>attrazione di industrie con un valore aggiunto più elevato e con gli specialisti necessari, che promuoveranno lo sviluppo dei campi dell'istruzione e della ricerca e garantiranno la crescita di una forza lavoro istruita sia nella regione di Kurzeme che in Lettonia;</li><li>lo sviluppo di industrie a maggior valore aggiunto, dei loro meccanismi di cooperazione e di ecosistemi orientati verso soluzioni climaticamente neutre, che promuoveranno lo sviluppo di soluzioni innovative e la formazione di nuove imprese su scala locale;</li><li>aumentare le entrate fiscali nei bilanci dei governi statali e locali, che forniranno un contributo significativo al finanziamento delle funzioni dei governi statali e locali.</li></ul><p>Il finanziamento del progetto è previsto dal Piano 3.1 del Meccanismo di ripresa e resilienza dell’Unione europea. nel comma 3.1.1.3.i dell'indirizzo di riforma e investimenti “Politica regionale”. investimenti nell'ambito degli "Investimenti nelle infrastrutture pubbliche delle imprese per lo sviluppo dei parchi industriali e dei territori delle regioni".</p></div>
