<h1 class="article-title">Sviluppo di una valutazione tecnico-economica dello sviluppo del sito di deposito di sedimenti storicamente inquinato del Canale Karosta del Porto di Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Nel periodo dal 1 agosto 2024 al 31 ottobre 2024, l’Amministrazione della Zona Economica Speciale di Liepāja ha implementato lo strumento finanziario norvegese 2014-2021. del programma "Mitigazione del cambiamento climatico, adattamento ad esso e all'ambiente" dell'iniziativa del Fondo di cooperazione bilaterale "Sviluppo della valutazione tecnico-economica dello sviluppo del sito di deposito di sedimenti storicamente inquinato del Canale di Karosta del porto di Liepāja" (di seguito - l'Iniziativa). </p><p>Il canale Karosta del porto di Liepāja e l'inquinamento storico nel suo letto costituiscono un luogo inquinato unico che degrada l'ambiente del Mar Baltico, non solo in Lettonia, ma anche su scala dell'intera regione del Mar Baltico. Dal 1994, l'Amministrazione della Zona Economica Speciale di Liepāja ha portato avanti azioni mirate volte al recupero dell'ambiente del Canale Karosta, a seguito delle quali sono state implementate ambiziose campagne di bonifica dell'inquinamento del Canale Karosta nel 2015 e nel 2023, rimuovendo più di 200mila m dall'ambiente del canale<sup>3</sup> sedimenti contaminati e depositandoli nel sito di deposito di sedimenti storicamente contaminati del canale Karosta del porto di Liepāja. Il luogo di deposito dei sedimenti storicamente inquinati del Canale di Karosta è una parte appositamente delimitata dell'area acquatica del Canale di Karosta, dove è garantito lo stoccaggio sicuro dei sedimenti inquinati depositati. </p><p>Nonostante i numerosi studi dedicati alla situazione ambientale e ai lavori di risanamento del Canale di Karosta e ai lavori di risanamento del Canale di Karosta attuati, fino ad ora non è stata condotta alcuna ricerca sull'ulteriore sviluppo del sito di deposito di sedimenti contaminati, incl. limitare l'ulteriore diffusione degli inquinanti ivi depositati e sviluppare alternative per lo sviluppo del sito di deposito e valutare scenari di gestione. Pertanto, nell'ambito dell'iniziativa, in collaborazione con i partner norvegesi - il Norwegian Water Research Institute (NIVA) e il Norwegian Geotechnical Institute (NGI), che hanno una notevole esperienza non solo nella bonifica dell'inquinamento storico dell'ambiente marino, ma anche nella creazione di siti di smaltimento di sedimenti contaminati e nella loro successiva gestione, sono state sviluppate le alternative di sviluppo e la gestione più promettente del sito di deposizione di sedimenti storicamente contaminati nel Canale di Karosta del porto di Liepāja. scenari. </p><p><strong>Lavoriamo insieme per un'Europa verde!</strong></p><p>Il progetto è finanziato nell'ambito del programma dello strumento finanziario norvegese 2014-2021 "Mitigazione dei cambiamenti climatici, adattamento e ambiente". Il costo totale del progetto è di 264.500,00 euro, di cui 264.500,00 euro finanziati dallo strumento finanziario norvegese.</p></div>
