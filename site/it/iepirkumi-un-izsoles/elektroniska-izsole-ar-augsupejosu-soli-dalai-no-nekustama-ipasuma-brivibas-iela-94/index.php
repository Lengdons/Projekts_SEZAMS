<h1 class="article-title">Asta elettronica con gradino ascendente per una parte dell'immobile di via Brīvības 94 (asta chiusa)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><i><strong>Informazioni sui risultati dell'asta immobiliare:</strong></i></p><p><i>Il 12 settembre 2025 si è conclusa l'asta elettronica della parte immobiliare in via Brīvības 94, Liepāja, organizzata dall'Amministrazione della Zona Economica Speciale di Liepāja. Il prezzo più alto - <strong>378.750,00 euro</strong> (trecentosettantottomilasettecentocinquanta euro), IVA esclusa, ha presentato offerta <strong>SIA "Nordic Steel Lettonia"</strong>, registrazione n. 40203671003, sede legale: Krišjāņa Valdemāra iela 33-3F, Riga, LV-1010 (risultati dell'asta approvati durante la riunione del consiglio di LSEZ dell'08.10.2025, decisione del consiglio n. 103).</i></p><p>_____________________________________</p><p>L'Amministrazione della Zona Economica Speciale di Liepāja, registrazione unificata n. LV90000329402, indice un'asta elettronica con gradino ascendente per una parte dell'immobile in via Brīvības 94, Liepāja, designazione catastale 17000220059, che sarà composto da edifici con designazioni catastali 17000220059089 e 17000220059090, e parti dell'unità fondiaria con una superficie totale di ~21778 m<sup>2</sup> (l'area verrà specificata al termine del rilievo).</p><p>Prezzo di partenza – EUR 375.000,00 (EUR 375.000,00 (trecentosettantacinquemila euro), fase d'asta – EUR 3.750,00 (tremilasettecentocinquanta euro), cauzione d'asta – EUR 37.500,00 (trentasettemilacinquecento <i>euro</i>). Il pagamento dell'acquisto potrà essere effettuato nel seguente ordine:</p><ul><li>Entro 10 giorni lavorativi dalla data di entrata in vigore del contratto preliminare, l'acquirente versa un acconto pari al 30% (trenta per cento) del prezzo di acquisto. </li><li>La restante parte del prezzo d'acquisto dovrà essere pagata dall'acquirente entro due settimane dalla conclusione del contratto d'acquisto.</li></ul><p>L'asta inizia il 12.08.2025. alle 13:00 e termina il 11.09.2025. alle 13:00.</p><p>I candidati possono registrarsi all'asta dal 12.08.2025. alle 13:00 fino al 01.09.2025. alle 23:59 sul sito dell'asta:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Chi vuole partecipare all'asta deve versare un deposito cauzionale pari al 10% (dieci per cento) del prezzo iniziale dell'immobile messo all'asta, ovvero EUR 37.500,00 (trentasettemilacinquecento euro), che può essere accreditato sul conto corrente dell'amministrazione LSEZ: amministrazione della zona economica speciale di Liepāja, registrazione unificata n. LV90000329402, JSC "SEB banka", conto n. LV42UNLA0012000609480, con l'etichetta "Garanzia dell'asta immobiliare in via Brīvības 94". </p><p>L'asta si svolge elettronicamente sul sito: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Per l'asta immobiliare chiamare il 29294267, indirizzo email: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
