<h1 class="article-title">Asta ripetuta con rialzo per gli immobili in via Naglu</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Informazioni sui risultati dell'asta immobiliare:</p><p>Il 27 luglio 2026 si è conclusa l'asta elettronica di beni immobili in Naglu Street 1, Liepāja, organizzata dall'Amministrazione della Zona Economica Speciale di Liepāja. Il prezzo più alto – 297.950,00 EUR (duecentonovantasettemilanovecentocinquanta <i>euro</i>), esclusa l'imposta sul valore aggiunto, è stata offerta da FLESS Liepājas zona economica speciale SIA, registrazione n. 40203373393, sede legale: Satiksmes iela 6, Liepāja (i risultati dell'asta sono stati confermati durante la riunione del consiglio di amministrazione della LSEZ del 19.08.2026, decisione del consiglio n. 66).</p><p>______________________________</p><p> </p><p>L'Amministrazione della Zona Economica Speciale di Liepāja, registrazione unificata n. LV90000329402, è in corso una nuova asta elettronica con gradino ascendente per immobili in via Naglu 1, Liepaja, catasto n. 17000220152, che sarà costituito da un fabbricato con denominazione catastale 17000220059027 e da un'unità fondiaria della superficie complessiva di 15048 mq<sup>2</sup>.</p><p>Prezzo di partenza – 295.000,00 EUR (duecentonovantacinquemila <i>euro</i> e 00 centesimi), passo d'asta – 2950,00 EUR (duemilanovecentocinquanta <i>euro</i> e 00 centesimi), cauzione d'asta - 29.500,00 EUR (ventinovemilacinquecento <i>euro</i> e 00 centesimi). Il pagamento dell'acquisto potrà essere effettuato nel seguente ordine:</p><ul><li>Entro 10 giorni lavorativi dalla data di entrata in vigore del contratto preliminare, l'acquirente versa un acconto pari al 30% (trenta per cento) del prezzo di acquisto. </li><li>La restante parte del prezzo d'acquisto dovrà essere pagata dall'acquirente entro due settimane dalla conclusione del contratto d'acquisto.</li></ul><p>L'asta inizia il 19.06.2026. alle 13:00 e termina il 20.07.2026. alle 13:00.</p><p>I candidati possono registrarsi all'asta dal 19.06.2026. alle 13:00 fino al 09.07.2026. alle 23:59 sul sito dell'asta:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Chi intende partecipare all'asta dovrà versare un deposito cauzionale pari al 10% (dieci per cento) del prezzo base dell'immobile oggetto dell'asta, ovvero Euro 29.500,00 (ventinovemilacinquecento <i>euro</i> e 00 centesimi), che può essere accreditato sul conto corrente dell'amministrazione LSEZ: amministrazione della zona economica speciale di Liepaja, registrazione unificata n. LV90000329402, JSC "SEB banka", conto n. LV42UNLA0012000609480, con l'etichetta "Immobile in via Naglu 1 sicurezza all'asta". </p><p>L'asta si svolge elettronicamente sul sito: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Per ripetere l'asta immobiliare chiamare il 29294267, indirizzo e-mail: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
