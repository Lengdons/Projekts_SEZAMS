<h1 class="article-title">L'amministrazione della SEZ di Liepāja organizza un'asta elettronica con un passo in avanti per gli immobili in via Brīvības 98 (asta chiusa)</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><i><strong>Informazioni sui risultati dell'asta immobiliare:</strong></i></p><p><i>L'11 settembre 2025 si è conclusa l'asta elettronica degli immobili in via Brīvības 98 a Liepāja, organizzata dall'Amministrazione della Zona Economica Speciale di Liepāja. </i></p><p><i>L'8 ottobre 2025 il consiglio della zona economica speciale di Liepāja ha adottato la decisione n. 104 "Confermerò il risultato dell'asta", che ha approvato l'atto preparato dall'amministrazione giudiziaria del 9 settembre 2025. 4184890/0/2025-AKT per aver dichiarato che l'asta non ha avuto luogo. </i></p><p>____________________________________________</p><p>L'Amministrazione della Zona Economica Speciale di Liepāja, registrazione unificata n. LV90000329402, indice un'asta elettronica con gradino ascendente per un immobile in via Brīvības 98, Liepāja, designazione catastale 17000220152, che consisterà in un edificio con designazione catastale 17000220059027 e un'unità fondiaria con una superficie totale di ~15046 m<sup>2</sup> (l'area verrà specificata al termine del rilievo).</p><p>Prezzo di partenza – 295.000,00 EUR (duecentonovantacinquemila euro e 00 centesimi), fase d'asta – 2950,00 EUR (duemilanovecentocinquanta euro e 00 centesimi), denaro di garanzia dell'asta – 29.500,00 EUR (ventinovemilacinquecento euro e 00 centesimi). Il pagamento dell'acquisto potrà essere effettuato nel seguente ordine:</p><ul><li>Entro 10 giorni lavorativi dalla data di entrata in vigore del contratto preliminare, l'acquirente versa un acconto pari al 30% (trenta per cento) del prezzo di acquisto. </li><li>La restante parte del prezzo d'acquisto dovrà essere pagata dall'acquirente entro due settimane dalla conclusione del contratto d'acquisto.</li></ul><p>L'asta inizia il 7.08.2025. alle 13:00 e termina l'8.09.2025. alle 13:00.</p><p>I candidati possono registrarsi all'asta dal 7.08.2025. alle 13:00 fino al 27.08.2025. alle 23:59 sul sito dell'asta:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Chi vuole partecipare all'asta deve versare un deposito cauzionale pari al 10% (dieci per cento) del prezzo iniziale dell'immobile messo all'asta, ovvero EUR 29.500,00 (ventinovemilacinquecento euro e 00 centesimi), che viene accreditato sul conto corrente dell'amministrazione LSEZ: Amministrazione della zona economica speciale di Liepāja, registrazione unificata n. LV90000329402, AS "SEB banka", conto n. LV42UNLA0012000609480, contrassegnato con "Garanzia d'asta immobiliare in via Brīvības 98". </p><p>L'asta si svolge elettronicamente sul sito: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Per l'asta immobiliare chiamare il 29294267, indirizzo email: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p><p>Ulteriori informazioni: Il regolamento dell'asta è disponibile sul sito <a href="../index.php">https://liepaja-sez.lv/it/iepirkumi-un-izsoles/</a>.</p></div>
