<h1 class="article-title">APPALTI (NUMERO DI IDENTIFICAZIONE LSEZ 2024/21) MARPOL I e MARPOL IV (da navi da crociera) gestione dei rifiuti prodotti dalle navi nel porto di Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><strong>Oggetto dell'acquisto</strong><br>L'oggetto dell'appalto è l'accettazione dei rifiuti MARPOL I e MARPOL IV generati durante l'esercizio delle navi (da navi da crociera), in conformità con i regolamenti vincolanti del Consiglio comunale di Liepāja del 22 novembre 2018 "Regolamenti portuali di Liepāja", le Specifiche tecniche determinate dal Cliente (Appendice 1 dei Regolamenti), il Piano di gestione dei rifiuti del porto di Liepāja, i requisiti e le raccomandazioni delle leggi e dei regolamenti della Repubblica di Lettonia e del diritto internazionale (di seguito - Servizio).</p><p><br>1.1.1. Periodo di esecuzione del contratto: 48 (quarantotto) mesi dalla conclusione del contratto.</p><p>1.4.2. Luogo di esecuzione del contratto: Repubblica di Lettonia, Liepāja, porto di Liepāja. 1.4.3. Affinché i fornitori possano comprendere accuratamente il contenuto dell'oggetto dell'appalto (Oggetti), essere in grado di preparare un'offerta qualitativa, eseguire calcoli dei costi e comprendere appieno tutte le circostanze che influenzano o potrebbero influenzare la determinazione del prezzo contrattuale e l'esecuzione dei lavori, il Cliente stabilisce il sopralluogo di tutti gli Oggetti come condizione obbligatoria. L'orario dell'ispezione degli oggetti in coordinamento con Maija Uzolina, specialista del Dipartimento Sicurezza, Protezione e Ambiente dell'Amministrazione SEZ di Liepāja (maija.uzolina@lsez.lv), tel. 26469786. L'Amministrazione della SEZ di Liepāja rilascia ai Richiedenti un certificato relativo all'ispezione degli ormeggi del porto di Liepāja (Appendice 13 del Regolamento).</p><p>1.4.4. Durante la visita dell'oggetto avrà luogo solo l'ispezione dell'oggetto. Non verranno fornite ulteriori informazioni relative all'oggetto dell'appalto o ai regolamenti sugli appalti. Eventuali informazioni aggiuntive (risposte alle domande poste durante la visita alla struttura) saranno inviate a tutti i Richiedenti e contemporaneamente pubblicate nel sottosistema EIS www.eis.gov.lv e-tenders in questa sezione gare il più presto possibile dal momento della ricezione delle domande (le informazioni relative alle domande saranno fornite entro 5 (cinque) giorni lavorativi, ma non oltre 6 (sei) giorni prima della scadenza per la presentazione delle offerte</p><p><br>1.1.2. Le offerte devono essere presentate nel sottosistema di gare elettroniche del sistema di appalto elettronico, di seguito denominato EIS (https://www.eis.gov.lv/EKEIS/Supplier/). Il termine specifico per la presentazione delle offerte è rinvenibile nel relativo avviso dell'Ufficio Vigilanza sugli Appalti, di seguito denominato IUB, sul sito internet e nel sottosistema EIS bandi telematici.<br>1.10.1. L'accesso elettronico diretto e gratuito ai regolamenti e agli allegati è fornito nel sottosistema EIS e-tenders (https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290).<br>&nbsp;</p></div>
