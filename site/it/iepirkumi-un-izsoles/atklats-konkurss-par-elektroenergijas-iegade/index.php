<h1 class="article-title">Gara aperta per "Acquisto di elettricità per il fabbisogno dell'amministrazione della zona economica speciale di Liepāja" Numero di identificazione dell'appalto: LSEZ2021/73/K</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>L'oggetto dell'appalto è l'acquisto di energia elettrica per le esigenze dell'amministrazione della ZES di Liepāja, che deve essere effettuato in conformità con i requisiti del presente regolamento e degli allegati ad esso allegati (di seguito - il Regolamento). L'oggetto dell'appalto non comprende il trasporto (fornitura) di energia elettrica, la trasmissione e la distribuzione.</p><p>&nbsp;</p><p>Codice della nomenclatura dell'oggetto degli appalti (CPV) - 09310000-5.</p><p>&nbsp;</p><p>Il contratto di appalto viene concluso in conformità con il progetto di contratto di appalto (Allegato 6 del Regolamento).</p><p>&nbsp;</p><p>La durata della fornitura del servizio è di 4 (quattro) mesi - dal 1 dicembre 2021 al 31 marzo 2022.</p><p>&nbsp;</p><p>&nbsp;</p><p>Le informazioni aggiuntive fornite ai fornitori in merito ai documenti di appalto e alle modifiche ai documenti di appalto (se presenti) saranno disponibili sul sito web dell'Amministrazione della Zona Economica Speciale di Liepāja <a href="../index.php">http://www.liepaja-sez.lv/it/parvalde/iepirkumi</a>  e EIS nel profilo dell'acquirente <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>  nel sottosistema di gara elettronica nella sezione del presente appalto aperto.</p><p>&nbsp;</p><p>L'offerta dovrà essere presentata entro il 15 novembre 2021 alle ore 10:00 in formato elettronico nel sottosistema bandi elettronici VIA.</p></div>
