<h1 class="article-title">GARA APERTA (NUMERO DI IDENTIFICAZIONE LSEZ2023/13//K) Lavori di costruzione nel territorio del parco industriale di Liepāja nel 1° round del 1° round (tratti stradali Dūņi e "F")</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><strong>Oggetto dell'acquisto</strong></p><p>Lavori di costruzione nel cantiere, tratti delle strade Dūņi e "F", nel parco industriale di Liepāja.</p><p><strong>Codici CPV</strong></p><p>45233120-6 – Lavori di costruzione stradale.</p><p>45231000-5 – Lavori di costruzione di condutture, linee di comunicazione e di alimentazione elettrica.</p><p>44163121-4 – Tubi di riscaldamento.</p><p>34928400-2 - Infrastrutture cittadine.</p><p>34993000-4 – Illuminazione stradale.</p><p>65100000-4 - Approvvigionamento idrico e servizi connessi.</p><p>&nbsp;</p><p>La cauzione dell'offerta è fissata in Euro 10.000,00 (diecimila euro) e la durata è di 4 (quattro) mesi dal giorno di apertura dell'offerta. </p><p>&nbsp;</p><p>Il progetto n. 3.1.1.3.i.0/1/23/A/CFLA/004 "Sviluppo del territorio del parco industriale di Liepāja 1° turno" è attuato nel quadro del piano del meccanismo di ripresa e resilienza dell'Unione europea 3.1.riforme e direzione degli investimenti "Politica regionale" 3.1.1.3.i.investimenti "Investimenti nelle infrastrutture aziendali pubbliche per lo sviluppo di parchi e territori industriali nel regioni”.</p><p>&nbsp;</p><p>1.1.1. Nel pianificare l'esecuzione dei lavori edili, l'appaltatore dovrà garantire con l'atto di consegna-accettazione il termine di 210 (duecentodieci) giorni dalla consegna dell'oggetto edilizio al costruttore per l'inizio dei lavori.</p><p>1.1.2. Luogo di esecuzione dei lavori di costruzione: vie Dūņu e "F", territorio del parco industriale di Liepāja.</p><p>1.1.3. Le offerte devono essere presentate nel sottosistema gare elettroniche del Sistema Elettronico per gli Appalti, di seguito denominato SIA (<a href="https://www.eis.gov.lv/EKEIS/Supplier/">https://www.eis.gov.lv/EKEIS/Supplier/</a>). Il termine specifico per la presentazione delle offerte è rinvenibile nel relativo avviso dell'Ufficio Vigilanza sugli Appalti, di seguito denominato IUB, sul sito internet e nel sottosistema EIS bandi telematici.</p><p>1.1.4. Le gare vengono aperte nel sottosistema gare elettroniche EIS. L'orario di apertura delle gare è consultabile nell'apposito avviso presente sul sito IUB e nel sottosistema gare elettroniche del sistema EIS.</p><p>1.11.1. Nel profilo acquirente del cliente nel SIA è garantito l'accesso elettronico diretto e gratuito al regolamento con i suoi allegati <a href="https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290">https://www.eis.gov.lv/EKEIS/Supplier/Organizer/3290</a>.</p><p>1.11.2. Un soggetto interessato iscritto al SIA può registrarsi come destinatario del regolamento, vedi: <a href="https://www.eis.gov.lv/EIS/Publications/PublicationView.aspx?PublicationId=883">https://www.eis.gov.lv/EIS/Publications/PublicationView.aspx?PublicationId=883</a>.</p></div>
