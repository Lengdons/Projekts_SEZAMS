<h1 class="article-title">Il consiglio della SEZ di Liepaja organizza un'asta elettronica con un passo in avanti per gli immobili di nuova creazione in via Dūmu 6</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>L'Amministrazione della Zona Economica Speciale di Liepāja, numero di registrazione unificato LV90000329402, indice un'asta elettronica con fase ascendente per un immobile di nuova costruzione in via Dūmu 6, Liepāja, che sarà costituito da un edificio con designazione catastale 17000220059068 e un'unità fondiaria con designazione catastale 17000220351 con una superficie totale di 46.766 m<sup>2</sup>.</p><p>Prezzo di partenza – 480.000,00 EUR (quattrocentottantamila <i>euro</i> e 00 centesimi), passo d'asta – 4.800,00 euro (quattromilaottocento <i>euro</i> e 00 centesimi), cauzione d'asta – 48.000,00 euro (quarantottomila <i>euro</i> e 00 centesimi). Il pagamento dell'acquisto potrà essere effettuato nel seguente ordine:</p><ul><li>Entro 10 giorni lavorativi dalla data di entrata in vigore del contratto preliminare, l'acquirente versa un acconto pari al 30% (trenta per cento) del prezzo di acquisto. </li><li>La restante parte del prezzo d'acquisto dovrà essere pagata dall'acquirente entro due settimane dalla conclusione del contratto d'acquisto.</li></ul><p>L'asta inizia il 04.08.2026. alle 13:00 e termina il 03.09.2026. alle 13:00</p><p>I candidati possono registrarsi all'asta dal 04.08.2026. alle 13:00 fino al 24.08.2026. alle 23:59 sul sito dell'asta:  <a href="https://izsoles.ta.gov.lv/">https://izsoles.ta.gov.lv</a>.</p><p>Chi intende partecipare all'asta dovrà versare un deposito cauzionale pari al 10% (dieci per cento) del prezzo base dell'immobile messo all'asta, ovvero Euro 48.000,00 (quarantottomila <i>euro</i> e 00 centesimi), che può essere accreditato sul conto corrente dell'amministrazione LSEZ: amministrazione della zona economica speciale di Liepaja, registrazione unificata n. LV90000329402, AS "SEB banka", conto n. LV42UNLA0012000609480, contrassegnato con "Immobile in via Dūmu 6, Liepāja, garanzia d'asta". </p><p>L'asta si svolge elettronicamente sul sito: <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>. Per l'asta immobiliare chiamare il 29294267, indirizzo email: <a href="mailto:raivo.spaks@lsez.lv">raivo.spaks@lsez.lv</a>.</p></div>
