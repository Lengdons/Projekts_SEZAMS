<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Oggetto dell'appalto: esecuzione dei lavori di demolizione del molo n. 1 del porto di Liepāja in conformità con i requisiti del presente documento della procedura di appalto e degli atti normativi.</p><p>&nbsp;</p><p>I lavori di costruzione verranno realizzati e finanziati nell'ambito del progetto, che viene attuato conformemente al punto 6.1.1 del programma operativo "Crescita e occupazione". nell'ambito dell'obiettivo di sostegno specifico “Aumentare il livello di sicurezza dei grandi porti e migliorare la mobilità della rete di trasporti”.</p><p>&nbsp;</p><p>Il fornitore interessato può familiarizzare con i documenti di gara e riceverli gratuitamente in formato elettronico sul sito web dell'Amministrazione della Zona Economica Speciale di Liepāja su Internet <a href="https://liepaja-sez.lv/mgmt/purchases/107/Iepirkuma%20priek%C5%A1mets:%20Liep%C4%81jas%20ostas%20piest%C4%81tnes%20Nr.1%20nojauk%C5%A1anas%20b%C5%ABvdarbu%20izpilde%20%20saska%C5%86%C4%81%20ar%20%C5%A1%C4%AB%20iepirkuma%20proced%C5%ABras%20dokumentu%20un%20normat%C4%ABvo%20aktu%20pras%C4%ABb%C4%81m.%20%20%20%20%20B%C5%ABvdarbi%20tiks%20veikti%20un%20finans%C4%93ti%20projekta%20ietvaros,%20kura%20realiz%C4%81cija%20notiek%20saska%C5%86%C4%81%20ar%20darb%C4%ABbas%20programmas%20%E2%80%9CIzaugsme%20un%20nodarbin%C4%81t%C4%ABba%E2%80%9D%206.1.1.%20specifisk%C4%81%20atbalsta%20m%C4%93r%C4%B7a%20%E2%80%9CPalielin%C4%81t%20lielo%20ostu%20dro%C5%A1%C4%ABbas%20l%C4%ABmeni%20un%20uzlabot%20transporta%20t%C4%ABkla%20mobilit%C4%81ti%E2%80%9D%20ietvaros.%20%20%20%20%20%20%20%20Ar%20Iepirkuma%20dokumentiem%20Ieinteres%C4%93tais%20pieg%C4%81d%C4%81t%C4%81js%20var%20iepaz%C4%ABties%20un%20sa%C5%86emt%20tos%20elektroniski%20bez%20maksas%20Liep%C4%81jas">http://www.liepaja-sez.lv/it/parvalde/iepirkumi</a> e EIS <a href="https://www.eis.gov.lv/">www.eis.gov.lv</a>, nonché prendere visione gratuitamente dei documenti di gara in forma stampata presso l'Amministrazione della 