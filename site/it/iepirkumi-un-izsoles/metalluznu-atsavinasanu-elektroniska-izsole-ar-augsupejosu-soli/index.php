<h1 class="article-title">Smaltimento rottami metallici in asta elettronica con gradino ascendente</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>L'Amministrazione della Zona Economica Speciale di Liepāja (di seguito l'Amministrazione) organizza la cessione dei beni mobili di proprietà - rottami metallici in un'asta elettronica con scalino ascendente.</p><p>Il prezzo iniziale dell'asta (prezzo condizionato): per 1 (una) tonnellata di Prodotto è 123,08 EUR (centoventitre <i>euro</i> e 8 centesimi), esclusa l'imposta sul valore aggiunto.</p><p>Lo step dell'asta è determinato: EUR 5,00 (cinque <i>euro</i> e 0 centesimi).</p><p>Cauzione dell'asta: 10% del prezzo totale dell'oggetto - 1.520,04 EUR (millecinquecentoventi <i>euro</i> e 4 centesimi), esclusa l'imposta sul valore aggiunto, che è formata dal peso approssimativo del Prodotto (123,5 tonnellate) e dal prezzo iniziale del Prodotto messo all'asta per tonnellata (123,08 EUR). A garanzia dell'asta, entro 10 (dieci) giorni dalla data di inizio dell'asta, la persona che intende partecipare all'asta dovrà trasferire alla Direzione, registrazione unificata n. LV90000329402, AS "Swedbank", conto n. LV12HABA0001407037000. Nella notifica di pagamento indicare "Fondo per asta rottami metallici, id. n. LSEZ IZS 2025/9" e alla sede dell'asta deve essere inviata una richiesta di autorizzazione all'asta <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>.</p><p>L'asta si svolge sul sito di aste elettroniche <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a>.</p><p>L'asta inizia sul sito di aste elettroniche <a href="https://izsoles.ta.gov.lv/" target="_blank">https://izsoles.ta.gov.lv</a> 01.12.2025, ore 13:00. Applicazione fino al 11.12.2025, alle 23:59.</p><p>È possibile familiarizzare con il Prodotto nella sua natura ed effettuare una valutazione di controllo contattando preventivamente Viesturas Romanova, Vice Capo del Dipartimento Infrastrutture dell'Amministrazione, telefono: 26795153, e-mail: <a href="mailto:viesturs.romanovs@lsez.lv">viesturs.romanovs@lsez.lv</a> .</p></div>
