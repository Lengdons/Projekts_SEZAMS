<h2>Il terzo ciclo del progetto di riabilitazione ambientale del Canale Karosta sta per concludersi</h2>
<span class="mb-3">29.12.2023.</span>
</div>
<a aria-label="Leggi di più" class="mb-3 news_link d-none d-md-block" href="../nosledzas-karostas-kanala-vides-sanacijas-projekta-iii-karta/index.php">Leggi di più</a>
</div>
<div class="col-12 col-md-4 description">
<p>L'amministrazione della ZES di Liepāja ha implementato il progetto "Aree storicamente inquinate dei lavori di bonifica del canale di Karosta del porto di Liepāja" con l'obiettivo di ridurre l'impatto negativo dei sedimenti storicamente inquinati del canale di Karosta sull'ambiente, sulla salute umana e sullo stato ecologico del Mar Baltico. Il progetto è finanziato nell'ambito del programma dello strumento finanziario norvegese 2014-2021 "Mitigazione del cambiamento climatico, adattamento ad esso e all'ambiente" e sono stati rimossi un totale di 145.199 metri cubi di sedimenti storicamente contaminati contenenti circa 298 tonnellate di sostanze chimiche pericolose. Era il III round del progetto di riabilitazione del Canale di Karosta.</p>
