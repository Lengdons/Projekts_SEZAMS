<h1 class="article-title">Vi invitiamo a celebrare la Festa del Mare sull'acqua con la gara di remi dei marinai, la sfilata di navi e barche</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Per l'ottava volta l'amministrazione della ZES di Liepāja vi invita a dare il benvenuto al Festival del Mare con l'evento "La larghezza della città dal lago al mare", che avrà luogo il 10 luglio nel Canale Commerciale vicino al porto degli yacht. L'evento sarà aperto alle 16:00 dalla gara di canottaggio dei marittimi, dalle 19:00 alle 20:00 ci sarà un raduno per la sfilata, ma alle 20:00 i rimorchiatori del porto di Liepāja apriranno la sfilata con il suono delle trombe delle navi. Per gli spettatori dalle ore 16:00 la passeggiata sarà aperta anche sul lato Jaunliepāja.   </p><p>La manifestazione “Attraverso la città dal lago al mare” avrà inizio con la Gara di voga della Gente di Mare. Novità quest'anno. Per non spaventare coloro che non si definiscono velisti e remare in barca non è una cosa così comune, ci sarà l'opportunità di sentire lo spirito di squadra nella classe hobby, prevista su una distanza più breve e più facile. Naturalmente anche i vogatori con esperienza sono i benvenuti alla competizione. Puoi richiedere la tua adesione qui: <a href="https://ej.uz/pieteikumaanketajurasbrauceji" target="_blank">https://ej.uz/pieteikumaanketajurasbrauceji</a></p><p> </p><p>PROGRAMMA:</p><p>16:00 – 19:00 GARA DI VELA A CANOTTA</p><p>19:00 – 20:00 PREPARAZIONE ALLA SFILATA</p><p>20:00 – 21:00 SFILATA DI NAVI E BARCHE</p><p> </p><p>PER GLI SPETTATORI</p><p>INCONTRO – All'Old Quay e al New Quay di fronte allo Yacht Harbour.</p><p> </p><p>PER I PARTECIPANTI</p><p>GARA DI CANOTTAGGIO A VELA      </p><ul><li>Trova una persona che la pensa allo stesso modo, fai domanda, formati e partecipa.</li><li>La squadra deve essere composta da 7 membri (6 vogatori e 1 addetto al ritmo di voga o annunciatore).</li><li>Iscrizione alle gare e agli allenamenti: <a href="https://ej.uz/pieteikumaanketajurasbrauceji" target="_blank">https://ej.uz/pieteikumaanketajurasbrauceji</a></li></ul><p>SFILATA DI NAVI E IMBARCAZIONI</p><p>Per partecipare alla parata, registra te stesso, la tua squadra e il veicolo acquatico entro il 9 luglio per la partecipazione alla parata festiva.</p><ul><li>Applicazione: <a href="https://forms.isdev.lv/kugu-un-laivu-parade" target="_blank">https://forms.isdev.lv/kugu-un-laivu-parade</a></li><li>Raduno per la sfilata:</li></ul><p>                - barche marittime presso la dogana nel Canale del Commercio,</p><p>                - barche sul lago nel canale tra i ponti.</p><p> </p><p>L'amministrazione della SEZ di Liepāja vi invita a partecipare attivamente alle gare di canottaggio, alla sfilata di navi e barche, nonché ad osservare ciò che sta accadendo. Anche quest'anno il lungomare del Porto Nuovo sarà aperto agli spettatori per tutta la durata della manifestazione, che in futuro si prevede sarà un'area pubblica, simile a quella del Porto Vecchio, dove porto, navi e attività economica convivono con successo con la presenza di residenti e turisti.</p></div>
