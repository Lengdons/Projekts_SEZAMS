<h1 class="article-title">Il Saeima approva modifiche alla legge "Sull'applicazione delle tasse nei porti franchi e nelle zone economiche speciali"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Nella versione approvata dal Saeima della legge "Sull'applicazione delle tasse nei porti franchi e nelle zone economiche speciali" sono state inserite alcune condizioni che in futuro potrebbero favorire l'attività delle società per azioni della ZES di Liepāja, attrarre nuovi investitori e ridurre la concorrenza con altre zone economiche speciali nella regione del Mar Baltico.</p><p>Le modifiche più importanti:</p><p>· Prorogare il termine per la ripartizione dei costi salariali previsti fino al 31 dicembre 2035 (fino ad ora – 31 dicembre 2024). Ciò consentirà a Liepāja di continuare ad attrarre una forza lavoro qualificata e ben retribuita.</p><p>· Stabilire che in futuro i beni materiali possano essere acquistati anche tramite locazione finanziaria.</p><p>· Stabilire che l'industria della costruzione navale e l'industria delle fibre sintetiche saranno sostenute nel quadro della legge.</p><p>La Legge SEZ di Liepaja stabilisce che la SEZ di Liepaja è stata creata con l'obiettivo di sviluppare e promuovere il commercio, l'industria, il traffico marittimo e aereo, nonché lo scambio internazionale di merci attraverso la Lettonia. Il suo compito è attrarre investimenti per lo sviluppo della produzione e delle infrastrutture e la creazione di nuovi posti di lavoro a Liepāja. La SEZ di Liepāja deve promuovere lo sviluppo della regione di Liepāja.</p><p><strong>Nel periodo che va dall’istituzione della zona economica speciale di Liepāja dal 1997 al 2023, le società di capitali della SEZ di Liepāja hanno effettuato complessivamente circa 403 milioni di investimenti. per un importo di EUR incl. nelle tecnologie moderne.</strong></p><p>Nel 2023, l'Amministrazione della Zona Economica Speciale di Liepāja ha concluso 15 accordi di investimento con le società di capitali della ZES di Liepaja, il cui importo totale di investimento previsto è di 5.481.903,28 euro.</p><p>Nel 2024, il consiglio di amministrazione di Liepāja SEZ ha approvato 5 progetti di investimento per un importo totale di investimento previsto di 4.390 milioni. EURO.</p><p> </p></div>
