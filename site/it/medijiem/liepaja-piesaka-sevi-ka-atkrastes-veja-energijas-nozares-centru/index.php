<h1 class="article-title">Liepāja si presenta come il centro dell'industria dell'energia eolica offshore nella parte orientale del Mar Baltico</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Dal 27 al 29 novembre, il direttore della Zona Economica Speciale di Liepāja (Liepāja SEZ), Uldis Hmieļevskis, ha partecipato alla "Offshore Energy Exhibition &amp; Conference" ad Amsterdam, ha visitato i porti di Rotterdam e Amsterdam e ha incontrato i leader delle aziende leader nel settore energetico e logistico dell'Unione Europea.</p><p>Uldis Hmieļevskis, direttore della SEZ di Liepāja, ha ammesso dopo una visita di lavoro nei Paesi Bassi di essere ancora una volta convinto degli ambiziosi obiettivi dell'Unione Europea: creare 150 GW di nuova capacità entro il 2050. "Questa è una grande sfida, perché per raggiungere questo obiettivo, la capacità produttiva e la capacità portuale devono essere aumentate di tre volte. Per Liepāja e la Lettonia, ciò significa l'opportunità di costruire nuove fabbriche che produrranno fondazioni, alberi, ali e forse anche i generatori stessi.</p><p>Le aziende esistenti saranno in grado di produrre vari componenti e parti. Il Liepāja Maritime College sarà in grado di formare direttamente marinai per la costruzione e la manutenzione di parchi eolici, dando l'opportunità di esercitare la professione di marinaio proprio qui a casa, invece di intraprendere viaggi di diversi mesi lontano." </p><p>Il Mar Baltico è il Mare del Nord 2.0 - con questo nome non ufficiale, l'industria eolica offshore dei Paesi Bassi guarda al Mar Baltico verso gli obiettivi di indipendenza energetica e neutralità climatica fissati dall'Unione Europea - un paese che ha molta esperienza nel campo dell'energia, dai tempi in cui venivano costruite piattaforme di produzione di petrolio e gas nel Mare del Nord, fino ad oggi, quando si costruiscono parchi eolici in mare. </p><p>Il direttore della Liepāja SEZ ha dichiarato che la visita ai porti di Amsterdam e Rotterdam, la partecipazione alla fiera e alla conferenza sull'energia eolica hanno dato luogo a molte discussioni interessanti e nuovi contatti in cui sono stati discussi progetti di sviluppo. L'amministrazione della ZES di Liepāja sarà presto coinvolta nella realizzazione di numerosi progetti ambiziosi sia nel porto che nelle aree industriali.  </p><p>"L'industria eolica offshore è vasta e la Lettonia deve sfruttare l'opportunità per sfruttarla a proprio vantaggio, sia creando nuovi posti di lavoro, conoscenze, l'opportunità di fornire energia verde alle aziende esistenti, sia in futuro per creare e sviluppare nuove industrie richieste", sottolinea Uldis Hmieļevskis, direttore della SEZ di Liepāja. </p><p><br/> </p></div>
