<h1 class="article-title">Decisioni prese dal consiglio della Liepaja SEZ il 17 gennaio</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><strong>Sullo status della società di capitali di Liepāja SEZ</strong></p><p>Il consiglio della zona economica speciale di Liepāja ha esaminato i documenti presentati dalla Crimppi SIA e la richiesta per il riconoscimento dello status di società di capitali della zona economica speciale di Liepaja e l'ha appoggiata. Crimppi è il principale produttore finlandese di impianti e componenti elettronici, che ha deciso di aprire uno stabilimento a Liepāja, nel territorio di LSEZ SIA "Vecās Ostmalas Biznesa Parks" già questa primavera.</p><p> </p><p><strong>Sulla realizzazione di progetti di investimento</strong></p><p>Il consiglio della zona economica speciale di Liepāja ha esaminato e sostenuto tre progetti di investimento delle società di capitale Liepaja SEZ per un importo totale di EUR 2.710.053,47: La società di capitale della zona economica speciale di Liepaja Crimppi SIA prevede di attuare un progetto di investimento per la creazione di un impianto di produzione a Liepaja, la cui realizzazione è prevista entro il 31 dicembre 2026. Nell'ambito del progetto si prevede di investire in tecnologie moderne e acquistare due attrezzature di produzione per l'importo complessivo di euro 222.208,94.</p><p>La "Baltic Biofuel Company" SIA della zona economica speciale di Liepaja prevede di attuare il progetto di investimento "Tettoia di tipo aperto", la cui realizzazione è prevista entro il 31 dicembre 2024 per l'importo totale di 37.844,53 euro.</p><p>Zona economica speciale "Norplast Piemare" Liepāja, JSC intende realizzare il progetto di investimento "Costruzione di un edificio produttivo Atsljenieku iela 37, Liepāja". Sarà un edificio produttivo nel territorio del porto di Liepāja e la sua costruzione è prevista entro il 31 dicembre 2025. L'importo del progetto di investimento è di EUR 2.450.000,00.</p><p>Nel 2023, l'Amministrazione della Zona Economica Speciale di Liepāja ha concluso 15 accordi di investimento con le società di capitali della ZES di Liepaja, il cui importo totale di investimento previsto è di 5.481.903,28 euro.</p><p> </p><p><strong>Informazioni sull'accordo sullo svolgimento di attività commerciali</strong></p><p>Il consiglio della zona economica speciale di Liepāja ha esaminato e sostenuto il piano presentato dalla zona economica speciale di Liepaja SIA "GF Powdercoating" per i prossimi tre anni per lo svolgimento di attività commerciali nel territorio della zona economica speciale di Liepaja, indicando il fatturato netto previsto della società di capitale, il numero di posti di lavoro e il salario medio nell'azienda dal 2024 al 2026.</p></div>
