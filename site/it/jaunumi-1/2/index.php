<h2>La costruzione della strada di accesso all'attracco 92 del porto di Liepāja è in fase di completamento</h2>
<span class="mb-3">20.08.2026.</span>
</div>
<a aria-label="Leggi di più" class="mb-3 news_link d-none d-md-block" href="../noslegumam-tuvojas-piebraucama-cela-izbuve-uz-liepajas-ostas-92-piestatni/index.php">Leggi di più</a>
</div>
<div class="col-12 col-md-4 description">
<p>L’amministrazione della ZES di Liepāja continua a migliorare le infrastrutture necessarie ai pescatori costruendo la strada di accesso al 92° molo del porto. Il progetto è finanziato dal Programma d’azione per lo sviluppo della pesca 2021-2027 del Fondo europeo per gli affari marittimi, la pesca e l’acquacoltura. per l'anno. Nell’ambito del progetto è in corso la realizzazione di una strada di accesso pubblico lunga 364 metri, nonché di un sistema di illuminazione intelligente e di drenaggio dell’acqua piovana. Secondo gli esiti dell'appalto i lavori sono eseguiti da SIA “CTB”, che ha offerto la soluzione economicamente più vantaggiosa per 303.617,32 euro. Si prevede che i lavori di costruzione termineranno entro la fine di agosto.</p>
