<h2>Liepāja - il centro dell'industria dell'energia eolica offshore nella parte orientale del Mar Baltico</h2>
<span class="mb-3">14.04.2022.</span>
</div>
<a aria-label="Leggi di più" class="mb-3 news_link d-none d-md-block" href="../liepaja-atkrastes-veja-energijas-nozares-centrs-baltijas-juras-austrumu-dala/index.php">Leggi di più</a>
</div>
<div class="col-12 col-md-4 description">
<p>Il 14 aprile si è svolto a Liepāja il dibattito "I porti lettoni come base dell'indipendenza energetica", presieduto dal ministro dei trasporti Jānis Vitenbergs e dal ministro dell'Economia Ilze Indriksone, che si è concentrato sul potenziale del Mar Baltico per lo sviluppo di parchi eolici. L'aspetto più importante dei negoziati è stata la necessità che i grandi porti della Lettonia attraggano investitori privati per garantire questo sviluppo. Durante la discussione, il direttore della SEZ di Liepāja, Uldis Hmieļevskis, ha presentato il piano sviluppato per creare una base di supporto per l'energia eolica offshore nel porto di Liepāja, che soddisfa pienamente otto condizioni su dieci e comprende tutti i parchi eolici pianificati nelle acque territoriali lettoni entro un raggio di 100 km e tutti i parchi eolici pianificati negli Stati baltici entro un raggio di 250 km.</p>
