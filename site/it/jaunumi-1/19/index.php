<span class="mb-3">16.05.2024.</span>
</div>
<a aria-label="Leggi di più" class="mb-3 news_link d-none d-md-block" href="../liepajas-ostas-darbibas-stabilitati-nodrosina-kravu-veidu-dazadiba/index.php">Leggi di più</a>
</div>
<div class="col-12 col-md-4 description">
<p>Nei quattro mesi del 2024, le società di stivaggio del porto di Liepāja hanno movimentato 2,54 milioni di tonnellate. tonnellate di carichi vari, che equivalgono a 4 mesi del 2023. La stabilità delle operazioni portuali è assicurata dalla varietà delle tipologie di carico e dalla già tradizionale enfasi sui carichi di origine locale. Nei 4 mesi di quest'anno, sono state servite 479 navi, trasportati 24.691 passeggeri, mentre il numero di unità ro-ro semoventi/non motore trasportate via traghetto è stato di 31.945 e di unità container - 1.967.</p>
