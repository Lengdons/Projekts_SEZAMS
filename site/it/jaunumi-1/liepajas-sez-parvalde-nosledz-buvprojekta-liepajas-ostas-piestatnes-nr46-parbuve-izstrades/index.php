<h1 class="article-title">L'amministrazione della ZES di Liepāja conclude il processo di sviluppo del progetto di costruzione "Ricostruzione del molo del porto di Liepāja n. 46"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Lo scopo del progetto "Garantire l'ormeggio sicuro dei traghetti Ro-Ro nel porto di Liepāja" (di seguito: il Progetto) è quello di garantire l'ormeggio sicuro dei traghetti Ro-Ro nel porto di Liepāja, rafforzando così la capacità dell'infrastruttura TEN-T e migliorando l'accessibilità dei mercati interni ed esterni, utilizzando migliori collegamenti di trasporto marittimo.</p><p>Il 20 settembre 2024, l'Amministrazione della Zona Economica Speciale di Liepāja e SIA "CHR Design Solutions" hanno concluso un accordo sullo sviluppo del progetto di costruzione "Ricostruzione del molo del porto di Liepāja n. 46". Il 20 agosto 2025 l'Autorità edilizia della città di Liepāja ha sancito l'adempimento delle condizioni di progettazione nel permesso di costruzione n. BIS-BV-4.2-2025-18 (7/2025) del 21 gennaio 2025, approvando così il completamento dello sviluppo del progetto di costruzione "Ricostruzione del molo del porto di Liepāja n. 46". </p><p>L'attuazione del progetto prevede l'installazione di ulteriori pali di ormeggio, la ricostruzione delle strutture della banchina e l'aumento della profondità dell'acqua da 10,5 a 12,0 m e garantirà il funzionamento sicuro del traghetto RO - RO / RO - PAX con una lunghezza massima fino a 240,0 metri e un pescaggio fino a 11,0 metri. </p><p>Il costo totale di realizzazione del progetto è di 23.090.050 euro. </p><p>Il progetto "Garantire l'ormeggio sicuro dei traghetti Ro-Ro nel porto di Liepāja" (acronimo di progetto 22-LV-TG-LPXRORO) è parzialmente finanziato nell'ambito del programma CEF2027 (topic ID - CEF-T-2022-COMPGEN-MARP-WORKS, progetto n. 101122785). Il contributo del Connecting Europe Facility copre il 30% dei costi ammissibili del progetto pari a 6.927.015 euro.</p></div>
