<h1 class="article-title">La stabilità delle operazioni del porto di Liepāja è garantita dalla varietà dei tipi di carico</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Nei quattro mesi del 2024, le società di stivaggio del porto di Liepāja hanno movimentato 2,54 milioni di tonnellate. tonnellate di carichi vari, che equivalgono a 4 mesi del 2023. La stabilità delle operazioni portuali è assicurata dalla varietà delle tipologie di carico e dalla già tradizionale enfasi sui carichi di origine locale. Nei 4 mesi di quest'anno, sono state servite 479 navi, trasportati 24.691 passeggeri, mentre il numero di unità ro-ro semoventi/non motore trasportate via traghetto è stato di 31.945 e di unità container - 1.967.</p><p>Il volume delle merci di origine locale nel porto di Liepāja rappresenta oltre il 50%. La torba ottenuta in Lettonia, a Kurzeme, viene aggiunta al grano e ai suoi derivati, al legname, ai trucioli, al cemento, nonché al volume del carico trasportato sulla linea dei traghetti, fornito dalle società industriali nazionali, durante i mesi primaverili. Già dal quarto anno la società di stivaggio portuale di Liepāja "Mols L" collabora con successo con SIA BaltBio, la cui attività principale è l'estrazione e il trasporto della torba.</p><p>La torba viene esportata dal porto di Liepāja in diversi paesi europei come Germania, Danimarca e altri. In media, ogni primavera vengono caricate nel porto di Liepāja 4-5 navi, meno di 3mila. tonnellate ciascuno. Questo è sufficiente perché i paesi europei possano piantare pomodori e cetrioli, sottolinea Matīss Kozlovs, membro del consiglio di amministrazione della SIA "BaltBio". "Per l'azienda è vantaggioso esportare la torba dal porto, che è più vicino al luogo di estrazione, e "Mols L" lavora in modo rapido ed efficiente." Da più di 30 anni la "Mols L" opera stabilmente nel Porto Invernale del Porto di Liepāja, movimentando prevalentemente carichi di varia natura di origine locale.</p><p>Le merci alla rinfusa rappresentano ancora il gruppo di merci più numeroso nel porto di Liepāja e rappresentano il 67% di tutte le merci. Il secondo gruppo di merci più grande è quello delle merci generali, con il 30% o 759,2 mila tonnellate nei quattro mesi di quest'anno. Il maggior volume di merci nel segmento delle merci generali è fornito dal trasporto sulla linea di traghetti Liepāja-Travemunde. Quest'anno, la quantità di merci trasportate sulla linea dei traghetti è di 608.545,25 tonnellate ovvero 31.945 unità e rappresenta un aumento del +15,63%. Āris Ozoliņš, presidente del consiglio d'amministrazione della società di capitali "Terrabalt" della SEZ di Liepāja, è conciso: "Dobbiamo lavorare! Abbiamo rischi e flussi di merci diversificati. Ci sono carichi".</p><p>Le merci alla rinfusa sono il gruppo di merci relativamente più piccolo e costituiscono solo il 3% di tutte le merci, ovvero 81,2 mila. una tonnellata.</p></div>
