<h1 class="article-title">Conferenza internazionale "L'impatto dell'inquinamento chimico di origine antropica sul Mar Baltico e sui relativi ecosistemi"</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>L'11 e il 12 ottobre 2023 Liepāja ospiterà il progetto n. NFI/AK/02 "Lavori di ripristino del canale Karosta del porto di Liepāja di siti storicamente inquinati" conferenza internazionale "L'impatto dell'inquinamento chimico antropogenico sul Mar Baltico e sui relativi ecosistemi". Tutti sono invitati a partecipare alla conferenza in diretta.</p><p>La conferenza riunirà diversi importanti ricercatori ed esperti della regione del Mar Baltico, che condivideranno le loro conoscenze ed esperienze nella ricerca sull'inquinamento delle acque e sulla pratica della ricoltivazione dei siti inquinati.</p><p>Puoi leggere di più sulla conferenza e sul suo programma: <a href="https://ej.uz/konferenesprogramma">https://ej.uz/konferenesprogramma </a></p><p>L'11 ottobre 2023, dalle 10:00 alle 18:00, conferenza internazionale, presentazioni e tavole rotonde con rappresentanti di istituti di ricerca e gestione ambientale lettone, estone, finlandese e norvegese.</p><p>Il 12 ottobre 2023 i partecipanti avranno l'opportunità di conoscere meglio la storia del territorio stesso del Karosta, i lavori di ripristino ambientale realizzati nel progetto e i risultati raggiunti.</p><p>Il convegno è gratuito e aperto a tutti gli interessati. Si potrà partecipare sia di persona che a distanza alla diretta (11 ottobre).</p><p> </p><p><strong>Lavoriamo insieme per un'Europa verde!</strong></p><p>Il progetto è finanziato nell'ambito del programma dello strumento finanziario norvegese 2014-2021 "Mitigazione dei cambiamenti climatici, adattamento e ambiente". Il costo totale del progetto è di 5.117.647,05 euro, di cui 4.350.000,00 euro finanziati dallo strumento finanziario norvegese.</p></div>
