<h1 class="article-title">L'amministrazione Liepaja SEZ sta migliorando la cooperazione con i porti di Lubecca e Amburgo in Germania </h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Sviluppo dei porti, energia verde, rafforzamento dei corridoi di trasporto sono stati i temi principali dei Port Days di Amburgo e Lubecca, ai quali hanno partecipato il direttore della ZES di Liepāja Uldis Hmieļevskis e il consigliere Jānis Lapiņš. </p><p><br/>Alle Giornate portuali lettone-tedesche ad Amburgo e Lubecca il 14 e 15 aprile si è discusso del miglioramento della cooperazione esistente nel campo della logistica, dell'energia sostenibile e della trasformazione dello sviluppo portuale. L’energia rinnovabile e il suo successo nella trasmissione e nell’utilizzo dipendono principalmente da un’efficace combinazione di competenze nel settore industriale, energetico e marittimo.</p><p><br/>Liepāja e il sobborgo di Lubecca Travemundi sono letteralmente collegati dalla linea di traghetti Stena Line sei volte a settimana e viene spesso definita la continuazione dell'autostrada tedesca. Nel 2016 l’Autorità SEZ di Liepāja ha concluso un accordo di cooperazione con l’Autorità Portuale di Lubecca e nel 2021 con il Porto di Amburgo.</p><p><br/>La delegazione lettone era guidata dal ministro dei trasporti Atis Švinka. La visita si è conclusa con il forum Port Days lettone-tedesco. Il direttore della ZES di Liepāja, Uldis Hmieļevskis, durante il dibattito del forum, sottolineerà l'importanza dei partenariati e delle innovazioni a lungo termine nel rafforzamento della competitività, della sicurezza e della sostenibilità dei porti, nonché dei futuri progetti comuni.</p><p><br/>L'amministrazione SEZ di Liepāja è già attivamente coinvolta nella creazione dell'interconnessione elettrica baltico-tedesca, nella quale Liepāja è contrassegnata come potenziale punto di connessione terrestre. D’altro canto è stato appena concluso un accordo sullo sviluppo dell’ecosistema dell’idrogeno nordico-baltico, che lo collegherebbe alla Germania e segnerebbe Liepāja come punto di collegamento terrestre.</p><p><br/>Il direttore della SEZ di Liepāja, Uldis Hmieļevskis, afferma che ciò offrirà alla Lettonia l'opportunità di diventare un paese esportatore di elettricità eolica e solare, e allo stesso tempo Liepāja aprirà opportunità per lo sviluppo di nuovi progetti di investimento ad alta intensità energetica.</p><p><br/>Lo scopo delle Giornate dei porti lettone-tedeschi era quello di promuovere la cooperazione tra le aziende di trasporto e logistica tedesche e lettoni discutendo gli affari attuali del settore nel forum, nonché il rafforzamento dei contatti esistenti e la creazione di nuovi collegamenti commerciali tra le autorità portuali e le aziende tedesche e lettoni.</p><p> </p><p> </p></div>
