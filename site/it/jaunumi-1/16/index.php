<div class="col-12 col-md-4 description">
<p>Con la simbolica demolizione del passo dell'ex fabbrica "Liepājas metalurgs", oggi, 23 settembre, l'amministrazione della Zona Economica Speciale di Liepāja (SEZ) ha avviato solennemente la costruzione del Parco Industriale di Liepāja per trasformarlo in un moderno parco industriale verde basato sui principi fondamentali dell'economia circolare. Sono stati avviati i lavori di costruzione della fase successiva, che prevedono la costruzione di strade e comunicazioni ingegneristiche in 3 fasi, nonché la creazione di nuove reti di distribuzione elettrica. Ciò consentirà l'apertura parziale dell'area chiusa della fabbrica all'accesso del pubblico e creerà un'opportunità per attirare i primi investitori. </p>
