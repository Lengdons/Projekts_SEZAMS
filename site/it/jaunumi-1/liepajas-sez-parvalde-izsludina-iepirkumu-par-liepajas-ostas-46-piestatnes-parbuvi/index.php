<h1 class="article-title">L'amministrazione della ZES di Liepāja annuncia un appalto per la ricostruzione del 46° molo del porto di Liepāja</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p><strong>Al fine di promuovere lo sviluppo delle linee di traghetti merci e passeggeri con il porto di Liepāja e per garantire la continuità del flusso di merci, l'amministrazione Liepaja SEZ continua i suoi lavori per ricostruire il 46° molo del porto di Liepāja. Garantire un traffico regolare di traghetti è strategicamente importante non solo per Liepāja e la Lettonia, ma anche per l’economia e la mobilità militare dell’UE. L'anno scorso il molo ha trasportato 1,8 milioni di tonnellate di merci, il cui valore è di circa 4 miliardi di euro.</strong></p><p>Durante la ricostruzione del molo sarà garantito il servizio simultaneo in sicurezza di due navi mercantili o traghetti merci-passeggeri con una lunghezza massima fino a 240 metri e un pescaggio fino a 11 metri. La ricostruzione della banchina prevede l'installazione di ulteriori pali di ormeggio, la ricostruzione delle strutture della banchina e l'aumento della profondità dell'acqua da 10,5 a 12,0 m. D'altra parte, per accogliere i più nuovi e moderni traghetti RO - RO / RO - PAX, il molo deve essere dotato di un sistema di alimentazione per garantire l'alimentazione elettrica da terra dei traghetti e degli impianti locali di raccolta delle acque reflue. Si prevede che i lavori di ricostruzione del molo 46 saranno completati entro il 31 dicembre 2027.</p><p>Il molo 46 si trova nel porto franco del porto di Liepāja, nella parte centrale della costa orientale. La sua larghezza è di 51,5 m, la lunghezza sul lato nord è di 204,5 m e la lunghezza sul lato sud è di 181,0 m. Il molo 46 del porto di Liepāja fu costruito nel periodo dal 1972 al 1975 per garantire il parcheggio e la manutenzione delle navi e dei sottomarini della Marina sovietica. Oggi, il molo viene utilizzato per servire il traffico regolare di traghetti sulla rotta Liepāja-Trāveminde ed è esposto a un carico maggiore causato dalle navi che attraccano e disormeggiano dal molo utilizzando potenti motori navali. La ricostruzione e il rifacimento del molo sono necessari perché l'amministrazione della ZES di Liepāja è costantemente confrontata con difetti di costruzione del molo e con la sua usura generale che, nonostante i lavori di riparazione, ne deteriora irreversibilmente le condizioni tecniche generali e la sicurezza operativa.</p><p> </p></div>
