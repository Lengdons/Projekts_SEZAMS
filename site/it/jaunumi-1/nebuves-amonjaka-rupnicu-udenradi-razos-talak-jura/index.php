<h1 class="article-title">Non verrà costruito un impianto per l'ammoniaca, l'idrogeno verrà prodotto ulteriormente nel mare</h1>
<div class="block_text mt-5 mb-4">
<div class="row">
<div class="col"><div class="col-12 output"><p>Durante la riunione di lavoro, il capo della "CIS Liepāja" Tors Arne Pedersen ha annunciato che, in accordo con la direzione della ZES di Liepaja, la possibile ubicazione del previsto impianto di produzione di idrogeno è stata cambiata - più a nord nella zona del porto e che, a causa dei cambiamenti del mercato e della domanda, "CIS Liepāja" ha abbandonato lo sviluppo del progetto di produzione di ammoniaca verde. </p><p>Tor Arne Pedersen ha sottolineato che la sicurezza viene prima di tutto. "Fin dall'inizio dello sviluppo del progetto, abbiamo cercato le migliori posizioni e soluzioni tecnologiche per l'impianto e il terminale di produzione di idrogeno verde, la sicurezza è qualcosa che prendiamo molto sul serio e siamo pienamente consapevoli che è di fondamentale importanza per il progetto. Per questo motivo, abbiamo anche esaminato più da vicino varie soluzioni, come possiamo risolvere la sicurezza nel miglior modo possibile. Questo è importante per noi come sviluppatori del progetto, sia per il comune che per l'amministrazione della ZES di Liepāja".</p><p>Nel corso dell'incontro di lavoro, il direttore della "CIS Liepāja" Tors Arne Pedersens ha presentato ancora una volta l'idea del progetto, i suoi progressi, gli azionisti dell'azienda e l'esperienza nello sviluppo e nel progresso di vari progetti. Rispondendo alla domanda sul perché Liepāja, Tor Arne Pedersens ha ammesso che inizialmente hanno studiato tutti i paesi nordici - Norvegia, Svezia, Finlandia, dove l'ostacolo principale era il deficit delle reti elettriche ad alta tensione, poi hanno guardato ulteriormente ai paesi baltici. Un ruolo importante è stato svolto dalle raccomandazioni dell'Ambasciata norvegese in Lettonia e dall'ambiente imprenditoriale di alta qualità a Liepaja, insieme alla zona economica speciale di Liepaja e ai suoi vantaggi. Al momento sono state avviate le ricerche, è in corso la valutazione dei rischi e dell'impatto ambientale. </p><p>Per conoscere lo stato di avanzamento dei progetti industriali sostenibili nel territorio della zona economica speciale di Liepāja, la direzione della SEZ di Liepāja e del Consiglio comunale, i membri del comune, gli sviluppatori di progetti di investimento, la direzione del Servizio ambientale statale e i rappresentanti delle organizzazioni ambientaliste si sono riuniti per un incontro di lavoro congiunto.</p><p> </p></div>
