<div aria-labelledby="heading4720" class="collapse" data-parent="#accordion" id="collapse4720">
<div class="card-body">
<p>Fino all'inizio del XX secolo Karosta non aveva un collegamento diretto con il resto della città di Liepāja, perché la strada era interrotta da un ampio canale d'ingresso del porto. Il traffico attraverso il canale era mantenuto da un grande traghetto a vapore. Per collegare Liepāja con l'allora porto di Alessandro III, nel 1903 iniziarono i lavori di progettazione del ponte levatoio e nel 1904 iniziò la costruzione del ponte sul canale, progettato dall'ingegnere tedesco Harald Hall. Le strutture metalliche del ponte sono state realizzate nella città russa di Bryansk, mentre i meccanismi di rotazione e il motore elettrico sono stati realizzati in Belgio.</p><p> </p><h5>È stato inaugurato il 19 agosto 1906 ed è uno dei più antichi ponti di strutture metalliche in Lettonia, un monumento di ingegneria.</h5><p> </p><p>Nel 1908 sulla rivista di letteratura tecnica tedesca "Zeitschrift des vereines deutscher Ingenieure" fu pubblicata una pubblicazione dal titolo "Drehbrücke über den großen Hafenkanal in Libau", che è l'unica fonte autentica sulla costruzione del ponte, sui carichi calcolati e sul funzionamento dei meccanismi di taglio.</p><p>Durante i suoi 117 anni di esistenza, il ponte è sopravvissuto a due guerre e a diversi proprietari, che ne hanno influenzato il funzionamento. Durante la prima guerra mondiale il ponte fu fatto saltare in aria, ma dopo la guerra fu restaurato, ma già nel 1926 fu nuovamente danneggiato dal piroscafo "Narne". Il ponte fu nuovamente ricostruito, ma fu danneggiato anche durante la Seconda Guerra Mondiale, quando l’esercito sovietico attaccante bombardò il porto di Liepāja.</p><p> </p><h5>Il ponte pesa 300 tonnellate ed è costituito da due parti (lati nord e sud) costituite da due travi a sbalzo identiche. La larghezza della carreggiata del ponte è di 7,3 metri, il cui impalcato è costituito da assi di legno. La lunghezza della console di riva è di 27,55 metri e la lunghezza del canale è di 38,95 metri. La lunghezza totale del ponte è di 133 metri con uno schema di campate di 27,55 metri + 77,9 metri + 27,55 metri. L'altezza del ponte sopra il livello dell'acqua è di 8,32 metri.</h5><p> </p><p>L'ingegnere tedesco Harald Hall progettò il ponte in modo tale che fosse sicuro e in grado di funzionare anche con venti più forti. Ogni parte ritagliabile del ponte poggia su un punto di supporto: il cuscinetto e allinea con precisione la pendenza, assicurata da pesi di cemento.</p><p>Poiché il ponte Oskar Kalpak è un edificio con un patrimonio culturale e storico, durante qualsiasi riparazione deve essere preservato esattamente nella stessa forma in cui è stato ereditato oggi dal porto di Liepāja.</p><br/>
