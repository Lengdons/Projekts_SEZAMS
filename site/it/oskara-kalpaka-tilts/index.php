<div class="col"><h1 class="block-title mb-5">Il ponte potrà essere aperto al traffico navale<span></span></h1><div class="col-12 output"><h6><strong>dalle 01:00 alle 05:00</strong></h6><h6><strong>dalle 10:30 alle 12:00</strong></h6><h6><strong>dalle 14:30 alle 15:30</strong></h6><h6><strong>dalle 19:30 alle 21:00</strong></h6><p> </p><h6>Il ponte non verrà tagliato negli orari specificati se non c'è traffico navale programmato o se non è possibile farlo a causa delle condizioni meteorologiche.</h6></div>
